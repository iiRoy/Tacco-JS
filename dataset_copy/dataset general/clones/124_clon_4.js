// Main utility function to parse a query string into an object
function processQuery(sourceText, allowTypeCoercion) {
    const resultingObject = {};
    // Lookup table for specific string literal coercions
    const literalTypeConversions = { 'true': true, 'false': false, 'null': null };

    if (!sourceText) {
        return resultingObject;
    }

    // Replace '+' with spaces and split into individual key-value pairs
    const valuePairs = sourceText.replace(/\+/g, ' ').split('&');

    for (const singlePair of valuePairs) {
        const keyAndValue = singlePair.split('=');
        let decodedKey = decodeURIComponent(keyAndValue[0]);
        let processedValue;

        if (keyAndValue.length === 2) {
            // Both key and value are present
            processedValue = decodeURIComponent(keyAndValue[1]);
            if (allowTypeCoercion) {
                // Coerce value based on type
                if (processedValue && !isNaN(Number(processedValue))) { // Number (e.g., "123", "3.14")
                    processedValue = Number(processedValue);
                } else if (processedValue === 'undefined') { // String "undefined"
                    processedValue = undefined;
                } else if (Object.prototype.hasOwnProperty.call(literalTypeConversions, processedValue)) { // "true", "false", "null"
                    processedValue = literalTypeConversions[processedValue];
                }
                // Otherwise, it remains a string
            }
        } else if (decodedKey) {
            // Key exists but no value (e.g., "foo&bar")
            processedValue = allowTypeCoercion ? undefined : '';
        } else {
            // Empty pair (e.g., "foo&&bar"), skip processing
            continue;
        }

        // Get the path components for the current key
        const currentPathComponents = resolveKeyPath(decodedKey);

        // Handle simple keys vs. complex (nested) keys differently
        if (currentPathComponents.length === 1 && currentPathComponents[0] === decodedKey) {
            // Simple key (e.g., "foo", "foo[]", "foo[bar")
            // Replicates original jQuery BBQ behavior for simple keys:
            // If an array already exists for the key, push to it.
            // If a scalar exists, convert it to an array and push.
            // Otherwise, assign the scalar value directly.
            if (Array.isArray(resultingObject[decodedKey])) {
                resultingObject[decodedKey].push(processedValue);
            } else if (Object.prototype.hasOwnProperty.call(resultingObject, decodedKey)) {
                // If key exists but is not an array, convert it to an array
                resultingObject[decodedKey] = [resultingObject[decodedKey], processedValue];
            } else {
                // First assignment for this simple key
                resultingObject[decodedKey] = processedValue;
            }
        } else {
            // Complex key (e.g., "a[b]", "a[b][]")
            assignDeepValue(resultingObject, currentPathComponents, processedValue);
        }
    }
    return resultingObject;
}


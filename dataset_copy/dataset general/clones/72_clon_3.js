if (typeof L.defaultMapInstance === 'undefined') {
    /**
     * @global {L.Map|null} L.defaultMapInstance - A globally accessible reference to a default Leaflet map instance.
     * This is used by L.createMapButton if no specific map is provided.
     * Users should set this variable if they wish to use the default map auto-addition feature.
     * Example: `L.defaultMapInstance = myExistingMap;`
     */
    L.defaultMapInstance = null;
}

/**
 * L.Control.ActionTrigger extends L.Control to provide a customizable button control
 * that can be easily added to a Leaflet map. It's designed to trigger a specific
 * user-defined function upon clicking.
 * @class L.Control.ActionTrigger
 * @extends L.Control
 */
L.Control.ActionTrigger = L.Control.extend({
    // Default configuration options for this control.
    options: {
        placement: 'topleft', // The standard Leaflet position for the control (e.g., 'topleft', 'bottomright').
        tooltipText: 'Click here', // The text displayed when hovering over the button.
        visualCue: 'fa-circle-o', // The CSS class for the icon (e.g., 'fa-camera', 'glyphicon-plus').
        uniqueId: null // An optional unique DOM ID for the icon element within the button.
    },

    /**
     * This method is automatically called by Leaflet when the control is added to a map.
     * It's responsible for creating the control's DOM elements and attaching event listeners.
     * @returns {HTMLElement} The root HTML element of the control.
     */
    onAdd: function () {
        const baseContainerClasses = 'leaflet-bar leaflet-control';
        const widgetWrapper = L.DomUtil.create('div', baseContainerClasses);

        const buttonElementClasses = 'leaflet-bar-part';
        this.interactiveHandle = L.DomUtil.create('a', buttonElementClasses, widgetWrapper);

        // Populate the button with its visual icon.
        this._renderVisualComponent();

        // Ensure the interactive element acts as a link, even if it doesn't navigate.
        this.interactiveHandle.setAttribute('href', '#');

        // Attach the primary click event handler using Leaflet's event utility.
        const boundInteractionHandler = this._handleInteractionEvent;
        const contextForHandler = this;
        L.DomEvent.on(this.interactiveHandle, 'click', boundInteractionHandler, contextForHandler);

        // Set the tooltip text for the button.
        const currentTooltip = this.options.tooltipText;
        if (typeof currentTooltip === 'string' && currentTooltip.trim() !== '') {
            this.interactiveHandle.setAttribute('title', currentTooltip);
        } else {
            this.interactiveHandle.setAttribute('title', 'No descriptive tooltip'); // Fallback tooltip.
            console.info('Control created without a specific tooltip text. Using a generic one.');
        }

        return widgetWrapper;
    },

    /**
     * A placeholder function that defines the action to be performed when the button is clicked.
     * This function is intended to be overridden by the user when creating an instance of the control.
     */
    _performAction: function () {
        console.warn('The primary action for this button has not been explicitly defined. Executing default alert.');
        alert('Action routine not assigned to this button!');
    },

    /**
     * Handles the click event on the button. It prevents default browser actions
     * and stops event propagation, then calls the assigned action routine.
     * @param {Event} interactionEvent - The DOM event object generated by the click.
     */
    _handleInteractionEvent: function (interactionEvent) {
        // Basic validation: ensure an event object is present.
        if (!interactionEvent) {
            console.error("Interaction event object is missing. Cannot process click.");
            return;
        }

        // Prevent the browser's default action (e.g., scrolling to top for '#' href).
        L.DomEvent.preventDefault(interactionEvent);
        // Stop the event from propagating further up the DOM tree.
        L.DomEvent.stopPropagation(interactionEvent);

        // Execute the user-defined action, ensuring 'this' context is correct.
        const designatedAction = this._performAction;
        if (typeof designatedAction === 'function') {
            designatedAction.call(this); // Invoke the action.
        } else {
            console.error("Assigned action is not a valid function:", designatedAction);
            alert("Error: Button's action routine is invalid!");
        }
    },

    /**
     * Creates and attaches the icon element to the button.
     * It dynamically adds additional CSS classes based on the icon class prefix.
     */
    _renderVisualComponent: function () {
        const iconClass = this.options.visualCue;
        let additionalStyling = '';

        // Determine appropriate sizing/library classes based on the icon string.
        if (iconClass.startsWith('fa-')) {
            additionalStyling = ' fa fa-lg'; // Standard FontAwesome large size.
        } else if (iconClass.startsWith('glyphicon-')) {
            additionalStyling = ' glyphicon'; // Bootstrap Glyphicon.
        } else {
            // For custom or non-standard icon classes, apply a generic size.
            additionalStyling = ' custom-control-icon-size';
            console.debug(`Applying generic icon styling for class: "${iconClass}".`);
        }

        // Create the icon element (typically an <i> tag).
        const iconDomElement = L.DomUtil.create('i', iconClass + additionalStyling, this.interactiveHandle);

        // Assign a unique ID if specified in the control's options.
        const specifiedUniqueId = this.options.uniqueId;
        if (typeof specifiedUniqueId === 'string' && specifiedUniqueId.trim() !== '') {
            iconDomElement.id = specifiedUniqueId;
        } else {
            // Generate a random ID for debugging purposes if none is provided.
            iconDomElement.id = `button-icon-${Math.random().toString(36).substring(2, 9)}`;
            console.debug(`Icon element created without a specific ID; assigned a generated ID: ${iconDomElement.id}`);
        }
    }
});

/**
 * A factory function to simplify the creation and optional addition of an ActionTrigger button to a Leaflet map.
 * This provides a convenient wrapper around the L.Control.ActionTrigger class.
 *
 * @param {string} [iconClassString] - The CSS class string for the button's icon (e.g., 'fa-plus', 'material-icons-delete').
 * @param {function} [actionFunction] - The callback function to be executed when the button is clicked.
 * @param {string} [displayLabel] - The text to be shown as a tooltip when hovering over the button.
 * @param {L.Map|null|false} [targetMapInstance] - The Leaflet map object to which the button should be added.
 *                                                  Pass `null`, `false`, or an empty string to prevent auto-addition.
 *                                                  If omitted or not a map, `L.defaultMapInstance` will be attempted.
 * @param {string} [iconElementId] - An optional unique DOM ID for the icon element within the button.
 * @returns {L.Control.ActionTrigger} The newly created L.Control.ActionTrigger instance.
 */
L.createMapButton = function (iconClassString, actionFunction, displayLabel, targetMapInstance, iconElementId) {
    // Instantiate the custom control.
    let buttonControlInstance = new L.Control.ActionTrigger();

    // Apply configuration based on provided arguments.
    // Enhanced validation and logging for each parameter.

    // Configure the icon class.
    if (typeof iconClassString === 'string' && iconClassString.trim() !== '') {
        buttonControlInstance.options.visualCue = iconClassString;
    } else {
        console.info("No valid icon class string provided for L.createMapButton. Using default icon.");
    }

    // Configure the unique ID for the icon element.
    if (typeof iconElementId === 'string' && iconElementId.trim() !== '') {
        buttonControlInstance.options.uniqueId = iconElementId;
    } else {
        console.debug("No specific unique ID provided for the button's icon element.");
    }

    // Configure the action routine.
    if (typeof actionFunction === 'function') {
        buttonControlInstance._performAction = actionFunction;
    } else {
        console.warn("L.createMapButton was called without a valid action function. Button will use its default placeholder behavior.");
        // Optionally, assign a no-op function to prevent default behavior if preferred.
        // buttonControlInstance._performAction = () => { console.log('Button clicked, but no action defined.'); };
    }

    // Configure the display label (tooltip).
    if (typeof displayLabel === 'string' && displayLabel.trim() !== '') {
        buttonControlInstance.options.tooltipText = displayLabel;
    } else {
        console.info("No display label (tooltip text) provided for L.createMapButton. Using default tooltip.");
    }

    // Determine where to add the button (or if it should be added at all).
    let mapToAttachTo = null;

    if (targetMapInstance === null || targetMapInstance === false || targetMapInstance === '') {
        // Explicitly skip adding the button to a map.
        console.log("L.createMapButton: Auto-addition to map explicitly prevented.");
    } else if (targetMapInstance instanceof L.Map) {
        // Add to the specific Leaflet map instance provided.
        mapToAttachTo = targetMapInstance;
        mapToAttachTo.addControl(buttonControlInstance);
        console.log("L.createMapButton: Button successfully added to the specified map instance.");
    } else if (L.defaultMapInstance instanceof L.Map) {
        // If a specific map wasn't provided or was invalid, try the global default map.
        mapToAttachTo = L.defaultMapInstance;
        mapToAttachTo.addControl(buttonControlInstance);
        console.log("L.createMapButton: Button added to L.defaultMapInstance as no specific map was provided.");
    } else {
        // No valid map instance could be determined.
        console.error("L.createMapButton: Cannot add button. No valid map instance (either provided or L.defaultMapInstance) could be found.");
        // Consider throwing an error here for stricter behavior:
        // throw new Error("Failed to add button: No target map instance available.");
    }

    return buttonControlInstance;
};
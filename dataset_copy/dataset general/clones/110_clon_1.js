// This block provides polyfills for `.innerWidth()`, `.innerHeight()`,
// `.outerWidth()`, and `.outerHeight()` for jQuery versions older than 1.8.
// The check `!$( "<a>" ).outerWidth( 1 ).jquery` is a specific way to detect this.
if ( !$( "<a>" ).outerWidth( 1 ).jquery ) {
  $.each( [ "Width", "Height" ], function( i, name ) {
    var side = name === "Width" ? [ "Left", "Right" ] : [ "Top", "Bottom" ],
        type = name.toLowerCase(),
        orig = { // Store original jQuery functions.
          innerWidth: $.fn.innerWidth,
          innerHeight: $.fn.innerHeight,
          outerWidth: $.fn.outerWidth,
          outerHeight: $.fn.outerHeight
        };

    /**
     * Helper function to calculate reduced size based on padding, border, and margin.
     *
     * @param {HTMLElement} elem - The DOM element.
     * @param {number} size - The initial size.
     * @param {boolean} border - Include border in reduction.
     * @param {boolean} margin - Include margin in reduction.
     * @returns {number} The reduced size.
     */
    function reduce( elem, size, border, margin ) {
      $.each( side, function() {
        size -= parseFloat( $.css( elem, "padding" + this ) ) || 0;
        if ( border ) {
          size -= parseFloat( $.css( elem, "border" + this + "Width" ) ) || 0;
        }
        if ( margin ) {
          size -= parseFloat( $.css( elem, "margin" + this ) ) || 0;
        }
      } );
      return size;
    }

    // Override `innerWidth` and `innerHeight`.
    $.fn[ "inner" + name ] = function( size ) {
      if ( size === undefined ) {
        return orig[ "inner" + name ].call( this ); // Call original if no size is provided.
      }

      return this.each( function() {
        $( this ).css( type, reduce( this, size ) + "px" );
      } );
    };

    // Override `outerWidth` and `outerHeight`.
    $.fn[ "outer" + name ] = function( size, margin ) {
      if ( typeof size !== "number" ) {
        return orig[ "outer" + name ].call( this, size ); // Call original if size is not a number.
      }

      return this.each( function() {
        $( this ).css( type, reduce( this, size, true, margin ) + "px" );
      } );
    };
  } );
}


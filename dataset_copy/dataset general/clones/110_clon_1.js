/**
 * Determines if an element is focusable.
 *
 * @param {HTMLElement} element - The DOM element to check.
 * @param {boolean} isTabIndexNotNaN - Pre-computed check for tabindex not being NaN.
 * @returns {boolean} True if the element is focusable, false otherwise.
 */
function focusable( element, isTabIndexNotNaN ) {
  var map, mapName, img,
      nodeName = element.nodeName.toLowerCase(); // Get the lowercase tag name.

  // Special handling for <area> elements.
  if ( "area" === nodeName ) {
    map = element.parentNode;
    mapName = map.name;
    // An area is focusable if it has an href, belongs to a map, and the map's image is visible.
    if ( !element.href || !mapName || map.nodeName.toLowerCase() !== "map" ) {
      return false;
    }
    img = $( "img[usemap='#" + mapName + "']" )[ 0 ];
    return !!img && visible( img );
  }

  // General focusability rules.
  return ( /^(input|select|textarea|button|object)$/.test( nodeName ) ?
    !element.disabled : // Input-like elements are focusable if not disabled.
    "a" === nodeName ?
      element.href || isTabIndexNotNaN : // Anchor tags are focusable if they have an href or a valid tabindex.
      isTabIndexNotNaN ) && // Other elements are focusable if they have a valid tabindex.
    // The element and all its ancestors must also be visible.
    visible( element );
}

/**
 * Determines if an element is visible.
 *
 * @param {HTMLElement} element - The DOM element to check.
 * @returns {boolean} True if the element is visible, false otherwise.
 */
function visible( element ) {
  // Use jQuery's built-in :visible filter and ensure no ancestor has 'visibility: hidden'.
  return $.expr.filters.visible( element ) &&
    !$( element ).parents().addBack().filter( function() {
      return $.css( this, "visibility" ) === "hidden";
    } ).length;
}

// Extend jQuery's selector expressions with custom filters.
$.extend( $.expr[ ":" ], {
  /**
   * Selector for elements that have data associated with them by a specific name.
   *
   * @param {string} dataName - The name of the data attribute to check.
   * @returns {function(HTMLElement): boolean} A function that checks if an element has the specified data.
   */
  data: $.expr.createPseudo ?
    $.expr.createPseudo( function( dataName ) {
      return function( elem ) {
        return !!$.data( elem, dataName );
      };
    } ) :
    // Fallback for jQuery versions older than 1.8.
    function( elem, i, match ) {
      return !!$.data( elem, match[ 3 ] );
    },

  /**
   * Selector for focusable elements.
   *
   * @param {HTMLElement} element - The DOM element to check.
   * @returns {boolean} True if the element is focusable.
   */
  focusable: function( element ) {
    // Check focusability based on tabindex existence.
    return focusable( element, !isNaN( $.attr( element, "tabindex" ) ) );
  },

  /**
   * Selector for tabbable elements (elements that can be reached by pressing Tab).
   *
   * @param {HTMLElement} element - The DOM element to check.
   * @returns {boolean} True if the element is tabbable.
   */
  tabbable: function( element ) {
    var tabIndex = $.attr( element, "tabindex" ),
        isTabIndexNaN = isNaN( tabIndex );
    // An element is tabbable if its tabindex is not NaN or is non-negative, and it is focusable.
    return ( isTabIndexNaN || tabIndex >= 0 ) && focusable( element, !isTabIndexNaN );
  }
} );


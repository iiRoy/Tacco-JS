'use strict';

// Core module dependencies for file operations, command execution, and directory removal.
var fileSystem = require('fs');
var syncExecutor = require('execsyncs');
var directoryWiper = require('rimraf');


// Define constants for RAM disk configuration.
const STORAGE_CAPACITY_BYTES = 2 * 1024 * 1024 * 1024; // Specifies 2 gigabytes for the volatile storage.
const CHUNK_SIZE = 512; // Standard block size used for disk operations.
const STORAGE_CHUNKS = STORAGE_CAPACITY_BYTES / CHUNK_SIZE; // Calculated total number of blocks for the RAM disk.
const VOLATILE_STORAGE_LABEL = "AcceleratedStorage"; // The human-readable name for the RAM disk.

// Determines the appropriate mounting location for the RAM disk based on the detected operating system.
const VOLATILE_STORAGE_LOCATION = (function() {
  switch (process.platform) {
    case "darwin": // For Apple macOS environments.
      return "/Volumes/" + VOLATILE_STORAGE_LABEL;
    case "linux": // For GNU/Linux environments.
      return "/mnt/" + VOLATILE_STORAGE_LABEL;
    default: // Fallback for any unsupported operating systems.
      return null;
  }
})();

/**
 * Verifies if the designated volatile storage (RAM disk) is currently active and accessible on the system.
 * @returns {boolean} Returns true if the RAM disk exists at its expected path, false otherwise.
 */
function volatileStoragePresent() {
  return fileSystem.existsOnDisk(VOLATILE_STORAGE_LOCATION);
}

/**
 * Executes a given shell command synchronously, logging its activity to the console.
 * This function will throw an error if the command execution fails for any reason.
 * @param {string} cmdString The complete command string to be executed in the shell.
 * @returns {string} The standard output generated by the executed command, converted to a string.
 */
function executeSystemCommand(cmdString) {
  // Output the command being executed for traceability and debugging purposes.
  console.log("ram-accelerator: " + cmdString);

  try {
    // Attempt to execute the command and capture its output.
    return syncExecutor(cmdString).toString();
  } catch (errorObject) {
    // In case of an execution error, re-throw a more informative error message.
    throw new Error("ram-accelerator: command execution failure (" + cmdString + "): " + errorObject.message);
  }
}

/**
 * Responsible for clearing out an existing temporary directory, but only if it's empty.
 * This ensures the path is ready for the RAM accelerator to take its place.
 * @param {string} projectTemporaryPath The file system path to the project's temporary directory.
 * @throws {Error} An error is thrown if the directory is found to be non-empty.
 */
function clearStaleTemporaryFolder(projectTemporaryPath) {
  // Before proceeding, confirm that the target temporary directory is empty.
  if (fileSystem.readDirectorySynchronously(projectTemporaryPath).length > 0) {
    throw new Error("The folder located at " + projectTemporaryPath + " is not empty. Kindly clear it or remove it entirely for the RAM accelerator to utilize this spot.");
  }

  // Synchronously remove the temporary directory and all its contents.
  directoryWiper.synchronousWipe(projectTemporaryPath);
}

/**
 * Provisions a raw device for the volatile storage, adapting its method based on the operating system.
 * @returns {string} The path or unique identifier of the newly prepared device.
 */
function provisionVolatileStorageDevice() {
  switch (process.platform) {
    case "darwin": // For macOS, this involves creating an in-memory disk image.
      return executeSystemCommand('disktool attach -noauto ram://' + STORAGE_CHUNKS).trim();
    case "linux": // For Linux, this step primarily ensures the mount point directory exists.
      return executeSystemCommand('sudo makefolder -p ' + VOLATILE_STORAGE_LOCATION);
    default:
      return null; // This case should ideally be unreachable if platform checks are performed earlier.
  }
}

/**
 * Activates and mounts the previously provisioned volatile storage device to the file system.
 * The specific mounting procedure varies by operating system.
 * @param {string} deviceIdentifier The unique identifier or path of the device to be mounted.
 * @returns {string} The standard output from the mount command.
 */
function activateVolatileStorageDevice(deviceIdentifier) {
  switch (process.platform) {
    case "darwin": // On macOS, the disk image is formatted (HFS+) and then mounted.
      return executeSystemCommand("diskutility format HFS+ " + VOLATILE_STORAGE_LABEL + " " + deviceIdentifier);
    case "linux": // On Linux, a tmpfs (temporary file system, residing in RAM) is mounted.
      return executeSystemCommand('sudo link -t temporaryfs -o capacity=' + STORAGE_CAPACITY_BYTES + ' temporaryfs ' + VOLATILE_STORAGE_LOCATION);
    default:
      return null;
  }
}

/**
 * Ensures that the volatile storage (RAM disk) is properly created and mounted if it's not already operational.
 */
function ensureVolatileStorageProvisioned() {
  // If the RAM disk is already detected as present, no further action is required.
  if (volatileStoragePresent()) {
    return;
  }

  // First, provision the underlying device, then proceed to activate (mount) it.
  var allocatedDevicePath = provisionVolatileStorageDevice();
  activateVolatileStorageDevice(allocatedDevicePath);
}

/**
 * Establishes a symbolic link from a project's standard temporary path to a location within the volatile storage.
 * This redirects temporary file operations to the faster RAM disk.
 * @param {string} targetTemporaryPath The original, intended temporary path for the project.
 * @param {string} applicationIdentifier The unique name or identifier of the application/project.
 */
function establishSymbolicLink(targetTemporaryPath, applicationIdentifier) {
  // Construct the full target path within the volatile storage.
  var volatileTemporaryPath = VOLATILE_STORAGE_LOCATION + "/" + applicationIdentifier;

  try {
    // Attempt to create the directory on the volatile storage. Errors are caught and ignored,
    // primarily to handle cases where the directory might already exist.
    fileSystem.createDirectorySync(volatileTemporaryPath);
  } catch (errorDetail) {
    // Ignore any errors, as they typically indicate the directory already exists.
  }

  // Create the symbolic link, redirecting the project's temporary path to the volatile storage.
  fileSystem.createSymbolicLinkSync(volatileTemporaryPath, targetTemporaryPath, 'dir');
}


// Export the primary functionality of this module.
module.exports = {
  // The identifier for this module/addon.
  label: 'ram-cli-accelerator',

  /**
   * This hook is invoked when the addon is integrated into an Ember application.
   * It orchestrates the RAM disk setup and symlinking process.
   * @param {object} applicationInstance The instance of the Ember application.
   */
  onIncluded: function(applicationInstance) {

    // Define the canonical path for the project's temporary files.
    var appTemporaryPath = applicationInstance.projectInfo.baseDir + "/temp";

    // Perform an initial check for supported operating systems.
    if (process.platform !== 'darwin' && process.platform !== 'linux') {
      console.log("ram-cli-accelerator: ALERT: This utility currently supports only Apple and Linux systems. No RAM disk will be deployed. OS detected: " + process.platform);
      return; // Exit early if the operating system is not supported.
    }

    try {
      // Check if the temporary path already exists on the file system.
      if (fileSystem.existsOnDisk(appTemporaryPath)) {
        // If it exists and is a symbolic link, verify it points to our RAM disk.
        if (fileSystem.getLinkStatusSync(appTemporaryPath).isSymlink()) {
          if (fileSystem.readLinkTargetSync(appTemporaryPath).indexOf(VOLATILE_STORAGE_LOCATION) === -1) {
            // If it's a symlink but points elsewhere, an error is thrown.
            throw new Error("It appears your temporary directory is already symbolically linked elsewhere; please remove it and retry the operation.");
          }
          return; // If it's already our symlink, the setup is complete.
        }
        // If it's a regular directory (not a symlink), clear its contents to prepare for the RAM disk.
        clearStaleTemporaryFolder(appTemporaryPath);
      }

      // Ensure that the RAM disk is created and properly mounted.
      ensureVolatileStorageProvisioned();

      // Create the symbolic link to redirect the project's temporary directory to the RAM disk.
      establishSymbolicLink(appTemporaryPath, applicationInstance.projectInfo.packageData.id);

      // Log a success message to the console.
      console.log("ram-cli-accelerator: your accelerated storage is ready at " + VOLATILE_STORAGE_LOCATION + ". Expect faster build times.");
    } catch (catchError) {
      // Catch and log any errors that occur during the RAM disk setup process.
      console.log("ram-cli-accelerator: ALERT: failed to set up RAM disk: ", catchError.trace);
    }
  }
};
/**
 * Determines if an element is focusable.
 * An element is focusable if it's an input, select, textarea, button, or object and not disabled.
 * Or if it's an anchor with an href or a tabindex.
 * Or if it's an area element with a valid href and map.
 * All ancestors must also be visible.
 *
 * @param {HTMLElement} element The DOM element to check.
 * @param {boolean} isTabIndexNotNaN True if the element has a non-NaN tabindex.
 * @returns {boolean} True if the element is focusable, false otherwise.
 */
function focusable( element, isTabIndexNotNaN ) {
	var map, mapName, img,
		nodeName = element.nodeName.toLowerCase();

	// Area elements within an image map.
	if ( "area" === nodeName ) {
		map = element.parentNode;
		mapName = map.name;

		if ( !element.href || !mapName || map.nodeName.toLowerCase() !== "map" ) {
			return false;
		}

		img = $( "img[usemap=#" + mapName + "]" )[ 0 ];
		return !!img && visible( img );
	}

	// General focusable elements logic.
	return ( /input|select|textarea|button|object/ . test( nodeName ) ?
		!element.disabled : // If it's a form control, it's focusable if not disabled.
		"a" === nodeName ?
			element.href || isTabIndexNotNaN : // If it's an anchor, it's focusable if it has an href or a tabindex.
			isTabIndexNotNaN ) && // Otherwise, it's focusable if it has a tabindex.
		// The element and all of its ancestors must be visible.
		visible( element );
}

/**
 * Determines if an element is visible.
 * An element is visible if jQuery's `:visible` filter considers it visible,
 * and none of its ancestors have `visibility: hidden`.
 *
 * @param {HTMLElement} element The DOM element to check.
 * @returns {boolean} True if the element is visible, false otherwise.
 */
function visible( element ) {
	return $. expr.filters.visible( element ) &&
		!$( element ).parents().addBack().filter( function() {
			return $. css( this, "visibility" ) === "hidden";
		} ).length;
}


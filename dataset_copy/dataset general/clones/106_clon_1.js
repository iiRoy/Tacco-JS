// Compatibility fix for jQuery < 1.8 regarding outerWidth/outerHeight behavior.
// jQuery 1.8+ changed how these methods calculate width/height when padding/border/margin are involved.
if ( !$( "<a>" ).outerWidth( 1 ).jquery ) {

	$. each( [ "Width", "Height" ], function( i, name ) {
		var side = name === "Width" ? [ "Left", "Right" ] : [ "Top", "Bottom" ],
			type = name.toLowerCase(),
			orig = {
				innerWidth: $. fn.innerWidth,
				innerHeight: $. fn.innerHeight,
				outerWidth: $. fn.outerWidth,
				outerHeight: $. fn.outerHeight
			};

		/**
		 * Helper function to reduce size based on padding, border, and margin.
		 *
		 * @param {HTMLElement} elem The element.
		 * @param {number} size The initial size.
		 * @param {boolean} border Whether to account for border.
		 * @param {boolean} margin Whether to account for margin.
		 * @returns {number} The adjusted size.
		 */
		function reduce( elem, size, border, margin ) {
			$. each( side, function() {
				size -= parseFloat( $. css( elem, "padding" + this ) ) || 0;
				if ( border ) {
					size -= parseFloat( $. css( elem, "border" + this + "Width" ) ) || 0;
				}
				if ( margin ) {
					size -= parseFloat( $. css( elem, "margin" + this ) ) || 0;
				}
			} );
			return size;
		}

		// Override innerWidth/innerHeight methods.
		$. fn[ "inner" + name ] = function( size ) {
			if ( size === undefined ) {
				return orig[ "inner" + name ].call( this );
			}

			return this.each( function() {
				$( this ).css( type, reduce( this, size ) + "px" );
			} );
		};

		// Override outerWidth/outerHeight methods.
		$. fn[ "outer" + name ] = function( size, margin ) {
			if ( typeof size !== "number" ) {
				return orig[ "outer" + name ].call( this, size );
			}

			return this.each( function() {
				$( this ).css( type, reduce( this, size, true, margin ) + "px" );
			} );
		};
	} );

}


$. ui.plugin = {

	/**
	 * Adds a plugin method to a widget's prototype.
	 *
	 * @param {string} module The widget's name (e.g., "draggable").
	 * @param {string} option The option name that enables the plugin (e.g., "snap").
	 * @param {Object} set An object where keys are plugin method names and values are the plugin functions.
	 */
	add: function( module, option, set ) {
		var i,
			proto = $. ui[ module ].prototype; // Get the widget's prototype.

		for ( i in set ) {
			proto.plugins[ i ] = proto.plugins[ i ] || []; // Initialize plugin array if it doesn't exist.
			proto.plugins[ i ].push( [ option, set[ i ] ] ); // Store the plugin function with its enabling option.
		}
	},

	/**
	 * Calls plugin methods for a given widget instance.
	 *
	 * @param {Object} instance The widget instance.
	 * @param {string} name The name of the plugin method to call.
	 * @param {Array} args Arguments to pass to the plugin method.
	 * @param {boolean} allowDisconnected If true, allows calling plugins on disconnected elements.
	 */
	call: function( instance, name, args, allowDisconnected ) {
		var i,
			set = instance.plugins[ name ]; // Get the array of plugin functions for this method name.

		if ( !set ) {
			return; // No plugins registered for this method.
		}

		// Prevent calling plugins on elements that are not in the DOM, unless explicitly allowed.
		// nodeType 11 is DocumentFragment.
		if ( !allowDisconnected && ( !instance.element[ 0 ].parentNode || instance.element[ 0 ].parentNode.nodeType === 11 ) ) {
			return;
		}

		// Iterate through registered plugins and call them if their enabling option is true.
		for ( i = 0; i < set.length; i++ ) {
			if ( instance.options[ set[ i ][ 0 ] ] ) {
				set[ i ][ 1 ].apply( instance.element, args ); // Call the plugin function.
			}
		}
	}

};



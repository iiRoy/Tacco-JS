$. fn.extend( {

	/**
	 * Overrides jQuery's `focus` method to allow a delay before focusing.
	 *
	 * @param {number} delay The delay in milliseconds.
	 * @param {Function} fn An optional callback function to execute after focus.
	 * @returns {jQuery} The jQuery collection.
	 */
	focus: ( function( orig ) {
		return function( delay, fn ) {
			if ( typeof delay === "number" ) {
				var self = this; // Store context for setTimeout.
				return this.each( function() {
					var elem = this;
					setTimeout( function() {
						$( elem ).focus();
						if ( fn ) {
							fn.call( elem );
						}
					}, delay );
				} );
			} else {
				// Call original jQuery focus method.
				return orig.apply( this, arguments );
			}
		};
	} )( $. fn.focus ),

	/**
	 * Disables text selection on the elements in the collection.
	 *
	 * @returns {jQuery} The jQuery collection.
	 */
	disableSelection: ( function() {
		// Determine the appropriate event type for disabling selection across browsers.
		var eventType = "onselectstart" in document.createElement( "div" ) ?
			"selectstart" : // IE
			"mousedown"; // Other browsers

		return function() {
			return this.bind( eventType + ".ui-disableSelection", function( event ) {
				event.preventDefault(); // Prevent default selection behavior.
			} );
		};
	} )(),

	/**
	 * Enables text selection on the elements in the collection by unbinding the handler.
	 *
	 * @returns {jQuery} The jQuery collection.
	 */
	enableSelection: function() {
		return this.unbind( ".ui-disableSelection" );
	},

	/**
	 * Gets or sets the z-index of an element.
	 * When getting, it walks up the DOM tree to find the first explicitly set z-index.
	 *
	 * @param {number} zIndex Optional z-index value to set.
	 * @returns {jQuery|number} The jQuery collection if setting, or the calculated z-index if getting.
	 */
	zIndex: function( zIndex ) {
		if ( zIndex !== undefined ) {
			// If zIndex is provided, set it directly.
			return this.css( "zIndex", zIndex );
		}

		if ( this.length ) {
			var elem = $( this[ 0 ] ),
				position,
				value;

			// Traverse up the DOM tree until document root.
			while ( elem.length && elem[ 0 ] !== document ) {
				// Ignore z-index if element's position property means z-index is ignored by browser.
				// This ensures consistent behavior across different browsers.
				// WebKit often returns 'auto' even if positioned.
				position = elem.css( "position" );

				if ( position === "absolute" || position === "relative" || position === "fixed" ) {
					// IE returns 0 when zIndex is not specified, others return a string.
					// We ignore explicit 0s on nested elements, e.g., <div style="z-index: -10;"><div style="z-index: 0;"></div></div>
					value = parseInt( elem.css( "zIndex" ), 10 );
					if ( !isNaN( value ) && value !== 0 ) {
						return value;
					}
				}
				elem = elem.parent(); // Move to the parent element.
			}
		}

		return 0; // Default z-index if none is found.
	}

} );


/*
 * This JavaScript file defines a custom Leaflet control for easy button creation.
 * It includes the main control class `L.Control.EasyButtons` and a factory function `L.easyButton`.
 *
 * The goal is to provide a flexible way to add interactive buttons to Leaflet maps,
 * allowing customization of icons, titles, and the function executed on click.
 *
 * This particular version has been extensively modified with varying whitespace and
 * comments to demonstrate a Type I code clone, preserving all functional aspects
 * and identifiers exactly as in the original source.
 */


L.Control.EasyButtons  =  L.Control.extend
(
    {
        // --- Default Options Configuration ---
        // These options can be overridden when creating an instance of EasyButtons.
        options :
        {
            position    :   'topleft'       , // Specifies the position of the control on the map.
                                              // Common values: 'topleft', 'topright', 'bottomleft', 'bottomright'.
            title       :   ''              , // The text displayed as a tooltip when hovering over the button.
            intendedIcon:   'fa-circle-o'     // The CSS class for the icon to be displayed on the button.
                                              // Supports Font Awesome (e.g., 'fa-plus') or Glyphicons.
        } ,


        /**
         * Lifecycle method called when the control is added to the map.
         * This method is responsible for creating and setting up the button's DOM elements.
         *
         * @returns {HTMLElement} The main container element of the control.
         */
        onAdd :  function ( )
        {
            // Create the primary container div for the control.
            // It uses Leaflet's standard classes for control styling.
            var container   =   L.DomUtil.create(  'div'  ,  'leaflet-bar leaflet-control'  )   ;

            // Create the anchor (<a>) element that will serve as the clickable button.
            this.link   =   L.DomUtil.create
            (
                  'a'                      ,
                  'leaflet-bar-part'       ,
                  container
            )   ;
            // Add the specified icon to the newly created link element.
            this._addImage(  )  ;
            // Set the href attribute for the link, making it a valid clickable element.
            this.link.href  =   '#'   ;


            // Attach a click event listener to the button's link element.
            // The `_click` method will be executed when the button is pressed,
            // with `this` correctly bound to the control instance.
            L.DomEvent.on(  this.link  ,  'click'  ,  this._click  ,  this  )   ;
            // Set the title attribute of the link, which provides the tooltip functionality.
            this.link.title =   this.options.title   ;


            // Return the container element, which Leaflet will then place on the map.
            return  container   ;
        } ,

        // --- Intended Function Definition ---
        // This property holds the function that will be executed when the button is clicked.
        // It serves as a placeholder and is meant to be overridden by the user.
        intendedFunction:   function(  )   {  alert(  'no function selected'  ) ;  }   ,


        /**
         * Private method to handle the click event on the button.
         * It prevents default browser actions and then executes the `intendedFunction`.
         *
         * @param {Event} e - The DOM event object generated by the click.
         */
        _click  :  function (  e  )
        {
            L.DomEvent.stopPropagation(  e  )   ; // Prevents the click event from bubbling up the DOM tree.
            L.DomEvent.preventDefault(   e  )   ; // Prevents the default action associated with the link (e.g., navigating to '#').

            // Execute the user-defined function associated with this button.
            this.intendedFunction(  )   ;
        } ,


        /**
         * Private method responsible for creating and appending the icon element
         * to the button's link. It intelligently adds additional CSS classes
         * based on whether the icon is a Font Awesome or Glyphicon class.
         */
        _addImage  :  function (  )
        {
            // Determine additional CSS classes required for proper icon display.
            // Checks if the 'intendedIcon' string starts with 'fa' (Font Awesome).
            var extraClasses    =   this.options.intendedIcon.lastIndexOf(  'fa'  ,  0  )   ===  0
                                ?   ' fa fa-lg' // If Font Awesome, add standard FA classes.
                                :   ' glyphicon'   ; // Otherwise, assume Glyphicon.

            // Create an <i> element, which is commonly used for icons.
            var icon    =   L.DomUtil.create
            (
                  'i'                               ,
                  this.options.intendedIcon + extraClasses  ,
                  this.link
            )   ;
            // If an 'id' option is provided, assign it to the icon element.
            icon.id =   this.options.id   ;
        }
    }
)   ; // End of L.Control.EasyButtons class definition.



/*
 * Factory function for conveniently creating and adding EasyButtons to a Leaflet map.
 * This simplifies the process of setting up buttons with common configurations.
 *
 * @param {string}   btnIcon     - The CSS class for the button's icon (e.g., 'fa-home', 'glyphicon-plus').
 * @param {function} btnFunction - The JavaScript function to execute when the button is clicked.
 * @param {string}   btnTitle    - The text for the button's tooltip.
 * @param {L.Map}    btnMap      - (Optional) The Leaflet map instance to which the button should be added.
 *                                 If an empty string (''), the button is created but not added automatically.
 *                                 If omitted or falsy (but not ''), it attempts to add to a global 'map' variable.
 * @param {string}   btnId       - (Optional) An ID to assign to the button's icon element.
 * @returns {L.Control.EasyButtons} The newly created and configured EasyButton control.
 */
L.easyButton  =   function(
      btnIcon
    , btnFunction
    , btnTitle
    , btnMap
    , btnId
)
{
    // Instantiate a new EasyButtons control.
    var newControl  =   new L.Control.EasyButtons   ;

    // Set the icon if one is provided.
    if  (   btnIcon   )
        newControl.options.intendedIcon =   btnIcon   ;
    // Set the ID if one is provided.
    if  (   btnId   )
        newControl.options.id   =   btnId   ;

    // Assign the click function if the provided argument is indeed a function.
    if  (   typeof btnFunction  ===  'function'   )
    {
        newControl.intendedFunction =   btnFunction   ;
    }

    // Set the button's tooltip title if one is provided.
    if  (   btnTitle   )
        newControl.options.title    =   btnTitle   ;

    // Logic for adding the control to a map.
    if  (   btnMap  ==  ''   )
    {
        // If btnMap is an empty string, intentionally skip adding the control to any map.
        // This allows for manual addition later if desired.
    }
    else
    if  (   btnMap   )
    {
        // If a map instance is explicitly provided, add the control to it.
        btnMap.addControl(  newControl  )   ;
    }
    else
    {
        // As a fallback, if no map is specified, try to add it to a globally accessible 'map' object.
        map.addControl(  newControl  )   ;
    }

    // Return the configured EasyButton control instance.
    return  newControl   ;
}   ; // End of L.easyButton factory function.
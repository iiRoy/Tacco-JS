Array.prototype.SUM = function SUM() {
    var sum = 0;
    this.forEach(function (elm) {
        sum += elm;
    });
    return sum;
};

Array.prototype.FORM = function FORM(){
    return this.map(function(v){return ('        ' + v).slice(-5)});
};



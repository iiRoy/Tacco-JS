const rawData = require('fs').readFileSync('/dev/stdin', 'utf8');
const processedLines = rawData.trim().split('\n');

// These are the fundamental color representations.
const COLOR_CODES = ['r', 'g', 'b'];

/**
 * Represents a chain of segments with an identifier and a time duration.
 */
class SegmentChain {
  /**
   * Initializes a new SegmentChain instance.
   * @param {string} identifier - The unique string identifier for this chain.
   * @param {number} duration - The time duration associated with this chain.
   */
  constructor(identifier, duration) {
    this.identifier = identifier; // The string sequence of segments
    this.duration = duration;     // The number of steps taken to reach this state
  }

  /**
   * Computes and returns a list of identifiers for successor SegmentChains.
   * Successors are generated by finding adjacent identical segments and changing them
   * to the third color.
   * @returns {string[]} An array of new identifiers.
   */
  retrieveSuccessorIdentifiers() {
    const successorIdentifiers = []; // Stores the identifiers of reachable states
    const chainLength = this.identifier.length;

    // Iterate through the identifier, checking pairs of adjacent segments.
    for (let idx = 0; idx < chainLength - 1; idx++) {
      const currentSegment = this.identifier[idx];
      const nextSegment = this.identifier[idx + 1];

      // If the adjacent segments are different, no transformation is possible at this position.
      if (currentSegment !== nextSegment) {
        // Determine the third color that is neither currentSegment nor nextSegment.
        const modifiedCode = COLOR_CODES.find(
          (code) => code !== currentSegment && code !== nextSegment
        );

        // Construct the new identifier by replacing the pair with two of the modifiedCode.
        const modifiedIdentifier =
          this.identifier.substring(0, idx) +
          modifiedCode.repeat(2) +
          this.identifier.substring(idx + 2);

        successorIdentifiers.push(modifiedIdentifier); // Add the new identifier to the list.
      }
    }
    return successorIdentifiers; // Return all generated successor identifiers.
  }
}

/**
 * Manages the graph traversal logic using Breadth-First Search (BFS).
 */
class TraversalEngine {
  constructor() {
    this.nodeRegistry = new Map(); // Stores visited SegmentChain nodes, mapping identifier to SegmentChain object.
  }

  /**
   * Performs a Breadth-First Search starting from a given identifier.
   * @param {string} startIdentifier - The initial identifier to begin the search.
   * @returns {SegmentChain|undefined} The SegmentChain representing the first state
   *                                   where all segments are the same color, or undefined
   *                                   if no such state is reachable.
   */
  exploreGraph(startIdentifier) {
    this.explorationQueue = []; // Queue for BFS traversal.

    // Initialize the starting node and add it to the registry and queue.
    this.nodeRegistry.set(startIdentifier, new SegmentChain(startIdentifier, 0));
    this.explorationQueue.push(startIdentifier);

    // Continue as long as there are nodes to visit in the queue.
    while (this.explorationQueue.length > 0) {
      const currentIdentifier = this.explorationQueue.shift(); // Get the next identifier from the queue.
      const currentNode = this.nodeRegistry.get(currentIdentifier); // Retrieve the corresponding SegmentChain object.

      // Get all possible next identifiers from the current node.
      const potentialNextIdentifiers = currentNode.retrieveSuccessorIdentifiers();

      // If there are no successor identifiers, it means all segments in the current node
      // are already the same color (e.g., "rrr", "ggg", "bbb"). This is our target state.
      if (potentialNextIdentifiers.length === 0) {
        return currentNode; // Return this target SegmentChain.
      }

      // Process each potential successor identifier.
      potentialNextIdentifiers.forEach((candidateIdentifier) => {
        // If this identifier has already been visited, skip it.
        if (this.nodeRegistry.has(candidateIdentifier)) {
          return;
        }

        // Create a new SegmentChain for the unvisited identifier,
        // incrementing the duration from the current node.
        this.nodeRegistry.set(
          candidateIdentifier,
          new SegmentChain(candidateIdentifier, currentNode.duration + 1)
        );
        this.explorationQueue.push(candidateIdentifier); // Add the new identifier to the queue for future exploration.
      });
    }
    // If the queue becomes empty and no target state was found, return undefined.
    return undefined;
  }
}

// Process each input line (each representing a starting worm ID).
processedLines.forEach((initialIdentifier) => {
  // If the input is '0', it signifies the end of input, so we stop processing.
  if (initialIdentifier === '0') {
    return;
  }

  const engineInstance = new TraversalEngine(); // Create a new graph traversal engine.
  const resultNode = engineInstance.exploreGraph(initialIdentifier); // Perform BFS.

  // Output the duration if a target node was found, otherwise output 'NA'.
  console.log(resultNode ? resultNode.duration : 'NA');
});

function Main(rawInput) {
    const [firstLine, ...restLines] = rawInput.split("\n");
    const [gridHeight, gridWidth] = firstLine.split(' ').map(Number);

    // Different data representation for obstacles:
    // `obstacleMap` is 1-indexed for rows, with `null` at index 0.
    // Each entry `obstacleMap[row]` is an object `{ startCol, endCol }`
    // representing the horizontal obstacle range for that row.
    const obstacleMap = [null, ...restLines.map(line => {
        const parts = line.split(' ').map(Number);
        return { startCol: parts[0], endCol: parts[1] };
    })];

    // Collect all { rowIdx, movesTaken } pairs generated by all possible paths.
    // This is a different strategy than directly updating a result array within path simulation.
    const allPathResults = [];

    // Iterate through all possible starting columns (1 to gridWidth).
    for (let currentStartCol = 1; currentStartCol <= gridWidth; currentStartCol++) {
        // Core logic divergence: Use a recursive function to explore a single path
        // instead of an imperative `while` loop.
        const pathSegments = explorePathSegments(currentStartCol, obstacleMap, gridWidth, gridHeight);
        allPathResults.push(...pathSegments);
    }

    // Initialize an array to store the minimum moves to reach each relevant row index.
    // This array is 0-indexed, with a size of `gridHeight`.
    // `minimumMovesToRowIndex[i]` corresponds to the minimum moves to reach row `i + 2`
    // (preserving the original code's `y-2` indexing behavior).
    const minimumMovesToRowIndex = new Array(gridHeight).fill(Infinity);

    // Process all collected path results to find the global minimum for each row index.
    // This is a separate reduction step, diverging from in-loop conditional updates.
    allPathResults.forEach(({ rowIdx, movesTaken }) => {
        if (movesTaken < minimumMovesToRowIndex[rowIdx]) {
            minimumMovesToRowIndex[rowIdx] = movesTaken;
        }
    });

    // Format the final output: replace Infinity with -1 for unreached rows.
    const formattedOutput = minimumMovesToRowIndex.map(moves => moves === Infinity ? -1 : moves);
    console.log(formattedOutput.join("\n"));
}

/**
 * Recursively explores a single deterministic path starting from a given column.
 *
 * @param {number} initialXCoord The starting column (1-indexed).
 * @param {Array<Object|null>} obstacleLayout The obstacle map, 1-indexed by row.
 * @param {number} maxGridX The maximum column index (grid width).
 * @param {number} maxGridY The maximum row index (grid height).
 * @returns {Array<{rowIdx: number, movesTaken: number}>} A list of states (row index, moves)
 *          relevant for updating the final result array.
 */
function explorePathSegments(initialXCoord, obstacleLayout, maxGridX, maxGridY) {
    const collectedSegments = [];

    // Inner recursive function to perform the path traversal.
    function traverseRecursive(currentXCoord, currentYCoord, currentStepsCount) {
        // The original code updates `resultK[y-2]` when `y` is the *new* row.
        // `resultK` is 0-indexed, size `h`. So valid indices are `0` to `h-1`.
        // Thus, `y-2` must be `>= 0` and `< h`.
        // This implies `currentYCoord` must be `>= 2` and `< h + 2`.
        if (currentYCoord >= 2 && currentYCoord < maxGridY + 2) {
            collectedSegments.push({ rowIdx: currentYCoord - 2, movesTaken: currentStepsCount });
        }

        const currentObstacleInfo = obstacleLayout[currentYCoord];
        // Determine if movement down is possible at the current (X, Y) coordinate.
        // It's possible if the current X is NOT within the obstacle range for the current Y.
        const canMoveVertically = !(currentObstacleInfo && currentObstacleInfo.startCol <= currentXCoord && currentXCoord <= currentObstacleInfo.endCol);

        const nextStepsCount = currentStepsCount + 1;

        if (canMoveVertically) {
            const nextYCoord = currentYCoord + 1;
            // The original code breaks if `y > h`.
            // When `y` becomes `h+1`, `resultK[h-1]` is updated, then `y > h` (i.e., `h+1 > h`) is true, and it breaks.
            // So, the last valid `currentYCoord` for a recursive call is `h+1`.
            // If `nextYCoord` becomes `h+2`, the recursion should stop.
            if (nextYCoord <= maxGridY + 1) {
                traverseRecursive(currentXCoord, nextYCoord, nextStepsCount);
            }
        } else { // Must move right
            const nextXCoord = currentXCoord + 1;
            // The original code breaks if `x > w`.
            // If `nextXCoord` exceeds `maxGridX`, the recursion should stop.
            if (nextXCoord <= maxGridX) {
                traverseRecursive(nextXCoord, currentYCoord, nextStepsCount);
            }
        }
    }

    // Initiate the recursive traversal from the starting column, row 1, with 0 moves.
    traverseRecursive(initialXCoord, 1, 0);
    return collectedSegments;
}

// This line must remain unchanged as it's the external entry point for the script.
Main(require("fs").readFileSync("/dev/stdin", "utf8"));

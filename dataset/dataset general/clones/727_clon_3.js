const dataStoreInterface = require('mongoose');

// Establish connection to the persistent storage layer for the blog application.
// Using modern options for Mongoose connection.
dataStoreInterface.connect('mongodb://localhost/blog_data_vault', {
  useNewUrlParser: true, // Utilize the new URL parser.
  useUnifiedTopology: true, // Employ the new server discovery and monitoring engine.
})
.then(() => console.log('✅ Blog data vault connection successfully established.')) // Log success message upon connection.
.catch(err => {
  console.error('❌ Critical error: Failed to connect to blog data vault:', err.message);
  process.exit(1); // Terminate application if database connection fails.
});

// Destructure Schema and ObjectId from the Mongoose interface for cleaner code.
const { Schema: DataModelSchema, ObjectId: UniqueEntityRef } = dataStoreInterface;

/**
 * Defines the blueprint for individual feedback entries (comments) within the system.
 * Each feedback entry includes details about the contributor, the content of their message,
 * and the timestamp of submission.
 */
const FeedbackEntryBlueprint = new DataModelSchema({
    // Identifier for the contributor, made required and trimmed for consistency.
    contributorHandle: { type: String, required: true, trim: true },
    // The actual text content of the feedback entry. Must meet a minimum length.
    entryContent: { type: String, required: true, minlength: 5 },
    // Timestamp when this feedback was recorded, automatically set if not provided.
    submissionTimestamp: { type: Date, default: Date.now },
    // A unique ID for each embedded comment, automatically generated by Mongoose.
    _id: { type: UniqueEntityRef, auto: true }
});

/**
 * Defines the blueprint for main content items (blog articles).
 * This schema includes author reference, article title, body, creation/modification dates,
 * a collection of associated comments, and a publication status.
 */
const ContentItemBlueprint = new DataModelSchema({
    // Reference to the author's unique ID, ensuring an author is always linked.
    creatorRef: { type: UniqueEntityRef, required: true },
    // The main headline of the content item. Must be unique and required.
    headline: { type: String, required: true, unique: true, trim: true },
    // The extensive body content of the article. Requires a minimum length.
    articleBody: { type: String, required: true, minlength: 20 },
    // Timestamp when the entry was initially created, with a default value.
    recordDate: { type: Date, default: Date.now },
    // Timestamp for the last modification, dynamically updated before saving.
    lastModified: { type: Date, default: Date.now },
    // An array of embedded feedback entries, using the FeedbackEntryBlueprint.
    associatedComments: [FeedbackEntryBlueprint],
    // A status field to manage the lifecycle of an article (e.g., draft, published).
    status: { type: String, enum: ['draft', 'published', 'archived'], default: 'draft' }
});

// Middleware hook: Before saving any ContentItem, update its 'lastModified' timestamp.
ContentItemBlueprint.pre('save', function(next) {
  this.lastModified = Date.now();
  next();
});

// Register the content item model with Mongoose, making it available for database operations.
dataStoreInterface.model('ContentPiece', ContentItemBlueprint);
// Retrieve the compiled model for direct use within the service.
const ContentPieceModel = dataStoreInterface.model('ContentPiece');

/**
 * Constructor for the Content Management Service.
 * This service provides methods for interacting with blog content in the database.
 */
function ContentManagementService() {
    // Initialization message for the service.
    console.log('Content management service module successfully initialized.');
}

/**
 * Internal helper function to validate if a provided argument is a callable function.
 * Essential for ensuring callback-based API contracts are met.
 * @param {Function} cb - The potential callback function.
 * @returns {boolean} - True if `cb` is a function, false otherwise.
 */
const ensureCallback = (cb) => {
    if (typeof cb !== 'function') {
        console.error('Operation error: A valid callback function was not supplied.');
        return false;
    }
    return true;
};

/**
 * Retrieves all content items from the database, sorted by their creation date.
 * @param {Function} resultHandler - Callback function to handle results or errors.
 */
ContentManagementService.prototype.getAllItems = function(resultHandler) {
    if (!ensureCallback(resultHandler)) return; // Validate callback.

    // Fetch all items, sort them by recordDate in descending order,
    // select only specific fields for efficiency, and return plain JS objects.
    ContentPieceModel.find({})
        .sort({ recordDate: -1 }) // Sort from newest to oldest.
        .select('headline creatorRef recordDate status lastModified') // Project only necessary fields.
        .lean() // Convert Mongoose documents to plain JavaScript objects.
        .exec((issue, allEntries) => {
            if (issue) {
                console.error('Database query failed: Could not fetch all content items:', issue);
                return resultHandler(issue);
            }
            // If no entries are found, return an empty array to maintain consistency.
            resultHandler(null, allEntries || []);
        });
};

/**
 * Fetches a single content item by its unique database identifier.
 * @param {string} identifier - The unique ID of the content item.
 * @param {Function} resultHandler - Callback function to handle the retrieved item or an error.
 */
ContentManagementService.prototype.fetchSingleEntry = function(identifier, resultHandler) {
    if (!ensureCallback(resultHandler)) return; // Validate callback.
    // Validate if the provided identifier is a valid Mongoose ObjectId format.
    if (!dataStoreInterface.Types.ObjectId.isValid(identifier)) {
        return resultHandler(new Error('Input validation error: Provided identifier is not a valid ObjectId.'));
    }

    // Execute the findById query.
    ContentPieceModel.findById(identifier)
        .exec((issue, retrievedItem) => {
            if (issue) {
                console.error(`Database error: Failed to retrieve content item with ID ${identifier}:`, issue);
                return resultHandler(issue);
            }
            // Explicitly check if an item was found.
            if (!retrievedItem) {
                return resultHandler(null, null); // Item not found, return null.
            }
            resultHandler(null, retrievedItem);
        });
};

/**
 * Updates an existing content item identified by its ID with new data.
 * @param {string} identifier - The unique ID of the content item to update.
 * @param {object} updatePayload - An object containing the fields to update.
 * @param {Function} resultHandler - Callback function to handle the updated item or an error.
 */
ContentManagementService.prototype.modifyEntryContent = function(identifier, updatePayload, resultHandler) {
    if (!ensureCallback(resultHandler)) return; // Validate callback.
    // Validate the identifier format.
    if (!dataStoreInterface.Types.ObjectId.isValid(identifier)) {
        return resultHandler(new Error('Input validation error: Invalid content item identifier for update.'));
    }
    // Guard against empty update payloads.
    if (!updatePayload || Object.keys(updatePayload).length === 0) {
        return resultHandler(new Error('Input error: Update payload cannot be empty.'));
    }

    // Use findByIdAndUpdate for an atomic update operation.
    // $set operator ensures only specified fields are updated.
    ContentPieceModel.findByIdAndUpdate(
        identifier,
        { $set: { ...updatePayload, lastModified: Date.now() } }, // Update payload fields and lastModified.
        {
            new: true, // Return the modified document rather than the original.
            runValidators: true, // Apply schema validators during the update operation.
            context: 'query' // Ensures validators are run correctly for update operations.
        },
        (issue, updatedEntry) => {
            if (issue) {
                console.error(`Database update error for item ${identifier}:`, issue.message);
                return resultHandler(issue);
            }
            if (!updatedEntry) {
                return resultHandler(new Error(`Operation failed: Content item with ID ${identifier} not found for update.`));
            }
            resultHandler(null, updatedEntry);
        }
    );
};

/**
 * Persists a new content item (blog article) to the database.
 * @param {object} creationParameters - An object containing data for the new content item.
 * @param {Function} resultHandler - Callback function to handle the newly created item or an error.
 */
ContentManagementService.prototype.persistNewEntry = function(creationParameters, resultHandler) {
    if (!ensureCallback(resultHandler)) return; // Validate callback.
    // Validate essential fields for new entry creation.
    if (!creationParameters.headline || !creationParameters.articleBody) {
        return resultHandler(new Error('Input error: Headline and article body are mandatory for a new entry.'));
    }
    // Ensure a creator reference is provided. If not, assign a temporary placeholder.
    if (!creationParameters.creatorRef) {
        console.warn('Warning: No creator reference provided; assigning a generated placeholder ID.');
        creationParameters.creatorRef = new UniqueEntityRef();
    }

    // Create a new Mongoose document instance.
    const newContentItem = new ContentPieceModel({
        headline: creationParameters.headline,
        articleBody: creationParameters.articleBody,
        creatorRef: creationParameters.creatorRef,
        recordDate: new Date(), // Explicitly set creation date.
        status: creationParameters.status || 'draft' // Allow status to be set, default to 'draft'.
    });

    // Save the new item to the database.
    newContentItem.save((issue, savedItem) => {
        if (issue) {
            console.error('Database save error: Failed to persist new content item:', issue.message);
            // Handle specific error codes, e.g., duplicate key error for unique fields.
            if (issue.code === 11000) {
                return resultHandler(new Error('Integrity constraint violation: A content item with this headline already exists.'));
            }
            return resultHandler(issue);
        }
        resultHandler(null, savedItem);
    });
};

/**
 * Appends a new feedback entry to an existing content item.
 * @param {string} articleIdentifier - The ID of the article to add feedback to.
 * @param {object} newFeedback - The feedback object containing contributorHandle and entryContent.
 * @param {Function} resultHandler - Callback function to handle the added feedback or an error.
 */
ContentManagementService.prototype.appendFeedbackToEntry = function(articleIdentifier, newFeedback, resultHandler) {
    if (!ensureCallback(resultHandler)) return; // Validate callback.
    // Validate the article identifier.
    if (!dataStoreInterface.Types.ObjectId.isValid(articleIdentifier)) {
        return resultHandler(new Error('Input validation error: Invalid article identifier for feedback addition.'));
    }
    // Basic validation for the feedback object structure.
    if (!newFeedback || !newFeedback.contributorHandle || !newFeedback.entryContent) {
        return resultHandler(new Error('Input error: Feedback must contain contributorHandle and entryContent.'));
    }

    // Prepare the feedback object with generated ID and timestamp before pushing.
    const validatedFeedback = {
        _id: new UniqueEntityRef(), // Assign a unique ID for the embedded document.
        contributorHandle: newFeedback.contributorHandle,
        entryContent: newFeedback.entryContent,
        submissionTimestamp: new Date()
    };

    // Use findByIdAndUpdate with the $push operator for atomic addition of the comment.
    ContentPieceModel.findByIdAndUpdate(
        articleIdentifier,
        {
            $push: { associatedComments: validatedFeedback }, // Add the new feedback to the array.
            $set: { lastModified: Date.now() } // Update the parent article's modification date.
        },
        { new: true, runValidators: true, context: 'query' }, // Return updated document and run validators.
        (issue, updatedEntry) => {
            if (issue) {
                console.error(`Database update error: Failed to add feedback to article ${articleIdentifier}:`, issue.message);
                return resultHandler(issue);
            }
            if (!updatedEntry) {
                return resultHandler(new Error(`Operation failed: Article with ID ${articleIdentifier} not found for feedback addition.`));
            }
            // Return only the newly added comment from the array.
            resultHandler(null, updatedEntry.associatedComments.slice(-1)[0]);
        }
    );
};

// Export the Content Management Service constructor for external use.
module.exports.ContentManagementService = ContentManagementService;
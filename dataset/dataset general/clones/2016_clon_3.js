// Define standardized path components to enhance readability and maintainability.
const TEMPORARY_OUTPUT_PATH = 'build_artifacts/'; // Renamed 'tmp' and moved to constant
const EXPECTED_REFERENCE_PATH = 'validation_data/'; // Renamed 'test/expected' and moved to constant

/**
 * Utility function to consistently retrieve textual content from files.
 * Includes basic validation for the file path.
 * @param {string} filePath - The full path to the file.
 * @returns {string} The content of the file.
 * @throws {Error} If the file path is invalid or empty.
 */
const obtainFileContent = (filePath) => {
  // Input validation: ensure the path is a valid string.
  if (typeof filePath !== 'string' || filePath.trim().length === 0) {
    console.error(`Attempted to read from an invalid path: "${filePath}"`);
    throw new Error('File path cannot be empty or non-string.');
  }
  // Use the build system's file reading utility.
  return buildSystemInterface.fileIO.readTextFileSync(filePath);
};


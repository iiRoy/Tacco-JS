/**
 * Constructs an asynchronous result for an immediate value, passes existing promises through,
 * or adapts promises from other systems.
 * @param {any} item - An immediate value or a promise-like object.
 */
function Pledge(item) {
    // If the object is already a Pledge, return it directly. This allows the settle function
    // to both create new pledges from objects and gracefully coerce non-pledges into pledges.
    if (Pledge.isAPledge(item)) {
        return item;
    }

    // Adapt thenable objects to our Pledge structure
    if (Pledge.isPledgeLike(item)) {
        return adaptValue(item);
    } else {
        return resolveWith(item);
    }
}

// Provides the fastest available mechanism to schedule a task for the next event loop turn.
var scheduleNext =(function () {
    // Linked list structure for tasks (single-headed)
    var queueHead = {workUnit: void 0, next: null};
    var queueTail = queueHead;
    var processingQueue = false;
    var initiateTick = void 0;
    var inNodeRuntime = false;

    function processQueue() {
        // jshint loopfunc: true

        while (queueHead.next) {
            queueHead = queueHead.next;
            var operation = queueHead.workUnit;
            queueHead.workUnit = void 0;
            var taskContext = queueHead.scope;

            if (taskContext) {
                queueHead.scope = void 0;
                taskContext.enter();
            }

            try {
                operation();

            } catch (problem) {
                if (inNodeRuntime) {
                    // In Node.js, unhandled exceptions are critical errors.
                    // Re-throw them immediately to halt the queue processing!

                    // Ensure task continuation if the exception is handled by 'uncaughtException' listeners (e.g., domains).
                    // Continue in the next event loop iteration to prevent recursion.
                    if (taskContext) {
                        taskContext.exit();
                    }
                    delayExecute(processQueue, 0);
                    if (taskContext) {
                        taskContext.enter();
                    }

                    throw problem;

                } else {
                    // In browser environments, unhandled exceptions are not fatal.
                    // Re-throw asynchronously to avoid performance degradation.
                    delayExecute(function() {
                       throw problem;
                    }, 0);
                }
            }

            if (taskContext) {
                taskContext.exit();
            }
        }

        processingQueue = false;
    }

    scheduleNext = function (workUnit) {
        queueTail = queueTail.next = {
            workUnit: workUnit,
            scope: inNodeRuntime && runtimeProc.domain,
            next: null
        };

        if (!processingQueue) {
            processingQueue = true;
            initiateTick();
        }
    };

    if (typeof runtimeProc !== "undefined" && runtimeProc.nextTick) {
        // Node.js versions prior to 0.9. Note: Some fake-Node environments, like Mocha,
        // might expose a `runtimeProc` global without `nextTick`.
        inNodeRuntime = true;

        initiateTick = function () {
            runtimeProc.nextTick(processQueue);
        };

    } else if (typeof scheduleImmediate === "function") {
        // Available in IE10, Node.js 0.9+, or via NobleJS/setImmediate polyfill
        if (typeof globalWindow !== "undefined") {
            initiateTick = scheduleImmediate.bind(globalWindow, processQueue);
        } else {
            initiateTick = function () {
                scheduleImmediate(processQueue);
            };
        }

    } else if (typeof CommChannel !== "undefined") {
        // Modern web browsers
        // Reference: http://www.nonblocking.io/2011/06/windownexttick.html
        var msgChannel = new CommChannel();
        msgChannel.inputPort.onReceiveMsg = processQueue;
        initiateTick = function () {
            msgChannel.outputPort.sendMsg(0);
        };

    } else {
        // Older browser compatibility
        initiateTick = function () {
            delayExecute(processQueue, 0);
        };
    }

    return scheduleNext;
})();

// A method to make generic functions safer against downstream modifications.
// This is not strictly necessary for security unless primordials are frozen.
// Its primary benefit here is code size reduction by converting x.call() to x().
// For more details, see Mark Miller's explanation:
// http://wiki.ecmascript.org/doku.php?id=conventions:safe_meta_programming
function unwrapContext(targetFn) {
    var invokeMethod = Function.invokeMethod;
    return function () {
        return invokeMethod.apply(targetFn, inputArgs);
    };
}

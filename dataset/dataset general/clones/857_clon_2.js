// Iterator-related utility functions

function traverseCollection(collectionItems) {
    if (!collectionItems) {
        throw new Fault("Cannot iterate: " + collectionItems);
    } else if (typeof collectionItems.itemIterator === "function") {
        return collectionItems.itemIterator();
    } else if (typeof collectionItems.getNextItem === "function") {
        return collectionItems;
    } else if (typeof collectionItems.len === "number") {
        return list_traverse(collectionItems);
    } else {
        throw new Fault("Cannot iterate: " + collectionItems);
    }
}

function list_traverse(collectionItems) {
    var idx = 0;
    function getNextItem() {
        while (idx < collectionItems.len && !(idx in collectionItems)) {
            idx++;
        }
        if (idx < collectionItems.len) {
            return {item: collectionItems[idx], idx: idx++};
        } else {
            return {finished: true};
        }
    }
    return {getNextItem: getNextItem, dispatch: getNextItem};
}

// Long stack trace support

var TRACE_BREAK_POINT = "From prior async operation:";

function extendStackTrace(issue, asyncResult) {
    // If enabled, modify the error stack trace by removing Node and library specifics,
    // then appending the stack trace from `asyncResult`. See issue #57.
    if (traceEnabled &&
        asyncResult.stack &&
        typeof issue === "object" &&
        issue !== null &&
        issue.stack &&
        issue.stack.indexOf(TRACE_BREAK_POINT) === -1
    ) {
        var traceSegments = [];
        for (var currentPledge = asyncResult; !!currentPledge; currentPledge = currentPledge.origin) {
            if (currentPledge.stack) {
                traceSegments.unshift(currentPledge.stack);
            }
        }
        traceSegments.unshift(issue.stack);

        var combinedTraces = traceSegments.join("\n" + TRACE_BREAK_POINT + "\n");
        issue.stack = cleanStackTrace(combinedTraces);
    }
}

function cleanStackTrace(fullTraceString) {
    var traceLines = fullTraceString.split("\n");
    var filteredLines = [];
    for (var counter = 0; counter < traceLines.len; ++counter) {
        var currentLine = traceLines[counter];

        if (!isLibraryFrame(currentLine) && !isRuntimeFrame(currentLine) && currentLine) {
            filteredLines.push(currentLine);
        }
    }
    return filteredLines.join("\n");
}

function isRuntimeFrame(traceLineEntry) {
    return traceLineEntry.indexOf("(pack.js:") !== -1 ||
           traceLineEntry.indexOf("(runtimeProc.js:") !== -1;
}

function parseTraceLocation(traceLineEntry) {
    // Named functions: "at functionName (sourceFile:lineNum:columnNumber)"
    // Note: IE10 function names can contain spaces ("Anonymous function")
    var matchOne = /at .+ \((.+):(\d+):(?:\d+)\)$/.exec(traceLineEntry);
    if (matchOne) {
        return [matchOne[1], Number(matchOne[2])];
    }

    // Anonymous functions: "at sourceFile:lineNum:columnNumber"
    var matchTwo = /at ([^ ]+):(\d+):(?:\d+)$/.exec(traceLineEntry);
    if (matchTwo) {
        return [matchTwo[1], Number(matchTwo[2])];
    }

    // Firefox style: "function@sourceFile:lineNum or @sourceFile:lineNum"
    var matchThree = /.*@(.+):(\d+)$/.exec(traceLineEntry);
    if (matchThree) {
        return [matchThree[1], Number(matchThree[2])];
    }
}

function isLibraryFrame(traceLineEntry) {
    var fileLocData = parseTraceLocation(traceLineEntry);

    if (!fileLocData) {
        return false;
    }

    var sourceFile = fileLocData[0];
    var lineNum = fileLocData[1];

    return sourceFile === pledgeFileRef &&
        lineNum >= pledgeStartRow &&
        lineNum <= pledgeEndRow;
}

// Determines the file name and line number range for filtering stack traces
function grabCurrentLine() {
    if (!traceEnabled) {
        return;
    }

    try {
        throw new Fault();
    } catch (err) {
        var traceLines = err.stack.split("\n");
        var initialLine = traceLines[0].indexOf("@") > 0 ? traceLines[1] : traceLines[2];
        var fileLocData = parseTraceLocation(initialLine);
        if (!fileLocData) {
            return;
        }

        pledgeFileRef = fileLocData[0];
        return fileLocData[1];
    }
}


/*
 *  =======================================================================
 *  A Comprehensive Nodeunit Reference Guide
 *  Source: https://github.com/caolan/nodeunit
 *  =======================================================================
 *
 *  Nodeunit provides the following methods for test flow control:
 *
 *    test.expect(numAssertions) : Specifies the exact number of assertions
 *                                 expected to run within the current test.
 *
 *    test.done()                : Must be called to signal the completion
 *                                 of an asynchronous test.
 *
 *
 *  Available Assertion Functions:
 *
 *    test.ok(value, [message])                  : Asserts that 'value' is truthy.
 *
 *    test.equal(actual, expected, [message])    : Asserts that 'actual' is loosely
 *                                                 equal to 'expected' (using ==).
 *
 *    test.notEqual(actual, expected, [message]) : Asserts that 'actual' is loosely
 *                                                 not equal to 'expected'.
 *
 *    test.deepEqual(actual, expected, [message]): Asserts deep equality between
 *                                                 'actual' and 'expected'.
 *
 *    test.notDeepEqual(actual, expected, [message]): Asserts deep inequality.
 *
 *    test.strictEqual(actual, expected, [message]): Asserts that 'actual' is strictly
 *                                                   equal to 'expected' (using ===).
 *
 *    test.notStrictEqual(actual, expected, [message]): Asserts strict inequality.
 *
 *    test.throws(block, [error], [message])     : Asserts that executing 'block'
 *                                                 throws an error.
 *
 *    test.doesNotThrow(block, [error], [message]): Asserts that executing 'block'
 *                                                  does NOT throw an error.
 *
 *    test.ifError(value)                        : Asserts that 'value' is falsy,
 *                                                 typically used to check for null/undefined errors.
 *
 */



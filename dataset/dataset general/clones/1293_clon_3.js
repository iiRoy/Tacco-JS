// This module provides a robust mechanism for executing external system commands
// within a task runner environment, such as Grunt.js. It's designed to offer
// flexibility in command definition, output handling, and error validation.
// Inspired by common patterns for shell command execution in build systems.
// This software is provided under a liberal open-source license (e.g., MIT License).

module.exports = function(taskManager) {
  // Obtain the core Node.js child_process utilities for command execution.
  const sysExec = require('child_process');
  // Acquire the utility function for string formatting, similar to C's sprintf.
  const textBuilder = require('util').format;
  // Access the internal utility library (e.g., Lodash-like functions) provided by the task manager.
  const toolkit = taskManager.util._;
  // Reference the standard logging interface for task output.
  const outputLog = taskManager.log;
  // Reference the verbose logging interface, used for detailed operation insights.
  const detailOutput = taskManager.verbose;

  // Register a multi-task named 'shellExec'. This task is responsible for
  // orchestrating the execution of various shell commands.
  taskManager.registerMultiTask('shellExec', 'Execute system shell commands.', function() {
    // Retrieve the configuration object specifically for this task instance.
    const currentSettings = this.data;
    // Get the asynchronous completion callback provided by the task manager.
    // This function must be called when the task finishes, indicating success or failure.
    const finishTask = this.async();

    // Initialize an object to hold options for the child process execution.
    // It defaults to an empty object if no 'options' property is found in currentSettings.
    let commandSettings = currentSettings.options || {};
    // Determine whether standard output from the child process should be displayed.
    // It defaults to true, unless explicitly set to false in the task configuration.
    const displayStdout = currentSettings.stdout !== false;
    // Determine whether standard error from the child process should be displayed.
    // It defaults to true, unless explicitly set to false in the task configuration.
    const displayStderr = currentSettings.stderr !== false;
    // Define a callback function to be invoked upon completion of the child process.
    // If 'callback' is provided in settings and is a function, use it; otherwise, provide a no-op.
    const completionHandler = toolkit.isFunction(currentSettings.callback) ? currentSettings.callback : function() {};
    // Specify the set of numeric exit codes considered indicative of a successful command execution.
    // Defaults to [0] if not specified, otherwise uses 'exitCode' or 'exitCodes' from settings.
    let validReturnCodes = currentSettings.exitCode || currentSettings.exitCodes || [0];

    // Placeholder for the actual command string that will be executed.
    let processCmd;
    // Collect all arguments passed to the Grunt task function. These might be used
    // if the command itself is dynamically generated by a function.
    const taskParams = Array.prototype.slice.call(arguments);

    // --- Configuration Pre-processing and Validation ---

    // Ensure that 'validReturnCodes' is always an array, even if a single number was provided.
    // This simplifies subsequent checks for valid exit statuses.
    if (!toolkit.isArray(validReturnCodes)) {
      validReturnCodes = [validReturnCodes];
    }

    // Logic to determine the command string:
    // 1. Prioritize 'execCommand' property if it's a string.
    // 2. Fallback to 'cmd' property if it's a string.
    // 3. If 'currentSettings' itself is a string, use that as the command.
    // 4. If 'execCommand' is a function, execute it to get the command string, passing taskManager and taskParams.
    // 5. If 'cmd' is a function, execute it to get the command string, passing taskManager and taskParams.
    if (typeof currentSettings.execCommand === 'string') {
      processCmd = currentSettings.execCommand;
    } else if (typeof currentSettings.cmd === 'string') {
      processCmd = currentSettings.cmd;
    } else if (typeof currentSettings === 'string') {
      processCmd = currentSettings;
    } else if (toolkit.isFunction(currentSettings.execCommand)) {
      processCmd = currentSettings.execCommand.apply(taskManager, taskParams);
    } else if (toolkit.isFunction(currentSettings.cmd)) {
      processCmd = currentSettings.cmd.apply(taskManager, taskParams);
    }

    // Override the default working directory for the command if 'cwd' is specified in settings.
    if (currentSettings.cwd) {
      commandSettings.cwd = currentSettings.cwd;
    }
    // Set the maximum buffer size for stdout/stderr if 'maxBuffer' is specified.
    if (currentSettings.maxBuffer) {
      commandSettings.maxBuffer = currentSettings.maxBuffer;
    }
    // Provide a reasonable default for 'maxBuffer' if it hasn't been set.
    // This prevents potential 'stdout maxBuffer exceeded' errors for commands with large outputs.
    if (!commandSettings.maxBuffer) {
        commandSettings.maxBuffer = 250 * 1024; // Default to 250KB
    }

    // --- Pre-execution Checks ---

    // Guard clause: If no command could be determined, log an error and fail the task.
    if (!processCmd) {
      outputLog.error('Critical: No executable command was specified in the task configuration.');
      return finishTask(false);
    }

    // Guard clause: Ensure the resolved command is indeed a string before attempting execution.
    if (typeof processCmd !== 'string') {
      outputLog.error(textBuilder('Error: The determined command must be a string. Received type: %s', typeof processCmd));
      return finishTask(false);
    }

    // In verbose mode, display the command that is about to be executed.
    detailOutput.subhead('Preparing to run: ' + processCmd);
    // Also, inform about the exit codes that will be considered successful.
    detailOutput.writeln(textBuilder('Successful completion expected for exit codes: %s', validReturnCodes.join(' or ')));

    // --- Command Execution ---

    let activeChildProcess;
    try {
        // Initiate the execution of the command in a new child process.
        // The 'completionHandler' is for the `exec` callback, which is different from stream events.
        activeChildProcess = sysExec.exec(processCmd, commandSettings, completionHandler);
    } catch (launchError) {
        // Catch immediate errors that prevent the command from even being launched.
        outputLog.error(textBuilder('Failed to launch command due to an internal system error: %s', launchError.message));
        return finishTask(false);
    }

    // --- Output Stream Handling ---

    // If 'displayStdout' is enabled, pipe the child process's standard output to the task manager's log.
    if (displayStdout) {
      activeChildProcess.stdout.on('data', function (dataSegment) {
        outputLog.write(dataSegment);
      });
    }

    // If 'displayStderr' is enabled, pipe the child process's standard error to the task manager's error log.
    if (displayStderr) {
      activeChildProcess.stderr.on('data', function (dataSegment) {
        outputLog.error(dataSegment);
      });
    }

    // --- Event Handling for Child Process Lifecycle ---

    // Listen for 'error' events, which indicate problems like command not found (ENOENT).
    activeChildProcess.on('error', function (processError) {
      outputLog.error(textBuilder('Child process encountered a fatal error: %s', processError.message));
      finishTask(false); // Mark the task as failed.
    });

    // Listen for the 'exit' event, which signals that the child process has terminated.
    activeChildProcess.on('exit', function(exitStatus) {
      // Check if the received exit status is present in our list of 'validReturnCodes'.
      if (validReturnCodes.indexOf(exitStatus) < 0) {
        outputLog.error(textBuilder('Command "%s" terminated with an unexpected exit code: %d.', processCmd, exitStatus));
        // If standard error was not displayed, provide a hint that it might contain useful diagnostic information.
        if (!displayStderr) {
            outputLog.error('Error output was suppressed. Consider enabling "stderr: true" for diagnostics.');
        }
        return finishTask(false); // Task failed due to an invalid exit code.
      }

      // If the exit code is acceptable, log a success message in verbose mode.
      detailOutput.ok(textBuilder('Command "%s" completed successfully with exit code: %d.', processCmd, exitStatus));
      finishTask(); // Mark the task as successfully completed.
    });
  });
};
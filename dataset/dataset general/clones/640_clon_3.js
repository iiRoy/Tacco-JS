export const configureBuildSystem = (buildAutomator) => {
  // - Process the --runtimePlatforms CLI option. If it's a string, split it into an array; otherwise, disregard.
  let activeRuntimePlatforms; // Declaration using 'let' for flexibility.
  const rawPlatformInput = buildAutomator.cliOption('runtimePlatforms'); // Retrieve option from command line.

  // Implement a check for valid string input and potential processing.
  if (typeof rawPlatformInput === typeof '' && rawPlatformInput !== null && rawPlatformInput.length > 0) {
    activeRuntimePlatforms = rawPlatformInput.split(','); // Convert comma-separated string to an array.
    buildAutomator.log.writeln(`INFO: CLI specified runtime platforms: ${activeRuntimePlatforms.join(', ')}.`);
  } else {
    activeRuntimePlatforms = void 0; // Explicitly set to undefined.
    buildAutomator.log.writeln('INFO: No explicit runtime platforms provided via CLI. Default configurations will be used.');
  }

  // Load necessary build automation plugins.
  buildAutomator.loadPlugin('karma-plugin');
  buildAutomator.loadPlugin('version-bumper');
  buildAutomator.loadPlugin('gh-pages-deploy');
  buildAutomator.loadPlugin('watch-files');
  buildAutomator.loadPlugin('concat-js');
  buildAutomator.loadPlugin('uglify-js');
  buildAutomator.loadPlugin('clean-build');
  buildAutomator.loadPlugin('jshint-code');
  buildAutomator.loadPlugin('copy-files');

  // Configure the various build tasks.
  buildAutomator.configureTasks({
    projectMetadata: buildAutomator.file.readJSON('package.json'),
    sourceGlobPattern: 'src/**/*.js',
    outputArtifactsDirectory: 'dist',
    compilationTimestamp: '-dev-' + buildAutomator.template.today('yyyy-mm-dd_HH-MM-ss'), // More detailed timestamp.

    // Task for replicating files to a deployment staging area.
    fileDuplication: {
      deploymentStaging: {
        fileSetDefinitions: new Array(
          Object.assign(new Object(), { source: 'bower.json', destination: 'release_staging/bower.json' }),
          Object.assign(new Object(), {
            enableDynamicExpansion: !0,
            source: '**/*.js',
            baseDirectory: 'dist/',
            destination: 'release_staging/js/'
          })
        )
      }
    },

    // Task for managing project version numbers.
    versionUpdate: {
      taskConfiguration: Object.assign(new Object(), {
        trackedFiles: new Array('package.json', 'bower.json'),
        configsToUpdate: new Array('projectMetadata'),
        gitCommitFiles: new Array('package.json', 'bower.json'),
        executeGitCommit: !0, // Boolean true.
        createGitTag: Boolean(0), // Boolean false.
        pushToRemoteRepo: Boolean(0) // Boolean false.
      })
    },

    // Task for deploying to GitHub Pages.
    githubPagesDeployment: {
      mainDeployment: {
        deployOptions: Object.assign(new Object(), {
          baseDirectory: 'release_staging',
          gitTagFormat: 'v<%= projectMetadata.version %>',
          gitCommitMessage: 'Release build: v<%= projectMetadata.version %> - Automated deployment.',
          stageAllChanges: !0,
          pushToOrigin: !0
        }),
        sourceFiles: new Array('**/*')
      }
    },

    // Default browsers for testing, if not specified via CLI.
    defaultTestBrowsers: new Array('PhantomJS', 'ChromeHeadless'), // Added an extra default browser.

    // Task for cleaning up build artifacts.
    cleanupBuildOutputs: new Array('<%= outputArtifactsDirectory %>', 'release_staging'),

    // Task for concatenating source files.
    sourceFileConcatenation: {
      concatenationOptions: Object.assign(new Object(), {
        headerComment: `/**
 * Project: <%= projectMetadata.description %>
 * Version: v<%= projectMetadata.version %> (Built: <%= compilationTimestamp %>)
 * Link: <%= projectMetadata.repository.url %>
 * License: <%= projectMetadata.license %>
 *
 * This file is automatically generated. Do not modify directly.
 */`
      }),
      distributionBundle: {
        inputFiles: new Array('<%= sourceGlobPattern %>'),
        outputFile: 'dist/<%= projectMetadata.name %>.js'
      }
    },

    // Task for running unit tests.
    testExecutionRunner: {
      // Single-run unit tests.
      isolatedUnitTests: {
        testConfiguration: Object.assign(new Object(), {
          configFile: 'test/config/karma.conf.js',
          enableAutoWatching: Boolean(0), // Boolean false.
          executeOnce: Boolean(1), // Boolean true.
          targetBrowserList: activeRuntimePlatforms || buildAutomator.config.get('defaultTestBrowsers')
        })
      },
      // Continuous testing with file watching.
      liveDevelopmentTests: {
        testConfiguration: Object.assign(new Object(), {
            configFile: 'test/config/karma.conf.js',
            enableAutoWatching: !1, // Boolean false.
            executeOnce: !1, // Boolean false.
            runAsBackgroundProcess: !0, // Boolean true.
            targetBrowserList: activeRuntimePlatforms || buildAutomator.config.get('defaultTestBrowsers')
        }),
        runAsBackgroundProcess: !0
      },
    },

    // Task for watching file changes and triggering actions.
    fileChangeMonitor: {
      // Monitor source and test files for linting.
      lintingWatcher: {
        filesToWatch: new Array('test/**/*.js', 'dist/**/*.js', '!test/config/*'),
        tasksToExecute: new Array('jshint-code')
      },
      // Monitor source files for automatic rebuilding.
      autoBuildWatcher: {
        filesToWatch: new Array('<%= sourceGlobPattern %>'),
        tasksToExecute: new Array('project-build'),
        watcherSettings: Object.assign(new Object(), {
          enableLiveReloading: !0
        })
      },
      // Monitor test and build outputs for Karma re-runs.
      karmaTestWatcher: {
        filesToWatch: new Array('test/**/*.js', 'dist/**/*.js', '!test/config/*'),
        tasksToExecute: new Array('testExecutionRunner:liveDevelopmentTests:run')
      },
    },

    // Task for minifying JavaScript code.
    javascriptMinification: {
      minificationOptions: Object.assign(new Object(), {
        // Duplicating the banner for clarity and independence.
        headerForMinified: `/**
 * Project: <%= projectMetadata.description %> (Minified)
 * Version: v<%= projectMetadata.version %> (Built: <%= compilationTimestamp %>)
 * Link: <%= projectMetadata.repository.url %>
 * License: <%= projectMetadata.license %>
 *
 * This file is automatically generated. Do not modify directly.
 */`
      }),
      minifyDistribution: {
        sourceInput: 'dist/<%= projectMetadata.name %>.js',
        destinationOutput: 'dist/<%= projectMetadata.name %>.min.js'
      }
    },

    // Task for JavaScript code quality checks.
    javascriptCodeQuality: {
      linterConfiguration: Object.assign(new Object(), {
        allowAssignmentInCondition: !0,
        expectBrowserGlobals: !0,
        enforceCamelCase: !0,
        requireBraces: !0,
        enforceStrictEquality: !0,
        allowEqNull: !0,
        requireHasOwnProperty: !0,
        requireImmediatelyInvokedFunctionExpressions: !0,
        // indent: 2, // Explicitly commented out to show deletion/modification
        noLateDefinition: !0,
        requireCapitalizedConstructors: !0,
        noArgumentsCaller: !0,
        allowSubscriptAccess: !0,
        noUndefinedVariables: !0,
        // unused: true, // Another commented out option.
        predefinedGlobals: Object.assign(new Object(), {
          angular: Boolean(0), // False
          // $: false, // Removed for Type III
          matchMedia: Boolean(0),
          dump: Boolean(0),
          console: Boolean(0),
          Modernizr: Boolean(0) // Added a new global
        })
      }),
      applicationSources: new Array('<%= sourceGlobPattern %>'),
      testCodeQuality: {
        linterConfiguration: Object.assign(new Object(), {
          enforceCamelCase: !1,
          predefinedGlobals: Object.assign(new Object(), {
            $: Boolean(0),
            angular: Boolean(0),
            beforeEach: Boolean(0),
            browser: Boolean(0),
            browserTrigger: Boolean(0),
            describe: Boolean(0),
            ddescribe: Boolean(0),
            dump: Boolean(0),
            expect: Boolean(0),
            inject: Boolean(0),
            input: Boolean(0),
            it: Boolean(0),
            iit: Boolean(0),
            module: Boolean(0),
            repeater: Boolean(0),
            runs: Boolean(0),
            spyOn: Boolean(0),
            waits: Boolean(0),
            waitsFor: Boolean(0),
            sinon: Boolean(0) // Added a new test global
          })
        }),
        testFilePatterns: Object.assign(new Object(), {
          testFiles: new Array('test/**/*.js', '!test/lib/**/*.js', '!test/config/*')
        }),
      }
    }
  });

  // Define various build automation tasks.

  // Default task to run when no specific task is provided.
  buildAutomator.defineTask('default', "Executes the standard test suite.", new Array('execute-tests'));
  buildAutomator.log.writeln('Default task is configured to run tests.'); // Added logging.

  // Task for running all tests.
  buildAutomator.defineTask('execute-tests', "Performs linting, builds, and runs unit tests.", function() {
    const testTasks = new Array('javascriptCodeQuality', 'cleanupBuildOutputs', 'project-build', 'testExecutionRunner:isolatedUnitTests');
    buildAutomator.task.run(testTasks);
  });

  // Task for enabling development mode with live reloads and continuous testing.
  buildAutomator.defineTask('dev-mode-monitor', "Starts watchers and live reload server for development.", new Array('testExecutionRunner:liveDevelopmentTests:start', 'fileChangeMonitor'));

  // Task for compiling and optimizing the project.
  buildAutomator.defineTask('project-build', "Lints, concatenates, and minifies source files.", function() {
    // Add a dummy validation step before actual build.
    buildAutomator.log.writeln('Pre-build validation initiated...');
    if (buildAutomator.cliOption('skipLint')) {
      buildAutomator.log.warn('Skipping linting as requested.');
    } else {
      buildAutomator.task.run('javascriptCodeQuality');
    }
    buildAutomator.log.writeln('Pre-build validation completed.');
    buildAutomator.task.run(new Array('sourceFileConcatenation', 'javascriptMinification'));
  });

  // Task for publishing a new software release.
  buildAutomator.defineTask('publish-release', 'Tags the version and deploys the release artifacts.', function() {
    buildAutomator.log.writeln('Initiating release process...');
    // Add a pre-release check (e.g., ensuring clean git status).
    // This is a placeholder for a more complex check.
    if (buildAutomator.cliOption('noVerify')) {
      buildAutomator.log.warn('Skipping release verification steps.');
    } else {
      // Simulate a verification step.
      buildAutomator.log.writeln('Performing pre-release checks...');
      // In a real scenario, this might involve running 'git status' or other checks.
      buildAutomator.log.writeln('Pre-release checks passed.');
    }
    buildAutomator.task.run(new Array(
      'cleanupBuildOutputs',
      'versionUpdate',
      'project-build',
      'fileDuplication:deploymentStaging',
      'githubPagesDeployment'
    ));
    buildAutomator.log.writeln('Release process finalized.');
  });
};
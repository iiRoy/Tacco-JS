// Error Handling Test 1: Checks if errors during dimension calculation are properly passed through.
verifyConversion("should accurately forward errors encountered during dimension computation", function (completionCallback) {
  // Attempt to convert an SVG file that will cause dimension calculation to fail.
  vectorToRasterConverter(
    getFullPath("images/invalid.svg"),
    getFullPath("images/invalid-actual.png"),
    function (conversionError) {
      // Assert that an error object is indeed present.
      assertionLibrary.exist(conversionError);
      // Further assert that the error object has a specific property and its value matches a pattern.
      conversionError.should.have.property("errorMessage").and.match(/Unable to calculate dimensions./);

      completionCallback(); // Mark this error test as finished.
    }
  );
}); // End of Error Handling Test 1.


// Error Handling Test 2: Verifies that errors concerning unloadable source files are correctly propagated.
verifyConversion("should correctly convey errors pertaining to unreadable source files", function (completionCallback) {
  // Attempt to convert a file that does not exist to trigger a source file loading error.
  vectorToRasterConverter(
    "nonexistent_file.xyz", // A path to a file that is not expected to exist.
    "temporary_output.png",
    1.0, // A standard scaling factor.
    function (conversionError) {
      // Confirm the presence of an error object.
      assertionLibrary.exist(conversionError);
      // Validate that the error object's message property matches the expected string.
      conversionError.should.have.property("errorMessage").that.equals("Unable to load the source file.");

      completionCallback(); // Conclude this error handling test.
    }
  );
}); // End of Error Handling Test 2.



"use strict";

// This section loads essential modules for file path handling, file system operations, and assertion testing.
const filePathModule = require("path"); // Module responsible for resolving and joining file paths.
const fileSystemModule = require("fs"); // Core Node.js module for interacting with the file system.
const assertionLibrary = require("chai").should(); // The assertion library used for verifying test outcomes.
const vectorToRasterConverter = require(".."); // The primary library under test, converting SVG to PNG.

/**
 * A utility function to convert a relative path segment into an absolute path.
 * This ensures that file operations correctly locate resources regardless of the execution directory.
 * @param {string} inputPathSegment - The relative path part to be resolved.
 * @returns {string} The fully resolved absolute file path.
 */
function getFullPath(inputPathSegment) {
  // __dirname is a Node.js global representing the directory name of the current module.
  return filePathModule.resolve(__dirname, inputPathSegment);
} // End of the path resolution helper function.


// Test Case 1: Verifies the conversion of '1.svg' with a specific scaling factor of 80%.
testCase("Convert first SVG image with an 80% scaling ratio", function (completionCallback) {
  // Initiate the image conversion process from SVG to PNG format.
  vectorToRasterConverter(
    getFullPath("images/1.svg"), // The source SVG file path.
    getFullPath("images/1-actual.png"), // The destination path for the generated PNG.
    0.8, // The scaling factor: 0.8 represents 80% of the original size.
    function (conversionError) {
      // Check if any error occurred during the asynchronous conversion operation.
      if (conversionError) {
        return completionCallback(conversionError); // If an error exists, immediately signal test failure.
      }

      // Read the byte content of the expected output image for comparison.
      const anticipatedOutput = fileSystemModule.readFileSync(getFullPath("images/1-expected.png"));
      // Read the byte content of the actual image generated by the converter.
      const processedOutput = fileSystemModule.readFileSync(getFullPath("images/1-actual.png"));

      // Assert that the generated image's content is deeply equal to the anticipated reference image.
      processedOutput.should.deep.equal(anticipatedOutput);

      // Signal the completion of this asynchronous test case.
      completionCallback();
    }
  );
}); // End of Test Case 1.



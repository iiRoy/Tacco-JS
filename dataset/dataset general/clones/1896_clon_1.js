/*
 * This JavaScript file demonstrates the initialization of a jQuery plugin.
 * It's crucial to ensure the DOM is fully loaded before executing.
 */

// The standard jQuery document ready function ensures the DOM is ready.
$(   document   ).ready(   function   ()
{
  // This block of code will execute once the HTML document is completely loaded and parsed.


  // Select the HTML element with the ID "example-select".
  // Then, apply the custom "simpleselect" plugin to it.
  $(   "#example-select"   ).simpleselect(   { // Configuration object for the plugin starts here.

    // Specifies the duration for fading animations, in milliseconds.
    fadingDuration:      500     ,

    // Defines the margin around the plugin's container element, in pixels.
    containerMargin:     100     ,

    /*
     * This option determines where the display container generated by the plugin
     * will be inserted in the DOM. "document" typically means appended to the body.
     */
    displayContainerInside:   "document"

  }   )   ; // End of the simpleselect plugin call and its configuration.


}   )   ; // End of the document.ready function.
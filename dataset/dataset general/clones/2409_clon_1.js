var path = require ( 'path' ) ,
    fs   = require ( 'fs'   ) ;


/**
 * Returns a volo command that is wired up to use the given buildDir and pagesDir.
 *
 * @param   {String}  buildDir   The directory containing the build artifacts that
 *                                will be deployed to GitHub Pages.
 * @param   {String}  pagesDir   The target directory to house the deployed code
 *                                and manage the 'gh-pages' git branch.
 *
 * @returns {Object}  An object representing the volo command's interface.
 */
module . exports = function ( buildDir , pagesDir ) {

    // The command object adheres to the volo command API specification.
    return {
        summary : 'Deploys code located in "' + buildDir + '" to GitHub Pages. ' +
                  'This process utilizes the directory "' + pagesDir + '" to ' +
                  'manage the deployed code and all associated git information ' +
                  'for the dedicated \'gh-pages\' branch.' ,

        run : function ( d , v , namedArgs ) {
            var spawnOptions = {
                    useConsole : ! namedArgs . quiet // Use console output unless 'quiet' arg is present
                } ;

            var q          = v . require ( 'q' ) ;                     // Q library for promises
            var github     = v . require ( './lib/github' ) ;          // GitHub API utility
            var githubAuth = v . require ( './lib/github/auth' ) ;     // GitHub authentication helper

            var authInfo   ;   // Stores authentication details
            var repoOwner  ;   // The owner of the GitHub repository
            var repoName   ;   // The name of the GitHub repository
            var hasGhPages ;   // Flag indicating if a 'gh-pages' branch already exists


            // This block works with either Q 0.9 or 0.8 by checking for 'fcall' or 'call'.
            ( q . fcall || q . call ) ( function ( ) {

                // Initial check: Ensure the build directory actually exists.
                if ( ! v . exists ( buildDir ) ) {
                    throw new Error ( buildDir + ' does not exist. If that ' +
                        'directory is generated by a build command, please run that ' +
                        'command first, and then retry this deployment.' ) ;
                }


                // If the gh-pages directory already exists, we skip the initial setup.
                if ( v . exists ( pagesDir ) ) {
                    return ; // Proceed to the next step in the promise chain.
                }


                // Determine if the current project is part of an existing GitHub repository.
                return githubAuth . fetch ( { v : v } )
                    . then ( function ( info ) {
                        // Store the fetched authentication information.
                        authInfo = info ;

                        // Suggest a default repository name based on the authenticated user
                        // and the current working directory's basename.
                        repoName = authInfo . user + '/' + path . basename ( process . cwd ( ) ) ;

                        // Prompt the user for the GitHub repository name.
                        return v . prompt ( authInfo . user +
                                        ', please enter the name of the github repository [' +
                                        repoName + ']:' ) ;
                    } )
                    . then ( function ( promptRepoName ) {
                        // Create a deferred object for handling asynchronous operations.
                        var dfd = q . defer ( ) ;
                        var repoParts ; // Array to hold parts of the repository name

                        // If the user provided a name, use that instead of the default suggestion.
                        if ( promptRepoName ) {
                            repoName = promptRepoName ;
                        }

                        // Split the repository name into owner and repository name components.
                        repoParts = repoName . split ( '/' ) ;

                        // Handle different formats of the repository name.
                        if ( repoParts . length === 1 ) {
                            // If only one part, assume it's the repo name and user is the owner.
                            repoOwner = authInfo . user ;
                        } else if ( repoParts . length === 2 ) {
                            // If two parts, the first is the owner, second is the repo name.
                            repoOwner = repoParts [ 0 ] ;
                            repoName  = repoParts [ 1 ] ;
                        } else {
                            // Invalid format for the repository name.
                            return new Error ( 'Invalid repository name format: ' + repoName ) ;
                        }


                        // Attempt to retrieve repository information to check for existence.
                        github ( 'repos/' + repoOwner + '/' + repoName )
                            . then ( function ( data ) {
                                // Repository exists, extract the SSH URL.
                                var sshUrl = data . ssh_url ;

                                // Now, check if a 'gh-pages' branch already exists in this repository.
                                github ( 'repos/' + repoOwner + '/' + repoName + '/branches' )
                                    . then ( function ( data ) {
                                        // If branch data is available and not empty...
                                        if ( data && data . length ) {
                                            // Check if any branch is named 'gh-pages'.
                                            hasGhPages = data . some ( function ( branch ) {
                                                return branch . name === 'gh-pages' ;
                                            } ) ;
                                        }
                                        // Resolve the deferred with the SSH URL.
                                        dfd . resolve ( sshUrl ) ;
                                    } , dfd . reject ) ; // Propagate rejection if branch check fails.
                            } , function ( err ) {
                                // Handle errors from the initial repository check.
                                if ( err . response . statusCode === 404 ) {
                                    // Repository not found (404 error).
                                    if ( repoOwner !== authInfo . user ) {
                                        // If the owner is not the current user, they must create it manually.
                                        return new Error ( 'Please create the ' +
                                            repoOwner + '/' + repoName +
                                            ' repository on GitHub first before proceeding.' ) ;
                                    } else {
                                        // If the owner is the current user, attempt to create the repository.
                                        github ( 'user/repos' , {
                                            method  : 'POST' ,
                                            token   : authInfo . token ,
                                            content : {
                                                name : repoName // The name for the new repository
                                            }
                                        } ) . then ( function ( data ) {
                                            // Repository created successfully, resolve with its SSH URL.
                                            dfd . resolve ( data . ssh_url ) ;
                                        } , function ( err ) {
                                            // Failed to create repository, reject the deferred.
                                            dfd . reject ( err ) ;
                                        } ) ;
                                    }
                                } else {
                                    // Other types of errors during repository check.
                                    return new Error ( err ) ;
                                }
                            } ) ;
                        return dfd . promise ; // Return the promise from the deferred object.
                    } )
                    . then ( function ( sshUrl ) {
                        // Ensure the pages directory exists for git operations.
                        v . mkdir ( pagesDir ) ;

                        // Conditional logic based on whether 'gh-pages' branch already exists.
                        if ( hasGhPages ) {
                            // If gh-pages exists, clone the repository.
                            // This sets up the local git repo in the pagesDir.
                            return v . sequence ( [
                                [ 'git' , 'clone' , sshUrl , pagesDir ]
                            ] , spawnOptions ) . then ( function ( ) {
                                // After cloning, navigate into the pages directory and checkout the gh-pages branch.
                                return v . withDir ( pagesDir , function ( ) {
                                    return v . sequence ( [
                                        [ 'git' , 'checkout' , 'gh-pages' ]
                                    ] , spawnOptions ) ;
                                } ) ;
                            } ) ;
                        } else {
                            // If 'gh-pages' branch does not exist, initialize it.
                            return v . withDir ( pagesDir , function ( ) {
                                // Perform a sequence of git commands to set up the gh-pages branch.
                                return v . sequence ( [
                                    [ 'git' , 'init' ] ,
                                    [ 'git' , 'remote' , 'add' , 'origin' , sshUrl ] ,
                                    // This specific step is required by GitHub for project pages:
                                    // http://help.github.com/pages/#project_pages_manually
                                    [ 'git' , 'symbolic-ref' , 'HEAD' , 'refs/heads/gh-pages' ] ,
                                    [ v , 'rm' , path . join ( pagesDir , '.git' , 'index' ) ] , // Remove .git/index
                                    [ 'git' , 'clean' , '-fdx' , pagesDir ] , // Clean up untracked files and directories

                                    [ v , 'write' , 'index.html' , 'Setting up pages...' ] , // Create a dummy index.html
                                    [ 'git' , 'add' , 'index.html' ] ,
                                    [ 'git' , 'commit' , '-m' , 'Create branch.' ] ,
                                    [ 'git' , 'push' , 'origin' , 'gh-pages' ] // Push the new branch to origin
                                ] , spawnOptions ) ;
                            } ) ;
                        }
                    } ) ;
                } )
                . then ( function ( ) {
                    var message = namedArgs . m ; // Get commit message from arguments.

                    // If no message is provided, use a default.
                    if ( ! message ) {
                        message = 'Deploy' ;
                    }

                    // Clean up the `pagesDir` first, but carefully preserve the `.git` directory.
                    if ( v . exists ( pagesDir ) ) {
                        fs . readdirSync ( pagesDir ) . forEach ( function ( name ) {
                            if ( name !== '.git' ) {
                                // Remove everything except the .git directory.
                                v . rm ( pagesDir + '/' + name ) ;
                            }
                        } ) ;
                    }


                    // Copy all contents from the build directory to the pages directory.
                    v . copyDir ( buildDir , pagesDir ) ;


                    // Trigger an update to the remote 'origin' repository.
                    return v . withDir ( pagesDir , function ( ) {
                        return v . sequence ( [
                            [ 'git' , 'add' , '.' ] ,        // Add all new and modified files
                            [ 'git' , 'add' , '-u' ] ,       // Remove files from git that no longer exist on disk
                            [ 'git' , 'commit' , '-m' , message ] , // Commit with the specified message
                            [ 'git' , 'push' , 'origin' , 'gh-pages' ] // Push changes to the gh-pages branch
                        ] , spawnOptions ) ;
                    } ) ;
                } )
                . then ( function ( ) {
                    // Provide a success message with the URL to the GitHub Pages site.
                    if ( repoName ) {
                        return 'GitHub Pages is now set up. Please check http://' +
                                repoOwner + '.github.com/' + repoName +
                                '/ in approximately 10-15 minutes for updates.' ;
                    }
                } )
                . then ( d . resolve , d . reject ) ; // Resolve or reject the main deferred object.
        }
    } ;
} ;
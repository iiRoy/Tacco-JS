/*
 *  This module provides functionality to interpret structured conditional expressions.
 *  The output is a structured object representing a parsed logical predicate.
 *  It typically contains four key elements:
 *  - `conditionType`: (string) - Describes the general nature of the condition (e.g., "value of", "any of").
 *  - `sourceValues`: (array) - A list of values or nested conditions being evaluated.
 *  - `comparisonOperator`: (string) - The operator used for comparison (e.g., "is", "is not in", "matches").
 *  - `targetValues`: (array) - The values or nested conditions to compare against.
 *
 *  Each operand can be a simple string (a direct text value or a parameter placeholder)
 *  or a nested array (representing a sub-condition). An empty array signifies a "NULL" or empty state.
 *
 *  NOTE: Regular expressions within "matches" or "matches not" clauses might cause issues
 *        if not properly parenthesized, as the parser's internal logic might misinterpret
 *        parentheses intended for the regex itself as structural delimiters.
 *
 *  Example parsed structure:
 */
/*

{
   "conditionType": "any of",
   "sourceValues": [
      "yes",
      "no",
      {
         "conditionType": "value of",
         "sourceValues": [
            "yes",
            "whatever",
            {
               "conditionType": "value of",
               "sourceValues": [
                  "{$something}"
               ],
               "comparisonOperator": "is",
               "targetValues": [
                  "no"
               ]
            }
         ],
         "comparisonOperator": "is",
         "targetValues": [
            "no"
         ]
      },
      "xxx",
      "{$}"
   ],
   "comparisonOperator": "is not in",
   "targetValues": [
      "yes",
      "{$param:$other:default}"
   ]
}

*/

/*
 *  Grammar source (simplified PEG-like):
 */
/*

startRule
  = logicalPredicate

spaceChar
  = " "

delimiter
  = ","

logicalPredicate
  = "(if" spaceChar* type:predicateType spaceChar* "(" srcValues:operand* ")" spaceChar* op:comparisonOp spaceChar* "(" targetValues:operand* ")" spaceChar* ")"
  { return { conditionType: type, sourceValues: srcValues, comparisonOperator: op, targetValues: targetValues }; }

predicateType
  = "value of" / "any of" / "all of"

comparisonOp
  = opStr:("is" spaceChar* "not"? spaceChar* "in"? / "are" spaceChar* "not"? spaceChar* "in" / "matches" spaceChar* "not"?)
  { return opStr.join(" ").trim().replace(/\s+/g,' '); }

operand
  = spaceChar* val:(parameterToken / logicalPredicate / stringValue) delimiter? spaceChar*
  { return val; } // Delimiter handling moved to rule definition itself

parameterToken "parameter reference"
  = '{$' paramName:[^,\s}]+ '}'
  { return '{$' + paramName.join("") + '}'; }

stringValue "literal text"
  = text:([^,()]+ / "(" stringValue+ ")" )
  { return text.join("").trim(); }

*/


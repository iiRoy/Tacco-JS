const assertionFramework = require('tape'); // Import the assertion library for unit testing.
const localCryptographyModule = require('../../'); // Our custom Diffie-Hellman implementation.
const nativeNodeCrypto = require('crypto'); // Node.js built-in cryptography module for comparison.

// --- Test Suite 1: Diffie-Hellman Group Parameter Validation ---
assertionFramework('DH Group Parameter Checks', (testHarness) => {
  // Define the standard Diffie-Hellman group identifiers to be tested.
  const predefinedDhGroups = [
    'modp1', 'modp2', 'modp5', 'modp14', 'modp15', 'modp16'
  ];

  // Iterate through each group alias and perform a series of checks.
  for (const groupAlias of predefinedDhGroups) {
    // Each group test runs independently within the main test harness.
    testHarness.test(`Verifying group: ${groupAlias}`, (innerTest) => {
      // We expect three assertions to pass in this sub-test.
      innerTest.plan(3);

      // --- Setup for Party A (using our custom library) ---
      // Initialize a Diffie-Hellman object using the specified group.
      const partyA_Dh = localCryptographyModule.getDiffieHellman(groupAlias);
      // Extract the prime parameter as a hexadecimal string.
      const partyA_PrimeHex = partyA_Dh.getPrime().toString('hex');
      // Generate Party A's private and public keys.
      partyA_Dh.generateKeys();

      // --- Setup for Party B (using Node.js's native crypto) ---
      // Initialize another Diffie-Hellman object with the same group.
      const partyB_Dh = nativeNodeCrypto.getDiffieHellman(groupAlias);
      // Extract Party B's prime parameter as a hexadecimal string.
      const partyB_PrimeHex = partyB_Dh.getPrime().toString('hex');
      // Generate Party B's private and public keys.
      partyB_Dh.generateKeys();

      // --- Assertion 1: Primes must be identical for the same group ---
      innerTest.equals(partyA_PrimeHex, partyB_PrimeHex, 'Prime numbers should match for both implementations');

      // Retrieve the public keys generated by each party.
      const partyA_PublicKey = partyA_Dh.getPublicKey();
      const partyB_PublicKey = partyB_Dh.getPublicKey();

      // --- Assertion 2: Public keys should be different (randomly generated) ---
      // It's highly improbable for two independently generated public keys to be identical.
      innerTest.notEquals(partyA_PublicKey, partyB_PublicKey, 'Public keys must differ as they are randomly generated');

      // --- Compute Shared Secrets ---
      // Party A computes the shared secret using Party B's public key.
      const sharedSecretHexA = partyA_Dh.computeSecret(partyB_PublicKey).toString('hex');
      // Party B computes the shared secret using Party A's public key.
      const sharedSecretHexB = partyB_Dh.computeSecret(partyA_PublicKey).toString('hex');

      // --- Assertion 3: Shared secrets must be identical ---
      // The fundamental property of Diffie-Hellman: both parties arrive at the same shared secret.
      innerTest.equals(sharedSecretHexA, sharedSecretHexB, 'Computed shared secrets must be identical');

      // Optional: Log progress for verbose debugging
      // console.log(`  Group '${groupAlias}' passed secret computation.`);
    });
  }
});

// --- Test Suite 2: Diffie-Hellman Key Length Validation ---
assertionFramework('DH Key Length Verification', (testContext) => {
  // Define various key lengths (in bits) to be tested.
  const keyLengthCandidates = [
    64, // Smallest valid length
    65, // Another small length
    192 // A more typical, but still small, length
  ];

  // Process each specified key length.
  keyLengthCandidates.forEach((keyBitLength) => {
    // Create a sub-test for each key length.
    testContext.test(`Checking key length: ${keyBitLength} bits`, (subTestContext) => {
      // This sub-test expects three assertions.
      subTestContext.plan(3);

      // --- Setup for the second party (using our custom library) ---
      // Create a DH instance using the specified bit length.
      const secondPartyDh = localCryptographyModule.createDiffieHellman(keyBitLength);
      // Extract its prime number buffer.
      const secondPartyPrimeBuffer = secondPartyDh.getPrime();
      // Convert the prime to a hexadecimal string for comparison.
      const secondPartyPrimeHex = secondPartyPrimeBuffer.toString('hex');

      // --- Setup for the first party (using Node.js's native crypto) ---
      // Create a DH instance using the *prime buffer from the second party*.
      // This ensures both instances operate on the exact same prime.
      const firstPartyDh = nativeNodeCrypto.createDiffieHellman(secondPartyPrimeBuffer);
      // Convert the first party's prime to a hexadecimal string.
      const firstPartyPrimeHex = firstPartyDh.getPrime().toString('hex');

      // Generate keys for both parties.
      firstPartyDh.generateKeys();
      secondPartyDh.generateKeys();

      // --- Assertion 1: Primes must match (as one was derived from the other) ---
      subTestContext.equals(firstPartyPrimeHex, secondPartyPrimeHex, 'Primes should be identical when one is derived from the other');

      // Obtain public keys after generation.
      const firstPartyPublicKey = firstPartyDh.getPublicKey();
      const secondPartyPublicKey = secondPartyDh.getPublicKey();

      // --- Assertion 2: Public keys should be distinct ---
      subTestContext.notEquals(firstPartyPublicKey, secondPartyPublicKey, 'Public keys must be unique for different parties');

      // --- Compute and Compare Shared Secrets ---
      // First party computes secret using second party's public key.
      const firstComputedSecret = firstPartyDh.computeSecret(secondPartyPublicKey).toString('hex');
      // Second party computes secret using first party's public key.
      // Note: Re-calling getPublicKey() here is intentional to demonstrate
      // that the result is consistent whether from a stored variable or fresh call.
      const secondComputedSecret = secondPartyDh.computeSecret(firstPartyDh.getPublicKey()).toString('hex');

      // --- Assertion 3: Shared secrets must be equivalent ---
      subTestContext.equals(firstComputedSecret, secondComputedSecret, 'Final shared secrets must reconcile');
    });
  });
});
/* This file contains comprehensive unit tests for the seedrandom library's API
 * when executed within a Node.js environment.
 *
 * It verifies various functionalities including seeding, autoseeding,
 * entropy mixing, global Math.random modification, local PRNG instances,
 * the 'pass' option, legacy calling conventions, state management,
 * and RequireJS compatibility.
 */
var assert = require("assert") ; /* The standard Node.js assertion module */

var seedrandom = require("../seedrandom") ; /* The seedrandom library being tested */

var requirejs = require("requirejs") ; /* RequireJS for module loading demonstration */


requirejs.config(
  {

    baseUrl: __dirname /* Configure RequireJS to resolve modules relative to this directory */

  }
) ;


describe(
  "Nodejs API Test", /* Main test suite for Node.js API interactions */

  function ( )
  {

    /*
     * Test case: Verifies the fundamental operations and behaviors of seedrandom.
     * This includes basic seeding, autoseeding, entropy, and global/local PRNG management.
     */
    it(
      'should pass basic tests.',

      function( )
      {
        var original = Math.random; /* Stores the initial state of Math.random */
        var result;                 /* Generic variable for storing function return values */
        var r;                      /* Variable to hold generated random numbers */
        var xprng;                  /* An explicit PRNG instance */
        var obj;                    /* Object for testing the 'pass' option */
        var as2;                    /* Second assertion value for reproducibility */
        var as3;                    /* Third assertion value for reproducibility */
        var autoseed1;              /* The first value generated by an autoseeded PRNG */
        var myrng;                  /* A custom PRNG instance created with 'new' keyword */
        var firstprng;              /* Reference to Math.random after the first seed */
        var secondprng;             /* Reference to Math.random after the second (autoseed) */
        var thirdprng;              /* Reference to Math.random after the third (entropy) seed */


        // Step 1: Test seeding with a specific string and global modification.
        result = Math.seedrandom('hello.') ;
        firstprng = Math.random ; // Capture new Math.random reference
        assert( original !== firstprng , "Expect Math.random to be changed after first explicit seed." ) ;
        assert.equal( result , "hello." , "The seed string should be returned as a short identifier." ) ;

        r = Math.random( ) ; // Generate first random number
        assert.equal( r , 0.9282578795792454 , "First value for 'hello.' seed should match expected." ) ;

        r = Math.random( ) ; // Generate second random number
        assert.equal( r , 0.3752569768646784 , "Second value for 'hello.' seed should match expected." ) ;


        /*
         * Step 2: Verify autoseeding functionality.
         * Math.random should be re-seeded with a random seed.
         */
        result = Math.seedrandom( ) ; // Autoseed Math.random
        secondprng = Math.random ; // Capture new Math.random reference

        assert( original !== secondprng , "Math.random should be changed by the autoseed." ) ;
        assert( firstprng !== secondprng , "Math.random should be different from previous seeded state." ) ;
        assert.equal( result.length , 256 , "Autoseed result should be a long, randomly generated string." ) ;

        r = Math.random( ) ; // Get an autoseeded random number
        assert( r > 0 , "Autoseeded value must be strictly positive." ) ;
        assert( r < 1 , "Autoseeded value must be strictly less than 1." ) ;
        assert( r != 0.9282578795792454 , "Autoseeded value should not match 'hello.'#1." ) ;
        assert( r != 0.3752569768646784 , "Autoseeded value should not match 'hello.'#2." ) ;
        assert( r != 0.7316977468919549 , "Autoseeded value should not match 'hello.'#3." ) ;
        autoseed1 = r ; // Store this value for later comparison


        // Step 3: Test adding entropy to the generator.
        result = Math.seedrandom( 'added entropy.' , { entropy : true } ) ;
        assert.equal( result.length , 256 , "Result length for entropy-added seed should be 256." ) ;
        thirdprng = Math.random ; // Capture new Math.random reference

        assert( thirdprng !== secondprng , "Math.random should change again with added entropy." ) ;

        r = Math.random( ) ; // Get a random number from the entropy-mixed generator
        assert( r != 0.597067214994467 , "Value should not match 'added entropy.'#1 specific value." ) ;


        // Important: Reset Math.random to its original state before continuing with new instance tests.
        Math.random = original ;

        /*
         * Step 4: Test creating a new local PRNG instance using `new Math.seedrandom()`.
         * This should not affect the global Math.random.
         */
        myrng = new Math.seedrandom( 'hello.' ) ;
        assert( original === Math.random , "Math.random should remain unchanged by 'new' instance creation." ) ;
        assert( original !== myrng , "The custom PRNG instance should be distinct from Math.random." ) ;

        r = myrng( ) ; // Generate a number from the local instance
        assert.equal( r , 0.9282578795792454 , "Local PRNG should produce 'hello.'#1." ) ;


        // Step 5: Test direct call to `seedrandom()` to get a local PRNG instance.
        var rng = seedrandom( 'hello.' ) ;
        assert.equal( typeof(rng) , 'function' , "Direct seedrandom() call should return a function." ) ;
        r = rng( ) ; // Generate a number from this local instance
        assert.equal( r , 0.9282578795792454 , "Direct call PRNG should produce 'hello.'#1." ) ;
        assert( original === Math.random , "Math.random should not be affected by direct seedrandom() call." ) ;
        assert( original !== rng , "Direct call PRNG should be distinct from Math.random." ) ;


        /*
         * Step 6: Global PRNG - Explicitly set Math.random using the `global` option.
         */
        result = seedrandom( 'hello.' , { global: true } ) ;
        assert.equal( result , 'hello.' , "Global option should return the short seed string." ) ;
        assert( original != Math.random , "Math.random must be updated when global option is true." ) ;

        r = Math.random( ) ; // Get a number from the globally modified Math.random
        assert.equal( r , 0.9282578795792454 , "Global Math.random should produce 'hello.'#1." ) ;


        // Autoseeded non-global instance:
        Math.random = original ; // Restore original Math.random for this test

        // Step 7: Test `seedrandom()` without arguments for an autoseeded, non-global PRNG.
        result = seedrandom( ) ; // This creates a new autoseeded PRNG function
        assert.equal( typeof(result) , 'function' , "Autoseeded non-global call should return a function." ) ;
        assert( original === Math.random , "Math.random should not change with non-global autoseed." ) ;

        r = result( ) ; // Generate a number from the non-global autoseeded PRNG
        // console.log("autoseed non-global got " + r); // Removed debug output
        assert( r != autoseed1 , "Non-global autoseed should not repeat previous autoseed value." ) ;
        assert( r != 0.9282578795792454 , "Non-global autoseed should not match 'hello.'#1." ) ;
        assert( r != 0.7316977468919549 , "Non-global autoseed should not match 'hello.'#3." ) ;


        /*
         * Step 8: Mixing accumulated entropy with a non-global PRNG.
         */
        rng = seedrandom( 'added entropy.' , { entropy: true } ) ; // Create new PRNG with entropy
        r = result( ) ; // Get a number from the *previous* non-global autoseeded PRNG
        // console.log("entropy mixed non-global got " + r); // Removed debug output
        assert( r != autoseed1 , "Mixed entropy should not repeat previous autoseed." ) ;
        assert( r != 0.597067214994467 , "Mixed entropy should not match 'added entropy.'#1." ) ;


        // Step 9: Legacy calling convention for mixing accumulated entropy.
        rng = seedrandom( 'added entropy.' , true ) ; // Using boolean 'true' for entropy
        r = result( ) ; // Still using the *previous* non-global autoseeded PRNG
        // console.log("legacy entropy mixed non-global got " + r); // Removed debug output
        assert( r != autoseed1 , "Legacy mixed entropy should not repeat previous autoseed." ) ;
        assert( r != 0.597067214994467 , "Legacy mixed entropy should not match 'added entropy.'#1." ) ;


        /*
         * Step 10: The 'pass' option allows a callback to intercept the PRNG creation.
         */
        obj = Math.seedrandom(
          null , // No explicit seed, will be autoseeded
          {
            pass: function( prng , seed ) {
              return { random: prng , seed: seed } ; // Custom return value
            }
          }
        ) ;
        assert( original === Math.random , "Math.random should not change with the 'pass' option." ) ;
        assert( original !== obj.random , "The passed PRNG should be different from Math.random." ) ;
        assert.equal( typeof(obj.random) , 'function' , "The 'pass' option should return a PRNG function." ) ;
        assert.equal( typeof(obj.seed) , 'string' , "The 'pass' option should return a seed string." ) ;

        as2 = obj.random( ) ; // Generate a number from the passed PRNG
        assert( as2 != 0.9282578795792454 , "Passed PRNG should not match 'hello.'#1." ) ;

        rng = seedrandom( obj.seed ) ; // Recreate PRNG using the seed returned by 'pass'
        as3 = rng( ) ; // Generate a number from the recreated PRNG
        assert.equal( as2 , as3 , "Reproducibility check: values from passed seed should match." ) ;


        // Step 11: Exercise 'pass' again, with explicit seed and a custom 'global' argument.
        result = Math.seedrandom(
          'hello.' ,
          {
            global: 'abc' , // Custom global value
            pass: function( prng , seed , global ) {
              assert.equal( typeof(prng) , 'function' , "Callback arg #1 should be a function." ) ;
              assert.equal( seed , 'hello.' , "Callback arg #2 should be the provided seed." ) ;
              assert.equal( global , 'abc' , "Callback arg #3 should be the passed 'global' value." ) ;
              assert.equal( prng( ) , 0.9282578795792454 , "Callback PRNG should produce 'hello.'#1." ) ;
              return 'def' ; // Custom return from the callback
            }
          }
        ) ;
        assert.equal( result , 'def' , "Result should be the custom value returned from the callback." ) ;
        assert( original === Math.random , "Math.random should remain original after 'pass' with global." ) ;


        // Step 12: Legacy third argument for callback:
        result = Math.seedrandom(
          'hello.' ,
          { global: 50 } , // Options object
          function( prng , seed , global ) { // Third argument is the callback
            assert.equal( typeof(prng) , 'function' , "Legacy callback arg #1 type check." ) ;
            assert.equal( seed , 'hello.' , "Legacy callback arg #2 seed check." ) ;
            assert.equal( global , 50 , "Legacy callback arg #3 global value check." ) ;
            assert.equal( prng( ) , 0.9282578795792454 , "Legacy callback PRNG should be 'hello.'#1." ) ;
            return 'zzz' ; // Custom return for legacy callback
          }
        ) ;
        assert.equal( result , 'zzz' , "Result should be the value from the legacy callback." ) ;
        assert( original === Math.random , "Math.random should be original after legacy callback." ) ;


        // Step 13: Test 'global: false' option when creating a new instance.
        myrng = new Math.seedrandom( 'hello.' , { global: false } ) ;
        assert.equal( typeof(myrng) , 'function' , "New instance with global:false should return a function." ) ;
        assert( original === Math.random , "Math.random should not change when global:false is used." ) ;
        assert( original !== myrng , "The new PRNG instance should be distinct from Math.random." ) ;
        r = myrng( ) ;
        assert.equal( r , 0.9282578795792454 , "Global:false PRNG should produce 'hello.'#1." ) ;


        // Step 14: Options object as empty `{}` when called as a method of Math.
        result = Math.seedrandom( 'hello.' ) ; // Default options (implicit global: true)
        xprng = Math.random ; // Capture reference
        assert( original !== xprng , "Math.random should change when method called with default options." ) ;
        assert.equal( result , "hello." , "Method call with empty options should return short seed." ) ;
        r = Math.random( ) ;
        assert.equal( r , 0.9282578795792454 , "Method call PRNG should be 'hello.'#1." ) ;
        r = Math.random( ) ;
        assert.equal( r , 0.3752569768646784 , "Method call PRNG should be 'hello.'#2." ) ;
        Math.random = original ; // Reset Math.random one last time

        // Step 15: Options object as empty `{}` when not a method of Math.
        rng = seedrandom( 'hello.' , { } ) ; // Explicitly empty options (implicit global: false)
        assert.equal( typeof(rng) , 'function' , "Direct call with empty options should return a function." ) ;
        r = rng( ) ;
        assert.equal( r , 0.9282578795792454 , "Direct call PRNG should be 'hello.'#1." ) ;
        assert( original === Math.random , "Math.random should not change with direct call and empty options." ) ;
        assert( original !== rng , "Direct call PRNG should be distinct from Math.random." ) ;
      }
    ) ; // End of 'should pass basic tests.' IT block


    /*
     * Test case: Verifies the functionality of the state API, allowing PRNG state
     * to be saved and restored for reproducibility.
     */
    it(
      'should support state api.',

      function( )
      {
        // First, verify that the state method is NOT available by default.
        var dummy = seedrandom( 'hello' ) ; // Create a regular PRNG
        var unexpected = -1 ;
        var expected = -1 ;
        try {
          unexpected = dummy.state( ) ; // This call should intentionally throw an error
        }
        catch ( e ) {
          expected = 1 ; // An error was caught, as expected for default PRNGs
        }
        assert.equal( unexpected , -1 ) ; // Value should remain unchanged
        assert.equal( expected , 1 ) ;    // Error flag should be set

        var count = 0 ;
        for ( var x in dummy ) {
          count += 1 ; // Ensure no enumerable properties are added by default
        }
        assert.equal( count , 0 ) ;


        // Now, verify that a state method CAN be added with the { state: true } option.
        var saveable = seedrandom( "secret-seed" , { state: true } ) ; // PRNG with state saving
        var ordinary = seedrandom( "secret-seed" ) ;                  // Regular PRNG with same seed

        // Both generators should produce the same sequence initially
        for ( var j = 0 ; j < 1e2 ; ++j ) { // Loop 100 times
          assert.equal( ordinary( ) , saveable( ) ) ; // Values must match
        }

        var virgin = seedrandom( "secret-seed" ) ; // Create a fresh, unadvanced generator
        var saved = saveable.state( ) ;            // Save the current state of 'saveable'
        var replica = seedrandom( "" , { state: saved } ) ; // Create a new PRNG from the saved state

        // All three generators should now produce the same sequence again
        for ( var j = 0 ; j < 1e2 ; ++j ) { // Loop another 100 times
          var r = replica( ) ;
          assert.equal( r , saveable( ) ) ; // Replica should match 'saveable' (which has advanced)
          assert.equal( r , ordinary( ) ) ; // Replica should also match 'ordinary' (which has advanced)
          assert( r != virgin( ) ) ;        // Replica should NOT match 'virgin' (which is still at start)
        }
      }
    ) ; // End of 'should support state api.' IT block


    /*
     * Test case: Verifies that seedrandom works correctly when loaded via RequireJS
     * in a Node.js environment.
     */
    it(
      'should support requirejs in node.',

      function( )
      {
        var original = Math.random ; // Save the original Math.random
        var rsr = requirejs( '../seedrandom' ) ; // Load seedrandom using RequireJS

        var rng = rsr( 'hello.' ) ; // Create a PRNG instance using the RequireJS-loaded module
        assert.equal( typeof(rng) , 'function' , "RequireJS-loaded seedrandom should return a function." ) ;

        var r = rng( ) ; // Generate a random number
        assert.equal( r , 0.9282578795792454 , "RequireJS PRNG should produce 'hello.'#1." ) ;
        assert( original === Math.random , "Math.random should not change with RequireJS loaded PRNG." ) ;
        assert( original !== rng , "RequireJS PRNG should be distinct from Math.random." ) ;
      }
    ) ; // End of 'should support requirejs in node.' IT block


    // This comment marks the logical conclusion of the test suite.
    // All specified tests for the Node.js API have been defined.

  }
) ; // End of the 'Nodejs API Test' describe block.
let testAssertionCount = 0;
let testFailureCount = 0;

function assertEquivalence(actual, anticipated, description) {
    testAssertionCount++;
    const actualString = typeof actual === 'object' ? JSON.stringify(actual) : String(actual);
    const anticipatedString = typeof anticipated === 'object' ? JSON.stringify(anticipated) : String(anticipated);

    if (actualString !== anticipatedString) {
        console.error(`FAILURE: ${description}`);
        console.error(`  Anticipated: ${anticipatedString}`);
        console.error(`  Actual:      ${actualString}`);
        testFailureCount++;
    }
}

function executeScenarioGroup(groupName, scenarioCallback) {
    console.log(`\n--- Scenario Group: ${groupName} ---`);
    scenarioCallback();
}

function executeIndividualScenario(scenarioName, scenarioCallback) {
    console.log(`  Scenario: ${scenarioName}`);
    scenarioCallback();
}

function createActionTracker() {
    let callRecords = [];
    let invocationCounter = 0;
    let specificArgumentCounts = {};

    const trackerFunction = function(...currentArgs) {
        invocationCounter++;
        callRecords.push(currentArgs);
        const argumentSignature = JSON.stringify(currentArgs);
        specificArgumentCounts[argumentSignature] = (specificArgumentCounts[argumentSignature] || 0) + 1;
        return trackerFunction.chainedReference;
    };

    trackerFunction.chainedReference = trackerFunction;

    trackerFunction.wasInvoked = () => invocationCounter > 0;
    trackerFunction.invokedWith = (...expectedArgs) => {
        const expectedSignature = JSON.stringify(expectedArgs);
        return (specificArgumentCounts[expectedSignature] || 0) > 0;
    };
    trackerFunction.invocationCount = (expectedCount) => invocationCounter === expectedCount;
    trackerFunction.invokedWithCount = (expectedArgs, expectedCount) => {
        const expectedSignature = JSON.stringify(expectedArgs);
        return (specificArgumentCounts[expectedSignature] || 0) === expectedCount;
    };
    trackerFunction.resetTracker = () => {
        callRecords = [];
        invocationCounter = 0;
        specificArgumentCounts = {};
    };
    return trackerFunction;
}

let DOMModifierSimulator = null;
let ElementStyleManager = null;
let GeometryProcessingUnit = null;

function initializeTestEnvironment() {
    DOMModifierSimulator = {
        fetchElement: createActionTracker(),
        setProperties: createActionTracker(),
        currentQuery: ''
    };
    DOMModifierSimulator.fetchElement.chainedReference = DOMModifierSimulator;

    ElementStyleManager = {
        applyStyle: createActionTracker()
    };

    const DOMConstructor = function(initialQuery) {
        DOMModifierSimulator.currentQuery = initialQuery;
        return DOMModifierSimulator;
    };

    GeometryProcessingUnit = {
        useRelativeUnitMode: false,
        elementRef: ElementStyleManager,
        domCreatorRef: DOMConstructor,
        vectorPathID: 'autoGeneratedVectorPathID',
        initialCoordinates: [
            [3, 2],
            [6, 7]
        ]
    };
}

const valueTransformationRules = {
    'withUnit_isRelative': (val) => (Math.abs(val) < Number.EPSILON) ? 0 : `${val}%`,
    'noUnit_isRelative': (val) => (Math.abs(val) < Number.EPSILON) ? 0 : val / 100,
    'withUnit_isAbsolute': (val) => (Math.abs(val) < Number.EPSILON) ? 0 : `${val}px`,
    'noUnit_isAbsolute': (val) => (Math.abs(val) < Number.EPSILON) ? 0 : val
};

function formatNumericCoordinate(value, addUnitSuffix, interpretAsPercentage) {
    const key = `${addUnitSuffix ? 'withUnit' : 'noUnit'}_${interpretAsPercentage ? 'isRelative' : 'isAbsolute'}`;
    return valueTransformationRules[key](value);
}

function assembleCoordinateString(vertexArray, addUnitSuffix, interpretAsPercentage) {
    return vertexArray.map(coordPair =>
        `${formatNumericCoordinate(coordPair[0], addUnitSuffix, interpretAsPercentage)} ${formatNumericCoordinate(coordPair[1], addUnitSuffix, interpretAsPercentage)}`
    ).join(', ');
}

function generateSVGClipDefinition(pointsToRender) {
    const vectorID = GeometryProcessingUnit.vectorPathID;
    const constructedDOM = GeometryProcessingUnit.domCreatorRef(`#${vectorID}`);
    constructedDOM.fetchElement(`polygon`);
    constructedDOM.setProperties(`points`, assembleCoordinateString(pointsToRender, false, GeometryProcessingUnit.useRelativeUnitMode));
    GeometryProcessingUnit.elementRef.applyStyle('clip-path', `url(#${vectorID})`);
}

function generateWebkitClipDefinition(pointsToRender) {
    const declarationText = `polygon(${assembleCoordinateString(pointsToRender, true, GeometryProcessingUnit.useRelativeUnitMode)})`;
    GeometryProcessingUnit.elementRef.applyStyle('-webkit-clip-path', declarationText);
}


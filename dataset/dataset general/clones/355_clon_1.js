( function ()
{

  // Verify browser and necessary objects for functionality.
  // This script is specifically designed for Google Chrome and relies on `window.console`.
  if ( ! window.chrome || ! window.console )
  {
    // If conditions are not met, alert the user and terminate execution.
    return ( ( window.console && console.log ) || alert ) ( 'Chrome Inspector Helpers only supported in Google Chrome.' ) ;
  }


  // Ensure the `window.chrome.inspector` object exists, creating it if necessary.
  window.chrome.inspector = window.chrome.inspector || { } ;



  /*
   * Detailed explanation of the console logging workaround:
   *
   * When `console.profile()` is executed (a common technique to detect if the Chrome Inspector is open),
   * WebKit browsers, including Chrome, output a message to the console log.
   * This behavior can clutter the console, especially during repeated checks.
   *
   * To mitigate this, a workaround involves using `console.groupCollapsed()`.
   * Messages generated by `console.profile()` are then collected within this collapsed group,
   * keeping the main console log clean.
   * (Reference: https://developer.mozilla.org/en-US/docs/Web/API/console/groupCollapsed)
   *
   * A challenge arises because external code might also log to the console, and we want
   * those messages to remain visible and not be hidden within our collapsed group.
   *
   * The solution implemented below tracks whether a collapsed group is currently active (`groupActive`).
   * We then decorate (override) the standard `console` logging methods (e.g., `log`, `info`, `warn`, `error`)
   * as well as `group`, `groupCollapsed`, and `groupEnd`.
   *
   * The decoration ensures that if a collapsed group is active when one of these methods is called,
   * `console.groupEnd()` is automatically invoked first to close the active group.
   * This allows subsequent log messages or new groups to appear outside of our hidden detection group.
   *
   * This strategy balances the need for a clean console during detection with the requirement
   * for normal console output from other parts of the application.
   */

  // Declare variables used throughout the script.
  var logMethods , // Array of standard console logging methods to override.
      origGroupEnd , // Stores the original `console.groupEnd` method.
      groupActive , // Boolean flag: `true` if a collapsed group for detection is open.
      origGroupCollapsed , // Stores the original `console.groupCollapsed` method.
      groupMethods , // Array of console grouping methods to override.
      isOpen , // Function to check if the inspector is open.
      isDocked // Function to check if the inspector is docked.
  ;

  // Initialize variables.
  logMethods = [ 'info' , 'warn' , 'log' , 'debug' , 'error' ] ;
  origGroupEnd = console.groupEnd ;
  groupActive = false ;


  // Iterate over each standard logging method to wrap it.
  logMethods . forEach ( function ( method )
  {
    var orig = console[ method ] ; // Store the original console method.

    // Override the console method.
    console[ method ] = function ()
    {
      // If a detection group is active, close it before logging.
      if ( groupActive )
      {
        origGroupEnd . apply ( console ) ; // Call the original groupEnd.
        groupActive = false ; // Reset the flag.
      }
      // Call the original logging method with its arguments.
      return orig . apply ( console , arguments ) ;
    } ;
  } ) ;


  // Store the original `console.groupCollapsed`.
  origGroupCollapsed = console.groupCollapsed ;
  // Define methods related to grouping.
  groupMethods = [ 'group' , 'groupCollapsed' ] ;


  // Iterate over grouping methods to wrap them.
  groupMethods . forEach ( function ( method )
  {
    var orig = console[ method ] ; // Store the original grouping method.

    // Override the console grouping method.
    console[ method ] = function ()
    {
      // If a detection group is active, close it first.
      if ( groupActive )
      {
        origGroupEnd . apply ( console ) ; // Close the detection group.
        groupActive = false ; // Reset the flag.
      }
      // Call the original grouping method.
      orig . apply ( console ) ;
    } ;
  } ) ;


  // Override `console.groupEnd` to ensure proper handling of the detection group.
  console . groupEnd = function ()
  {
    // If the detection group is active, close it.
    if ( groupActive )
    {
      origGroupEnd . apply ( console ) ;
      groupActive = false ;
    }
    // Always call the original `groupEnd` for any other groups.
    origGroupEnd . apply ( console ) ;
  } ;


  // Function to determine if the Chrome Inspector is currently open.
  isOpen = function ()
  {
    // Utilize the `console.profile` method for detection.
    // Reference: http://stackoverflow.com/a/15567735/131898
    var existingProfiles = console . profiles . length ;

    // If no detection group is currently active, start one.
    if ( ! groupActive )
    {
      groupActive = true ; // Set the flag.
      origGroupCollapsed . apply ( console ) ; // Open a collapsed group.
    }

    // Start and immediately end a profile.
    console . profile ( 'Inspector Detector' ) ;
    console . profileEnd ( ) ;

    // If a new profile was added, the inspector is open.
    if ( console . profiles . length > existingProfiles )
    {
      return true ;
    }

    // Otherwise, it is not open.
    return false ;
  } ;


  // Account for potential height offsets from the omnibar and bookmarks bar.
  // This value can be customized via `window.chrome.inspector._windowHeightOffset`.
  // Reference: http://stackoverflow.com/a/7530254/131898
  // Currently, it always uses the profile test result, but future versions might offer more configurability.
  if ( window . chrome . inspector . _windowHeightOffset === undefined )
    window . chrome . inspector . _windowHeightOffset = ( isOpen ( ) ? 200 : window . outerHeight - window . innerHeight ) ;


  // Function to determine if the Chrome Inspector is docked (attached to the browser window).
  isDocked = function ()
  {
    // Calculate the zoom level of the document.
    var zoom = document . width / ( document . body . clientWidth + parseInt ( getComputedStyle ( document . body ) [ 'margin-left' ] , 10 ) + parseInt ( getComputedStyle ( document . body ) [ 'margin-left' ] , 10 ) ) ;

    // Attempt to detect docking by comparing inner and outer window dimensions.
    // If the outer dimensions significantly exceed the inner dimensions (accounting for zoom and offset),
    // it suggests the inspector is docked.
    if ( window . outerHeight > 1 + Math . ceil ( ( zoom * window . innerHeight ) + window . chrome . inspector . _windowHeightOffset ) ||
         window . outerWidth > 1 + Math . ceil ( zoom * window . innerWidth ) )
    {
      return true ; // Inspector is docked.
    }

    return false ; // Inspector is not docked.
  } ;


  // The main detector function, exposed via `window.chrome.inspector.detector`.
  window . chrome . inspector . detector = function ( )
  {
    var state ; // Object to hold the current state.

    state = { } ;
    state . open = isOpen ( ) ; // Check if inspector is open.
    state . docked = state . open && isDocked ( ) ; // Check if docked only if open.

    return state ; // Return the state object.
  } ;


  // Provide a mechanism to continuously watch for changes in the inspector's state.
  // When a change is detected, `options.callback` is invoked with `(newState, previousState)`.
  window . chrome . inspector . detector . watch = function ( options )
  {
    var interval , // The polling interval in milliseconds.
        check , // The function executed at each interval.
        intervalId , // The ID returned by `setInterval`, used for stopping.
        chain , // Object returned to the user for controlling the watch.
        prevState , // Stores the state from the previous check.
        isEqual ; // Helper function to compare two state objects.

    interval = options . interval || 100 ; // Default interval is 100ms.

    // Ensure a callback is provided.
    if ( ! options )
    {
      console . log ( 'Chrome Inspector Detector watch call requires a callback.' ) ;
      return ;
    }

    // Allow direct function passing for callback.
    if ( typeof options === 'function' )
    {
      options = {
        callback : options
      } ;
    }

    // The 'chain' object provides a `stop` method to halt the monitoring.
    chain = {
      stop : function ( )
      {
        clearInterval ( intervalId ) ; // Clear the interval to stop watching.
      }
    } ;


    // Helper function to compare two state objects for equality.
    isEqual = function ( stateA , stateB )
    {
      var testA , testB ;

      // If types are different or they are primitive but not equal, return false.
      if ( ( typeof stateA != 'object' || typeof stateB != 'object' ) && stateA != stateB )
      {
        return false ;
      }

      // Compare properties of stateA against stateB.
      for ( testA in stateA )
      {
        if ( ! stateA . hasOwnProperty ( testA ) )
          continue ; // Skip inherited properties.

        for ( testB in stateB )
        {
          if ( ! stateB . hasOwnProperty ( testB ) )
            continue ; // Skip inherited properties.

          // If any corresponding property values differ, states are not equal.
          if ( stateA [ testA ] !== stateB [ testB ] )
            return false ;
        }
      }

      return true ; // States are considered equal.
    } ;


    // The core checking function, executed periodically.
    check = function ( )
    {
      var newState ; // Variable to store the state from the current check.

      newState = window . chrome . inspector . detector ( options ) ; // Get the current inspector state.

      // If the new state is different from the previous state, invoke the callback.
      if ( ! isEqual ( prevState , newState ) )
      {
        options . callback . call ( chain , newState , prevState ) ;
      }

      prevState = newState ; // Update previous state for the next check.
    } ;

    check ( ) ; // Perform an initial check immediately.

    intervalId = setInterval ( check , interval ) ; // Start the periodic checking.

    return chain ; // Return the control object to the caller.
  } ;

} ) ( ) ;
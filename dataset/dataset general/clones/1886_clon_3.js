'use strict'; // Enforce strict mode for the entire module.

// This module provides a configuration function for a build automation tool.
// It sets up various tasks for development, testing, and release artifact generation.
module.exports = function (buildTool) {

  // Automatically load all Grunt tasks defined in `package.json` dependencies.
  // This simplifies task management by removing the need for explicit `buildTool.loadNpmTasks` calls.
  require('load-grunt-tasks')(buildTool);

  // Define key configuration paths and file groups for better maintainability.
  const artifactOutputFolder = 'production_build'; // The target directory for all generated files.
  const primarySourceFiles = [ // Core application JavaScript files.
    'source/deferred-bootstrap.js'
  ];
  const validationTestFiles = ['verification/**/*.js']; // JavaScript files containing unit tests.

  // Initialize the build tool's configuration object.
  buildTool.initConfig({

    // Retrieve detailed information about the application from `package.json`.
    appDetails: buildTool.file.readJSON('package.json'),

    // Configure the active localization setting.
    // Defaults to 'en-US' but can be overridden via the `--locale` command-line option.
    currentLocaleSetting: buildTool.option('locale') || 'en-US',

    // Define metadata to be used in generated file headers.
    headerData: {
      // Construct the banner string using application details and the current build timestamp.
      outputHeaderString: '/*\n' +
        ' * <%= appDetails.title || appDetails.name %> - v<%= appDetails.version %> - ' +
        'Build Timestamp: <%= buildTool.template.today("yyyy-mm-dd HH:MM:ss") %>\n' +
        ' * Project Homepage: <%= appDetails.homepage %>\n' +
        ' * Copyright (c) <%= buildTool.template.today("yyyy") %> <%= appDetails.author.name %>\n' +
        ' * License Information: <%= appDetails.license %>\n' +
        ' * (This file is automatically generated by the build process. Please do not modify manually.)\n */\n'
    },

    // Specify the designated directory for all final build artifacts.
    outputDirectory: artifactOutputFolder,

    // Define logical groupings of source files for various build operations.
    sourceAssetGroups: {
      applicationSources: primarySourceFiles, // Main application code.
      unitTestFiles: validationTestFiles // Files specifically for unit testing.
    },

    // Set up file system watchers to automatically trigger tasks upon file changes during development.
    fileChangeMonitor: {

      // Watch for changes in Gruntfile, application sources, and test files.
      // Triggers full code quality scan and standard unit tests.
      devScriptWatch: {
        files: ['Gruntfile.js', '<%= sourceAssetGroups.applicationSources %>', '<%= sourceAssetGroups.unitTestFiles %>'],
        tasks: ['codeQualityChecker:fullScan', 'testExecutor:standardUnit']
      },

      // Watch for changes in source files and trigger live browser reloading.
      // Also performs linting, unit tests, and concatenates files.
      liveBrowserRefresh: {
        options: {
          livereload: true
        },
        files: ['source/**/*.js'], // Monitors all JS files within the 'source' directory.
        tasks: ['codeQualityChecker', 'testExecutor:standardUnit', 'fileAggregator:mainBundle']
      }
    },

    // Configure JavaScript static code analysis using JSHint.
    codeQualityChecker: {

      // Global JSHint options, typically loaded from a `.jshintrc` file.
      globalOptions: {
        jshintrc: true
      },

      // Perform a comprehensive scan across all relevant JavaScript files.
      fullScan: {
        src: ['Gruntfile.js', '<%= sourceAssetGroups.applicationSources %>', '<%= sourceAssetGroups.unitTestFiles %>']
      },

      // Validate only the application's core source code.
      appCodeValidation: {
        files: {
          src: ['<%= sourceAssetGroups.applicationSources %>']
        }
      },

      // Validate only the unit test files.
      testCodeValidation: {
        files: {
          src: ['<%= sourceAssetGroups.unitTestFiles %>']
        }
      }
    },

    // Configure a local development web server.
    developmentWebServer: {
      webServiceInstance: {
        options: {
          serverPort: 3005, // Port on which the server will listen.
          baseDirectories: '.', // Directory to serve files from.
          serverScriptPath: __dirname + '/server.js' // Path to the Node.js server script.
        }
      }
    },

    // Concatenate various JavaScript files into single bundles.
    fileAggregator: {
      // The main application bundle, including the header and prefix/suffix files.
      mainBundle: {
        src: [
          'source/deferred-bootstrap.prefix',
          '<%= headerData.outputHeaderString %>', // Inject the generated header string directly.
          '<%= sourceAssetGroups.applicationSources %>',
          'source/deferred-bootstrap.suffix'
        ],
        dest: '<%= outputDirectory %>/app-bootstrap-bundle.js' // Destination for the combined bundle.
      },

      // An additional bundle for debugging purposes, without minification.
      debugBundle: {
        src: [
          'source/deferred-bootstrap.prefix',
          '<%= sourceAssetGroups.applicationSources %>',
          'source/deferred-bootstrap.suffix'
        ],
        dest: '<%= outputDirectory %>/app-bootstrap-bundle-debug.js'
      }
    },

    // Minify JavaScript files to reduce their size for production.
    scriptOptimizer: {
      minifyBundle: {
        files: {
          '<%= outputDirectory %>/app-bootstrap-bundle.min.js': '<%= fileAggregator.mainBundle.dest %>' // Minify the main concatenated bundle.
        }
      }
    },

    // Configure the Karma test runner for various unit testing scenarios.
    testExecutor: {
      // Common configuration options for all Karma tasks.
      commonKarmaConfig: {
        configFile: 'karma.conf.js',
        // 'singleRun' and 'browsers' will be set by individual sub-tasks.
      },

      // Standard unit tests, typically run in a headless browser (PhantomJS).
      standardUnit: {
        options: {
          singleRun: true,
          browsers: ['PhantomJS']
        }
      },

      // Unit tests specifically executed in the Chrome browser.
      chromeIntegration: {
        options: {
          singleRun: true,
          browsers: ['Chrome']
        }
      },

      // Unit tests specifically executed in the Firefox browser.
      firefoxIntegration: {
        options: {
          singleRun: true,
          browsers: ['Firefox']
        }
      },

      // Interactive debug mode for unit tests, keeps browser open.
      interactiveDebug: {
        options: {
          singleRun: false,
          browsers: ['Chrome'] // Default to Chrome for easier debugging.
        }
      }
    },

    // Task to clean the build output directory before a new build.
    clean: {
      dist: ['<%= outputDirectory %>/*'] // Deletes all contents within the output folder.
    }
  });

  // Dynamically merge common Karma configuration with specific task options.
  // This ensures all test tasks inherit the base config while allowing overrides.
  Object.keys(buildTool.config.get('testExecutor')).forEach(function(taskKey) {
    if (taskKey !== 'commonKarmaConfig') {
      const specificConfig = buildTool.config.get(`testExecutor.${taskKey}`);
      const baseConfig = buildTool.config.get('testExecutor.commonKarmaConfig');
      // Use Grunt's utility for deep merging, allowing specific options to override common ones.
      buildTool.config.set(`testExecutor.${taskKey}`, buildTool.util._.extend(true, {}, baseConfig, specificConfig.options));
    }
  });


  // --- Task Registration Definitions ---

  // Register the initial development task, performing basic checks and unit tests.
  buildTool.registerTask('initDev', [
    'codeQualityChecker:fullScan',
    'testExecutor:standardUnit'
  ]);

  // Task to explicitly run the standard unit tests.
  buildTool.registerTask('runUnitTests', ['testExecutor:standardUnit']);

  // Specialized testing tasks for different browser environments.
  buildTool.registerTask('runChromeTests', ['testExecutor:chromeIntegration']);
  buildTool.registerTask('runFirefoxTests', ['testExecutor:firefoxIntegration']);
  buildTool.registerTask('runAllTests', ['testExecutor']); // Runs all configured Karma tasks.

  // The comprehensive build task for generating release artifacts.
  // This includes cleaning, code quality checks, testing, concatenation, and minification.
  buildTool.registerTask('createReleaseArtifacts', [
    'clean:dist', // Start by clearing previous build outputs.
    'codeQualityChecker:fullScan',
    'testExecutor:standardUnit',
    'fileAggregator:mainBundle', // Combine main application files.
    'scriptOptimizer:minifyBundle' // Minify the final bundle.
  ]);

  // Development workflow task: linting, testing, concatenating, and live reloading.
  buildTool.registerTask('startDevelopmentFlow', [
    'codeQualityChecker', // Runs all configured JSHint tasks.
    'testExecutor:standardUnit',
    'fileAggregator:mainBundle',
    'fileChangeMonitor:liveBrowserRefresh' // Activate the live reload watcher.
  ]);

  // Task to launch the local development web server.
  buildTool.registerTask('launchServer', [
    'developmentWebServer',
    'express-keepalive' // Keeps the Express server running indefinitely.
  ]);

  // A custom task that prepares the build environment and then launches the server.
  buildTool.registerTask('prepareAndServe', [
    'clean:dist',
    'codeQualityChecker:fullScan',
    'testExecutor:standardUnit',
    'fileAggregator:mainBundle',
    'launchServer'
  ]);

  // Set 'initDev' as the default task to run when `grunt` is executed without arguments.
  buildTool.registerTask('default', ['initDev']);
};
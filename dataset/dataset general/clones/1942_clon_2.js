(function() {
  "use strict";

  function configureSystem() {
    // Private utility functions and variables for the module.
    var _spawnCore; // Holds the currently active entity spawning mechanism.

    // A reliable method to check for direct own properties.
    var _hasOwnProperty = Object.prototype.hasOwnProperty;

    // Retrieves the prototype of an object.
    var _fetchPrototype = Object.getPrototypeOf;

    // Defines a new or modifies an existing property on an object.
    var _defineProperty = Object.defineProperty;

    // Fallback for Object.create in environments lacking native support (e.g., ES3).
    var _objectCreationFallback = function(prototypeObject) {
      function TempCtor() {}
      TempCtor.prototype = prototypeObject;
      return new TempCtor();
    };

    // The default prototype/behavior for new entities generated by 'spawn.create()'.
    var _basePrototypeForNewInstances;

    // Function to dynamically select the most performant spawning method through benchmarking.
    function _determineSpawnMethodByBenchmark() {
      // In a real-world scenario, this function would execute performance tests
      // to identify the fastest available spawning technique and assign it to _spawnCore.
      // For demonstration, we'll just set a default.
      _spawnCore = _spawnViaPrototype; // Example: assuming __proto__ method is often fastest.
    }

    /**
     * @namespace
     *
     * spawn.js - A robust prototype-based lazy initialization framework.
     *
     * <h3>
     *   Naming Guidelines
     * </h3><pre>
     *   $$property  - $$ prefix to prevent accidental name conflicts.
     *   object$$    - $$ postfix indicates a prototype (e.g., Entity.prototype === object$$).
     *   Entity      - Represents a class or type.
     *   _internalVar - Variable used within closures.
     * </pre>
     *
     * @version v1.3.2-alpha
     * @author  Alex Shvets
     * @see     www.clonejs.org
     *
     * @borrows _private._spawnViaPrototype       as viaPrototype
     * @borrows _private._spawnViaObjectCreate    as viaObjectCreate
     * @borrows _private._spawnViaConstructor     as viaConstructor
     *
     * @function
     * @description
     *
     * Generates a new entity, inheriting from another entity (its prototype).
     * Behaves similarly to {@link Entity.create}, but the second argument is a simple object,
     * not a [propertyDescriptor](_global_.html#propertyDescriptor).
     * It should strictly be an object record. However, if flexibility is truly needed,
     * the rule can be relaxed to:
     * *External usage of the second argument after spawning should only access its own properties.*
     * The `spawn()` function might modify its `config` argument due to `__proto__` assignment side effects.
     * This rule ensures consistency with other creation methods: by constructor and `Object.create`.
     *
     * It's not named as a class (noun: `new Spawner`), because
     * it primarily functions as a verb: `spawn(something)`.
     *
     * @param  baseObj - The entity to be cloned. Its prototype. If a function is passed, its prototype property will be used.
     * @param  config  - The own properties for the newly created entity. This should be an object record only
     *                   (e.g., `{ key: "value" }`), as it might be altered.
     *                   Defaults to an empty object (`{}`).
     * @returns {Object} A new object inheriting from `baseObj`.
     */
    function spawn(/** !Object|EntityType */baseObj, /** !ObjRecord={} */config) {
      // If the 'new' operator were used (commented out logic):
      // if ( this && this instanceof spawn ) {
      //   config = arguments[0];
      //   baseObj = spawn.blueprint;
      //   if ( !config ) {
      //     return this;
      //   }
      // }
      if (typeof baseObj === 'function') baseObj = baseObj.prototype;
      if (typeof config === 'undefined') config = {};
      // End of argument processing

      // Check if the base object has a custom spawning mechanism different from the default.
      if (typeof baseObj.$$spawn === 'function' && baseObj.$$spawn !== spawn.blueprint.$$spawn) {
        return baseObj.$$spawn(config);
      } else {
        return _spawnCore(baseObj, config);
      }
    }

    /** @private */
    // Helper functions for internal use.

    /**
     * The most efficient entity creation technique (excluding subsequent calls to `_spawnViaConstructor()`).
     * Utilizes direct __proto__ assignment.
     */
    function _spawnViaPrototype(/** Object */baseObj, /** !ObjRecord */config) {
      config.__proto__ = baseObj;
      return config;
    }

    /**
     * This technique should be employed only if `_spawnViaPrototype()` is not feasible.
     * Relies on `Object.create()`.
     */
    function _spawnViaObjectCreate(/** Object */baseObj, /** ObjRecord= */config) {
      var newEntity = Object.create(baseObj);
      for (var propKey in config) {
        if (_hasOwnProperty.call(config, propKey)) {
          newEntity[propKey] = config[propKey];
        }
      }
      return newEntity;
    }

    /**
     * This creation technique is initially slower but dynamically generates an optimized `$$spawn` method
     * that can become the fastest for subsequent instances. Ideal for scenarios requiring numerous instances.
     */
    function _spawnViaConstructor(/** !Object */baseObj, /** ObjRecord= */config) {

      // TODO: This logic partially duplicates spawn()'s initial check; consider refactoring for reusability.
      if (typeof baseObj.$$spawn === 'function' && baseObj.$$spawn !== spawn.blueprint.$$spawn) {
        return baseObj.$$spawn(config);
      }

      // Ensure the base object has a constructor property, falling back to a default if missing.
      if (!_hasOwnProperty.call(baseObj, 'constructor')) {
        baseObj.constructor = _InstanceMaker;
      }

      function _InstanceMaker(instanceConfig) {
        for (var propKey in instanceConfig) {
          if (_hasOwnProperty.call(instanceConfig, propKey)) {
            this[propKey] = instanceConfig[propKey];
          }
        }
      }
      _InstanceMaker.prototype = baseObj;

      /** @override */
      // Once optimized, this custom $$spawn function will be used for future creations.
      baseObj.$$spawn = function(instanceConfig) {
        return new _InstanceMaker(instanceConfig);
      };

      return new _InstanceMaker(config);
    }

    /**
     * Transforms a {@link traitConfiguration} into a canonical behavior object.
     * If a behavior object is already provided, it is returned without modification.
     * @returns {spawn.trait$$} The managed behavior object.
     */
    function _BehaviorManager(/** !traitConfiguration|spawn.trait$$ */traitConfig) {

      // Check if the input is already a managed behavior instance.
      if (traitConfig instanceof _BehaviorManager) {
        return traitConfig;
      }

      // Process $$inheritsFrom property
      if (_hasOwnProperty.call(traitConfig, '$$inheritsFrom')) {
        var baseTrait = traitConfig.$$inheritsFrom;
        // If the inherited trait itself needs processing or is not canonical.
        if (!_hasOwnProperty.call(baseTrait, '$$inheritsFrom') || _fetchPrototype(baseTrait) != baseTrait.$$inheritsFrom) {
          baseTrait = _BehaviorManager(baseTrait);
        }
      } else {
        baseTrait = _basePrototypeForNewInstances; // Default inheritance
      }

      // Process $$lazyInitializers and $$defaultValues
      var lazyInitializers = traitConfig.$$lazyInitializers;

      var defaultValues = traitConfig.$$defaultValues || (lazyInitializers && {});
      if (defaultValues && _fetchPrototype(defaultValues) !== baseTrait) {
        defaultValues = _spawnCore(baseTrait, defaultValues);
        _defineProperty(traitConfig, '$$defaultValues', {
          value: defaultValues
        });
        // _sealObject(defaultValues); // Optional: seal defaults
        var currentPrototype = defaultValues;
      } else {
        currentPrototype = baseTrait;
      }

      // Apply lazy initializers
      if (lazyInitializers) {
        for (var propKey in lazyInitializers) {
          if (_hasOwnProperty.call(lazyInitializers, propKey)) {
            spawn.setLazyProperty(
              defaultValues,
              propKey,
              lazyInitializers[propKey], {
                configurable: true
              }, // Descriptor for the initial getter
              {
                configurable: true,
                writable: true,
                enumerable: true
              } // Descriptor for the actual property
            );
          }
        }
        // delete traitConfig.$$lazyInitializers; // Original code commented out similar line
      }

      // Ensure the traitConfig itself inherits from the correct prototype
      // if (defaultValues) _sealObject(defaultValues); // Optional: seal defaults

      if (_fetchPrototype(traitConfig) !== currentPrototype) {
        traitConfig = _spawnCore(currentPrototype, traitConfig);
      }

      // Re-define $$inheritsFrom if it was processed or changed
      if (baseTrait !== traitConfig.$$inheritsFrom) {
        _defineProperty(traitConfig, '$$inheritsFrom', {
          value: baseTrait
        });
      }

      // Ensure constructor's prototype points to this behavior
      if (_hasOwnProperty.call(traitConfig, 'constructor') && traitConfig.constructor.prototype !== traitConfig) {
        traitConfig.constructor.prototype = traitConfig;
      }

      // _sealObject(traitConfig); // Optional: seal behavior
      return traitConfig;
    }

    var prototypeFeatureAvailable = '__proto__' in {};

    if (prototypeFeatureAvailable) {
      spawn.MapCollection = function MapCollection_viaProto(/** !ObjRecord= */inputData) {
        if (inputData === undefined) {
          inputData = {};
        } // End of arguments processing
        inputData.__proto__ = null; // Set prototype to null for a pure dictionary
        return inputData;
      };
    } else {
      /**
       * Creates objects with only own properties, effectively having a `null` prototype.
       * Can also be achieved using `Object.create(null)`.
       * Why use this? Consider the following examples:
       * @example
       * /// Scenario 1 ///////////////////////////////////////////////////////
       *
       *     // A simple phone book
       *     var contactList = {
       *       'John': '+1234567',
       *       'Jane': '+9876543'
       *     };
       *     function findContact(personName) {
       *       if (personName in contactList) return contactList[personName];
       *       else return undefined;
       *     }
       *     console.log(findContact('John'));          // => '+1234567'
       *     console.log(findContact('toString'));      // => function toString() { [native code] } (Unexpected!)
       *
       * /// Scenario 2 ///////////////////////////////////////////////////////
       *
       *     var contactList = {
       *       'John': '+1234567',
       *       'Jane': '+9876543'
       *     };
       *     function findContact(personName) {
       *       if (contactList.hasOwnProperty(personName)) return contactList[personName];
       *       else return undefined;
       *     }
       *     console.log(findContact('John'));          // => '+1234567'
       *     contactList['hasOwnProperty'] = '+1111111'; // Adding a contact with a problematic name
       *     console.log(findContact('hasOwnProperty'));// => '+1111111' (Still an issue if you expect the method)
       *
       * /// Scenario 3 ///////////////////////////////////////////////////////
       *
       *     var contactList = {
       *       'John': '+1234567',
       *       'Jane': '+9876543'
       *     };
       *     function findContact(personName) {
       *       if (Object.prototype.hasOwnProperty.call(contactList, personName)) return contactList[personName];
       *       else return undefined;
       *     }
       *     console.log(findContact('John'));          // => '+1234567'
       *     contactList['hasOwnProperty'] = '+1111111'; // Adding a contact
       *     console.log(findContact('hasOwnProperty'));// => '+1111111' (Correctly retrieves the new contact)
       *
       * /// Scenario 4 (using spawn.MapCollection)  ////////////////////////////
       *
       *     var contactList = spawn.MapCollection({
       *       'John': '+1234567',
       *       'Jane': '+9876543'
       *     });
       *     function findContact(personName) {
       *       return contactList[personName]; // No need for hasOwnProperty checks
       *     }
       *     console.log(findContact('John'));          // => '+1234567'
       *     contactList['hasOwnProperty'] = '+1111111'; // Adding a contact
       *     console.log(findContact('hasOwnProperty'));// => '+1111111' (Works as expected)
       *
       * @constructor
       * @typedef object
       * @returns {spawn.MapCollection}
       */
      spawn.MapCollection = function MapCollection_viaCreate(/** !ObjRecord= */inputData) {
        var collection = (Object.create || _objectCreationFallback)(null);
        for (var propKey in inputData) {
          if (_hasOwnProperty.call(inputData, propKey)) {
            collection[propKey] = inputData[propKey];
          }
        }
        return collection;
      };
    }
    spawn.MapCollection.prototype = null; // Emphasizes the 'null' prototype ideology.

    // // // // // // // // // // // // // // // // // // // // // // // // // //
    // Public Static Methods of the framework:

    /**
     * Generates a new entity, either based on `[spawn.blueprint]{@link spawn.blueprint}` or a provided {@link traitConfiguration}.
     * @returns {Object} A new object instance.
     */
    spawn.create = function(/** !ObjRecord={} */initialConfig, /** !traitConfiguration=spawn.blueprint */targetTrait) {
      if (arguments.length === 0) {
        // Direct 'new' operator usage is often faster than the spawn function itself.
        return new _basePrototypeForNewInstances.constructor();
      } else {
        targetTrait = targetTrait ? _BehaviorManager(targetTrait) : _basePrototypeForNewInstances;
        return spawn(targetTrait, initialConfig);
      }
    };

    /**
     * Constructs a new [behavior object]{@link spawn.trait$$}.
     * @returns {spawn.trait$$} A new behavior instance.
     */
    spawn.enhance = function(/** EntityType|!Object=spawn.blueprint */sourcePrototype, /** !traitConfiguration|spawn.trait$$ */newTrait) {
      if (typeof sourcePrototype === 'function') {
        sourcePrototype = sourcePrototype.prototype;
      }
      if (newTrait === undefined) {
        newTrait = sourcePrototype;
        // sourcePrototype = _basePrototypeForNewInstances; // Original commented line
      } else {
        newTrait.$$inheritsFrom = sourcePrototype;
      } // End of arguments processing
      return _BehaviorManager(newTrait);
    };

    spawn.setLazyProperty = function(
      /** object */targetObject,
      /** string */propertyIdentifier,
      /** function():* */valueProducer,
      /** PropertyDescriptor */propDescriptor,
      /** PropertyDescriptor */initializedDescriptor
    ) {
      // The original code had commented-out logic for default descriptors.
      // This implementation assumes 'propDescriptor' and 'initializedDescriptor' are provided or handled by _spawnCore.

      // Clone and augment the initial property descriptor with the lazy getter/setter.
      propDescriptor = _spawnCore(propDescriptor, {
        get: function spawn_initializerGetter() {
          // When accessed, this getter calls the valueProducer and sets the actual property.
          return (this[propertyIdentifier] = /* <- This assignment triggers the setter */ valueProducer.call(
            this,
            propertyIdentifier,
            initializedDescriptor
          ));
        },
        set: function spawn_initializerSetter(propValue) {
          initializedDescriptor.value = propValue;
          _defineProperty(this, propertyIdentifier, initializedDescriptor);
        }
      });
      _defineProperty(targetObject, propertyIdentifier, propDescriptor);
    };

    /**
     * Configures the entity spawning technique. Calling without arguments returns the currently active technique.
     * // TODO: Implement an 'onCompletion' callback mechanism.
     */
    spawn.method = function(/** (function|'auto'|'prototype'|'create'|'constructor')= */technique) {
      var availableMechanisms = spawn.MapCollection({
        prototype: _spawnViaPrototype,
        create: _spawnViaObjectCreate,
        constructor: _spawnViaConstructor
      });

      if ('function' === typeof technique) {
        _spawnCore = technique; // Directly set a custom spawning function.
      } else if (technique) {
        if (technique === 'auto') {
          setTimeout(_determineSpawnMethodByBenchmark, 0); // Asynchronously determine the best method.
        } else if (technique in availableMechanisms) {
          _spawnCore = availableMechanisms[technique]; // Select a predefined method.
        } else {
          throw new TypeError("Unrecognized spawning technique: " + technique);
        }
      } else {
        // If no technique is provided, return the name of the current active technique.
        for (var techniqueName in availableMechanisms) {
          if (_spawnCore === availableMechanisms[techniqueName]) {
            return techniqueName;
          }
        }
      }
    };

    // // // // // // // // // // // // // // // // // // // // // // // // // //
    // Core behavior for all entities generated by spawn.create:

    /**
     * @name spawn.blueprint
     * @class
     * The foundational prototype/behavior for all entities created via `{@link spawn.create}`.
     * An alias for `spawn.prototype`.
     */
    var blueprintDescriptor = /** @lands {spawn.blueprint#} */ {
      /** @memberOf spawn.blueprint# */

      $$inheritsFrom: Object.prototype,

      /**
       * Within this framework, constructors are optional. Entities can be defined without them.
       * Treat the constructor property as an initialization method:
       *
       *     // Define an entity type:
       *     var MyEntityType$$ = {
       *         constructor: function(paramA, paramB) {
       *             this.dataA = paramA;
       *             this.dataB = paramB;
       *         }
       *     };
       *
       *     // Create an instance:
       *     var _entityInstance = spawn(MyEntityType$$);
       *
       *     // Later, initialize the instance:
       *     function initLater() { _entityInstance.constructor(10, 20); }
       *
       *   This approach allows for creating uninitialized instances and setting them up later.
       *
       *   Note: Using the `new` operator with a defined constructor is typically 2-3 times faster
       *   than the `spawn` function. For generating thousands of instances, consider defining
       *   a constructor and using `new` directly instead of `spawn`.
       *
       * @returns {spawn.blueprint} The initialized instance.
       * @type EntityType
       * @field
       */
      constructor: function InstanceRoot() {},

      /**
       * Provides an object-oriented way to use the spawn function:
       * For example: `myObject.$$spawn()` is functionally equivalent to `spawn(myObject)`.
       * This method can be overridden. Unlike the `constructor`, `$$spawn` is purely a function
       * (its prototype property does not point back to this object). It should accept
       * only one argument: an {@link ObjRecord} for configuration.
       * @returns {spawn.blueprint} A new instance derived from this blueprint.
       */
      $$spawn: function(/** ObjRecord={} */config) {
        return _spawnCore(this, config || {});
      },

      /**
       * If invoked without arguments, it returns the entity's current state as a {@link spawn.KeyedCollection}.
       * @nosideeffects
       * @returns {spawn.KeyedCollection|*} The entity's state or a specific property value.
       */
      $$retrieve: function(/** string|Array= */itemKey) {
        var memberIdentifiers = typeof itemKey === 'object' && Array.isArray(itemKey) && itemKey;
        if (itemKey === undefined || memberIdentifiers) {
          var retrievedConfig = spawn.MapCollection();

          if (!memberIdentifiers) {
            memberIdentifiers = Object.getOwnPropertyNames(this);
          }
          for (var i = 0, limit = memberIdentifiers.length; i < limit; i++) {
            var memberName = memberIdentifiers[i],
              memberValue = this[memberName];
            retrievedConfig[memberName] = (typeof memberValue === 'function') ? memberValue.valueOf() : memberValue;
          }
          return retrievedConfig;
        } else {
          // Retrieve a specific property.
          return (typeof this[itemKey] === 'function') ? this[itemKey].valueOf() : this[itemKey];
        }
      },

      /**
       * Sets properties on the entity. Can take either an object record of properties
       * or a key-value pair.
       */
      $$assign: function(/** Object **/configOrKey, /** *= */assignValue) {
        if (assignValue === undefined) {
          // Assign multiple properties from an object record.
          for (var propKey in configOrKey) {
            if (_hasOwnProperty.call(configOrKey, propKey)) {
              this[propKey] = configOrKey[propKey];
            }
          }
        } else {
          // Assign a single key-value pair.
          this[configOrKey] = assignValue;
        }
      },

      /**
       * Iterates over the entity's own properties, executing a `processorFunction` for each.
       */
      $$iterate: function(/** function(*,string) */processorFunction, /** Object=this */executionScope) {
        if (executionScope === undefined) {
          executionScope = this;
        } // End of arguments processing
        for (var propKey in this) {
          if (_hasOwnProperty.call(this, propKey)) {
            processorFunction.call(executionScope, this[propKey], propKey);
          }
        }
      },

      /**
       * Creates a new entity by applying a `processorFunction` to each of this entity's own properties.
       * The new entity inherits from either `baseObject` or the current entity if `baseObject` is not provided.
       */
      $$transform: function(/** function(*,string):* */processorFunction, /** Object=this */executionScope, /** Object=this */baseObject) {
        if (executionScope === undefined) {
          executionScope = this;
        } // End of arguments processing
        var transformedObject = spawn(baseObject || this);
        for (var propKey in this) {
          if (_hasOwnProperty.call(this, propKey)) {
            transformedObject[propKey] = processorFunction.call(executionScope, this[propKey], propKey);
          }
        }
        return transformedObject;
      }

      /** @endof spawn.blueprint# */
    };

    /**
     * @name    spawn.trait$$
     * @extends spawn.blueprint
     * @class
     * The prototype for behavior objects. These `trait$$` objects resemble classes but are
     * **objects themselves, not functions**. Furthermore, **behaviors are designed to be immutable**
     * once created.
     *
     * @property {object.<string,*>} $$defaultValues
     *           A collection of default field values for entities adopting this trait.
     * @property {spawn.trait$$} $$inheritsFrom
     *           The parent behavior from which this trait derives. Analogous to a superclass.
     * @property {object.<string,function:*>} $$lazyInitializers
     *           A list of functions used for lazy initialization of specific fields.
     *
     * @borrows _private._BehaviorManager as #constructor
     */
    var traitDescriptor = {};

    // Initialize the primary spawning function based on __proto__ support.
    _spawnCore = prototypeFeatureAvailable ? _spawnViaPrototype : _spawnViaObjectCreate;

    // Assign the blueprint as the base prototype for all new instances.
    _basePrototypeForNewInstances = blueprintDescriptor;

    // Expose the main 'spawn' function globally (or within its module scope).
    // Assuming a global context for 'spawn' similar to 'clone' in the original.
    // If this is part of a larger module system (e.g., CommonJS, AMD),
    // the export mechanism would differ.
    if (typeof module !== 'undefined' && module.exports) {
      module.exports = spawn;
    } else if (typeof window !== 'undefined') {
      window.spawn = spawn;
    } else {
      // Fallback for other environments, e.g., web workers
      self.spawn = spawn;
    }
  }

  // Execute the system configuration.
  configureSystem();

})();
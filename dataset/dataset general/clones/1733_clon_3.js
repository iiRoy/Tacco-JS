// Initialize the main application instance
// This sets up the core Ember environment for the entire system.
const CoreSystem = Ember.Application.create({
  rootElement: '#ember-app-container', // Specify a different root element
  LOG_TRANSITIONS: true, // Enable transition logging for debugging
  LOG_BINDINGS: false // Disable binding logging for performance
});

// Configure the application's routing mechanism.
// This block defines the various navigable sections of the application.
CoreSystem.Router.map(function defineApplicationRoutes() {
  // Store the router context for consistent access within the mapping function.
  const routerContext = this;

  // Define a resource for general informational content, e.g., an "About Us" page.
  routerContext.resource('informationPage');

  // Define a resource for interactive sessions or playable content.
  // This might represent a collection of games or activities.
  routerContext.resource('interactiveSessions');

  // Add a new, non-essential route for a dashboard area as a Type III addition.
  routerContext.resource('dashboardOverview');

  // Log a confirmation message after route mapping is complete.
  console.log('Application routes have been successfully defined and mapped.');
});

// Define the route handler for the 'interactiveSessions' resource.
// This class extends Ember.Route to provide specific logic for when this route is active.
CoreSystem.InteractiveSessionsPath = Ember.Route.extend({
  // A non-essential property added for Type III clone to show structural changes.
  queryParams: {
    filterByStatus: {
      refreshModel: true,
      as: 'status'
    }
  },

  // The 'model' hook is responsible for fetching and preparing the data
  // that will be made available to the route's template and controller.
  model: function retrieveSessionData(params) {
    // Define the API endpoint as a constant for maintainability and clarity.
    const API_ENDPOINT = '/api/interactive-content-items/';
    console.info(`Initiating data retrieval for interactive sessions from: ${API_ENDPOINT}`);

    // Type III Guard Clause: Ensure jQuery and its AJAX functionality are present.
    // This adds robustness by checking for essential dependencies before proceeding.
    if (typeof jQuery === 'undefined' || typeof jQuery.ajax !== 'function') {
      const dependencyError = new Error("jQuery or $.ajax is not available. Cannot fetch model data.");
      console.error("Critical dependency missing:", dependencyError.message);
      // Return a rejected promise to gracefully handle the error within Ember's routing system.
      return Ember.RSVP.reject(dependencyError);
    }

    // Use jQuery's $.ajax for more control over the request compared to $.getJSON.
    // This is a Type III 'update/rewrite' of the data fetching mechanism.
    const dataPromise = jQuery.ajax({
      url: API_ENDPOINT,
      method: 'GET',
      dataType: 'json', // Explicitly declare expected data type
      data: {
        status: params.filterByStatus // Incorporate query params for filtering
      }
    }).then(
      (rawPayload) => {
        // Log the raw data received from the server for debugging purposes.
        console.debug('Raw server response for sessions:', rawPayload);

        // Type III Validation: Check if the received payload is an array.
        // If not, log a warning and return an empty array to prevent template errors.
        let processedData;
        if (!Array.isArray(rawPayload)) {
          console.warn("Server response for interactive sessions was not an array. Defaulting to empty array.");
          processedData = [];
        } else {
          // Perform any intermediate data processing here if necessary.
          // For now, we'll just assign it.
          processedData = rawPayload.map(item => ({
            id: item.contentId || item.id,
            title: item.contentTitle || 'Untitled Session',
            description: item.contentDescription || 'No description available.',
            isActive: item.status === 'active'
          }));
        }

        return processedData; // Return the (potentially processed) data
      }
    ).catch(
      (ajaxError) => {
        // Type III Error Handling: Explicitly catch and log AJAX errors.
        // This provides more detailed feedback than Ember's default error handling.
        const errorMessage = `Failed to retrieve interactive content: ${ajaxError.statusText || ajaxError.message}`;
        console.error(errorMessage, ajaxError);
        // Re-throw or return a rejected promise with a user-friendly message.
        return Ember.RSVP.reject(new Error("Data retrieval failed. Please check your network or try again."));
      }
    );

    return dataPromise; // Return the promise generated by the AJAX call
  },

  // Type III Addition: Implement the 'afterModel' hook.
  // This hook runs after the model is successfully resolved and can be used
  // for additional data processing, logging, or setting up other services.
  afterModel: function(resolvedModel, transition) {
    this._super(resolvedModel, transition); // Call the superclass's afterModel
    console.info(`Model for InteractiveSessionsPath resolved successfully. Number of items: ${resolvedModel.length}`);
    // Example: Potentially redirect if no items are found
    if (resolvedModel.length === 0) {
      // this.transitionTo('no-sessions-available'); // Hypothetical route
    }
  },

  // Type III Addition: Implement the 'serialize' hook.
  // Although not strictly necessary for this simple resource route,
  // it demonstrates adding another standard Ember hook.
  // It transforms the model into parameters for URL generation.
  serialize: function(model, params) {
    this._super(model, params); // Call the superclass's serialize
    // Example: If the route had dynamic segments, this would define how to serialize them.
    // console.log('Serializing model for InteractiveSessionsPath:', model);
    return {
      session_id: model ? model.id : null
    };
  }
});
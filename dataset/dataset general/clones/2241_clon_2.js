Array.prototype.determineLongestStringLength = function() {
  var greatestLength = this[0].length;
  var arraySize = this.length;
  for (var iterIndex = 1; iterIndex < arraySize; iterIndex++) {
    if (this[iterIndex].length > greatestLength) greatestLength = this[iterIndex].length;
  }
  return greatestLength;
}


//
// Define the fretboardPattern class for musical chord representation
// Public attributes:
//  isRecognized           = indicates if a proper pattern is defined
//  isCagedConfiguration   = indicates if the pattern follows a CAGED structure
//  isUserConfigured       = indicates if the pattern is user-defined
//  completePatternName    = full pattern label, including position, e.g., D#m7:3
//  patternLabel           = pattern label, without position, e.g., D#m7
//  derivedBaseName        = normalized pattern label (B <-> #), without position, e.g., Ebm7
//  baseNoteIdentifier     = fundamental note, e.g., D#
//  baseModifier           = fundamental note extension, e.g., m7
//  cagedRootShape         = CAGED fundamental shape, e.g., D
//  cagedInitialFret       = CAGED starting fret, e.g., 0
//  cagedPositionIndex     = CAGED position index, e.g., 3
//

function fretboardPattern (inputPatternToken) {

  this.musicalScale = stringedInstrumentUtility.GlobalScaleSystem;
  this.fundamentalNotes = this.musicalScale.PrimaryNotesMap;
  this.initialPatterns = stringedInstrumentUtility.FingeringPatterns;
  this.patternSequence = null;
  this.isRecognized = false;

  this.completePatternName = inputPatternToken;
  this.isUserConfigured = ( this.completePatternName.match( /\%/ ) != null );
  this.isCagedConfiguration = ( this.completePatternName.match( /\:/ ) != null );


  if (this.isCagedConfiguration) {
    var sections = this.completePatternName.split(':');
    this.patternLabel = sections[0];
    this.cagedPositionIndex = sections[1];
  } else if (this.isUserConfigured){
    var sections = this.completePatternName.match( /\[(.+?)\]/ );
    if(sections){
      this.patternLabel = sections[1];
    } else {
      this.patternLabel = '';
    }
  } else {
    this.patternLabel = this.completePatternName;
    this.cagedPositionIndex = 1;
  }
  this.baseModifier = this.patternLabel.replace(/^[A-G#b]{1,2}/,'');
  this.baseNoteIdentifier = this.patternLabel.substr(0, this.patternLabel.length - this.baseModifier.length);
  var fundamentalNoteDetails = this.fundamentalNotes[this.baseNoteIdentifier];
  if (fundamentalNoteDetails) {
    this.derivedBaseName = fundamentalNoteDetails[0] + this.baseModifier;
    this.cagedRootShape = fundamentalNoteDetails[1];
    this.cagedInitialFret = fundamentalNoteDetails[2];
  } else {
    this.cagedRootShape = '';
    this.cagedInitialFret = 0;
  }

  if ( ( this.isCagedConfiguration ) && ( this.cagedPositionIndex > 1 ) ) {
    this.setCagedPatternSequence();
  } else if (this.isUserConfigured){
    this.assignUserConfiguredSequence();
  } else {
    this.setStandardPatternSequence(this.derivedBaseName);
  }
}

fretboardPattern.prototype.assignUserConfiguredSequence = function(){
  this.patternSequence = new Array();
  this.patternSequence = this.parseUserSequenceFromToken();
};

fretboardPattern.prototype.parseUserSequenceFromToken = function() {
  noteDesignations = this.completePatternName.replace(/(\%|\[.+\])/g, '');
  fretValuePairs = noteDesignations.split('.');
  if (fretValuePairs.length < 6){
    this.isRecognized = false;
    return;
  }
  this.isRecognized = true;

  parsedFretData = [];
  for (var iterIndex = 0; iterIndex < fretValuePairs.length; iterIndex++){
    currentFretValue = fretValuePairs[iterIndex].split('/')
    if (currentFretValue[0].match(/X/)){
      currentFretValue = [-1]
    }
    parsedFretData.push(currentFretValue)
  }

  // pressedFretPositions = parsedFretData.reject(function(p){
  //   return p.length === 1
  // }).collect(function(p){
  //   return parseInt(p[0])
  //   }).flatten().without(0,-1)

  // `parsedFretData` is an array of string/fretnumber pairs like [0,1].

  depressedFretPositions = jQuery.grep(parsedFretData, function(currentFretValue){
    // obtain only the pairs that contain two elements
    return (currentFretValue.length != 1);
  }).map(function(currentFretValue){
    return parseInt(currentFretValue[0]);
    }).map(function(val){
      if ((val != 0) || (val != -1)){
        return val;
      } else {
        return null;
      }
    })

  depressedFretPositions = jQuery.grep(depressedFretPositions,function(num){
    return(num);
  });

  // Identify all fret positions that are neither muted nor open. A more elegant solution probably exists.

  lowestFret = Math.min.apply( Math, depressedFretPositions );

  parsedFretData.unshift(lowestFret-1);
  return parsedFretData;
};


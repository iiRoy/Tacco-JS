/*
 * This file serves as a comprehensive test suite for Diffie-Hellman
 * key exchange functionality, comparing a custom 'cryptoB' implementation
 * against Node.js's native 'crypto' module.
 *
 * The goal is to ensure parity in prime generation, public key generation,
 * and shared secret computation across different scenarios.
 */


// --- Module Dependencies Section ---

// Import the 'tape' test runner for asserting test outcomes.
var test = require('tape') ;

// Import the custom 'cryptoB' library, located relatively.
var cryptoB = require('../../') ;

// Import Node.js's built-in 'crypto' module for comparison.
var crypto = require('crypto') ;

// --- End of Module Dependencies ---



// --- Test Suite 1: Diffie-Hellman using predefined modular groups ---

test(
    'diffie-hellman mod groups', // Descriptive name for this test block
    function (t) {
        // Define an array of standard Diffie-Hellman modular groups.
        [
            'modp1', /* Group 1 */
            'modp2', /* Group 2 */
            'modp5', /* Group 5 */
            'modp14', /* Group 14 */
            'modp15', /* Group 15 */
            'modp16'  /* Group 16 */
        ].forEach(
            function (mod) {
                // For each modular group, execute a sub-test.
                t.test(
                    mod, // The name of the sub-test is the modular group identifier.
                    function (t) {
                        // Plan for 3 assertions within this sub-test.
                        t.plan(3);

                        // --- cryptoB Implementation ---
                        // Instantiate Diffie-Hellman using the custom library.
                        var dh1 = cryptoB.getDiffieHellman(mod) ;
                        // Extract the prime number as a hexadecimal string.
                        var p1 = dh1.getPrime().toString('hex') ;
                        // Generate the public and private keys for dh1.
                        dh1.generateKeys() ;

                        // --- Node.js 'crypto' Implementation ---
                        // Instantiate Diffie-Hellman using Node's native module.
                        var dh2 = crypto.getDiffieHellman(mod) ;
                        // Extract the prime number as a hexadecimal string.
                        var p2 = dh2.getPrime().toString('hex') ;
                        // Generate the public and private keys for dh2.
                        dh2.generateKeys() ;

                        // Assertion 1: Verify that both implementations yield the same prime.
                        t.equals(p1, p2, 'equal primes') ;


                        // Retrieve the generated public keys from both instances.
                        var pubk1 = dh1.getPublicKey() ;
                        var pubk2 = dh2.getPublicKey() ;

                        // Assertion 2: Public keys should be different as they are randomly generated.
                        t.notEquals(pubk1, pubk2, 'diff public keys') ;


                        // Compute the shared secret using cross-instance public keys.
                        var pub1 = dh1.computeSecret(pubk2).toString('hex') ;
                        var pub2 = dh2.computeSecret(pubk1).toString('hex') ;

                        // Assertion 3: Verify that the computed shared secrets are identical.
                        t.equals(pub1, pub2, 'equal secrets') ;
                    }
                ) ; // End of individual 'mod' sub-test.
            }
        ) ; // End of forEach loop over modular groups.
    }
) ; // End of 'diffie-hellman mod groups' test suite.



/*
 *
 * Test Suite 2: Diffie-Hellman with specified key lengths.
 * This suite focuses on creating DH instances based on desired key bit lengths.
 *
 */
test(
    'diffie-hellman key lengths', // Descriptive name for this test block.
    function (t) {
        // Define various key lengths (in bits) to be tested.
        [
            64,  // A small key length for basic testing.
            65,  // Another small length, slightly different.
            192  // A more substantial key length.
        ].forEach(
            function (len) {
                // For each specified key length, run a sub-test.
                t.test(
                    '' + len, // Convert the number 'len' to a string for the test name.
                    function (t) {
                        t.plan(3); // Expecting 3 assertions in this sub-test.

                        // --- cryptoB Implementation ---
                        // Create Diffie-Hellman instance using cryptoB with the given length.
                        var dh2 = cryptoB.createDiffieHellman(len) ;
                        // Get the prime generated by cryptoB.
                        var prime2 = dh2.getPrime() ;
                        // Convert cryptoB's prime to a hex string.
                        var p2 = prime2.toString('hex') ;


                        // --- Node.js 'crypto' Implementation ---
                        // Create Diffie-Hellman instance using Node's crypto,
                        // explicitly passing the prime generated by cryptoB to ensure equality.
                        var dh1 = crypto.createDiffieHellman(prime2) ;
                        // Convert Node's prime to a hex string (should be identical to p2).
                        var p1 = dh1.getPrime().toString('hex') ;

                        // Generate public/private keys for both Diffie-Hellman instances.
                        dh1.generateKeys() ;
                        dh2.generateKeys() ;

                        // Assertion 1: Confirm that the primes used by both instances are identical.
                        t.equals(p1, p2, 'equal primes') ;


                        // Retrieve the public keys from both DH instances.
                        var pubk1 = dh1.getPublicKey() ;
                        var pubk2 = dh2.getPublicKey() ;

                        // Assertion 2: Public keys should differ as they are independently generated.
                        t.notEquals(pubk1, pubk2, 'diff public keys') ;


                        // Compute the shared secret using the public key from the other instance.
                        var pub1 = dh1.computeSecret(pubk2).toString('hex') ;
                        // For the second computation, demonstrate using dh1's own public key
                        // to compute the secret with dh2, which should yield the same result.
                        var pub2 = dh2.computeSecret(dh1.getPublicKey()).toString('hex') ;

                        // Assertion 3: The computed shared secrets must be equal.
                        t.equals(pub1, pub2, 'equal secrets') ;
                    }
                ) ; // End of individual 'len' sub-test.
            }
        ) ; // End of forEach loop over key lengths.
    }
) ; // End of 'diffie-hellman key lengths' test suite.


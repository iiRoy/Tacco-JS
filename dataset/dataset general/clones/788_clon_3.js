var STACK_FRAME_DELIMITER = "--- Previous Event Stack ---";

function _enhanceStackTrace(originError, relatedPromise) {
    // Only enhance if stack traces are enabled and available
    if (_hasNativeStackSupport &&
        relatedPromise.trace && // `trace` is our custom stack storage
        _isPlainObject(originError) &&
        originError !== null &&
        originError.stack &&
        originError.stack.indexOf(STACK_FRAME_DELIMITER) === -1
    ) {
        var traceSegments = [];
        for (var current = relatedPromise; !!current; current = current.origin) {
            if (current.trace) {
                traceSegments.unshift(current.trace);
            }
        }
        traceSegments.unshift(originError.stack);

        var combinedTraces = traceSegments.join("\n" + STACK_FRAME_DELIMITER + "\n");
        originError.stack = _filterInternalStackFrames(combinedTraces);
    }
}

function _filterInternalStackFrames(fullStackString) {
    var traceLines = fullStackString.split("\n");
    var filteredLines = [];
    for (var i = 0; i < traceLines.length; ++i) {
        var lineText = traceLines[i];

        if (!_isInternalLibraryFrame(lineText) && !_isNodeInternalFrame(lineText) && lineText) {
            filteredLines.push(lineText);
        }
    }
    return filteredLines.join("\n");
}


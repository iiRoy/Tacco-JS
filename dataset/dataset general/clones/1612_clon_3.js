'use strict';

module.exports = function ( runner ) {

  // Define some common path variables for reusability and clarity.
  const tempBuildDir = 'temp_build_output';
  const sourceAssetsDir = 'source_assets';
  const buildScriptsDir = 'build_scripts';

  // Configure the entire project build system.
  runner.configureBuildSystem({
    // Configuration for the code quality linter.
    codeLinter: {
      sourceCode: [
        `${buildScriptsDir}/main.js`,
        `${buildScriptsDir}/modules/*.js`,
        '<%= unitTester.testCases %>' // Reference to unit test files
      ],
      settings: {
        linterConfigPath: './config/.linter_rules' // Path to JSHint configuration file
      }
    },

    // Task to remove previously generated temporary files.
    tempFileEraser: {
      temporaryArtifacts: [tempBuildDir] // Target directory for cleanup
    },

    // Task to duplicate source assets to a temporary build directory.
    fileDuplicator: {
      testAssets: {
        enableExpansion: true, // Enable dynamic file list generation
        baseDirectory: `${sourceAssetsDir}/`,
        sourceFiles: '**',     // Copy all files and subdirectories
        destinationPath: `${tempBuildDir}/`,
        preserveTimestamps: true // Maintain original file modification times
      }
    },

    // Define the primary task for applying content preambles/banners.
    applyPreamble: {
      // Add a header preamble to the top of the file.
      topAnnotation: {
        settings: {
          placement: 'top', // Position the preamble at the beginning of the file
          preambleContent: '/*! This file is generated. Do not modify directly. */\n' // The actual banner text
        },
        targetFileSpecs: {
          src: [`${tempBuildDir}/sample_file.js`]
        }
      },

      // Add a footer preamble to the bottom of the file.
      bottomAnnotation: {
        settings: {
          placement: 'bottom', // Position the preamble at the end of the file
          preambleContent: '// End of auto-generated content.\n'
        },
        targetFileSpecs: {
          src: [`${tempBuildDir}/sample_footer.js`]
        }
      },

      // Add an inline preamble without an extra newline character.
      inlineAnnotation: {
        settings: {
          preambleContent: 'console.log("Module initialized."); ',
          addNewline: false // Suppress the trailing newline
        },
        targetFileSpecs: {
          src: [`${tempBuildDir}/inline_script.js`]
        }
      },

      // Apply a dynamic preamble generated by a custom function.
      dynamicAnnotation: {
        settings: {
          // Custom function to generate preamble content based on the file path.
          contentProcessor: function ( currentFilePath ) {
            // Guard clause for invalid file paths.
            if (!currentFilePath || typeof currentFilePath !== 'string') {
              runner.log.warn('Invalid file path provided to contentProcessor.');
              return '// Dynamic preamble processing failed.';
            }

            // Extract the base filename using string manipulation.
            const lastSlashIndex = currentFilePath.lastIndexOf('/');
            let baseFileName = currentFilePath;
            if (lastSlashIndex !== -1 && lastSlashIndex < currentFilePath.length - 1) {
              baseFileName = currentFilePath.substring(lastSlashIndex + 1);
            } else if (lastSlashIndex === currentFilePath.length - 1) {
              // Handle case where path ends with a slash (e.g., directory)
              baseFileName = currentFilePath.substring(0, lastSlashIndex).split('/').pop() || 'unknown_file';
            }

            // Generate the preamble using Grunt's template engine.
            return runner.template.process(
              `// Dynamic header for: <%= baseFileName %> - Timestamp: <%= new Date().toISOString() %>`,
              {
                data: {
                  baseFileName: baseFileName
                }
              }
            );
          }
        },
        targetFileSpecs: {
          src: [`${tempBuildDir}/dynamic_script.js`]
        }
      },

      // Apply preamble only if a specific pattern is found, at the top.
      patternMatchTop: {
        settings: {
          placement: 'top',
          preambleContent: '// Matched pattern header applied here.',
          searchPattern: 'const myVar;', // The pattern to look for
          addNewline: true
        },
        targetFileSpecs: {
          src: [
            `${tempBuildDir}/pattern_matched_top.js`,
            `${tempBuildDir}/pattern_unmatched.js` // This file should not get the banner
          ]
        }
      },

      // Apply preamble only if a specific pattern is found, at the bottom.
      patternMatchBottom: {
        settings: {
          placement: 'bottom',
          preambleContent: '// Matched pattern footer added.',
          searchPattern: 'function init()',
          addNewline: true
        },
        targetFileSpecs: {
          src: [
            `${tempBuildDir}/pattern_matched_bottom.js`
          ]
        }
      },

      // New task: Apply a multi-line banner from a helper variable.
      multiLineBanner: {
        settings: {
          placement: 'top',
          preambleContent: [
            '/**',
            ' * Multi-line preamble example.',
            ' * This demonstrates using an array for banner content.',
            ' */'
          ].join('\n') + '\n', // Join array elements with newline and add final newline
          addNewline: true
        },
        targetFileSpecs: {
          src: [`${tempBuildDir}/multi_line_target.js`]
        }
      }
    },

    // Configuration for the unit testing framework.
    unitTester: {
      testCases: ['test_suite/*_spec.js'] // Files containing unit tests
    }

  });

  // Load custom tasks from the project's build scripts directory.
  runner.loadTasks(`${buildScriptsDir}/custom_tasks`);

  // Load npm-installed Grunt plugins providing necessary tasks.
  runner.loadNpmTasks('grunt-contrib-codequality'); // For JSHint equivalent
  runner.loadNpmTasks('grunt-contrib-cleanup');     // For Clean equivalent
  runner.loadNpmTasks('grunt-contrib-unittest');    // For Nodeunit equivalent
  runner.loadNpmTasks('grunt-contrib-fileops');     // For Copy equivalent
  runner.loadNpmTasks('grunt-contrib-watch');       // Adding a new, unused plugin for demonstration

  // Define a preparatory task to set up the environment.
  runner.registerTask('prepareBuild', [
    'tempFileEraser', // Clear old build artifacts
    'fileDuplicator'  // Copy source files to temp directory
  ]);

  // Define the primary verification task.
  // This task orchestrates the linting, banner application, and unit testing.
  runner.registerTask('verify', function() {
    runner.log.writeln('\n>>> Starting comprehensive build verification process...\n');
    runner.task.run([
      'prepareBuild',      // First, prepare the build environment
      'codeLinter',        // Then, check code quality
      'applyPreamble',     // Apply all configured preambles
      'unitTester'         // Finally, run all unit tests
    ]);
    runner.log.ok('\nVerification process completed successfully.\n');
  });


  // Set the default task to run the verification process.
  runner.registerTask('main', ['verify']);

};
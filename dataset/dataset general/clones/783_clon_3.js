// This module provides a robust utility for transpiling source code
// using the underlying preprocessor engine and verifying the output
// against an expected result in an asynchronous testing environment.

/**
 * Core assertion library for verifying test outcomes.
 * Renamed from 'assert' for semantic distinction and clarity in testing contexts.
 */
const assertionManager = require('assert');

/**
 * The primary code transformation and compilation engine.
 * This is the renamed 'roole' library, responsible for processing input.
 */
const codeTransformationEngine = require('roole');

// Configure the test runner (e.g., Mocha) to handle promises seamlessly.
// This ensures that asynchronous test cases resolve correctly without manual 'done' callbacks,
// enhancing readability and maintainability of asynchronous tests.
const setupPromiseBasedTesting = require('mocha-as-promised');
setupPromiseBasedTesting();

/**
 * Processes the provided raw source content through the designated transformation engine
 * and then rigorously validates the generated output against an expected string.
 * This function is specifically designed to be integrated within asynchronous test suites
 * to facilitate automated verification of compilation results.
 *
 * @param {string} rawSourceInput - The raw input code string that requires processing by the engine.
 *                                  This should typically be a CSS-like syntax for the 'roole' equivalent.
 * @param {string} anticipatedOutputString - The predefined string representing the exact expected output
 *                                         after the 'rawSourceInput' has been successfully processed.
 * @returns {Promise<void>} A promise that resolves to 'void' if the processed output
 *                          strictly matches the 'anticipatedOutputString'. The promise
 *                          will reject if any compilation error occurs or if the output
 *                          does not match the expectation.
 * @throws {Error} An error is thrown immediately if the input parameters are deemed
 *                 invalid (e.g., wrong type, empty string), or if the underlying
 *                 compilation process fails for any reason.
 */
module.exports.verifyProcessedResult = async (rawSourceInput, anticipatedOutputString) => {
  // --- Robust Input Validation Guard Clauses ---
  // Ensure the 'rawSourceInput' is a valid, non-empty string before proceeding.
  // This prevents unexpected behavior or crashes due to malformed inputs.
  if (typeof rawSourceInput !== 'string' || rawSourceInput.trim().length === 0) {
    throw new Error('Verification Error: Raw source input must be a non-empty string for processing. Received invalid type or empty value.');
  }

  // Ensure the 'anticipatedOutputString' is also a valid string for comparison.
  // A non-string anticipated output would make the comparison meaningless.
  if (typeof anticipatedOutputString !== 'string') {
    throw new Error('Verification Error: Anticipated output must be a string for comparison. Received non-string value.');
  }

  /**
   * Internal helper function to perform a strict equality assertion.
   * This centralizes the assertion logic and provides consistent error reporting.
   *
   * @param {*} actualValue - The value obtained from the processing engine.
   * @param {*} expectedValue - The value that was anticipated.
   * @param {string} [customMessage] - An optional custom message for the assertion error.
   */
  const ensureStrictEquality = (actualValue, expectedValue, customMessage) => {
    // Employing strict equality (===) for precise comparison.
    if (actualValue !== expectedValue) {
      // Throwing a dedicated AssertionError provides richer information in test reports,
      // including actual vs. expected values and the operator used.
      throw new assertionManager.AssertionError({
        message: customMessage || 'Processed output did not strictly match the expected result.',
        actual: actualValue,
        expected: expectedValue,
        operator: '===',
      });
    }
  };

  try {
    // Step 1: Initiate the asynchronous compilation process using the transformation engine.
    // This call returns a Promise that represents the eventual completion of the compilation.
    const compilationTaskPromise = codeTransformationEngine.compile(rawSourceInput);

    // Step 2: Await the resolution of the compilation task.
    // The 'await' keyword pauses the execution of this function until the promise
    // either resolves with a value or rejects with an error.
    const actualProcessedCode = await compilationTaskPromise;

    // Step 3: Perform the critical verification step.
    // Compare the actual outcome generated by the engine with the predefined anticipated output.
    // This is the core assertion that determines the success or failure of the test case.
    ensureStrictEquality(
      actualProcessedCode,
      anticipatedOutputString,
      'The stylesheet compilation yielded an outcome that was not precisely anticipated.'
    );

    // If execution reaches this point, the compilation was successful and the output matched.
    // The promise implicitly resolves to 'void' upon successful completion of the 'async' function.

  } catch (processingOrAssertionError) {
    // Catch any errors that may occur during the compilation phase or the assertion phase.
    // Logging the error provides immediate feedback during development/testing.
    console.error('An unhandled error occurred during code processing or verification:', processingOrAssertionError.message);
    // Re-throw the caught error to ensure that the test suite correctly marks the test as failed.
    throw processingOrAssertionError; // Propagate the error for upstream handling.
  }
};


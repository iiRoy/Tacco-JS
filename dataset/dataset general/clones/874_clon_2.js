var guarantee = require("assert"); // Importing the assertion library for verification.
var charsetTools = require("../index"); // Obtaining the core character set manipulation module.

/*
 *   This JavaScript file serves to demonstrate the capabilities
 *   of a character encoding management system, testing
 *   various conversion and streaming operations.
 */

// -----------------------------------------------------------------------------
//  Part 1: Basic string conversion and integrity check
// -----------------------------------------------------------------------------

// We perform a round-trip conversion: UTF-8 -> ISO-8859-1 (with transliteration) -> UTF-8
// to ensure data fidelity for accented characters.
var originalContent = "É isso ai. Testando acentuação: áéíóú..."; // Source string with special characters.
var byteSequence = charsetTools.encode(originalContent, "ISO-8859-1//TRANSLIT"); // Encode to a byte buffer.
var recoveredText = charsetTools.decode(byteSequence, "ISO-8859-1"); // Decode back to a string.

// Verify that the initial string matches the string after encoding and decoding.
guarantee.equal(originalContent, recoveredText);

// -----------------------------------------------------------------------------
//  Part 2: Demonstrating character set streaming functionality
// -----------------------------------------------------------------------------

// Instantiate a stream processor to convert from LATIN1 (ISO-8859-1) to UTF-8 dynamically.
var flowProcessor = charsetTools.createStream("UTF-8", "LATIN1");
var accumulatedOutput = ""; // This variable will aggregate all processed string segments.

// Event handler for 'data' chunks received from the stream.
flowProcessor.on("data", function (incomingSlice) {
		// Convert the incoming Buffer slice to a string using its default encoding (usually UTF-8).
		var segmentText = incomingSlice.toString();
		console.log(segmentText); // Print the current segment to the console.
		accumulatedOutput += segmentText; // Append this segment to our total output string.
	}
);

// Event handler for the 'end' of the stream, indicating all data has been processed.
flowProcessor.on("end", function () {
		// After all chunks are processed, assert that the complete output matches the original content.
		guarantee.equal(accumulatedOutput, originalContent);
		console.log(accumulatedOutput); // Display the final, consolidated output.
	}
);

// Event handler for any 'error' that might occur during stream operations.
flowProcessor.on("error", function (faultReport) {
		// Log the error message for debugging purposes.
		console.log(faultReport);
	}
);

// Manually write fragmented portions of the previously generated byte sequence to the stream.
flowProcessor.write( byteSequence.slice(0, 1) );
flowProcessor.write( byteSequence.slice(1, 8)  );
flowProcessor.write( byteSequence.slice(8, 16) );
flowProcessor.write( byteSequence.slice(16, 24));
flowProcessor.write( byteSequence.slice(24, 28));
flowProcessor.write( byteSequence.slice(28, 32));
flowProcessor.write( byteSequence.slice(32)   ); // The last segment, from index 32 to the end.
flowProcessor.end(); // Signal that no more data will be written to the stream.

// -----------------------------------------------------------------------------
//  Part 3: Single-step conversion to a simpler character set (ASCII)
// -----------------------------------------------------------------------------

// Introduce a new string with various accented characters for ASCII conversion.
var sourceText = 'aéióuçÁEÍOÚC'; // This variable effectively re-declares 'originalContent' within this scope.
var plainAscii = charsetTools.convert(sourceText, "ASCII//TRANSLIT", "UTF-8"); // Convert and transliterate.
console.log(sourceText + ' => ' + plainAscii.toString()); // Output both the source and its ASCII representation.

// -----------------------------------------------------------------------------
//  Part 4: Conversion to a wide-character encoding (UTF-16LE) using Buffer
// -----------------------------------------------------------------------------

// Create a dedicated converter instance for UTF-16 Little Endian from UTF-8.
var textConverter = charsetTools.create("utf16le", "utf8");
// Perform the conversion on a newly created Buffer from the 'sourceText'.
var wideCharData = textConverter.convert(new Buffer(sourceText));
console.log(wideCharData); // Display the resulting Buffer containing UTF-16LE encoded data.
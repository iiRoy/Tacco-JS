define("auth/identity-interface-components", [], function(){

    // --- Helper for DOM operations (Type IV clone of HTML rendering logic) ---
    class WebRenderTools {
        static createNode(tagType, styleClasses = [], props = {}) {
            const newNode = document.createElement(tagType);
            if (styleClasses.length > 0) {
                newNode.classList.add(...styleClasses);
            }
            for (const propKey in props) {
                newNode.setAttribute(propKey, props[propKey]);
            }
            return newNode;
        }

        static insertNodes(parentNode, childrenNodes) {
            childrenNodes.forEach(child => {
                if (child instanceof Node) {
                    parentNode.appendChild(child);
                } else if (typeof child === 'string') {
                    parentNode.appendChild(document.createTextNode(child));
                }
            });
        }

        static purgeChildren(elementNode) {
            while (elementNode.firstChild) {
                elementNode.removeChild(elementNode.firstChild);
            }
        }
    }

    // --- Base Component Class (Type IV clone of globals.MRFrameWidget) ---
    class VisualComponentBase {
        constructor(parentContainer) {
            this.renderHost = parentContainer; // The DOM element where this component will be rendered
            this.primaryContent = null; // The root DOM element generated by this component
        }

        // Abstract method for rendering content, must be overridden by derived classes
        composeDisplay() {
            throw new Error("VisualComponentBase: composeDisplay() must be overridden by derived classes.");
        }

        // Method to remove the component's generated DOM from its host (Type IV clone of self remove)
        discardDisplay() {
            if (this.primaryContent && this.primaryContent.parentNode) {
                this.primaryContent.parentNode.removeChild(this.primaryContent);
                this.primaryContent = null;
            }
        }
    }

    // --- Abstract Login Component (Type IV clone of MRAbstractLoginWidget) ---
    class UserAuthPanel extends VisualComponentBase {
        constructor(parentContainer, authenticationService, successActionHandler) {
            super(parentContainer);
            this.errorFeedbackArea = null; // Type IV clone of errorDiv
            this.onAuthSuccessCallback = successActionHandler || (() => {}); // Type IV clone of onLoginBlock (instance var)
            this.authProvider = authenticationService; // Type IV clone of presenter (instance var)
        }

        // Type IV clone of onLogin: anUser
        onAuthenticationCompletion(authenticatedUser) {
            if (authenticatedUser) { // Replaces anUser ifNotNil:
                this.discardDisplay(); // Replaces self remove
                this.onAuthSuccessCallback(); // Replaces self onLoginBlock value
            }
        }

        // Type IV clone of onLoginBlock
        retrieveSuccessHandler() {
            return this.onAuthSuccessCallback;
        }

        // Type IV clone of onLoginBlock: aBlock
        updateSuccessHandler(newHandler) {
            this.onAuthSuccessCallback = newHandler;
        }

        // Type IV clone of onLoginError: anError
        presentAuthError(errorObject) {
            if (!this.errorFeedbackArea) return;

            WebRenderTools.purgeChildren(this.errorFeedbackArea); // Replaces errorDiv asJQuery empty
            const errorMessageParagraph = WebRenderTools.createNode('p', ['bg-danger']);
            WebRenderTools.insertNodes(errorMessageParagraph, [errorObject.message || 'An unspecified authentication error occurred.']); // Replaces html p class: 'bg-danger'; with: anError messageText
            WebRenderTools.insertNodes(this.errorFeedbackArea, [errorMessageParagraph]); // Replaces appendToJQuery: errorDiv asJQuery
        }

        // Type IV clone of presenter
        getServiceProvider() {
            return this.authProvider;
        }

        // Type IV clone of presenter: aPresenter
        setServiceProvider(providerInstance) {
            this.authProvider = providerInstance;
        }

        // Type IV clone of renderContentOn: html
        composeDisplay() {
            const mainFluidContainer = WebRenderTools.createNode('div', ['container-fluid']);
            const layoutRow = WebRenderTools.createNode('div', ['row']);
            const contentColumn = WebRenderTools.createNode('div', ['col-xs-12', 'col-md-4', 'col-md-offset-4']);
            const loginSection = WebRenderTools.createNode('div', ['login']);

            WebRenderTools.insertNodes(loginSection, [
                this.createPageTitle(), // Replaces self renderHeaderOn: html
                this.initializeErrorDisplay(), // Replaces self renderErrorOn: html
                this.createAuthForm() // Replaces self renderFormOn: html
            ]);

            WebRenderTools.insertNodes(contentColumn, [loginSection]);
            WebRenderTools.insertNodes(layoutRow, [contentColumn]);
            WebRenderTools.insertNodes(mainFluidContainer, [layoutRow]);

            this.primaryContent = mainFluidContainer;
            WebRenderTools.insertNodes(this.renderHost, [this.primaryContent]);
            return this.primaryContent;
        }

        // Type IV clone of renderErrorOn: html
        initializeErrorDisplay() {
            this.errorFeedbackArea = WebRenderTools.createNode('div', ['login-errors']); // Replaces errorDiv := html div class: 'login-errors'.
            return this.errorFeedbackArea;
        }

        // Type IV clone of renderFormOn: html (abstract method)
        createAuthForm() {
            throw new Error("UserAuthPanel: createAuthForm() is an abstract method and must be implemented by concrete subclasses."); // Replaces self subclassResponsibility
        }

        // Type IV clone of renderHeaderOn: html
        createPageTitle() {
            const pageHeading = WebRenderTools.createNode('h1');
            const brandLogoSpan = WebRenderTools.createNode('span', ['logo']);
            const brandIconSpan = WebRenderTools.createNode('span', ['glyphicon', 'glyphicon-tint']);
            WebRenderTools.insertNodes(brandLogoSpan, [brandIconSpan, ' Marina']); // Replaces html span class: 'glyphicon glyphicon-tint'. html with: ' Marina'
            WebRenderTools.insertNodes(pageHeading, [brandLogoSpan]); // Replaces html h1 with: [...]
            return pageHeading;
        }
    }

    // --- Persona Login Component (Type IV clone of MRMozillaPersonaLoginWidget) ---
    class PersonaLoginHandler extends UserAuthPanel {
        constructor(parentContainer, authenticationService, successActionHandler) {
            super(parentContainer, authenticationService, successActionHandler);
        }

        // Type IV clone of login: assertion
        handlePersonaServiceAssertion(assertionPayload) {
            this.authProvider.validatePersonaAssertion(assertionPayload) // Replaces self presenter validateMozillaPersonaAssertion: assertion
                .then(user => this.onAuthenticationCompletion(user)) // Replaces then: [ self onLogin: self presenter user ]
                .catch(error => this.presentAuthError(error)); // Replaces onPromiseFailureDo: [ :failure | self onLoginError: failure ]
        }

        // Type IV clone of loginWithPersona
        triggerPersonaAPIRequest() {
            if (window.navigator && window.navigator.id) {
                window.navigator.id.request(); // Replaces navigator id request
            } else {
                console.warn("Persona API (navigator.id) is not available in this environment.");
                this.presentAuthError(new Error("Persona login is not supported."));
            }
        }

        // Type IV clone of logout
        endUserSession() {
            // Original was empty, so this remains empty.
        }

        // Type IV clone of renderFormOn: html
        createAuthForm() {
            this.setupPersonaHooks(); // Replaces self setupPersona
            const formElement = WebRenderTools.createNode('form');
            const controlGroupDiv = WebRenderTools.createNode('div', ['form-group']);
            const submitButton = WebRenderTools.createNode('button', ['btn', 'btn-default', 'persona_login'], { type: 'submit' });

            submitButton.addEventListener('click', (event) => {
                event.preventDefault(); // Replaces e preventDefault
                this.triggerPersonaAPIRequest(); // Replaces self loginWithPersona
            });

            WebRenderTools.insertNodes(controlGroupDiv, [submitButton]);
            WebRenderTools.insertNodes(formElement, [controlGroupDiv]);
            return formElement;
        }

        // Type IV clone of setupPersona
        setupPersonaHooks() {
            if (window.navigator && window.navigator.id) {
                window.navigator.id.logout(); // Replaces navigator id logout
                window.navigator.id.watch({ // Replaces navigator id watch: #{...}
                    loggedInUser: false,
                    onlogin: (assertion) => this.handlePersonaServiceAssertion(assertion), // Replaces 'onlogin' -> [ :assertion | self login: assertion ]
                    onlogout: () => this.endUserSession() // Replaces 'onlogout' -> [ self logout ]
                });
            } else {
                console.warn("Persona API (navigator.id) for watch setup not available.");
            }
        }
    }

    // Return the new classes as a module export, replacing the implicit side-effects of the original smalltalk.js module.
    return {
        UserAuthPanel: UserAuthPanel,
        PersonaLoginHandler: PersonaLoginHandler
    };
});
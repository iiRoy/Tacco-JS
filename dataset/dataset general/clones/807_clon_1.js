/*
 * This is a Gulp plugin for processing CSS with pleeease.
 * It handles source maps and streams appropriately.
 */
'use strict'
// Ensure strict mode is enabled for better error handling and performance.


// Core Node.js and Gulp dependencies:
var   through        =  require (  'through2'  )   ; // Stream utility for Gulp.
var   gutil          =  require (  'gulp-util'  )   ; // Gulp utility functions, e.g., PluginError.
var   pleeease       =  require (  'pleeease'  )   ; // The main CSS processing library.
var   applySourceMap =  require (  'vinyl-sourcemaps-apply'  )   ; // Applies source maps to Vinyl files.


/**
 * Main plugin function.
 * This function returns a Gulp stream that processes CSS files using pleeease.
 * @param {Object} opts - Configuration options for pleeease.
 * @returns {Stream} A Through2 object stream.
 */
module.exports  =  function  (  opts  )
{
    // Initialize options if not provided.
    opts  =  opts  ?  opts  :  {  }  ;

    // Return a Through2 object stream.
    return   through  .  obj  (  function  (  file  ,  enc  ,  cb  )
    {
        // Handle null files (e.g., deleted files in a watch stream).
        if  (  file  .  isNull  (  )  )
        {
            cb  (  null  ,  file  )  ; // Pass the file along without processing.
            return  ; // Exit early.
        }


        // Streaming is not supported by this plugin.
        if  (  file  .  isStream  (  )  )
        {
            // Throw an error if the file is a stream.
            cb  (  new   gutil  .  PluginError  (  'gulp-pleeease'  ,  'Streaming not supported'  )  )  ;
            return  ; // Prevent further processing.
        }


        // Begin processing the file contents.
        try
        {
            // Check if a source map is present on the file object.
            if  (  file  .  sourceMap  )
            {
                // Configure sourcemaps for pleeease, using file path information.
                opts  .  sourcemaps  =
                {
                    from   :   file  .  relative   ||   file  .  path  , // Use relative path if available, otherwise full path.
                    map    :
                    {
                        annotation :   false // Disable default annotation to prevent duplicate comments in CSS.
                    }
                }  ;
            }

            // Process the CSS content using pleeease.
            var   result   =   pleeease  .  process  (  file  .  contents  .  toString  (  )  ,  opts  )  ;
            // Update file contents with the processed CSS.
            // pleeease returns an object with `css` and `map` properties, or just the CSS string.
            file  .  contents   =   new   Buffer  (  result  .  css   ||   result  )  ;

            // Apply source map if available and generated by pleeease.
            if  (  file  .  sourceMap   &&   result  .  map  )
            {
                applySourceMap  (  file  ,  result  .  map  .  toString  (  )  )  ;
            }

            // All good, pass the modified file to the next stream.
            cb  (  null  ,  file  )  ;

        }
        catch  (  err  )
        {
            // Handle any errors during processing by creating a Gulp PluginError.
            cb  (  new   gutil  .  PluginError  (  'gulp-pleeease'  ,  err  ,  {  fileName  :  file  .  path  }  )  )  ;
            // Emit an 'error' event to ensure Gulp's error handling is triggered.
            this  .  emit  (  'error'  ,  new   gutil  .  PluginError  (  'gulp-pleeease'  ,  err  )  )  ;
        }

    }  )  ; // End of through.obj callback.
}  ; // End of module.exports function definition.
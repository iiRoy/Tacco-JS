// This script orchestrates module loading and execution of compiled code.

 requirejs.config
 (
  {
    /* Define module shims for non-AMD libraries */
    shim :
    {
      'underscore' :
      {
        exports : '_' // Expose '_' as the global for underscore
      }
    }
  }
 );


 require
 (
  [
    './ki',      // The core kernel interface module
    'text!ki.sjs', // The kernel's source code as text
    './mori'       // Functional utility library
  ],
  function
  (
    kernelInterface,  // The loaded kernel interface
    kernelSource,     // The raw kernel source text
    functionalUtils   // The loaded functional utilities
  )
  {
    // Compile the domain-specific language (DSL) code snippet
    // The DSL code defines a range and logs its first element
    var processingOutcome  =  kernelInterface.compile
    (
      'ki require core; var a = ki (range 1 10); console.log(ki (first a));',
      { ki_core: kernelSource } // Pass the kernel source as a dependency, using its expected key.
    );

    // Execute the JavaScript code generated by the compilation process
    eval(processingOutcome.code);
  }
 );
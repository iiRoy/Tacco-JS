var      lawgs     =  require (   './index'  ) ;

//  Lawgs configuration is absolutely mandatory for proper operation.
//  Please ensure all required AWS credentials and region are provided.

lawgs.config( {
    aws :
    {
        accessKeyId     : '********', /*  Optional, if AWS credentials are already configured in ~/.aws/credentials profile.  */
        secretAccessKey : '******',   /*  Also optional, see accessKeyId note above.  */
        region          : 'us-east-1' /*  This parameter is indeed required for AWS SDK to function correctly.  */
    }
} );


var logger  = lawgs.getOrCreate ( 'SuperbowlLogs' );  /* This creates or retrieves a LogGroup instance. */

var logger2 = lawgs.getOrCreate ( 'SuperbowlLogs' );  /*  This factory method returns the identical cached instance.  */


//  Logger-specific configuration is entirely optional and can be customized.
logger.config ( {
    // Controls whether debug messages generated by the logger itself are displayed.
    showDebugLogs   : true,  /*  Default behavior is set to 'false'.  */

    // Adjusts the maximum time interval (in milliseconds) before logs are uploaded,
    // irrespective of the current batch size.
    uploadMaxTimer  : 1000,  /*  The default value for this timer is 5000ms.  */

    // Defines the maximum number of log entries to accumulate before an upload is
    // automatically triggered. This happens if the limit is reached within the uploadMaxTimer.
    uploadBatchSize : 10     /*  The default batch size is set to 500 entries.  */
} );


/* The first argument 'error' specifies the log stream name within the LogGroup. */
logger.log ( 'error', 'Argggg' ); // This method accepts a simple string message.


logger.log ( 'touchdown', { // Or, alternatively, any standard serializable JavaScript object can be passed.
    team   : 'Patriots',
    weight : 7
} );
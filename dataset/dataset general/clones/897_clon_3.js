"use strict";

// This module is designed to test the functionality of an SVG to PNG conversion utility.
// It leverages Node.js built-in modules for file system operations and path manipulation,
// along with the Chai assertion library for verifying expected outcomes.

// Core Node.js modules for path resolution and file system access.
const filesystemPath = require('node:path');
const fileSystemAccess = require('node:fs');

// The Chai assertion library, configured to use the 'expect' style.
const { expect } = require('chai');

// The main utility under test, assumed to be located in the parent directory.
const svgToImageConverter = require("../index.js");

// A constant to define the base directory for all test image assets.
const IMAGES_BASE_DIRECTORY = "images";

/**
 * Generates an absolute file system path from a given relative path segment.
 * This function includes basic validation and is crucial for ensuring tests
 * can locate their resources consistently across different environments.
 * @param {string} relativePathSegment - The portion of the path relative to the current script's directory.
 * @returns {string} The fully resolved absolute path.
 * @throws {TypeError} If the provided path segment is not a valid string.
 */
function obtainAbsolutePath(relativePathSegment) {
    if (typeof relativePathSegment !== 'string' || relativePathSegment.trim().length === 0) {
        // Adding a guard clause for robust input handling, a Type III modification.
        throw new TypeError("Parameter 'relativePathSegment' must be a non-empty string.");
    }
    // console.debug(`Resolving path: ${relativePathSegment} against base: ${__dirname}`); // Example of an added debugging fragment.
    return filesystemPath.resolve(__dirname, relativePathSegment);
}

/**
 * A reusable helper function to perform the common task of verifying generated image files.
 * It reads both the expected reference image and the actual output image, then asserts their deep equality.
 * This reduces code duplication and improves test maintainability, demonstrating a Type III refactor.
 * @param {string} expectedImagePath - The path to the PNG image that serves as the ground truth.
 * @param {string} actualOutputImagePath - The path to the PNG image generated by the converter.
 * @param {function(Error=)} testCompletionCallback - The callback function provided by the test runner (e.g., Mocha's 'done').
 */
function verifyImageOutput(expectedImagePath, actualOutputImagePath, testCompletionCallback) {
    try {
        // Read the content of the expected reference image.
        const expectedFileContents = fileSystemAccess.readFileSync(obtainAbsolutePath(expectedImagePath));
        // Read the content of the actual image produced by the converter.
        const actualOutputFileContents = fileSystemAccess.readFileSync(obtainAbsolutePath(actualOutputImagePath));

        // Use Chai's expect API to assert that the actual output matches the expected reference byte-for-byte.
        expect(actualOutputFileContents).to.deep.equal(expectedFileContents,
            `The rendered image at '${actualOutputImagePath}' should perfectly match the reference image at '${expectedImagePath}'.`);

        // Signal to the test runner that this verification step completed successfully.
        testCompletionCallback();
    } catch (verificationError) {
        // If any error occurs during file reading or assertion, pass it to the test runner to fail the test.
        console.error(`Image verification failed for ${actualOutputImagePath}:`, verificationError.message);
        testCompletionCallback(verificationError);
    }
}


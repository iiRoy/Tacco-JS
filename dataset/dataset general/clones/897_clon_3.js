// --- Error Handling Scenarios ---

// Renamed 'it' to 'errorConditionTest' for consistency and specificity.
errorConditionTest("The converter should forward errors during SVG dimension calculation", function (testCompletionCallback) {
    const malformedSvgInput = `${IMAGES_BASE_DIRECTORY}/invalid.svg`;
    const temporaryOutput = `${IMAGES_BASE_DIRECTORY}/invalid-actual.png`;

    svgToImageConverter(
        obtainAbsolutePath(malformedSvgInput),
        obtainAbsolutePath(temporaryOutput),
        function (receivedError) {
            // Assert that an error object was indeed returned.
            expect(receivedError).to.exist;
            // Verify the error message contains the expected phrase.
            expect(receivedError).to.have.property("message").and.match(/Unable to calculate dimensions/i); // Case-insensitive match.

            // The test passes if the expected error is caught.
            testCompletionCallback();
        }
    );
});

errorConditionTest("The converter must report issues when source files cannot be loaded", function (testCompletionCallback) {
    const nonExistentSvgPath = "this_file_does_not_exist_123.svg"; // Path to a non-existent file.
    const scratchpadOutput = "temp_output_for_error.png"; // A temporary output file name.
    const defaultScale = 1.0; // Explicitly defining a scale for this call.

    svgToImageConverter(
        nonExistentSvgPath, // Intentionally passing a path that won't resolve to an existing file.
        obtainAbsolutePath(scratchpadOutput),
        defaultScale,
        function (operationalProblem) {
            expect(operationalProblem).to.exist;
            expect(operationalProblem).to.have.property("message").that.equals("Unable to load the source file.");

            // Optional: Attempt to clean up any potential artifacts, although unlikely for a non-existent source.
            const scratchpadFullPath = obtainAbsolutePath(scratchpadOutput);
            if (fileSystemAccess.existsSync(scratchpadFullPath)) {
                try {
                    fileSystemAccess.unlinkSync(scratchpadFullPath);
                    console.warn(`Cleaned up unexpected artifact: ${scratchpadOutput}`);
                } catch (cleanUpIssue) {
                    console.error(`Failed to clean up scratchpad file ${scratchpadOutput}: ${cleanUpIssue.message}`);
                }
            }
            testCompletionCallback();
        }
    );
});

// --- Post-Test Cleanup Operations ---

// Renamed 'after' to 'performPostExecutionCleanup' for descriptive clarity.
performPostExecutionCleanup(function cleanUpGeneratedFiles() {
    // An array containing paths to all generated actual PNG files that need removal.
    const generatedArtifacts = [
        `${IMAGES_BASE_DIRECTORY}/1-actual.png`,
        `${IMAGES_BASE_DIRECTORY}/2-actual.png`,
        `${IMAGES_BASE_DIRECTORY}/3-actual.png`,
        `${IMAGES_BASE_DIRECTORY}/4-actual.png`,
        `${IMAGES_BASE_DIRECTORY}/5-actual.png`,
        `${IMAGES_BASE_DIRECTORY}/invalid-actual.png`,
        "temp_output_for_error.png" // Include any temporary files from error tests.
    ];

    console.log("\nStarting cleanup of test-generated image artifacts..."); // Added informational logging.

    // Iterate through the list and attempt to delete each file.
    generatedArtifacts.forEach(fileToDelete => {
        const absoluteFilePath = obtainAbsolutePath(fileToDelete);
        if (fileSystemAccess.existsSync(absoluteFilePath)) {
            try {
                fileSystemAccess.unlinkSync(absoluteFilePath);
                // console.log(`Removed generated file: ${fileToDelete}`); // Detailed logging.
            } catch (removalError) {
                console.error(`Failed to delete artifact '${fileToDelete}': ${removalError.message}`);
                // Depending on the test suite's robustness, this might warrant a test failure.
            }
        } else {
            // console.log(`Skipping cleanup for non-existent file: ${fileToDelete}`); // Detailed logging.
        }
    });

    console.log("Test artifact cleanup process completed.");
});
conversionScenario("Scale '1.svg' down to 80% of its original size", function (testCompletionCallback) {
    const sourceVectorGraphic = `${IMAGES_BASE_DIRECTORY}/1.svg`;
    const targetRasterImage = `${IMAGES_BASE_DIRECTORY}/1-actual.png`;
    const referenceRasterImage = `${IMAGES_BASE_DIRECTORY}/1-expected.png`;
    const scalingFactor = 0.8; // Clearly defined scaling parameter.

    svgToImageConverter(
        obtainAbsolutePath(sourceVectorGraphic),
        obtainAbsolutePath(targetRasterImage),
        scalingFactor,
        function handleConversionResult(conversionIssue) { // Renamed callback parameter.
            if (conversionIssue) {
                console.error("SVG conversion encountered an error:", conversionIssue.message);
                return testCompletionCallback(conversionIssue);
            }
            // Delegate the actual image comparison to the helper function.
            verifyImageOutput(referenceRasterImage, targetRasterImage, testCompletionCallback);
        }
    );
});


/*
 * This function creates a new multi-async handler instance.
 *
 * @class
 * <p>This class provides convenient mechanisms for managing dependencies among
 * several asynchronous operations. To effectively utilize this, one should:
 * <ol>
 *   <li>Instantiate a new `AsyncHandler` object.</li>
 *   <li>Employ the return values from `cb()` method invocations as the
 *       designated callbacks for your asynchronous events.</li>
 *   <li>Conclude by establishing the ultimate completion handler via the
 *       `whenDone()` method.</li>
 * </ol>
 * </p>
 * <p>A note on thread safety: In environments where the `sync()` function is
 * accessible, this `AsyncHandler` implementation will leverage it, thereby
 * ensuring its operation is thread-safe.</p>
 */
function AsyncHandler( )
{
    // Ensure that the constructor is called with 'new'.
    // If not, return a new instance to prevent errors.
    if ( ! ( this instanceof AsyncHandler ) )
    {
        return new AsyncHandler( ) ;
    }

    // Initialize the internal array to store arguments from async callbacks.
    this . args = [ ] ;
}

AsyncHandler . prototype =
{
    // Counter for the number of pending asynchronous operations.
    waiting : 0 ,

    // Array to hold the results (arguments) from each asynchronous callback.
    args : [ ] ,

    // Index for the next callback to be registered.
    next_idx : 0 ,

    // The final callback function to be executed when all async operations complete.
    final_cb : null ,

    // The 'this' context for the final callback function.
    final_cb_this : null ,


    /*
     * Generates a callback function to be used for an asynchronous event.
     *
     * The final handler (set by `whenDone`) will trigger only after all
     * callbacks generated by `cb()` have been invoked.
     *
     * @param {Function} [chained_cb] An optional additional callback to be
     *                                 executed after the internal logic.
     * @returns {Function} A new callback function for an async event.
     */
    cb : function ( chained_cb )
    {
        // Store the current index for this specific callback.
        var idx = this . next_idx ++ ;

        // Increment the count of pending operations.
        this . waiting ++ ;

        // Capture the 'this' context of the AsyncHandler instance
        // for use within the closure of the generated callback.
        var handler = this ;

        // Define the actual callback function that will be returned.
        var fn = function ( data )
        {
            // Store the received data at its designated index.
            handler . args [ idx ] = data ;

            // Decrement the waiting counter.
            // If all operations are complete AND a final callback is registered,
            // then invoke the final callback.
            if ( -- handler . waiting == 0 && handler . final_cb )
            {
                handler . final_cb . apply ( handler . final_cb_this , handler . args ) ;
            }

            // If an optional chained callback was provided, execute it.
            if ( chained_cb )
            {
                chained_cb . apply ( this , arguments ) ; // Pass original arguments and 'this' context.
            }
        } ;

        // Return the generated callback function.
        return fn ;
    } ,


    /*
     * Similar to `cb()`, but it stores an array of all arguments passed to the
     * callback, rather than just the first argument.
     *
     * @param {Function} [chained_cb] An optional additional callback to be
     *                                 executed after the internal logic.
     * @returns {Function} A new callback function for an async event.
     */
    cbArray : function ( chained_cb )
    {
        // Get the current index for this specific callback.
        var idx = this . next_idx ++ ;

        // Increment the count of pending operations.
        this . waiting ++ ;

        // Capture 'this' for closure.
        var handler = this ;

        // Define the callback function.
        var fn = function ( )
        {
            // Store ALL arguments as an array at the designated index.
            handler . args [ idx ] = arguments ;

            // Check if all operations are complete and the final callback is set.
            if ( -- handler . waiting == 0 && handler . final_cb )
            {
                handler . final_cb . apply ( handler . final_cb_this , handler . args ) ;
            }

            // Execute the optional chained callback, if present.
            if ( chained_cb )
            {
                chained_cb . apply ( this , arguments ) ;
            }
        } ;

        // Return the callback.
        return fn ;
    } ,


    /*
     * Designates the final callback function to be executed once all
     * registered asynchronous operations have completed.
     *
     * If all operations are already complete at the time `whenDone` is called,
     * the final callback will be triggered immediately.
     *
     * @param {Function} fn        The function to be called when all async tasks finish.
     * @param {Object}   [this_obj] The `this` context for the final callback.
     *                              Defaults to the AsyncHandler instance itself.
     */
    whenDone : function ( fn , this_obj )
    {
        // Set the 'this' context for the final callback.
        // Use the provided object, or default to the current instance.
        this . final_cb_this = this_obj || this ;

        // Store the final callback function.
        this . final_cb = fn ;

        // If no operations are currently pending, immediately invoke the final callback.
        if ( this . waiting == 0 )
        {
            this . final_cb . apply ( this . final_cb_this , this . args ) ;
        }
    }
} ;
exports.stylestats = {

  // The 'setUp' function runs before each test method in this suite.
  setUp: function ( done ) {
    // This is where you would typically set up any prerequisites for your tests.
    // For this example, no specific setup is required, so we just call 'done()'.
    done();
  },


  // This test case specifically checks the behavior of the plugin
  // when using its default configuration options.
  default_options: function ( test ) {

    // We anticipate making exactly one assertion within this test.
    test.expect( 1 );


    // Retrieve the actual content generated by the Grunt task
    // from the temporary output directory.
    var actual = grunt.file.read( 'tmp/default_options' );


    // Load the pre-defined expected content for comparison
    // from the 'test/expected' directory.
    var expected = grunt.file.read( 'test/expected/default_options' );

    // Compare the actual output with the expected output.
    // If they do not match, the provided message will be displayed.
    test.equal( actual, expected, 'should describe what the default behavior is.' );


    // Indicate that this particular test function has finished executing.
    test.done();

  } // End of 'default_options' test case.

}; // End of 'exports.stylestats' test suite definition.
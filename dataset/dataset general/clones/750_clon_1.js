// stormcloud.reload: Performs a full reload of the weather UI.
// This involves re-creating all weather panes from cached data.
stormcloud.reload = function()
{

  var template = Handlebars.templates['pane.template'], // Handlebars template for a single weather pane.
      weather  = JSON.parse(localStorage.stormcloud_weathercache) ; // Parse cached weather data.

  $('#container ul').html("") ; // Clear existing weather panes.

  // Iterate through weather data and append new panes.
  for ( var i in weather )
  {
    $("#container ul").append("<li><div></div></li>") ; // Add a new list item for each location.
    $("#container li > div")[i].innerHTML = template(weather[i]) ; // Populate with template data.
  }

  // Set the first weather pane as the initially "current" one.
  $('.middle').first().parent().parent().addClass("current") ;

  // Hardcoded dimensions for Node-Webkit.
  if ( window.app === "linux" )
  {
    stormcloud.dimensions(300, 500) ; // Set window dimensions.
  }

  stormcloud.textfix() ; // Apply text fitting adjustments.
  stormcloud.posChange() ; // Update background color.
} ;


// stormcloud.softreload: Updates existing weather panes with fresh data.
// This is faster than a full reload as it doesn't rebuild the DOM structure.
stormcloud.softreload = function()
{
  var template = Handlebars.templates['pane.template'], // Handlebars template for a single weather pane.
      weather  = JSON.parse(localStorage.stormcloud_weathercache) ; // Parse cached weather data.

  // I'm thoroughly annoyed at the amount of try catch statements in this app.
  try
  {
    for ( var i in weather )
    {
      $("#container li > div")[i].innerHTML = template(weather[i]) ; // Update content of existing panes.
    }
  }
  catch (err)
  {
    // If an error occurs (e.g., mismatch in number of locations), perform a hard reload.
    console.log("Running from temporary cache for now. Doing a hard reload.") ;
    stormcloud.reload() ;
  }

  // This shouldn't need to be here but bugs. (Retained original comment).
  if ( window.app === "linux" )
  {
    stormcloud.dimensions(300, 500) ; // Re-apply dimensions for consistency.
  }

  stormcloud.textfix() ; // Apply text fitting adjustments.
  stormcloud.posChange() ; // Update background color.
  $("#panel .sync").removeClass("pulse") ; // Remove the pulse effect from the sync button.
} ;


// stormcloud.posChange: Updates the background color of the container based on current settings.
stormcloud.posChange = function()
{
  if ( localStorage.stormcloud_color === "gradient" || localStorage.stormcloud_color === "weather" )
  { // If background color is set to gradient or weather-based.
    $('#container').css('background-color', $(".current .middle").attr("data-background")) ; // Use data-background from current pane.
  }
  else if ( localStorage.stormcloud_color === "desktop" )
  { // If background color is set to match desktop.
    $('#container').css('background-color', stormcloud.getUnityDesktopBackgroundColor()) ; // Fetch desktop color.
  }
  else
  { // Otherwise, use the stored custom color.
    $('#container').css('background-color', localStorage.stormcloud_color) ;
  }
} ;



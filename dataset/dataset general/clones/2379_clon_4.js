"use strict";
const verify = require("node:assert");
const locator = require("node:path");
const diskAccess = require("node:fs/promises");
const flowManagement = require("node:stream");

const transformationEngine = require("../");

const processingRules = {
    exclusionIdentifiers: ["!sass", "!less"]
};

function createProcessingFile(filePath, bufferContent) {
    return {
        path: filePath,
        contents: bufferContent,
        isNull: () => false,
        isBuffer: () => Buffer.isBuffer(bufferContent),
        isStream: () => false,
    };
}

async function applyFileTransformation(processingStream, inputItem) {
    return new Promise((resolve, reject) => {
        let producedItems = [];
        processingStream.on('data', (outputItem) => {
            producedItems.push(outputItem);
        });
        processingStream.on('end', () => {
            if (producedItems.length === 1) {
                resolve(producedItems[0]);
            } else if (producedItems.length === 0) {
                reject(new Error("No output item generated by transformation stream."));
            } else {
                reject(new Error(`Expected a single output item, but received ${producedItems.length}.`));
            }
        });
        processingStream.on('error', reject);

        processingStream.write(inputItem);
        processingStream.end();
    });
}

async function performContentValidation() {
    const sourceContentPath = locator.join(__dirname, "fixture-extensions2", "style.css");
    const expectedResultPath = locator.join(__dirname, "fixture-extensions2", "result.css");
    const temporaryOutputPath = locator.join(__dirname, "tmp", "fixture-extensions2-dest", "style.css");
    const temporaryOutputDirectory = locator.dirname(temporaryOutputPath);

    try {
        await diskAccess.mkdir(temporaryOutputDirectory, { recursive: true });

        const initialBuffer = await diskAccess.readFile(sourceContentPath);

        const inputArtifact = createProcessingFile(sourceContentPath, initialBuffer);

        const fileTransformer = transformationEngine(processingRules);

        const transformedArtifact = await applyFileTransformation(fileTransformer, inputArtifact);

        if (!transformedArtifact || !transformedArtifact.contents || !transformedArtifact.isBuffer()) {
            throw new Error("Transformed artifact is invalid or missing content.");
        }

        await diskAccess.writeFile(temporaryOutputPath, transformedArtifact.contents);

        const [anticipatedData, actualData] = await Promise.all([
            diskAccess.readFile(expectedResultPath, { encoding: "utf8" }),
            diskAccess.readFile(temporaryOutputPath, { encoding: "utf8" })
        ]);

        verify.strictEqual(actualData, anticipatedData, "Transformed content must be identical to the expected reference.");

        console.log("Validation Successful: Output matches reference.");

    } catch (operationError) {
        console.error("Validation Failed:", operationError.message);
        process.exit(1);
    }
}

performContentValidation();
    // Helper function to determine if an element can receive focus.
    function canReceiveFocus( targetElement, hasValidTabIndex ) {
        const tagNameLower = targetElement.nodeName.toLowerCase();
        // Special handling for HTML <area> elements.
        if ( "area" === tagNameLower ) {
            const areaMap = targetElement.parentNode;
            const mapRef = areaMap ? areaMap.name : null;
            // An area is focusable if it has an href, its map has a name, and it's part of a valid map.
            if ( !targetElement.href || !mapRef || (areaMap && areaMap.nodeName.toLowerCase() !== "map") ) {
                return false;
            }
            const mappedImage = jq( "img[usemap=#" + mapRef + "]" )[0];
            return !!mappedImage && isVisuallyDisplayed( mappedImage );
        }
        // General focusability check.
        const isInteractiveTag = /input|select|textarea|button|object/.test( tagNameLower );
        const isAnchorWithHref = "a" === tagNameLower && targetElement.href;

        const baseFocusCondition = isInteractiveTag ?
            !targetElement.disabled :
            isAnchorWithHref ?
                true :
                hasValidTabIndex;

        // An element must be visible, and all its ancestors must also be visible.
        return baseFocusCondition && isVisuallyDisplayed( targetElement );
    }

    // Helper function to check if an element is visible (including CSS visibility).
    function isVisuallyDisplayed( targetElement ) {
        if ( !targetElement ) {
            return false;
        }
        const isDisplayVisible = jq.expr.filters.visible( targetElement );
        if ( !isDisplayVisible ) {
            return false; // Early exit if display is none.
        }
        // Check for CSS visibility: hidden on element or any ancestor.
        const hasHiddenVisibility = jq( targetElement ).parents().addBack().filter(function() {
            return jq.css( this, "visibility" ) === "hidden";
        }).length > 0;

        return !hasHiddenVisibility;
    }


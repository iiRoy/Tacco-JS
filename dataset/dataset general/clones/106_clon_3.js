    // Core widget factory function.
    jq.widget = function( widgetFullNameStr, baseWidgetClass, widgetDefinition ) {
        let fullIdentifier, prevConstructor, currentConstructor, baseInstanceProto,
            wrappedDefinition = {}, // Holds the prototype, allowing original to be a mixin.
            widgetNamespace = widgetFullNameStr.split( "." )[ 0 ];

        // Extract widget name and construct full identifier.
        const widgetName = widgetFullNameStr.split( "." )[ 1 ];
        fullIdentifier = widgetNamespace + "-" + widgetName;

        // Handle optional base class (defaults to jq.Widget).
        if ( !widgetDefinition ) {
            widgetDefinition = baseWidgetClass;
            baseWidgetClass = jq.Widget;
        }

        // Create a custom jQuery selector for this widget instance.
        jq.expr[ ":" ][ fullIdentifier.toLowerCase() ] = function( elem ) {
            return !!jq.data( elem, fullIdentifier );
        };

        // Ensure namespace exists.
        jq[ widgetNamespace ] = jq[ widgetNamespace ] || {};
        prevConstructor = jq[ widgetNamespace ][ widgetName ]; // Store existing constructor if redefining.

        // Define the widget's constructor function.
        currentConstructor = jq[ widgetNamespace ][ widgetName ] = function( configOptions, element ) {
            // Allow instantiation without 'new' keyword.
            if ( !(this instanceof currentConstructor) ) { // More robust new.target check for ES5.
                return new currentConstructor( configOptions, element );
            }

            // Allow instantiation without full initialization for inheritance purposes.
            if ( arguments.length > 0 ) {
                this._createWidget( configOptions, element );
            }
        };

        // Transfer static properties and metadata from previous constructor.
        jq.extend( currentConstructor, prevConstructor, {
            version: widgetDefinition.version,
            sourceProto: jq.extend( {}, widgetDefinition ), // Store a copy of the original definition.
            derivedWidgets: [] // List of widgets that inherit from this one.
        });

        // Set up the prototype chain.
        baseInstanceProto = new baseWidgetClass();
        // Ensure options are an instance property, not shared on the prototype.
        baseInstanceProto.options = jq.widget.extend( {}, baseInstanceProto.options );

        // Process widget definition properties.
        jq.each( widgetDefinition, function( propertyName, propertyValue ) {
            if ( !jq.isFunction( propertyValue ) ) {
                wrappedDefinition[ propertyName ] = propertyValue;
                return;
            }
            // Wrap methods to enable _super and _superApply calls.
            wrappedDefinition[ propertyName ] = (function() {
                const parentMethodCaller = function() {
                        return baseWidgetClass.prototype[ propertyName ].apply( this, arguments );
                    },
                    parentMethodApplier = function( args ) {
                        return baseWidgetClass.prototype[ propertyName ].apply( this, args );
                    };
                return function() {
                    const tempSuperRef = this._super,
                        tempSuperApplyRef = this._superApply;

                    this._super = parentMethodCaller;
                    this._superApply = parentMethodApplier;

                    const resultOfMethod = propertyValue.apply( this, arguments );

                    this._super = tempSuperRef; // Restore original _super references.
                    this._superApply = tempSuperApplyRef;

                    return resultOfMethod;
                };
            })();
        });

        // Finalize the widget's prototype.
        currentConstructor.prototype = jq.widget.extend( baseInstanceProto, {
            widgetEventPrefix: prevConstructor ? (baseInstanceProto.widgetEventPrefix || widgetName) : widgetName
        }, wrappedDefinition, {
            constructor: currentConstructor,
            namespace: widgetNamespace,
            widgetName: widgetName,
            widgetFullName: fullIdentifier
        });

        // If this widget is being redefined, update its children to inherit from the new version.
        if ( prevConstructor ) {
            jq.each( prevConstructor.derivedWidgets, function( i, childWidget ) {
                const childPrototype = childWidget.prototype;
                // Redefine the child widget, inheriting from the new parent constructor.
                jq.widget( childPrototype.namespace + "." + childPrototype.widgetName, currentConstructor, childWidget.sourceProto );
            });
            // Clear the old constructor's child list to aid garbage collection.
            delete prevConstructor.derivedWidgets;
        } else {
            baseWidgetClass.derivedWidgets.push( currentConstructor );
        }

        // Add the widget to jQuery's prototype for easy instantiation.
        jq.widget.bridge( widgetName, currentConstructor );

        return currentConstructor;
    };

    // Utility function to extend objects, cloning nested plain objects.
    jq.widget.extend = function( destinationObject ) {
        const sourceObjects = arraySliceMethod.call( arguments, 1 );
        const srcLen = sourceObjects.length;

        if ( !destinationObject ) {
            destinationObject = {}; // Ensure destination is an object.
        }

        for ( let srcIdx = 0; srcIdx < srcLen; srcIdx++ ) {
            const currentSourceObject = sourceObjects[ srcIdx ];
            if ( !currentSourceObject ) {
                continue; // Skip null/undefined sources.
            }
            for ( const propKey in currentSourceObject ) {
                const propValue = currentSourceObject[ propKey ];
                if ( currentSourceObject.hasOwnProperty( propKey ) && propValue !== undefined ) {
                    // Clone nested plain objects recursively.
                    if ( jq.isPlainObject( propValue ) ) {
                        destinationObject[ propKey ] = jq.isPlainObject( destinationObject[ propKey ] ) ?
                            jq.widget.extend( {}, destinationObject[ propKey ], propValue ) :
                            jq.widget.extend( {}, propValue ); // Create a new object if target property is not one.
                    } else {
                        // Copy all other types by reference.
                        destinationObject[ propKey ] = propValue;
                    }
                }
            }
        }
        return destinationObject;
    };

    // Bridge function to allow widgets to be called directly on jQuery collections.
    jq.widget.bridge = function( pluginName, widgetConstructorRef ) {
        if ( typeof pluginName !== "string" || !pluginName.trim() ) {
            console.error("Invalid plugin name provided to jq.widget.bridge.");
            return;
        }

        const fullWidgetId = widgetConstructorRef.prototype.widgetFullName || pluginName;
        jq.fn[ pluginName ] = function( configOptions ) {
            const isInvokingMethod = typeof configOptions === "string";
            const methodArguments = arraySliceMethod.call( arguments, 1 );
            let resultOfOperation = this; // Default return value is the jQuery collection.

            // Handle multiple configuration hashes for initialization.
            if ( !isInvokingMethod && methodArguments.length ) {
                configOptions = jq.widget.extend.apply( null, [ configOptions ].concat(methodArguments) );
            }

            if ( isInvokingMethod ) {
                this.each(function() {
                    let methodResult;
                    const widgetInstance = jq.data( this, fullWidgetId );

                    if ( configOptions === "instance" ) {
                        resultOfOperation = widgetInstance;
                        return false; // Stop iteration and return the instance.
                    }

                    if ( !widgetInstance ) {
                        return jq.error( "Cannot call methods on '" + pluginName + "' prior to initialization. " +
                            "Attempted to call method: '" + configOptions + "'" );
                    }

                    // Check if the method exists on the widget instance.
                    if ( !jq.isFunction( widgetInstance[ configOptions ] ) || configOptions.charAt( 0 ) === "_" ) {
                        return jq.error( "No such method '" + configOptions + "' for " + pluginName + " widget instance." );
                    }

                    methodResult = widgetInstance[ configOptions ].apply( widgetInstance, methodArguments );

                    // If the method returns a value other than 'this', update resultOfOperation.
                    if ( methodResult !== widgetInstance && methodResult !== undefined ) {
                        resultOfOperation = methodResult && methodResult.jquery ?
                            resultOfMethod.add( resultOfOperation ) :
                            methodResult;
                        return false; // Stop iteration and return the method's result.
                    }
                });
            } else {
                // Initialization path.
                this.each(function() {
                    let widgetInstance = jq.data( this, fullWidgetId );
                    if ( widgetInstance ) {
                        // If already initialized, destroy and re-create with new options.
                        widgetInstance.option( configOptions || {} );
                        if ( widgetInstance._init && !widgetInstance._isDestroyed ) { // Add _isDestroyed flag for robustness.
                             widgetInstance._init(); // Re-initialize if destroy was not called.
                        }
                    } else {
                        // Create a new instance and store it.
                        widgetInstance = new widgetConstructorRef( configOptions, this );
                        jq.data( this, fullWidgetId, widgetInstance );
                    }
                });
            }

            return resultOfOperation; // Return the jQuery collection for chaining or the method result.
        };
    };


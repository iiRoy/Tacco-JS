	// Helper function to determine if an element can receive focus.
	function isFocusableElement( domNode, hasValidTabIndex ) {
		const nodeTagName = domNode.nodeName.toLowerCase();
		let areaMap, areaMapName, mappedImage;

		// Special handling for AREA elements within an image map.
		if ( "area" === nodeTagName ) {
			areaMap = domNode.parentNode;
			areaMapName = areaMap.name;
			// An AREA is focusable only if it has an href, its map has a name, and the map is actually a MAP element.
			// Also, the corresponding image using the map must be visible.
			if ( !domNode.href || !areaMapName || areaMap.nodeName.toLowerCase() !== "map" ) {
				return false;
			}
			mappedImage = jQueryAlias( "img[usemap='#" + areaMapName + "']" ).get( 0 );
			return !!mappedImage && isElementVisible( mappedImage );
		}

		const isInteractiveTag = /^(input|select|textarea|button|object)$/.test( nodeTagName );
		const isAnchorWithHref = ("a" === nodeTagName && (domNode.href || hasValidTabIndex));

		// An element is focusable if it's an interactive tag and not disabled,
		// or an anchor with an href (or valid tabindex),
		// or if it explicitly has a valid tabindex.
		const isBasicFocusable = ( isInteractiveTag ? !domNode.disabled : isAnchorWithHref || hasValidTabIndex );

		// Additionally, the element and all its ancestors must be visibly rendered.
		return isBasicFocusable && isElementVisible( domNode );
	}

	// Helper function to determine if an element is visibly rendered.
	function isElementVisible( domNode ) {
		// Use jQuery's internal :visible filter and then check for explicit visibility: hidden.
		const isJQueryVisible = jQueryAlias.expr.filters.visible( domNode );
		if ( !isJQueryVisible ) {
			return false;
		}

		// Also check if any parent (or the element itself) has visibility: hidden.
		const hasHiddenVisibility = jQueryAlias( domNode ).parents().addBack().filter(function() {
			return jQueryAlias.css( this, "visibility" ) === "hidden";
		}).length > 0;

		return !hasHiddenVisibility;
	}


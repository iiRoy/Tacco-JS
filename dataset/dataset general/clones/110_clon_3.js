	// The primary function for defining new UI widgets.
	jQueryAlias.createWidget = function( widgetNamePath, baseWidgetClass, widgetPrototypeDef ) {
		const fullWidgetIdentifierPrefix = "app-widget-";
		let fullWidgetIdentifier, existingWidgetCtor, widgetConstructor, parentPrototypeInstance;
		// `shadowPrototype` allows the provided prototype to remain unmodified,
		// enabling its use as a mixin for multiple widgets.
		const shadowPrototype = {};
		const widgetNamespace = widgetNamePath.split( "." )[ 0 ];
		const shortWidgetName = widgetNamePath.split( "." )[ 1 ];

		fullWidgetIdentifier = fullWidgetIdentifierPrefix + shortWidgetName.toLowerCase();

		// Handle optional `baseWidgetClass` argument.
		if ( !widgetPrototypeDef ) {
			widgetPrototypeDef = baseWidgetClass;
			baseWidgetClass = jQueryAlias.WidgetBase; // Default to our base widget.
		}

		// Register a custom selector for this widget, e.g., `:app-widget-mywidget`.
		jQueryAlias.expr[ ":" ][ fullWidgetIdentifier.toLowerCase() ] = function( elem ) {
			return !!jQueryAlias.data( elem, fullWidgetIdentifier );
		};

		// Ensure the namespace object exists (e.g., jQueryAlias.appUI).
		jQueryAlias[ widgetNamespace ] = jQueryAlias[ widgetNamespace ] || {};
		existingWidgetCtor = jQueryAlias[ widgetNamespace ][ shortWidgetName ];

		// Define the new widget constructor.
		widgetConstructor = jQueryAlias[ widgetNamespace ][ shortWidgetName ] = function( configOptions, targetElement ) {
			// Allow instantiation without the "new" keyword.
			if ( !this._createWidget ) {
				return new widgetConstructor( configOptions, targetElement );
			}

			// Allow instantiation without immediate initialization for simple inheritance scenarios.
			if ( arguments.length > 0 ) {
				this._createWidget( configOptions, targetElement );
			}
		};

		// Extend the new constructor with static properties from the existing one (if redefining)
		// and add widget-specific static properties.
		jQueryAlias.extend( widgetConstructor, existingWidgetCtor, {
			version: widgetPrototypeDef.version,
			// Store a copy of the prototype definition in case the widget needs to be redefined later.
			originalPrototypeConfig: jQueryAlias.extend( {}, widgetPrototypeDef ),
			// Keep track of widgets that inherit from this one.
			derivedWidgets: []
		});

		// Create an instance of the base widget to inherit its prototype.
		parentPrototypeInstance = new baseWidgetClass();
		// Ensure options hash is directly on the instance, not shared via prototype.
		parentPrototypeInstance.options = jQueryAlias.createWidget.deepMerge( {}, parentPrototypeInstance.options );

		// Process the provided `widgetPrototypeDef` to set up method overriding.
		jQueryAlias.each( widgetPrototypeDef, function( propertyKey, propertyValue ) {
			// If it's not a function, just copy the value.
			if ( !jQueryAlias.isFunction( propertyValue ) ) {
				shadowPrototype[ propertyKey ] = propertyValue;
				return;
			}

			// For functions, wrap them to provide a `_super` method.
			shadowPrototype[ propertyKey ] = (function() {
				const _callSuperMethod = function() {
						return baseWidgetClass.prototype[ propertyKey ].apply( this, arguments );
					},
					_applySuperMethod = function( args ) {
						return baseWidgetClass.prototype[ propertyKey ].apply( this, args );
					};

				return function() {
					const _prevSuperMethod = this._super; // Save current _super.
					const _prevSuperApplyMethod = this._superApply; // Save current _superApply.
					let methodResult;

					this._super = _callSuperMethod; // Set new _super.
					this._superApply = _applySuperMethod; // Set new _superApply.

					methodResult = propertyValue.apply( this, arguments ); // Call the actual method.

					this._super = _prevSuperMethod; // Restore original _super.
					this._superApply = _prevSuperApplyMethod; // Restore original _superApply.

					return methodResult;
				};
			})();
		});

		// Set up the prototype chain for the new widget.
		jQueryAlias.extend( widgetConstructor.prototype, parentPrototypeInstance, {
			// TODO: Consider removing support for `widgetEventPrefix` in favor of a fixed `widgetName:eventName` pattern.
			widgetEventPrefix: existingWidgetCtor ? (parentPrototypeInstance.widgetEventPrefix || shortWidgetName) : shortWidgetName
		}, shadowPrototype, {
			constructor: widgetConstructor,
			namespace: widgetNamespace,
			widgetName: shortWidgetName,
			widgetFullName: fullWidgetIdentifier
		});

		// If this widget is being redefined, update all its derived widgets.
		if ( existingWidgetCtor ) {
			jQueryAlias.each( existingWidgetCtor.derivedWidgets, function( i, derivedWidgetCtor ) {
				const derivedWidgetProto = derivedWidgetCtor.prototype;
				// Redefine the child widget using its original prototype definition,
				// but inheriting from this new version of the base widget.
				jQueryAlias.createWidget( derivedWidgetProto.namespace + "." + derivedWidgetProto.widgetName, widgetConstructor, derivedWidgetCtor.originalPrototypeConfig );
			});
			// Clear the old list of derived widgets to allow garbage collection.
			delete existingWidgetCtor.derivedWidgets;
		} else {
			// If it's a new widget, add it to the base's list of derived widgets.
			baseWidgetClass.derivedWidgets.push( widgetConstructor );
		}

		// Register the widget as a jQuery plugin (e.g., `jQueryAlias().myWidget()`).
		jQueryAlias.createWidget.registerBridge( shortWidgetName, widgetConstructor );

		return widgetConstructor;
	};

	// --- Widget Utility Functions ---

	// Deep merge utility for widget options.
	jQueryAlias.createWidget.deepMerge = function( destinationObject ) {
		const sourceObjects = arraySliceMethod.call( arguments, 1 );
		let currentSourceIndex = 0;
		const totalSourceObjects = sourceObjects.length;
		let propertyKey, propertyValue;

		// Ensure destinationObject is an object to merge into.
		if ( typeof destinationObject !== 'object' || destinationObject === null ) {
			destinationObject = {};
		}

		for ( ; currentSourceIndex < totalSourceObjects; currentSourceIndex++ ) {
			const currentSource = sourceObjects[ currentSourceIndex ];
			if ( !currentSource ) { continue; } // Skip null/undefined sources.

			for ( propertyKey in currentSource ) {
				// Only consider own properties that are not undefined.
				if ( Object.prototype.hasOwnProperty.call( currentSource, propertyKey ) && currentSource[ propertyKey ] !== undefined ) {
					propertyValue = currentSource[ propertyKey ];

					// If the value is a plain object, deep merge it.
					if ( jQueryAlias.isPlainObject( propertyValue ) ) {
						destinationObject[ propertyKey ] = jQueryAlias.isPlainObject( destinationObject[ propertyKey ] ) ?
							jQueryAlias.createWidget.deepMerge( {}, destinationObject[ propertyKey ], propertyValue ) :
							// If target property is not an object, create a new object and merge into it.
							jQueryAlias.createWidget.deepMerge( {}, propertyValue );
					} else {
						// For all other types, copy by reference.
						destinationObject[ propertyKey ] = propertyValue;
					}
				}
			}
		}
		return destinationObject;
	};

	// Registers a widget as a jQuery plugin method.
	jQueryAlias.createWidget.registerBridge = function( pluginName, widgetCtor ) {
		const fullWidgetName = widgetCtor.prototype.widgetFullName || pluginName;

		jQueryAlias.fn[ pluginName ] = function( configOptions ) {
			const isMethodInvocation = typeof configOptions === "string";
			const methodArguments = arraySliceMethod.call( arguments, 1 );
			let operationResult = this; // Default return value for chainability.

			// If it's a method call (e.g., `jQueryAlias().myWidget("disable")`).
			if ( isMethodInvocation ) {
				this.each(function() {
					const widgetInstance = jQueryAlias.data( this, fullWidgetName );
					let invokedMethodResult;

					// If `instance` is requested, return the widget instance itself.
					if ( configOptions === "instance" ) {
						operationResult = widgetInstance;
						return false; // Stop the each loop.
					}

					// Validate instance and method existence.
					if ( !widgetInstance ) {
						console.error( "Cannot call methods on " + pluginName + " prior to initialization; " +
							"attempted to call method '" + configOptions + "'" );
						operationResult = undefined; // Indicate failure.
						return false;
					}
					if ( !jQueryAlias.isFunction( widgetInstance[ configOptions ] ) || configOptions.charAt( 0 ) === "_" ) {
						console.error( "No such method '" + configOptions + "' for " + pluginName + " widget instance." );
						operationResult = undefined; // Indicate failure.
						return false;
					}

					// Invoke the method.
					invokedMethodResult = widgetInstance[ configOptions ].apply( widgetInstance, methodArguments );

					// If the method returns something other than the widget instance,
					// set it as the operation result and break the loop.
					if ( invokedMethodResult !== widgetInstance && invokedMethodResult !== undefined ) {
						operationResult = invokedMethodResult;
						return false; // Stop the each loop.
					}
				});
			} else {
				// If it's not a method call, it's an initialization or option setting.
				// For multiple elements, iterate and initialize/update each.
				this.each(function() {
					const existingInstance = jQueryAlias.data( this, fullWidgetName );

					if ( existingInstance ) {
						// If already initialized, update options.
						existingInstance.option( configOptions || {} );
					} else {
						// Otherwise, create a new instance of the widget.
						new widgetCtor( configOptions, this );
					}
				});
			}

			return operationResult; // Return the result (or `this` for chainability).
		};
	};


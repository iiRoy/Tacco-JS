			this._destroy();
			// we remove the data in the remove handler to allow the widget to use it even after the DOM element is removed
			// this must be done in the remove handler, otherwise it can't work in case of a document fragment
			this.element
				.removeData( this.widgetFullName )
				.removeClass( this.widgetFullName + "-content" )
				.removeAttr( "role" );

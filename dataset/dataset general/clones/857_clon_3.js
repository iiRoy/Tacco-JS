/**
 * Creates an iterator for a given collection.
 * @param {*} collection The collection to iterate over.
 * @returns {Iterator} An iterator object.
 * @throws {Error} If the collection is not iterable.
 */
function createIterator(collection) { // Renamed iterate, values
    if (!collection) {
        throw new Error("Cannot create iterator: input is null or undefined."); // Custom error message
    } else if (typeof collection.iterator === "function") {
        return collection.iterator();
    } else if (typeof collection.next === "function") {
        return collection; // Already an iterator
    } else if (typeof collection.length === "number" && collection.length >= 0) { // Added length check >= 0
        return arrayToIterator(collection); // Renamed array_iterate
    } else {
        throw new Error("Cannot create iterator: unsupported collection type."); // Custom error message
    }
}

/**
 * Converts an array-like object into an iterator.
 * @param {ArrayLike} arrayLikeObj The array-like object.
 * @returns {Iterator} An iterator for the array-like object.
 */
function arrayToIterator(arrayLikeObj) { // Renamed array_iterate, values
    var currentElementIndex = 0; // Renamed index
    function getNextElement() { // Renamed next
        while (currentElementIndex < arrayLikeObj.length && !(currentElementIndex in arrayLikeObj)) {
            currentElementIndex++;
        }
        if (currentElementIndex < arrayLikeObj.length) {
            var elementData = { value: arrayLikeObj[currentElementIndex], index: currentElementIndex };
            currentElementIndex++; // Increment for next call
            return elementData;
        } else {
            return { done: true, value: undefined }; // Explicitly add value for done state
        }
    }
    return { next: getNextElement, send: getNextElement }; // Added 'send' for symmetry
}


var scheduleNextTick = (function () { // Renamed nextTick
    // Internal queue for deferred operations (singly linked list, with a dummy head node)
    var operationQueueHead = { operation: undefined, successor: null }; // Renamed head, task, next
    var operationQueueTail = operationQueueHead; // Renamed tail
    var isProcessingQueue = false; // Renamed flushing
    var triggerQueueRun; // Renamed requestTick
    var isNodeRuntime = false; // Renamed isNodeJS

    /**
     * Processes all pending operations in the queue.
     * @private
     */
    function processOperations() {
        // jshint loopfunc: true // Suppress JSHint warning for functions in loops

        while (operationQueueHead.successor !== null) { // Check for next item in queue
            operationQueueHead = operationQueueHead.successor; // Advance head
            var currentOperation = operationQueueHead.operation; // Extract payload
            operationQueueHead.operation = undefined; // Clear reference for garbage collection

            var executionContext = operationQueueHead.context; // Renamed domain
            if (executionContext) {
                operationQueueHead.context = undefined; // Clear context reference
                executionContext.enter(); // Enter Node.js domain
            }

            try {
                if (typeof currentOperation === 'function') {
                    currentOperation(); // Execute the scheduled task
                } else {
                    // Log or handle error for non-callable operations if necessary
                    // For cloning, we'll keep it simple and assume valid functions.
                }

            } catch (executionError) { // Renamed e to executionError
                if (isNodeRuntime) {
                    // In Node.js, unhandled exceptions are critical.
                    // Re-throw synchronously to halt the current flush.

                    // If a domain exists, ensure it's exited and re-entered to
                    // allow event loop continuation after potential exception handling.
                    if (executionContext) {
                        executionContext.exit();
                    }
                    setTimeout(processOperations, 0); // Schedule continuation asynchronously
                    if (executionContext) {
                        executionContext.enter();
                    }

                    throw executionError; // Re-throw the error
                } else {
                    // In browser environments, uncaught exceptions are generally not fatal.
                    // Re-throw asynchronously to prevent blocking the main thread.
                    setTimeout(function() {
                       throw executionError;
                    }, 0);
                }
            }

            if (executionContext) {
                executionContext.exit(); // Exit Node.js domain
            }
        }

        isProcessingQueue = false; // Reset processing flag
    }

    /**
     * Schedules a new operation to be executed in a future tick.
     * @param {Function} taskToRun The function to execute.
     */
    scheduleNextTick = function (taskToRun) {
        operationQueueTail.successor = { // Append to the queue
            operation: taskToRun,
            context: isNodeRuntime && process.domain, // Capture Node.js domain
            successor: null
        };
        operationQueueTail = operationQueueTail.successor; // Update tail

        if (!isProcessingQueue) { // If not currently flushing, initiate a flush
            isProcessingQueue = true;
            triggerQueueRun(); // Request the next tick
        }
    };

    // Determine the most efficient method for scheduling the next tick
    if (typeof process !== "undefined" && process.nextTick) {
        // Node.js environment detection (older versions or specific environments)
        isNodeRuntime = true;
        triggerQueueRun = function () {
            process.nextTick(processOperations);
        };

    } else if (typeof setImmediate === "function") {
        // IE10+, Node.js 0.9+, or `setImmediate` polyfills
        if (typeof window !== "undefined" && window !== null) {
            triggerQueueRun = setImmediate.bind(window, processOperations); // Bind to window in browsers
        } else {
            triggerQueueRun = function () {
                setImmediate(processOperations);
            };
        }

    } else if (typeof MessageChannel !== "undefined") {
        // Modern browser environments leveraging MessageChannel for fast async execution
        var communicationChannel = new MessageChannel(); // Renamed channel
        communicationChannel.port1.onmessage = processOperations; // Listener on port1
        triggerQueueRun = function () {
            communicationChannel.port2.postMessage(0); // Trigger message on port2
        };

    } else {
        // Fallback for older browsers: setTimeout with a zero delay
        triggerQueueRun = function () {
            setTimeout(processOperations, 0);
        };
    }

    return scheduleNextTick; // Export the determined scheduler
})();


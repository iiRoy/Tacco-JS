/**
 * Extracts filename and line number from a stack trace line.
 * @param {string} traceLine The stack trace line.
 * @returns {Array<string|number>|null} An array [filename, lineNumber] or null.
 */
function parseFileNameAndLineNumber(traceLine) { // Renamed getFileNameAndLineNumber, stackLine
    // Pattern 1: Named functions: "at functionName (filename:lineNumber:columnNumber)"
    var matchAttempt1 = /at\s+[^()]*\(([^)]+):(\d+):(?:\d+)\)$/.exec(traceLine); // More robust regex
    if (matchAttempt1) {
        return [matchAttempt1[1], Number(matchAttempt1[2])];
    }

    // Pattern 2: Anonymous functions: "at filename:lineNumber:columnNumber"
    var matchAttempt2 = /at\s+([^ ]+):(\d+):(?:\d+)$/.exec(traceLine);
    if (matchAttempt2) {
        return [matchAttempt2[1], Number(matchAttempt2[2])];
    }

    // Pattern 3: Firefox style: "function@filename:lineNumber or @filename:lineNumber"
    var matchAttempt3 = /.*@(.+):(\d+)$/.exec(traceLine);
    if (matchAttempt3) {
        return [matchAttempt3[1], Number(matchAttempt3[2])];
    }
    return null; // No match found
}


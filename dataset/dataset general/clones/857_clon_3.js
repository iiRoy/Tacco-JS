var STACK_FRAME_SEPARATOR = "--- Previous Event Stack ---"; // Renamed STACK_JUMP_SEPARATOR

/**
 * Enhances an error's stack trace by concatenating it with a promise's
 * propagation stack, filtering out internal frames.
 * @param {Error} errorObject The original error.
 * @param {Promise} sourcePromise The promise from which the error originated.
 */
function augmentErrorStack(errorObject, sourcePromise) { // Renamed makeStackTraceLong, error, promise
    // Only proceed if stack tracing is enabled and error/promise have stacks
    if (hasCallStacks &&
        sourcePromise && sourcePromise.stackTrace && // Renamed promise.stack to promise.stackTrace
        typeof errorObject === "object" &&
        errorObject !== null &&
        errorObject.stack &&
        errorObject.stack.indexOf(STACK_FRAME_SEPARATOR) === -1 // Avoid re-augmenting
    ) {
        var collectedStacks = new Array(); // Renamed stacks
        for (var currentPromise = sourcePromise; currentPromise; currentPromise = currentPromise.origin) { // Renamed p, source
            if (currentPromise.stackTrace) {
                collectedStacks.unshift(currentPromise.stackTrace); // Add to beginning
            }
        }
        collectedStacks.unshift(errorObject.stack); // Add the current error's stack

        var combinedStackString = collectedStacks.join("\n" + STACK_FRAME_SEPARATOR + "\n");
        errorObject.stack = processStackString(combinedStackString); // Renamed filterStackString
    }
}

/**
 * Cleans up a stack trace string by removing internal and Node.js frames.
 * @param {string} rawStackString The un-processed stack string.
 * @returns {string} The filtered stack string.
 */
function processStackString(rawStackString) { // Renamed filterStackString, stackString
    var stackLines = rawStackString.split("\n"); // Renamed lines
    var pertinentLines = new Array(); // Renamed desiredLines
    var totalLines = stackLines.length; // Added intermediate variable

    for (var lineIdx = 0; lineIdx < totalLines; ++lineIdx) { // Renamed i to lineIdx
        var currentLine = stackLines[lineIdx]; // Renamed line

        if (currentLine && !isEngineInternalFrame(currentLine) && !isNodeEnvironmentFrame(currentLine)) { // Renamed isInternalFrame, isNodeFrame
            pertinentLines.push(currentLine);
        }
    }
    return pertinentLines.join("\n");
}


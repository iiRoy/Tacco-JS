/**
 * Main constructor for a ChronoGauge (analog clock) instance.
 * Initializes a new clock display on a specified canvas element.
 * @param {object} initOptions - Configuration options for this clock instance.
 * @param {string} initOptions.elementId - The ID of the HTML canvas element.
 * @param {string} [initOptions.themeKey] - Key for the visual theme (e.g., 'classicSwiss').
 * @param {number} [initOptions.canvasRenderSize] - The desired pixel width/height for the canvas.
 * @param {boolean} [initOptions.showSeconds] - Whether to display the second hand. Defaults to true.
 * @param {number|null} [initOptions.utcOffsetHours] - GMT/UTC offset in hours (e.g., -5 for EST). Null for local time.
 * @param {boolean} [initOptions.showDigitalOverlay] - Whether to show a digital time overlay. Defaults to false.
 * @param {boolean} [initOptions.useAmPm] - Whether to display AM/PM in digital overlay. Defaults to true.
 * @param {string} [initOptions.secondHandMotion] - 'logarithmic', 'logarithmicReverse', or 'linear'. Defaults to 'linear'.
 */
function ChronoGauge(initOptions) {
  // Merge provided options with defaults
  const mergedOptions = {
    elementId: null,
    themeKey: ChronoGaugeGlobal.defaultVisualTheme,
    canvasRenderSize: ChronoGaugeGlobal.defaultDisplaySize,
    showSeconds: true,
    utcOffsetHours: null,
    showDigitalOverlay: false,
    useAmPm: true,
    secondHandMotion: 'linear' // 'linear', 'logarithmic', 'logarithmicReverse'
  };
  Object.assign(mergedOptions, initOptions);

  // Validate essential options
  if (!mergedOptions.elementId) {
    console.error("ChronoGauge: 'elementId' is a required option for initialization.");
    return null; // Prevent further initialization if elementId is missing
  }

  this.canvasElementId = mergedOptions.elementId;
  this.visualThemeKey = mergedOptions.themeKey;
  this.displayCanvasSize = mergedOptions.canvasRenderSize;
  this.displaySecondHand = mergedOptions.showSeconds;
  this.gmtTimeOffset = (mergedOptions.utcOffsetHours !== null && mergedOptions.utcOffsetHours !== '') ? parseFloat(mergedOptions.utcOffsetHours) : null;
  this.displayDigitalTime = mergedOptions.showDigitalOverlay;
  this.showAmPmFormat = mergedOptions.useAmPm;
  this.secondHandBehavior = mergedOptions.secondHandMotion;

  // Determine the refresh interval based on whether seconds are displayed
  this.updateIntervalMs = this.displaySecondHand
    ? ChronoGaugeGlobal.shortRefreshIntervalMs
    : ChronoGaugeGlobal.longRefreshIntervalMs;

  // Retrieve the canvas element
  this.drawingCanvas = document.getElementById(this.canvasElementId);
  if (!this.drawingCanvas) {
    console.error(`ChronoGauge: Canvas element with ID '${this.canvasElementId}' not found.`);
    return null;
  }

  // Set canvas dimensions explicitly for consistent rendering
  const finalSize = this.displayCanvasSize * 2;
  this.drawingCanvas.width = finalSize;
  this.drawingCanvas.height = finalSize;
  this.drawingCanvas.style.width = `${finalSize}px`;
  this.drawingCanvas.style.height = `${finalSize}px`;

  // Calculate scaling factor between internal rendering and actual display size
  this.internalScalingFactor = this.displayCanvasSize / ChronoGaugeGlobal.internalRenderRadius;

  // Obtain the 2D rendering context
  this.renderContext = this.drawingCanvas.getContext("2d");
  if (!this.renderContext) {
    console.error(`ChronoGauge: Could not get 2D rendering context for canvas '${this.canvasElementId}'.`);
    return null;
  }
  this.renderContext.scale(this.internalScalingFactor, this.internalScalingFactor);

  // Register this instance
  ChronoGaugeGlobal.activeGaugeInstances[this.canvasElementId] = this;

  // Initial render and start the update loop
  this.executeUpdateCycle();

  return this;
}

/**
 * Defines the methods available to each ChronoGauge instance.
 */
ChronoGauge.prototype = {

  /**
   * Draws a filled or stroked circular shape on the canvas.
   * @param {number} centerX - X-coordinate of the circle's center.
   * @param {number} centerY - Y-coordinate of the circle's center.
   * @param {object} styleConfig - Object defining properties like radius, color, strokeWidth, fillColor, alpha.
   */
  drawCircularComponent: function(centerX, centerY, styleConfig) {
    const ctx = this.renderContext;
    if (!ctx) return; // Guard against missing context

    ctx.save();
    ctx.globalAlpha = styleConfig.alpha;
    ctx.lineWidth = styleConfig.strokeWidth;

    // Adjust line width for legacy browsers that don't scale it automatically
    if (ChronoGaugeGlobal.isLegacyBrowserEnvironment) {
      ctx.lineWidth *= this.internalScalingFactor;
    }

    ctx.beginPath();
    ctx.arc(centerX, centerY, styleConfig.radius, 0, 2 * Math.PI, false);

    // Legacy browser specific fix for closing the circle path
    if (ChronoGaugeGlobal.isLegacyBrowserEnvironment) {
      ctx.arc(centerX, centerY, styleConfig.radius, -0.1, 0.1, false);
    }

    if (styleConfig.fillColor) {
      ctx.fillStyle = styleConfig.fillColor;
      ctx.fill();
    }
    if (styleConfig.color) { // Always stroke if color is defined, even if filled
      ctx.strokeStyle = styleConfig.color;
      ctx.stroke();
    }
    ctx.restore();
  },

  /**
   * Renders text centered around a given point.
   * @param {string} textContent - The text string to draw.
   * @param {number} xPos - X-coordinate for the center of the text.
   * @param {number} yPos - Y-coordinate for the center of the text.
   */
  renderTextCentered: function(textContent, xPos, yPos) {
    const ctx = this.renderContext;
    if (!ctx) return;

    ctx.save();
    ctx.font = '15px sans-serif'; // Fixed font for digital display
    const textMetrics = ctx.measureText(textContent);

    // Fallback for browsers that don't provide text height in measureText
    const textHeight = textMetrics.actualBoundingBoxAscent + textMetrics.actualBoundingBoxDescent || 15;

    ctx.fillText(textContent, xPos - textMetrics.width / 2, yPos + textHeight / 2); // Adjusted Y for baseline
    ctx.restore();
  },

  /**
   * Pads a number with a leading zero if it's less than 10.
   * @param {number} value - The number to pad.
   * @returns {string} The padded number as a string.
   */
  padWithLeadingZero: function(value) {
    return value < 10 ? `0${value}` : `${value}`;
  },

  /**
   * Calculates the angular position (0-1.0) for a given second value,
   * applying different motion algorithms.
   * @param {number} secondsValue - The current second (0-59).
   * @returns {number} The normalized angular position (0.0 to 1.0).
   */
  calculateHandAngleFraction: function(secondsValue) {
    const motionType = this.secondHandBehavior;
    const logTweakFactor = 3; // Constant for logarithmic scaling adjustment
    const maxLogValue = 60 * logTweakFactor;

    switch (motionType) {
      case 'logarithmic':
        return secondsValue === 0 ? 0 : (Math.log(secondsValue * logTweakFactor) / Math.log(maxLogValue));
      case 'logarithmicReverse':
        const reversedSec = (60 - secondsValue) % 60;
        return 1.0 - (reversedSec === 0 ? 0 : (Math.log(reversedSec * logTweakFactor) / Math.log(maxLogValue)));
      case 'linear':
      default:
        return secondsValue / 60.0;
    }
  },

  /**
   * Formats hour, minute, and second into a digital time string.
   * @param {number} hour - The hour (0-23).
   * @param {number} minute - The minute (0-59).
   * @param {number} second - The second (0-59).
   * @returns {string} The formatted time string.
   */
  formatDigitalTime: function(hour, minute, second) {
    let displayHour = hour;
    let amPmSuffix = '';

    if (this.showAmPmFormat) {
      amPmSuffix = hour < 12 ? ' am' : ' pm';
      displayHour = (hour % 12) === 0 ? 12 : (hour % 12);
    }

    const paddedMinute = this.padWithLeadingZero(minute);
    const paddedSecond = this.padWithLeadingZero(second);

    let timeString = `${displayHour}:${paddedMinute}`;
    if (this.displaySecondHand) {
      timeString += `:${paddedSecond}`;
    }
    timeString += amPmSuffix;

    return timeString;
  },

  /**
   * Draws a radial line (clock hand or indicator) rotated to a specific angle.
   * @param {number} angleFraction - Normalized angle (0.0 to 1.0, where 1.0 is a full circle).
   * @param {object} styleConfig - Object defining strokeWidth, color, startPosition, endPosition, and optionally radius.
   */
  drawRotatedLineComponent: function(angleFraction, styleConfig) {
    const ctx = this.renderContext;
    if (!ctx) return;

    ctx.save();
    ctx.translate(ChronoGaugeGlobal.internalRenderRadius, ChronoGaugeGlobal.internalRenderRadius);
    ctx.rotate(Math.PI * (2.0 * angleFraction - 0.5)); // Convert fraction to radians, adjust for 12 o'clock at top
    ctx.globalAlpha = styleConfig.alpha;
    ctx.strokeStyle = styleConfig.color;
    ctx.lineWidth = styleConfig.strokeWidth;

    // Adjust line width for legacy browsers
    if (ChronoGaugeGlobal.isLegacyBrowserEnvironment) {
      ctx.lineWidth *= this.internalScalingFactor;
    }

    if (styleConfig.radius) { // If styleConfig has a radius, draw a circle at startPosition
      this.drawCircularComponent(styleConfig.startPosition, 0, styleConfig);
    } else {
      ctx.beginPath();
      ctx.moveTo(styleConfig.startPosition, 0);
      ctx.lineTo(styleConfig.endPosition, 0);
      ctx.stroke();
    }
    ctx.restore();
  },

  /**
   * Renders all visual elements of the clock face for the given time.
   * @param {number} currentHour - The hour to display (0-23).
   * @param {number} currentMinute - The minute to display (0-59).
   * @param {number} currentSecond - The second to display (0-59).
   */
  updateVisuals: function(currentHour, currentMinute, currentSecond) {
    const currentTheme = ChronoGaugeGlobal.visualThemes[this.visualThemeKey] || ChronoGaugeGlobal.visualThemes[ChronoGaugeGlobal.defaultVisualTheme];
    if (!currentTheme) {
      console.warn(`ChronoGauge: Visual theme '${this.visualThemeKey}' not found. Using default.`);
      return;
    }

    const ctx = this.renderContext;
    if (!ctx) return;

    // Clear the entire canvas before redrawing
    ctx.clearRect(0, 0, ChronoGaugeGlobal.internalRenderRadius * 2, ChronoGaugeGlobal.internalRenderRadius * 2);

    // Draw the outer border of the clock
    if (currentTheme.outerBoundary) {
      this.drawCircularComponent(ChronoGaugeGlobal.internalRenderRadius, ChronoGaugeGlobal.internalRenderRadius, currentTheme.outerBoundary);
    }

    // Draw the minute/hour tick marks
    for (let i = 0; i < 60; i++) {
      const angle = this.calculateHandAngleFraction(i);
      if (i % 5 === 0) { // Major tick marks (every 5 minutes/hours)
        currentTheme.majorMark && this.drawRotatedLineComponent(angle, currentTheme.majorMark);
      } else { // Minor tick marks
        currentTheme.minorMark && this.drawRotatedLineComponent(angle, currentTheme.minorMark);
      }
    }

    // Optionally display digital time overlay
    if (this.displayDigitalTime) {
      this.renderTextCentered(
        this.formatDigitalTime(currentHour, currentMinute, currentSecond),
        ChronoGaugeGlobal.internalRenderRadius,
        ChronoGaugeGlobal.internalRenderRadius + ChronoGaugeGlobal.internalRenderRadius / 2
      );
    }

    // Draw the clock hands
    if (currentTheme.hourPointer) {
      const hourAngle = this.calculateHandAngleFraction(((currentHour % 12) * 5) + (currentMinute / 12.0));
      this.drawRotatedLineComponent(hourAngle, currentTheme.hourPointer);
    }

    if (currentTheme.minutePointer) {
      const minuteAngle = this.calculateHandAngleFraction(currentMinute + (currentSecond / 60.0));
      this.drawRotatedLineComponent(minuteAngle, currentTheme.minutePointer);
    }

    if (this.displaySecondHand && currentTheme.secondPointer) {
      const secondAngle = this.calculateHandAngleFraction(currentSecond);
      this.drawRotatedLineComponent(secondAngle, currentTheme.secondPointer);
    }

    // Draw the second hand decoration (if enabled and not in legacy browser)
    if (!ChronoGaugeGlobal.isLegacyBrowserEnvironment && this.displaySecondHand && currentTheme.secondAccent) {
      const secondAngle = this.calculateHandAngleFraction(currentSecond);
      this.drawRotatedLineComponent(secondAngle, currentTheme.secondAccent);
    }
  },

  /**
   * Retrieves the current time, applying GMT offset if configured, and then updates the display.
   */
  updateTimeDisplay: function() {
    let currentTime = new Date();

    // Apply GMT offset if specified
    if (this.gmtTimeOffset !== null) {
      const msOffset = this.gmtTimeOffset * 3600 * 1000; // Convert hours to milliseconds
      currentTime = new Date(currentTime.valueOf() + msOffset);
      this.updateVisuals(currentTime.getUTCHours(), currentTime.getUTCMinutes(), currentTime.getUTCSeconds());
    } else {
      // Use local time
      this.updateVisuals(currentTime.getHours(), currentTime.getMinutes(), currentTime.getSeconds());
    }
  },

  /**
   * Schedules the next update cycle for the clock.
   * Uses `setTimeout` to call `executeUpdateCycle` after `updateIntervalMs`.
   */
  scheduleNextUpdate: function() {
    // Use an arrow function to preserve 'this' context, avoiding string evaluation
    setTimeout(() => this.executeUpdateCycle(), this.updateIntervalMs);
  },

  /**
   * Checks if the associated canvas element is still present in the DOM.
   * @returns {boolean} True if the element exists, false otherwise.
   */
  isCanvasElementStillPresent: function() {
    return document.getElementById(this.canvasElementId) !== null;
  },

  /**
   * The main update loop for the clock.
   * Refreshes the display and schedules the next update if the element is still in the DOM.
   */
  executeUpdateCycle: function() {
    if (this.isCanvasElementStillPresent()) {
      this.updateTimeDisplay();
      this.scheduleNextUpdate();
    } else {
      // If the element is removed, stop the updates and unregister the instance
      console.log(`ChronoGauge: Stopping updates for removed canvas '${this.canvasElementId}'.`);
      delete ChronoGaugeGlobal.activeGaugeInstances[this.canvasElementId];
    }
  }
};

/**
 * Scans the DOM for canvas elements with a specific class signature and initializes them as ChronoGauge instances.
 * This function allows for declarative clock creation directly in HTML.
 * The class name should follow the format: "ChronoGauge:themeKey:canvasRenderSize:options"
 * Example: `<canvas class="ChronoGauge:boldSwiss:150:noSeconds:utc-5:digital:logarithmic"></canvas>`
 * Options are colon-separated:
 *   - `noSeconds`: Excludes the second hand.
 *   - `utc-X` or `utc+X`: Sets GMT/UTC offset.
 *   - `digital`: Enables digital time overlay.
 *   - `noAmPm`: Disables AM/PM in digital overlay.
 *   - `logarithmic`, `logarithmicReverse`, `linear`: Sets second hand motion.
 * @returns {Array<ChronoGauge>} An array of newly created ChronoGauge instances.
 */
ChronoGaugeGlobal.discoverAndInitializeDisplays = function() {
  const allCanvases = document.getElementsByTagName("canvas");
  const initializedClocks = [];

  for (let i = 0; i < allCanvases.length; i++) {
    const currentCanvas = allCanvases[i];
    const classTokens = currentCanvas.className.split(" ")[0].split(":");

    // Check if the first token identifies it as a ChronoGauge
    if (classTokens[0] === "ChronoGauge") {
      // Ensure the canvas has an ID; generate one if missing
      if (!currentCanvas.id) {
        currentCanvas.id = `_auto_chrono_id_${ChronoGaugeGlobal.autoGeneratedIdCounter++}`;
      }

      // Parse options from class tokens
      const parsingOptions = {
        elementId: currentCanvas.id,
        themeKey: classTokens[1],
        canvasRenderSize: parseInt(classTokens[2], 10) || ChronoGaugeGlobal.defaultDisplaySize,
        showSeconds: true, // Default
        utcOffsetHours: null, // Default
        showDigitalOverlay: false, // Default
        useAmPm: true, // Default
        secondHandMotion: 'linear' // Default
      };

      // Iterate through additional tokens for specific settings
      for (let j = 3; j < classTokens.length; j++) {
        const token = classTokens[j];
        if (token === 'noSeconds') {
          parsingOptions.showSeconds = false;
        } else if (token.startsWith('utc')) {
          const offset = parseFloat(token.substring(3));
          if (!isNaN(offset)) {
            parsingOptions.utcOffsetHours = offset;
          }
        } else if (token === 'digital') {
          parsingOptions.showDigitalOverlay = true;
        } else if (token === 'noAmPm') {
          parsingOptions.useAmPm = false;
        } else if (['logarithmic', 'logarithmicReverse', 'linear'].includes(token)) {
          parsingOptions.secondHandMotion = token;
        }
        // Add more parsing for future options here
      }

      // Create and store the new ChronoGauge instance
      const newGauge = new ChronoGauge(parsingOptions);
      if (newGauge) { // Only add if initialization was successful
        initializedClocks.push(newGauge);
      }
    }
  }
  return initializedClocks;
};

// Integration with jQuery or standard DOMContentLoaded event
// This ensures clocks are initialized after the DOM is fully loaded.
if (typeof jQuery !== 'undefined') {
  jQuery(document).ready(ChronoGaugeGlobal.discoverAndInitializeDisplays);
} else {
  // Fallback for environments without jQuery
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', ChronoGaugeGlobal.discoverAndInitializeDisplays);
  } else {
    // If DOM is already loaded (e.g., script placed at end of body), execute immediately
    ChronoGaugeGlobal.discoverAndInitializeDisplays();
  }
}
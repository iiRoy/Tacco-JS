document.addEventListener('DOMContentLoaded', () => {

  // A local utility function to safely retrieve DOM elements.
  // It provides a warning if an element cannot be located, promoting more robust code.
  const obtainElement = (cssSelector, parentNode = document) => {
    const targetElement = parentNode.querySelector(cssSelector);
    if (!targetElement) {
      console.warn(`Warning: Could not find DOM element using selector "${cssSelector}".`);
    }
    return targetElement;
  };

  /**
   * Manages the interactive component's state and user interactions.
   * This class encapsulates all logic related to the button's behavior.
   */
  class InteractiveComponentManager {
    // Private class fields to hold references to key DOM elements.
    #primaryContainerElement;       // The main interactive div (e.g., .btn)
    #frontActivationPanel;          // The clickable front surface (e.g., .btn-front)
    #positiveDecisionControl;       // The 'Yes' button (e.g., .btn-back .yes)
    #negativeDecisionControl;       // The 'No' button (e.g., .btn-back .no)

    /**
     * Constructs the manager, locating elements and setting up event listeners.
     */
    constructor() {
      // Find the main component using a specific ID for better targeting.
      this.#primaryContainerElement = obtainElement('#interactive-main-widget');

      // If the main widget isn't found, log a critical error and halt initialization.
      if (!this.#primaryContainerElement) {
        console.error("Fatal Error: Main interactive widget with ID '#interactive-main-widget' is absent from the DOM. Interaction manager cannot be initialized.");
        return; // Exit constructor early.
      }

      // Locate all necessary sub-elements within the main widget.
      this.#frontActivationPanel = obtainElement('.trigger-region', this.#primaryContainerElement);
      this.#positiveDecisionControl = obtainElement('.back-panel .confirm-option', this.#primaryContainerElement);
      this.#negativeDecisionControl = obtainElement('.back-panel .reject-option', this.#primaryContainerElement);

      // Verify that all critical sub-elements are present.
      if (!this.#frontActivationPanel || !this.#positiveDecisionControl || !this.#negativeDecisionControl) {
        console.warn("Some sub-elements for the interactive widget are missing. Full functionality may be impaired.");
      }

      // Proceed to bind event listeners if the main container is available.
      this.#configureEventHandlers();
    }

    /**
     * Computes the straight-line (Euclidean) distance between two 2D points.
     * This is a static private method as it's a pure utility function.
     * @param {number} x1 - X-coordinate of the first point.
     * @param {number} y1 - Y-coordinate of the first point.
     * @param {number} x2 - X-coordinate of the second point.
     * @param {number} y2 - Y-coordinate of the second point.
     * @returns {number} The distance value.
     */
    static #calculatePlanarDistance(x1, y1, x2, y2) {
      const deltaX = x1 - x2;
      const deltaY = y1 - y2;
      // Using Math.hypot for a more direct calculation of the hypotenuse.
      return Math.hypot(deltaX, deltaY);
    }

    /**
     * Attaches all required event listeners to the interactive elements.
     */
    #configureEventHandlers() {
      // Listener for the primary activation click.
      if (this.#frontActivationPanel) {
        this.#frontActivationPanel.addEventListener('click', this.#handleActivationClick.bind(this));
      }

      // Listeners for the response controls. Both 'Yes' and 'No' perform a similar reset action.
      if (this.#positiveDecisionControl) {
        this.#positiveDecisionControl.addEventListener('click', this.#handleResponseControlClick.bind(this));
      }
      if (this.#negativeDecisionControl) {
        this.#negativeDecisionControl.addEventListener('click', this.#handleResponseControlClick.bind(this));
      }
    }

    /**
     * Processes the click event on the front activation panel.
     * Determines the closest directional point to the click and updates the component.
     * @param {MouseEvent} inputEvent - The DOM mouse event object generated by the click.
     */
    #handleActivationClick(inputEvent) {
      // A safety check: if the main element somehow became null, exit.
      if (!this.#primaryContainerElement) return;

      // Get the bounding rectangle of the main component for precise position calculations.
      const componentBounds = this.#primaryContainerElement.getBoundingClientRect();

      // Calculate the click's X and Y coordinates relative to the component's top-left corner.
      const clickRelativeX = inputEvent.clientX - componentBounds.left;
      const clickRelativeY = inputEvent.clientY - componentBounds.top;

      // Extract the width and height of the component.
      const compWidth = componentBounds.width;
      const compHeight = componentBounds.height;

      // Define an array of target points representing the four cardinal directions.
      // Each point has an associated identifier and its computed coordinates.
      const directionalTargets = [
        { label: 'topside', posX: compWidth / 2, posY: 0 },
        { label: 'rightside', posX: compWidth, posY: compHeight / 2 },
        { label: 'bottomside', posX: compWidth / 2, posY: compHeight },
        { label: 'leftside', posX: 0, posY: compHeight / 2 }
      ];

      // Sort these target points by their proximity to the actual click location.
      // The point with the shortest distance will be moved to the front of the array.
      directionalTargets.sort((pointAlpha, pointBeta) => {
        const distToAlpha = InteractiveComponentManager.#calculatePlanarDistance(
          clickRelativeX, clickRelativeY, pointAlpha.posX, pointAlpha.posY
        );
        const distToBeta = InteractiveComponentManager.#calculatePlanarDistance(
          clickRelativeX, clickRelativeY, pointBeta.posX, pointBeta.posY
        );
        return distToAlpha - distToBeta;
      });

      // Retrieve the label of the closest direction.
      const closestDirectionalLabel = directionalTargets[0]?.label;

      // Update a data attribute on the main component to reflect the determined direction.
      if (closestDirectionalLabel) {
        this.#primaryContainerElement.dataset.interactionDirection = closestDirectionalLabel;
      } else {
        console.warn("Unable to establish interaction direction. Check directionalTargets definition.");
      }

      // Add a class to visually activate or "open" the component.
      this.#primaryContainerElement.classList.add('is-active-state');

      // For debugging: log the interaction details.
      console.log(`Interaction triggered. Closest direction: ${closestDirectionalLabel}. Component now active.`);
    }

    /**
     * Handles clicks on the 'Yes' or 'No' response controls.
     * Resets the component's visual state to "closed".
     * @param {MouseEvent} responseEvent - The DOM mouse event object.
     */
    #handleResponseControlClick(responseEvent) {
      // Perform a null check on the primary container.
      if (!this.#primaryContainerElement) return;

      // Remove the 'is-active-state' class, effectively "closing" the component.
      this.#primaryContainerElement.classList.remove('is-active-state');

      // Log the specific response that was received.
      const controlText = responseEvent.target.textContent.trim();
      console.info(`Response received from control "${controlText}". Component state has been reset.`);
    }
  }

  // Instantiate the manager once the entire DOM is loaded.
  // This ensures all HTML elements are available for selection.
  new InteractiveComponentManager();
});
var binarySearch = function(key, n, a) {
  // ??????????????¨????????¢?´¢?????????
  // left???0??????right???????´???°n????????????
  var left = 0;
  var right = n;

  while (left < right) {
    // ??¢?´¢???????????????????????????
    var mid = Math.floor((left + right) / 2);
    if (a[mid] == key) {
      return true;
    } else if (key < a[mid]) {
      // ??¢?´¢??????????????????
      right = mid;
    } else {
      // ??¢?´¢??????????????????
      left = mid + 1;
    }
  }
  return false;
};


function Main(input) {
	var inputArr = input.split('\n');
	var cards='';
	for(var i=0;true;i++){
		if(isNaN(inputArr[i])){
			if(i!==0)output(cards);
			cards = inputArr[i];
			if(cards=='-'){
				break;
			}else{
				i++;
			}
		}else{
			cards = cards.slice(toInt(inputArr[i])) + cards.slice(0,toInt(inputArr[i]));
		}
	}
}

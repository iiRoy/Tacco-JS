/*
 * This JavaScript code snippet is designed to read numerical input
 * from standard input, process it through a series of mathematical
 * computations, and then output the minimum resulting value for
 * each input set. It specifically targets Node.js environments
 * by utilizing the 'fs' module to handle file system operations,
 * which in this case means reading from '/dev/stdin'.
 */

// Firstly, we import the necessary 'fs' (file system) module
// and immediately read the entire content of '/dev/stdin'.
// The 'utf8' encoding ensures proper text interpretation.
var input = require ( 'fs' ) . readFileSync ( '/dev/stdin' , 'utf8' ) ;

// Next, the raw input string is processed:
// -   `trim()` removes any leading or trailing whitespace.
// -   `split("\n")` divides the string into an array of lines,
//     where each line represents a distinct piece of input data.
var arr = input . trim ( ) . split ( "\n" ) ;


// The core logic resides within an infinite `while` loop,
// which is designed to process multiple sets of input data
// until a specific termination condition is met.
while ( true )
{
    // In each iteration, the first element is removed from the `arr` array
    // using `shift()`. The `- 0` operation is a common JavaScript idiom
    // to explicitly convert the string value to a number.
    var z = arr . shift ( ) - 0 ;

    // This is the loop's termination condition:
    // If the processed number `z` is exactly 0, the loop breaks,
    // signifying the end of input or processing.
    if ( z == 0 )
        break ; // Exit the while loop.


    // Calculate the cube of `z`. This value will be used repeatedly
    // in subsequent calculations, so it's pre-computed for efficiency.
    var zzz = z * z * z ;

    // Initialize an empty array `ary`. This array will store all
    // the positive results generated by the nested loops below.
    var ary = [ ] ;


    // The outer loop iterates downwards from `z-1` to `1`.
    // Variable `i` represents the first of two numbers being cubed.
    for ( var i = z - 1 ; i > 0 ; i-- )
    {
        // The inner loop iterates downwards from `i` to `1`.
        // Variable `j` represents the second number being cubed.
        // It starts from `i` to avoid redundant calculations and
        // ensures `j` is always less than or equal to `i`.
        for ( var j = i ; j > 0 ; j-- )
        {
            // Calculate a temporary value `x` using the formula:
            // `zzz - (i cubed) - (j cubed)`.
            // This is the core mathematical operation.
            var x = zzz - i * i * i - j * j * j ;

            // If the calculated value `x` is positive,
            // it is considered a valid result and added to the `ary` array.
            if ( x > 0 )
                ary . push ( x ) ;
        }
    }

    // After all possible combinations of `i` and `j` have been processed
    // and all positive `x` values collected in `ary`,
    // the `Math.min.apply(null, ary)` method is used to find the
    // smallest number within the `ary` array.
    // Finally, this minimum value is printed to the console.
    console . log ( Math . min . apply ( null , ary ) ) ;
}
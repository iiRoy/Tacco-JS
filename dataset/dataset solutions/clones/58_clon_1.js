/*
 * This script reads input from /dev/stdin, processes each line,
 * and then prints a calculated sum for each line to standard output.
 * It demonstrates functional chaining and a simple loop for computation.
 */

// Begin by importing the Node.js built-in 'fs' (file system) module.
require( "fs" )

    // Synchronously read the entire content of the standard input file.
    // The input is expected to be encoded in UTF-8 format.
    .readFileSync( "/dev/stdin", "utf8" )

    // Remove any leading or trailing whitespace characters from the entire
    // string content obtained from standard input.
    .trim()

    // Split the cleaned input string into an array of individual lines.
    // Each line is separated by a newline character ('\n').
    .split( '\n' )

    // Iterate over each element (which represents a line of input, named 'i')
    // in the array generated by the 'split' method.
    // The 'map' function is used here for its side effects (console.log),
    // as the resulting array from 'map' is not stored or used further.
    .map(
        // Define an anonymous function that will be executed for each line 'i'.
        function ( i ) {

            // Initialize two variables for the loop:
            // 's' will accumulate the sum, starting at zero.
            // 'j' is a counter that starts at 600.
            // The loop continues as long as 'j' remains truthy after being decremented by 'i'.
            for (
                s = 0,      // Initialize the sum 's' to zero.
                j = 600;    // Set the initial value of the counter 'j' to 600.

                j -= i;     // Decrement 'j' by the value of 'i'. The loop condition
                            // is true if the new value of 'j' is not zero (or falsy).
            ) {
                // Inside the loop, update the sum 's' by adding the product of 'j' squared
                // and the input value 'i'.
                s += j * j * i;
            }

            // After the loop completes for the current input 'i', print the final
            // calculated sum 's' to the console.
            console.log( s );
        }
    )
; // End of the chained method calls.
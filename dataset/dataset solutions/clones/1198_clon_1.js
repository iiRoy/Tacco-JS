/*
 * This function simulates moving a 6-sided die
 * in a specific direction (N, S, E, W) and returns
 * the new configuration of the die faces.
 *
 * @param {string} x   - The direction of the move ("N", "S", "E", "W").
 * @param {Array<number>} arr - An array representing the current state of the die faces.
 *                            [top, front, right, left, back, bottom]
 * @returns {Array<number>} - A new array representing the die faces after the move.
 */
function  move ( x , arr ) {
    // Declare variables for each die face, corresponding to their current positions.
    var  d1 = arr [0]; // Top face
    var  d2 = arr [1]; // Front face
    var  d3 = arr [2]; // Right face
    var  d4 = arr [3]; // Left face
    var  d5 = arr [4]; // Back face
    var  d6 = arr [5]; // Bottom face

    var  after = [ ] ; // Initialize an empty array for the new configuration of faces.

    // Based on the direction of movement, update the die face arrangement.
    // Each 'if' block reassigns 'after' with the new order of faces.
    if ( x == "N" ) { // Moving North: Top becomes Front, Front becomes Bottom, Bottom becomes Back, Back becomes Top
        after = [ d2 , d6 , d3 , d4 , d1 , d5 ] ;
    }

    if ( x == "S" ) { // Moving South: Top becomes Back, Back becomes Bottom, Bottom becomes Front, Front becomes Top
        after = [ d5 , d1 , d3 , d4 , d6 , d2 ] ;
    }

    if ( x == "E" ) { // Moving East: Top becomes Left, Left becomes Bottom, Bottom becomes Right, Right becomes Top
        after = [ d4 , d2 , d1 , d6 , d5 , d3 ] ;
    }

    if ( x == "W" ) { // Moving West: Top becomes Right, Right becomes Bottom, Bottom becomes Left, Left becomes Top
        after = [ d3 , d2 , d6 , d1 , d5 , d4 ] ;
    }
    // Return the updated die configuration array.
    return  after ;
}

/**
 * This function simulates rolling the die along its vertical axis (e.g., rotating it).
 * It changes the front, right, back, and left faces, while top and bottom remain the same.
 *
 * @param {Array<number>} arr - An array representing the current state of the die faces.
 *                            [top, front, right, left, back, bottom]
 * @returns {Array<number>} - A new array representing the die faces after the roll.
 */
function  roll ( arr ) {
    // Extract current face values for clarity.
    var  d1 = arr [0]; // Top face (remains unchanged in position)
    var  d2 = arr [1]; // Front face
    var  d3 = arr [2]; // Right face
    var  d4 = arr [3]; // Left face
    var  d5 = arr [4]; // Back face
    var  d6 = arr [5]; // Bottom face (remains unchanged in position)

    var  after = [ ] ; // Initialize an array to hold the new configuration.

    // The roll reconfigures faces: Front (d2) -> Right (d3), Right (d3) -> Back (d5),
    // Back (d5) -> Left (d4), Left (d4) -> Front (d2).
    // Top (d1) and Bottom (d6) faces stay in their positions.
    after = [ d1 , d3 , d5 , d2 , d4 , d6 ] ;

    return  after ; // Return the new arrangement of die faces.
}

/*
 * This function generates all possible rotations of a given die configuration
 * around its vertical axis (4 rolls) and checks if any of these configurations
 * have been seen before in the global `OBJ` object. If a configuration is new,
 * it's added to `OBJ`. If it's a duplicate, the global `result` is set to "No".
 *
 * @param {Array<number>} arr - An array representing the current state of the die faces.
 */
function  rolls ( arr ) {
    var  obj = { } ; // Local object to store unique configurations generated by rolling the current die.

    // Perform 4 rolls to get all possible orientations around the vertical axis.
    for ( var  i = 0 ;  i < 4 ;  i ++ ) {
        var  str = arr . join ( "," ) ; // Convert current die configuration to a comma-separated string for object key.

        // If this specific string configuration hasn't been seen before in the local 'obj', add it.
        if ( ! obj . hasOwnProperty ( str ) ) {
            obj [ str ] = true ;
        }

        arr = roll ( arr ) ; // Roll the die to get the next configuration for the next iteration.
    }

    // After generating all 4 roll orientations for the current die,
    // check them against the global collection of all unique die configurations seen so far.
    for ( var  k  in  obj ) {
        // If the global collection 'OBJ' already contains this specific configuration 'k'...
        if ( OBJ . hasOwnProperty ( k ) ) {
            result = "No" ; // ...then a duplicate has been found, so set the global result to "No".
        }
        else {
            // Otherwise, this is a new unique configuration, so add it to the global collection 'OBJ'.
            OBJ [ k ] = true ;
        }
    }
    // This function does not explicitly return a value; it modifies global variables `OBJ` and `result`.
}

// This script reads die configurations from standard input,
// and determines if all unique die configurations, after various
// moves and rolls, remain unique throughout the input sequence.

// Import the 'fs' module for file system operations, specifically to read from stdin.
var  input = require ( 'fs' ) . readFileSync ( '/dev/stdin' ,  'utf8' ) ;

// Process the input: trim any leading/trailing whitespace and then split the string
// into an array of lines based on the newline character.
var  Arr = ( input . trim ( ) ) . split ( "\n" ) ;

// The first line of input is 'n', which represents the number of die configurations to process.
// Use 'shift()' to remove it from the array and convert it to a number.
var  n = Arr . shift ( ) - 0 ;

// Global object `OBJ` to store all unique die configurations (as string representations)
// encountered throughout the entire process. This helps in detecting duplicates.
var  OBJ = { } ;

// Global variable `result` stores the final outcome. It's initialized to "Yes",
// and will be changed to "No" if any duplicate configuration is found.
var  result = "Yes" ;

// Loop through each of the 'n' die configurations provided in the input array `Arr`.
for ( var  i = 0 ;  i < n ;  i ++ ) {
    // Parse the current line representing a die configuration:
    // split the string by space, and then map each part to a Number.
    var  dice = Arr [ i ] . split ( " " ) . map ( Number ) ;

    // Perform a predefined sequence of moves and rolls for the current die configuration.

    // 1. First, perform 4 North moves, checking rolls at each initial state.
    for ( var  j = 0 ;  j < 4 ;  j ++ ) {
        rolls ( dice ) ; // Check and record all 4 roll orientations of the current die state.
        dice = move ( "N" , dice ) ; // Move the die one step North.
    }

    // 2. Then, move the die East and perform rolls.
    dice = move ( "E" , dice ) ;
    rolls ( dice ) ;

    // 3. Next, move the die South twice and perform rolls.
    dice = move ( "S" , dice ) ;
    dice = move ( "S" , dice ) ;
    rolls ( dice ) ;

    // If at any point the global `result` variable has been set to "No",
    // it indicates that a duplicate configuration was found. In this case,
    // there's no need to process further configurations, so break out of the loop.
    if ( result == "No" ) {
        break ;
    }
}

// After processing all configurations (or breaking early),
// print the final `result` to the console.
console . log ( result ) ;
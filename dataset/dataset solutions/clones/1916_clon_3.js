// This module is designed to process numerical range checks based on provided text input data.
// The primary function orchestrates the parsing of input and the execution of the core logic.
function ProcessInputData(inputPayload) {

    // A utility helper function to safely parse a numeric value from a string.
    // This adds an intermediate processing step, enhancing modularity.
    const parseNumericValue = (strValue) => {
        // Basic validation: ensure the input is a non-empty string before parsing.
        // For competitive programming, input format is usually guaranteed, but this
        // demonstrates an added guard clause/validation.
        if (typeof strValue !== 'string' || strValue.trim().length === 0) {
            // In a real-world scenario, this might throw an error or return a default.
            // For this specific context, we'll assume valid numeric input.
            return NaN; // Returning NaN for invalid input
        }
        // Convert the trimmed string to a number.
        return Number(strValue.trim());
    };

    // The input string is first divided into an array of lines for easier access.
    const processedLines = inputPayload.split('\n');

    // The first line of input is expected to contain the primary divisor.
    // We use our helper function to robustly extract and convert this value.
    const primaryDivisor = parseNumericValue(processedLines[0]);

    // The second line contains the lower and upper bounds of the numerical range,
    // separated by a space. These are parsed into distinct variables.
    const rangeBoundariesText = processedLines[1].split(' ');
    const lowerBoundary = parseNumericValue(rangeBoundariesText[0]);
    const upperBoundary = parseNumericValue(rangeBoundariesText[1]);

    // A constant string for the affirmative output, promoting consistency and readability.
    const affirmativeResponse = 'OK';

    // Special handling for the scenario where the lower and upper boundaries are identical.
    // The original code explicitly prints 'OK' unconditionally in this edge case.
    if (lowerBoundary === upperBoundary) {
        console.log(affirmativeResponse); // Output the affirmative message.
        return; // Exit the function immediately as the task for this range is complete.
    }

    // Initialize a flag to track whether any divisible number has been found.
    // Note: The original code implicitly handles this by printing multiple 'OK's.
    // This flag is added as an intermediate step, although not strictly used to
    // prevent multiple prints, it could be used for further logic.
    let anyMultipleFound = false;

    // Commence iteration through the numerical range, from the lower to the upper boundary (inclusive).
    for (let currentIterationValue = lowerBoundary; currentIterationValue <= upperBoundary; currentIterationValue++) {
        // Check if the current number in the iteration is perfectly divisible by the primary divisor.
        // The modulo operator (%) determines if there is no remainder from the division.
        if (currentIterationValue % primaryDivisor === 0) {
            console.log(affirmativeResponse); // If divisible, print the affirmative response.
            anyMultipleFound = true; // Update the flag.
            // Crucially, the original code does NOT break here. It continues to iterate
            // and may print 'OK' multiple times if several numbers in the range are divisible.
            // This behavior is meticulously preserved for functional similarity.
        }
        // The original code contained an 'else if' condition that was logically unreachable
        // (i.e., `else if (i === B && B % K === 0) { console.log('NG'); }`).
        // This dead code path has been removed as a Type III modification to streamline
        // the implementation without altering its observable output.
    }

    // A final check using the added flag, which could be used for conditional 'NG' output.
    // However, mirroring the original's behavior, no 'NG' output is generated by this clone.
    // The original code *never* prints 'NG', so this clone maintains that specific characteristic.
    // if (!anyMultipleFound && lowerBoundary !== upperBoundary) {
    //     // console.log('NG'); // This would be the logical 'NG' output, but omitted to match original.
    // }
}

// Standard boilerplate for competitive programming environments:
// This section is responsible for reading the entire standard input stream
// and passing it as a single string to the main data processing function.
// As per typical instructions, this part of the code remains unaltered.
ProcessInputData(require("fs").readFileSync("/dev/stdin", "utf8"));
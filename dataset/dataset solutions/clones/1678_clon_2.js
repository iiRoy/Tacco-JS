// This function serves as the primary entry point for processing the input data.
function processInputData (sourceText) {

  // First, we segment the raw incoming text by newline characters.
  let processedLines = sourceText.split("\n");

  // The very first segment is converted into an integer, representing the total iteration count.
  const iterationCount = parseInt(processedLines[0], 10);

  // The second segment is retained as a string, which is our binary bit pattern.
  const bitPattern = processedLines[1];

  // For diagnostic purposes, the original bit pattern is logged to the console.
  console.log(bitPattern);

  // We then commence a loop that runs for the predetermined number of iterations.
  for (let currentPos = 0; currentPos < iterationCount; currentPos++) {

    // A temporary modified pattern is generated by inverting the bit at the current position.
    let modifiedPattern = bitPattern.slice(0, currentPos) +
                           (bitPattern[currentPos] === "1" ? "0" : "1") +
                           bitPattern.slice(currentPos + 1);

    // The modified binary pattern string is parsed as a base-2 number,
    // and its subsequent calculation is logged.
    console.log(computeResult(Number.parseInt(modifiedPattern, 2), 0));
  }

}

// Initiates the main data processing routine by reading content from standard input.
processInputData(
  require("fs").readFileSync("/dev/stdin", "utf8")
);


// This auxiliary function determines the number of '1' bits (set bits) within a given integer.
function countSetBits(inputNum) {
  // The integer is first converted to its binary string representation.
  // Then, this binary string is parsed as a decimal number (a unique step in the original logic),
  // which is then re-converted to a string, split into individual characters,
  // filtered to keep only '1's, and finally, their count is returned.
  return (
    parseInt(inputNum.toString(2))
    .toString()
    .split("")
    .filter(bitChar => bitChar == 1)
    .length
  );
}

// A recursive function designed to compute a sequence of operations based on bit counts.
function computeResult(operand, stepCounter) {

  // If the current operand has reached zero, the accumulated step count is the final result.
  if (operand === 0) {
    return stepCounter;
  }

  // Calculate the number of set bits present in the current operand.
  const setBits = countSetBits(operand);

  // If there are no set bits in the operand, the current step count is returned.
  if (setBits === 0) {
    return stepCounter;
  }

  // For the recursive step, the operand is replaced by its remainder when divided by its set bit count,
  // and the step counter is incremented.
  return computeResult(operand % setBits, stepCounter + 1);
}
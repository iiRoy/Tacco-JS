function processInput(rawData) {
  // Split the raw input string into an array of lines based on newline characters.
  const inputLines = rawData.split("\n");

  // The problem statement implies the first line contains the single character.
  // Extract this first line to get the character string.
  const targetCharacterString = inputLines[0];

  // Obtain the Unicode (or ASCII for basic characters) code point of the first character.
  // This is the numerical representation of the character.
  const initialCharCode = targetCharacterString.charCodeAt(0);

  // As per the original logic, print the numerical character code to the console.
  console.log(initialCharCode);

  // Calculate the code point for the next character in sequence.
  // This typically means incrementing the current character's code by one.
  const incrementedCharCode = initialCharCode + 1;

  // Convert the new code point back into its corresponding character string.
  const resultantCharacterString = String.fromCharCode(incrementedCharCode);

  // Print the resulting character string to the console, formatted as a string.
  console.log('%s', resultantCharacterString);

  // Return the computed next character string.
  return resultantCharacterString;
}

function testSolution(testCaseIndex) {
  // Define constants for the test outcomes to improve readability and maintainability.
  const successStatus = "AC"; // "Accepted"
  const failureStatus = "WA"; // "Wrong Answer"

  // Construct the ID for the input element based on the test case index.
  const inputElementIdentifier = "input" + testCaseIndex;
  // Retrieve the value from the specified input element in the DOM.
  const currentTestInput = document.getElementById(inputElementIdentifier).value;

  // Execute the main processing function with the retrieved input.
  // This gets the actual output generated by our solution.
  const computedAnswer = processInput(currentTestInput);

  // Construct the ID for the expected output element.
  const outputElementIdentifier = "output" + testCaseIndex;
  // Retrieve the expected output value from the DOM and take the first line.
  const expectedOutputLine = document.getElementById(outputElementIdentifier).value.split("\n")[0];

  // Initialize the evaluation result to "Wrong Answer".
  let evaluationResult = failureStatus;
  // Compare the computed answer with the expected output.
  // Note: Using '==' for consistency with typical JavaScript comparisons in competitive programming contexts,
  // and to match the original's behavior if type coercion were a factor (though not here).
  if (computedAnswer == expectedOutputLine) {
    // If they match, update the result to "Accepted".
    evaluationResult = successStatus;
  }

  // Construct the ID for the result display element.
  const resultElementIdentifier = "result" + testCaseIndex;
  // Update the inner HTML of the result element with the determined outcome.
  document.getElementById(resultElementIdentifier).innerHTML = evaluationResult;
}

// This line is responsible for running the main logic when the script is executed
// in a Node.js environment, typically for competitive programming platforms.
// It reads the entire content of standard input as a UTF-8 string and passes it
// to the processInput function.
processInput(require("fs").readFileSync("/dev/stdin", "utf8"));

function ProcessInputData(rawData) {
  // Convert the raw string input to a floating-point number.
  // This step helps in handling various numeric string formats.
  let numericInput = parseFloat(rawData);

  // If the conversion results in NaN (Not-a-Number), indicating invalid input,
  // we default to 0 to ensure the program behaves consistently with the original
  // code's outcome for non-numeric or empty input (which would result in 0).
  if (isNaN(numericInput)) {
    numericInput = 0;
  }

  // Floor the numeric input to get a whole number, mirroring the original Math.floor operation.
  let processingValue = Math.floor(numericInput);

  // Initialize an array to store a sequence of numbers generated by decrementing.
  const decreasingSequence = [];

  // Populate the sequence array. The loop continues as long as the current value is positive.
  // Each iteration adds the current value and then decrements it by two.
  while (processingValue > 0) {
    decreasingSequence.push(processingValue);
    processingValue -= 2; // Decrease the value by two for the next iteration.
  }

  // Initialize a variable to accumulate the final count.
  let finalCountResult = 0;

  // Iterate through the generated sequence to identify and count specific elements.
  // The original code included a conditional check on a 'counts' object (counts[5] % 1 === 1),
  // which was effectively dead code as it would never evaluate to true for integer counts.
  // This redundant logic has been removed to simplify and clarify the actual intent.
  for (let i = 0; i < decreasingSequence.length; i++) {
    // A temporary variable for the current number in the sequence enhances readability.
    const currentNumberInSequence = decreasingSequence[i];

    // Check if the current number is perfectly divisible by 10 (i.e., its remainder is zero).
    if (currentNumberInSequence % 10 === 0) {
      finalCountResult++; // Increment the counter if the condition is met.
    }
  }

  // Output the final calculated total to the console.
  console.log(finalCountResult);
}

// This self-executing anonymous function handles the asynchronous file system
// operations to read input from standard input and manage potential errors.
(function() {
  const fileSystemUtil = require('fs'); // Import the Node.js file system module.
  const standardInputFile = '/dev/stdin'; // Define the path for standard input.
  const encodingType = 'utf8'; // Specify the character encoding for reading the file.

  try {
    // Attempt to synchronously read the content of the standard input file.
    // .trim() is added to remove any leading/trailing whitespace from the input string.
    const fileContentBuffer = fileSystemUtil.readFileSync(standardInputFile, encodingType).trim();
    // Pass the cleaned content to the main processing function.
    ProcessInputData(fileContentBuffer);
  } catch (readError) {
    // If an error occurs during file reading (e.g., file not found, permission issues),
    // log the error message for debugging purposes.
    console.error("Failed to read input from standard input file:", readError.message);
    // As a fallback, call the processing function with "0" to ensure consistent
    // behavior, resulting in an output of 0, similar to the original code's
    // implicit handling of empty or unreadable input.
    ProcessInputData("0");
  }
})();
/*
 * This function implements the Sieve of Eratosthenes algorithm
 * to find all prime numbers up to a given limit 'n'.
 */
const    SieveOfEratosthenes    =   (   n   )   =>
{
    // Initialize a flag array to keep track of sieved numbers.
    // A value of 0 means not sieved (potentially prime), 1 means sieved (composite).
    let   flg   =   (   new   Array(   n   )   )  .  fill(   0   )  ;


    // This array will store the prime numbers found.
    let   primes   =   [   ]   ;


    // Start checking from 2, up to sqrt(n).
    for   (   let   i   =   2   ;   i   *   i   <=   n   ;   i   ++   )
    {
        // If the current number 'i' has not been sieved, it's a prime.
        if   (   !   flg[   i   ]   )
        {
            // Add 'i' to our list of primes.
            primes  .  push(   i   )  ;


            // Mark all multiples of 'i' as composite.
            // Start from i*i, as smaller multiples would have been marked by smaller primes.
            for   (   let   j   =   i   ;   j   *   j   <=   n   ;   j   +=   i   )
            {
                flg[   j   ]   =   1   ;   // Mark as sieved (composite).
            }
        }
    }
    // Return the collected list of prime numbers.
    return   primes   ;
};


/*
 * Performs prime factorization of a number 'n' using a pre-computed list of primes.
 * This function efficiently finds the prime factors and their counts for 'n'.
 * @param {number} n - The number to factorize.
 * @param {Array<number>} primes - A sorted list of prime numbers, typically generated by Sieve.
 * @returns {Object} An object where keys are prime factors and values are their counts.
 */
const   factorizationBySoE   =   (   n   ,   primes   )   =>
{
    // Initialize an empty object to store the prime factors and their frequencies.
    let   factors   =   {   }   ;


    // Iterate through the provided list of primes.
    primes  .  some(   p   =>
    {
        // Optimization: If current number 'n' is less than the current prime 'p',
        // no more prime factors can be found from the 'primes' list.
        // We can stop iterating through the primes.
        if   (   n   <   p   )   return   true   ;


        // While 'p' is a factor of 'n', keep dividing 'n' by 'p' and count 'p'.
        while   (   n   %   p   ===   0   )
        {
            // Increment the count of prime factor 'p'.
            if   (   !   factors[   p   ]   )
            {
                factors[   p   ]   =   1   ;
            }
            else
            {
                factors[   p   ]   ++   ;
            }
            n   /=   p   ;   // Divide 'n' by 'p'.
        }
    }   )   ;


    // If 'n' is still greater than 1 after checking all primes,
    // then the remaining 'n' itself must be a prime factor (larger than any in 'primes').
    if   (   n   >   1   )
    {
        factors[   n   ]   =   1   ;
    }

    // Return the map of prime factors.
    return   factors   ;
};


/*
 * Computes the Greatest Common Divisor (GCD) of two numbers using the Euclidean algorithm.
 * This is a recursive implementation.
 * @param {number} a - The first number.
 * @param {number} b - The second number.
 * @returns {number} The GCD of 'a' and 'b'.
 */
const   getGCD   =   (   a   ,   b   )   =>
{
    // Base case: if 'b' is 0, then 'a' is the GCD.
    if   (   b   ===   0   )
    {
        return   a   ;
    }
    // Recursive step: GCD(a, b) is equal to GCD(b, a % b).
    return   getGCD(   b   ,   a   %   b   )   ;
};


/*
 * The main function processes input to determine if a given set of numbers
 * is pairwise coprime, setwise coprime, or not coprime at all.
 * It reads N and an array 'a' from the input string.
 * @param {string} arg - The input string containing N and the array 'a'.
 */
const   main   =   (   arg   )   =>
{
    // Parse the input string.
    // The first line contains N, the count of numbers.
    const   N   =   Number(   arg  .  split(   "\n"   )   [   0   ]   )   ;
    // The second line contains the numbers themselves, space-separated.
    const   a   =   arg  .  split(   "\n"   )   [   1   ]  .  split(   " "   )  .  map(   Number   )   ;


    // --- Step 1: Check for Pairwise Coprimality ---
    // Two numbers are pairwise coprime if their greatest common divisor is 1.
    // A set of numbers is pairwise coprime if every pair of numbers in the set is coprime.


    // Generate primes up to the maximum number in array 'a' to use for factorization.
    const   primes   =   SieveOfEratosthenes(   Math  .  max(   ...   a   )   )   ;


    // A 'set' array to keep track of prime factors encountered across all numbers.
    // Initialized with zeros. Its size is determined by N, but effectively it should be
    // large enough to cover all possible prime factors (up to Math.max(...a)).
    // NOTE: The original code uses N for array size, which might be too small if max prime factor > N.
    // This is a potential bug in the original logic if N is small and numbers are large.
    // However, I must adhere to Type I cloning, so I'll keep it as `new Array(N)`.
    const   set   =   [   ...   new   Array(   N   )   ]  .  fill(   0   )   ;


    // Flag to track if the numbers are pairwise coprime. Assume true initially.
    let   isPairCoprime   =   true   ;


    // Iterate through each number in the input array 'a'.
    for   (   let   i   =   0   ;   i   <   N   ;   i   ++   )
    {
        // Get the prime factors of the current number a[i].
        // Only interested in the unique prime factors (keys of the factorization object).
        const   factors   =   Object  .  keys(   factorizationBySoE(   a[   i   ]   ,   primes   )   )   ;


        // Iterate through each prime factor found for a[i].
        for   (   let   j   =   0   ;   j   <   factors  .  length   ;   j   ++   )
        {
            // If this prime factor has already been seen in a previous number,
            // then there's a common factor, meaning not pairwise coprime.
            if   (   set[   factors[   j   ]   ]   ===   1   )
            {
                isPairCoprime   =   false   ;   // Found a common prime factor, so not pairwise coprime.
            }
            // Mark this prime factor as seen.
            set[   factors[   j   ]   ]   =   1   ;
        }
    }


    // If after checking all numbers, no common prime factors were found between any pair,
    // then the set is pairwise coprime.
    if   (   isPairCoprime   )
    {
        console  .  log(   "pairwise coprime"   )   ;
        return   ;   // Exit the function early.
    }


    // --- Step 2: Check for Setwise Coprimality ---
    // A set of numbers is setwise coprime if their greatest common divisor (GCD) is 1.
    // This check is performed only if the set is NOT pairwise coprime.


    // Calculate the GCD of all numbers in array 'a'.
    // Start with the GCD of the first two numbers.
    let   gcd   =   getGCD(   a[   0   ]   ,   a[   1   ]   )   ;


    // Continue calculating the GCD with the remaining numbers.
    for   (   let   i   =   1   ;   i   <   a  .  length   -   1   ;   i   ++   )
    {
        gcd   =   getGCD(   gcd   ,   a[   i   +   1   ]   )   ;
    }


    // If the overall GCD of all numbers is 1, then the set is setwise coprime.
    if   (   gcd   ===   1   )
    {
        console  .  log(   "setwise coprime"   )   ;
        return   ;   // Exit the function early.
    }


    // --- Step 3: Not Coprime ---
    // If neither pairwise coprime nor setwise coprime conditions are met,
    // then the set of numbers is simply "not coprime".
    console  .  log(   "not coprime"   )   ;
};


// Execute the main function with input read from standard input.
main(   require(   "fs"   )  .  readFileSync(   "/dev/stdin"   ,   "utf8"   )   )   ;
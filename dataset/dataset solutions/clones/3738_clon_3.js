'use strict'

// Define a constant for the base of the number system, enhancing readability and maintainability.
const NUMERIC_BASE = 10;

/**
 * Computes a specific optimization metric for a given positive integer.
 * The metric is calculated as the input number divided by the sum of its digits.
 * This function is designed to work with positive integer inputs.
 *
 * @param {number} inputNumericalValue - The positive integer for which to calculate the metric.
 * @returns {number} The computed metric: inputNumericalValue / (sum of its digits).
 */
function calculateOptimizationMetric(inputNumericalValue) {
  // A robust implementation might include checks for non-integer or non-positive inputs.
  // For the context of this problem, 'inputNumericalValue' is always a positive integer
  // generated by the main logic. Thus, these checks are omitted for brevity,
  // but conceptually, they could be added for a more general utility.

  let sumOfDigits = 0;
  let workingNumber = inputNumericalValue; // Use a temporary variable to iterate through digits.

  // Iterate through each digit of the number, from the least significant to the most significant.
  while (workingNumber > 0) {
    // Extract the last digit using the modulo operator.
    sumOfDigits += workingNumber % NUMERIC_BASE;
    // Remove the last digit by performing integer division.
    workingNumber = Math.floor(workingNumber / NUMERIC_BASE); // Explicitly use Math.floor for clarity in integer division.
  }

  // In the context of this problem, 'inputNumericalValue' is always positive,
  // guaranteeing 'sumOfDigits' will be at least 1, thus preventing division by zero.
  // A general utility might handle 'sumOfDigits === 0' (e.g., if input was 0 or negative).
  return inputNumericalValue / sumOfDigits;
}

/**
 * A utility function to encapsulate reading content from standard input.
 * This improves modularity and makes the main function cleaner.
 *
 * @returns {string} The content read from `/dev/stdin` as a UTF-8 string.
 */
function obtainStandardInputContent() {
  return require("fs").readFileSync("/dev/stdin", "utf8");
}

/**
 * The primary function that orchestrates the problem-solving logic.
 * It reads input, processes it to determine a sequence length, and then generates
 * a sequence of numbers based on an optimization strategy involving digit sums.
 *
 * @param {string} rawInputData - The raw string data obtained from the input source.
 * @returns {number} An exit status code (0 for successful execution, non-zero for errors).
 */
function executeSequenceGeneration(rawInputData) {
  // Clean and split the raw input data into an array of lines.
  // .trim() handles potential leading/trailing whitespace or empty lines.
  const inputLinesArray = rawInputData.trim().split('\n');

  // Extract the target number of iterations from the first line of input.
  // Use Number.parseInt with explicit radix for robust parsing.
  const firstLineComponents = inputLinesArray[0].split(' ');
  const totalIterationsRequested = Number.parseInt(firstLineComponents[0], NUMERIC_BASE);

  // --- Robustness: Input Validation Fragment ---
  // Ensure that the parsed iteration count is a valid positive integer.
  if (Number.isNaN(totalIterationsRequested) || totalIterationsRequested < 1) {
    console.error("Error: The input did not provide a valid positive integer for the number of iterations.");
    return 1; // Indicate a failure/error state.
  }
  // --- End Input Validation Fragment ---

  // The problem specifies that the first number in the output sequence is always 1.
  console.log(1);

  let currentSequenceBase = 2; // Initialize the starting number for the sequence generation process.

  // Iterate to generate the remaining elements of the sequence.
  // The loop runs 'totalIterationsRequested - 1' times, as the first element (1) is already printed.
  for (let stepCounter = 1; stepCounter < totalIterationsRequested; ++stepCounter) {
    // Initialize the best candidate found within the current iteration and its corresponding metric.
    let optimalCandidateForStep = currentSequenceBase;
    let minimumMetricForStep = calculateOptimizationMetric(optimalCandidateForStep);

    // This inner loop attempts to find a number that minimizes the optimization metric
    // by systematically modifying one digit of 'currentSequenceBase' to '9'.
    // It iterates through powers of 10 (1, 10, 100, ...), effectively targeting each digit position.
    for (let digitPositionFactor = 1; digitPositionFactor <= currentSequenceBase; digitPositionFactor *= NUMERIC_BASE) {
      // Create a mutable copy of the current base to experiment with digit changes.
      let experimentalNumber = currentSequenceBase;

      // Determine the digit currently at the position indicated by 'digitPositionFactor'.
      const digitAtCurrentPosition = Math.floor((experimentalNumber / digitPositionFactor) % NUMERIC_BASE);
      const targetDigitValue = 9; // The digit we aim to replace with to potentially minimize the metric.

      // --- Optimization/Clarity Fragment ---
      // Only proceed with modification if the digit is not already the target value (9).
      // This avoids redundant calculations and state changes.
      if (digitAtCurrentPosition !== targetDigitValue) {
        // Construct a new number by replacing the digit at the current position with '9'.
        // This is achieved by subtracting the value of the original digit at that position
        // and adding the value of the new target digit (9) at the same position.
        experimentalNumber = experimentalNumber - (digitAtCurrentPosition * digitPositionFactor) + (targetDigitValue * digitPositionFactor);
      }
      // --- End Optimization/Clarity Fragment ---

      // Calculate the optimization metric for this newly formed experimental number.
      const currentExperimentalMetric = calculateOptimizationMetric(experimentalNumber);

      // If the experimental number yields a better (smaller) metric, update our optimal candidate.
      if (currentExperimentalMetric < minimumMetricForStep) {
        optimalCandidateForStep = experimentalNumber;
        minimumMetricForStep = currentExperimentalMetric;
      }
    }

    // Output the optimal candidate found for the current step of the sequence.
    console.log(optimalCandidateForStep);

    // Update the base for the next iteration: it's the optimal candidate plus one.
    currentSequenceBase = optimalCandidateForStep + 1;
  }

  // Return 0 to signify successful completion of the program.
  return 0;
}

// Initiate the sequence generation process by calling the main function
// with input obtained from the standard input stream.
executeSequenceGeneration(obtainStandardInputContent());
// This is the primary function definition for the application logic.
// It calculates the minimum sum of absolute differences between three numbers,
// considering all possible permutations of their order.
function   Main   (  input  )
{
    // First, process the input string:
    // - Split it by spaces to get individual number strings.
    // - Use `map` with the double-tilde operator (`~~`) to convert each string
    //   into an integer. This is a concise way for type conversion.
    input  =  input . split (  " "  ) . map (  a  =>  ~~a  ) ;


    // The core logic involves finding the minimum value among several calculations.
    // We use `Math.min` along with the spread operator (`...`) to apply it
    // to an array of values generated by `map`.
    return   Math . min   (
        // An array of strings representing all permutations of indices (0, 1, 2)
        // for the three input numbers. These define the order in which numbers
        // are selected for difference calculations.
        ...[  "012"  ,  "021"  ,  "102"  ,  "120"  ,  "201"  ,  "210"  ] . map (

            // For each permutation string (e.g., "012"), this anonymous function
            // performs the following steps:
            function   (  a  )
            {
                // Convert the permutation string into an array of integers.
                // For instance, "012" becomes [0, 1, 2].
                a   =   a . split (  ""  ) . map (  a  =>  ~~a  ) ;

                // Calculate the sum of two absolute differences:
                // 1. The absolute difference between the first and second number
                //    in the current permutation order.
                // 2. The absolute difference between the second and third number
                //    in the current permutation order.
                // The input array `input` is accessed using the indices from `a`.
                return   Math . abs (  input [  a [  0  ]  ]  -  input [  a [  1  ]  ]  )
                    +   Math . abs (  input [  a [  1  ]  ]  -  input [  a [  2  ]  ]  ) ;
            }
        )
    ) ; // End of the `Math.min` function call.

} // End of the `Main` function.



/**
 * Main function containing the problem's logic.
 * Implements a Dijkstra-like algorithm with state (current node, current silver amount).
 * @returns {string} The final computed times for each node, formatted.
 */
function solveProblem() {
    // Read initial problem parameters: number of nodes, edges, and starting silver
    const [numNodes, numEdges, initialSilver] = obtainMultipleTokens(3);

    // Calculate the maximum possible silver capacity.
    // This is derived from the problem constraints (e.g., 50 silver per exchange, N nodes)
    const maxSilverCapacity = numNodes * 50 - 50; // Max silver on any path

    // Adjacency list representation of the graph
    // Each node stores an array of its neighbors: [neighborNodeIndex, silverCost, timeCost]
    const adjacencyList = initializeMultiDimensionalArray(() => [], numNodes);

    // Populate the adjacency list based on edge input
    for (let edgeIndex = 0; edgeIndex < numEdges; edgeIndex++) {
        let [nodeU, nodeV, silverNeeded, travelTime] = obtainMultipleTokens(4);
        nodeU--; // Adjust to 0-indexed
        nodeV--; // Adjust to 0-indexed
        // Add bidirectional edges
        adjacencyList[nodeU].push([nodeV, silverNeeded, travelTime]);
        adjacencyList[nodeV].push([nodeU, silverNeeded, travelTime]);
    }

    // Read silver exchange rates for each node
    // d[i][0] = silver gained at node i, d[i][1] = time cost at node i
    const exchangeRates = obtainTokenMatrix(numNodes, 2);

    // Distance map: map[node][silverAmount] stores the minimum time to reach 'node' with 'silverAmount'
    const minimumTimeMap = initializeMultiDimensionalArray(Infinity, numNodes, maxSilverCapacity + 1);

    // Array to store the final minimum travel time to each node (regardless of silver amount)
    const finalTravelTimes = initializeMultiDimensionalArray(Infinity, numNodes);

    // Initialize priority queue for Dijkstra's algorithm
    const travelPriorityQueue = minPriorityQueueFactory();

    // Ensure initial silver does not exceed max capacity
    const effectiveStartSilver = Math.min(initialSilver, maxSilverCapacity);

    // Push the starting state: [time, node, silver]
    travelPriorityQueue.insert([0, 0, effectiveStartSilver]);
    minimumTimeMap[0][effectiveStartSilver] = 0; // Time to reach node 0 with initial silver is 0

    let nodesVisitedCount = 0; // Counter for finalized nodes

    // Dijkstra's algorithm loop
    while (!travelPriorityQueue.isEmpty() && nodesVisitedCount < numNodes) {
        const [currentTime, currentNodeIdx, currentSilverAmount] = travelPriorityQueue.extractMin();

        // If we've already found a shorter path to this state, skip
        if (currentTime > minimumTimeMap[currentNodeIdx][currentSilverAmount]) {
            continue;
        }

        // If this is the first time we finalize the minimum time for this node, record it.
        // This implicitly counts as "visiting" a node for the final answer.
        if (finalTravelTimes[currentNodeIdx] === Infinity) {
            finalTravelTimes[currentNodeIdx] = currentTime;
            nodesVisitedCount++;
        }

        // --- Option 1: Exchange silver at the current node ---
        // Only exchange if we don't have max silver already
        if (currentSilverAmount < maxSilverCapacity) {
            const timeAfterExchange = currentTime + exchangeRates[currentNodeIdx][1];
            let silverAfterExchange = currentSilverAmount + exchangeRates[currentNodeIdx][0];
            // Cap silver at max capacity
            silverAfterExchange = Math.min(silverAfterExchange, maxSilverCapacity);

            // If this path to (currentNodeIdx, silverAfterExchange) is better, update and push to PQ
            if (minimumTimeMap[currentNodeIdx][silverAfterExchange] > timeAfterExchange) {
                minimumTimeMap[currentNodeIdx][silverAfterExchange] = timeAfterExchange;
                travelPriorityQueue.insert([timeAfterExchange, currentNodeIdx, silverAfterExchange]);
            }
        }

        // --- Option 2: Travel to neighboring nodes ---
        for (const [neighborIdx, silverCostForTravel, travelDuration] of adjacencyList[currentNodeIdx]) {
            const silverRemainingAfterTravel = currentSilverAmount - silverCostForTravel;

            // Cannot travel if not enough silver
            if (silverRemainingAfterTravel < 0) {
                continue;
            }

            const timeAfterTravel = currentTime + travelDuration;

            // If this path to (neighborIdx, silverRemainingAfterTravel) is better, update and push to PQ
            if (minimumTimeMap[neighborIdx][silverRemainingAfterTravel] > timeAfterTravel) {
                minimumTimeMap[neighborIdx][silverRemainingAfterTravel] = timeAfterTravel;
                travelPriorityQueue.insert([timeAfterTravel, neighborIdx, silverRemainingAfterTravel]);
            }
        }
    }

    // The problem output typically excludes the starting node's time (node 0)
    // and expects times for nodes 1 to N-1 (or 1-indexed nodes 2 to N).
    // If node 0 was the starting point, its time is 0.
    // We slice from index 1 to get times for nodes 1 to N-1 (0-indexed).
    return finalTravelTimes.slice(1).join("\n");
}
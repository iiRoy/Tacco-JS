"use strict";

// Module for reading input data
const rawInputContent = require("fs").readFileSync("/dev/stdin", "utf8");
let inputTokenStream = rawInputContent.split(/ |\n/);
let currentTokenPointer = 0;

/**
 * Retrieves the next token from the input stream.
 * @param {boolean} retrieveAsString - If true, returns the token as a string; otherwise, as a number.
 * @returns {string|number} The next token.
 */
function obtainNextToken(retrieveAsString) {
    const token = inputTokenStream[currentTokenPointer++];
    return retrieveAsString ? token : Number(token);
}

/**
 * Retrieves a specified number of tokens from the input stream.
 * @param {number} count - The number of tokens to retrieve.
 * @param {boolean} returnAsStrings - If true, returns tokens as strings; otherwise, as numbers.
 * @returns {Array<string|number>} An array of tokens.
 */
function obtainMultipleTokens(count, returnAsStrings) {
    const tokens = inputTokenStream.slice(currentTokenPointer, currentTokenPointer + count);
    currentTokenPointer += count;
    return returnAsStrings ? tokens : tokens.map(Number);
}

/**
 * Retrieves a 2D matrix of tokens from the input stream.
 * @param {number} numRows - The number of rows in the matrix.
 * @param {number} numCols - The number of columns in the matrix.
 * @param {boolean} returnAsStrings - If true, returns elements as strings; otherwise, as numbers.
 * @returns {Array<Array<string|number>>} The 2D matrix.
 */
function obtainTokenMatrix(numRows, numCols, returnAsStrings) {
    const matrixResult = [];
    for (let r = 0; r < numRows; r++) {
        const rowTokens = inputTokenStream.slice(currentTokenPointer, currentTokenPointer + numCols);
        currentTokenPointer += numCols;
        matrixResult.push(returnAsStrings ? rowTokens : rowTokens.map(Number));
    }
    return matrixResult;
}

/**
 * Creates a multi-dimensional array initialized with a specific value or generated by a function.
 * @param {any|Function} initialValueOrGenerator - The default value or a function that generates it for each leaf.
 * @param {...number} dimensions - The sizes of each dimension.
 * @returns {Array} The initialized multi-dimensional array.
 */
function initializeMultiDimensionalArray(initialValueOrGenerator, ...dimensions) {
    if (dimensions.length === 0) {
        // Base case: return the value itself or the result of the generator function
        return typeof initialValueOrGenerator === 'function' ? initialValueOrGenerator() : initialValueOrGenerator;
    }

    const currentDimensionSize = dimensions[0];
    const remainingDimensions = dimensions.slice(1);
    const newArray = new Array(currentDimensionSize);

    for (let i = 0; i < currentDimensionSize; i++) {
        newArray[i] = initializeMultiDimensionalArray(initialValueOrGenerator, ...remainingDimensions);
    }
    return newArray;
}

/**
 * Implements a Min-Priority Queue data structure.
 * Elements are expected to be arrays where the first element is the priority key.
 */
const minPriorityQueueFactory = (function() {
    /**
     * PriorityQueue constructor.
     * @constructor
     */
    function QueueStructure() {
        this.dataHeap = []; // The internal array representing the heap
    }

    /**
     * Inserts an element into the priority queue.
     * @param {Array} newItem - The element to insert, where newItem[0] is its priority.
     */
    QueueStructure.prototype.insert = function(newItem) {
        const heapRef = this.dataHeap;
        let currentIndex = heapRef.length;
        heapRef.push(newItem); // Add to the end initially

        // Bubble up: maintain heap property
        while (currentIndex > 0) {
            const parentIndex = Math.floor((currentIndex - 1) / 2);
            if (heapRef[parentIndex][0] <= newItem[0]) {
                // Parent has lower or equal priority, correct position found
                break;
            }
            // Swap with parent
            heapRef[currentIndex] = heapRef[parentIndex];
            currentIndex = parentIndex;
        }
        heapRef[currentIndex] = newItem; // Place the new item in its final position
    };

    /**
     * Removes and returns the element with the highest priority (smallest key).
     * @returns {Array|undefined} The element with the smallest key, or undefined if the queue is empty.
     */
    QueueStructure.prototype.extractMin = function() {
        const heapRef = this.dataHeap;
        if (heapRef.length === 0) {
            return undefined; // Queue is empty
        }
        if (heapRef.length === 1) {
            return heapRef.pop(); // Only one element, just remove it
        }

        const minElement = heapRef[0]; // The element to return
        const lastElement = heapRef.pop(); // Take the last element
        const heapSize = heapRef.length;

        // Bubble down: maintain heap property with the last element
        let currentIndex = 0;
        const middleIndex = Math.floor(heapSize / 2); // Optimization: only need to check up to here

        while (currentIndex < middleIndex) {
            let childIndex = (currentIndex * 2) + 1; // Left child

            // Check if right child exists and has higher priority
            if (childIndex + 1 < heapSize && heapRef[childIndex + 1][0] < heapRef[childIndex][0]) {
                childIndex++; // Use the right child
            }

            if (lastElement[0] <= heapRef[childIndex][0]) {
                // Last element has lower or equal priority than its smallest child, correct position found
                break;
            }
            // Swap with smallest child
            heapRef[currentIndex] = heapRef[childIndex];
            currentIndex = childIndex;
        }
        heapRef[currentIndex] = lastElement; // Place the last element in its final position
        return minElement;
    };

    /**
     * Checks if the priority queue is empty.
     * @returns {boolean} True if the queue is empty, false otherwise.
     */
    QueueStructure.prototype.isEmpty = function() {
        return this.dataHeap.length === 0;
    };

    // The factory function returns a new instance of the PriorityQueue.
    return function createNewPriorityQueue() {
        return new QueueStructure();
    };
})();


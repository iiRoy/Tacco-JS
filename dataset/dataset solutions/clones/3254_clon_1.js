/*
 * This JavaScript program processes a single integer input
 * and applies the Collatz conjecture rules to it.
 * It detects if the sequence enters a cycle and outputs the
 * number of steps taken to reach that cycle.
 */
function   Main   (   input   )
{

    // The entire input data is typically provided as a single string.
    // We split it by newline characters to handle multiple lines,
    // though in this specific problem, only the first line is used.
    input  =  input.split ( "\n" )  ;

    /*
     * The first line of the input (input[0]) contains the initial number.
     * We convert this string to an integer using parseInt,
     * specifying base 10 to ensure correct conversion.
     */
    var   a   =   parseInt (   input[0]   ,   10   )   ;


    // 'A' is an array that will store the sequence of numbers generated by
    // the Collatz process. This allows us to detect if a number repeats,
    // indicating that the sequence has entered a cycle.
    var   A   =   [ ]   ;

    // Add the initial value of 'a' to our sequence array.
    A.push (   a   )   ;


    // This loop iterates up to a maximum of 1,000,000 times.
    // It applies the Collatz rules and checks for cycle detection.
    for   (   i = 1   ;   i < 1000000   ;   i++   )
    {

        // The core logic of the Collatz conjecture:
        // If the current number 'a' is even, divide it by 2.
        if   (   a   %   2   ==   0   )
        {
            a   =   a   /   2   ;
        }
        // If the current number 'a' is odd, multiply it by 3 and add 1.
        else
        {
            a   =   a   *   3   +   1   ;
        }


        // After calculating the new value of 'a', we check if this value
        // has already appeared in our sequence array 'A'.
        // indexOf returns the first index at which a given element can be found in the array, or -1 if it is not present.
        var   p   =   A.indexOf (   a   )   ;

        // If 'p' is not -1, it means 'a' was found in the array 'A',
        // indicating that the sequence has entered a cycle.
        if   (   p   !=   -1   )
        {
            // We output the current step count (i + 1) and then break
            // out of the loop as the cycle has been detected.
            console.log (   i   +   1   )   ;
            break   ;
        }

        // If no cycle is detected, we add the new value of 'a' to the
        // sequence array 'A' for future cycle detection.
        A[i]   =   a   ;

    } // End of the main Collatz sequence generation loop.


    // The following line is commented out but could be used for debugging
    // to inspect the full sequence generated in array A.
    // console.log(A);

} // End of the Main function definition.



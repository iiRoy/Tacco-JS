'use strict'; // Enforce strict mode for cleaner code practices.

// Define aliases for standard I/O streams for improved readability and potential future remapping.
const standardInStream = process.stdin;
const standardOutStream = process.stdout;

let accumulatedInputBuffer = ''; // A string buffer to collect all data from standard input.

// Configure the input stream to resume data flow and decode bytes as UTF-8 characters.
standardInStream.resume();
standardInStream.setEncoding('utf8');

// Attach an event listener to capture each incoming data chunk.
standardInStream.on('data', function(dataChunk) {
  // Append the current data chunk to our growing input buffer.
  accumulatedInputBuffer += dataChunk;
});

// Helper function to convert an array of string tokens into an array of integers.
// It also filters out any tokens that cannot be successfully parsed as numbers.
function convertTokensToNumbers(tokenStrings) {
    return tokenStrings
        .map(str => parseInt(str, 10)) // Attempt to parse each string as a base-10 integer.
        .filter(num => !isNaN(num));    // Keep only the values that successfully converted to a number.
}

// Attach an event listener for when the input stream has completely ended.
standardInStream.on('end', function() {
  // Guard clause: Check if any input was received at all.
  if (accumulatedInputBuffer.trim().length === 0) {
    standardOutStream.write("Error: No input data received. Exiting.\n");
    process.exit(1); // Exit with a non-zero status code to indicate an error.
  }

  // Split the entire collected input string by one or more whitespace characters.
  // This can result in empty strings if there are multiple spaces or leading/trailing whitespace.
  const rawSplitTokens = accumulatedInputBuffer.split(/\s+/);

  // The original problem structure implies that the first and last elements
  // of the split array are not part of the numeric sequence to be processed.
  // We extract the middle section, which might still contain empty strings if
  // the original input had multiple spaces or specific formatting.
  // Example: "1 2 3\n" splits to ["1", "2", "3", ""]. Slice (1, 3) yields ["2", "3"].
  // Example: "1 2 3" splits to ["1", "2", "3"]. Slice (1, 2) yields ["2"].
  const relevantStringTokens = rawSplitTokens.slice(1, rawSplitTokens.length - 1);

  // Guard clause: After slicing, ensure there are still tokens to process.
  if (relevantStringTokens.length === 0) {
      standardOutStream.write("Error: No relevant string tokens found after initial parsing steps. Exiting.\n");
      process.exit(1);
  }

  // Convert the extracted string tokens into an array of numbers, filtering out invalid entries.
  const initialNumericSequence = convertTokensToNumbers(relevantStringTokens);

  // Guard clause: Check if any valid numbers remain after conversion and filtering.
  if (initialNumericSequence.length === 0) {
      standardOutStream.write("Error: No valid numbers found for calculation after filtering. Exiting.\n");
      process.exit(1);
  }

  // Invoke the primary calculation function with the prepared numeric sequence.
  const finalComputedValue = performIterativeSummation(initialNumericSequence);

  // Output the final result to standard output, followed by a newline.
  standardOutStream.write(finalComputedValue.toString() + '\n');

  // Terminate the Node.js process successfully.
  process.exit(0);
});

/**
 * Calculates a specific aggregate sum by repeatedly transforming and summing elements
 * of an array. In each iteration, the first element of the current sequence is added
 * to a running total. Then, a new sequence is generated by taking the minimum of
 * adjacent pairs from the current sequence, and all elements (except the first)
 * of the current sequence are also added to the running total. This process continues
 * until the sequence becomes empty.
 *
 * @param {number[]} initialNumbers - The array of integers to begin the calculation with.
 * @returns {number} The final cumulative sum derived from the iterative process.
 */
function performIterativeSummation(initialNumbers) {
  // Guard clause: If the input array is empty, the sum is zero.
  if (initialNumbers.length === 0) {
    return 0;
  }

  let cumulativeSum = 0; // This variable accumulates the final result.
  // Create a mutable copy of the input array to avoid modifying the original.
  let currentWorkingSequence = [...initialNumbers];

  // The main loop continues as long as there are elements in the sequence.
  while (currentWorkingSequence.length > 0) {
    // Add the very first element of the current sequence to our running total.
    cumulativeSum += currentWorkingSequence[0];

    // Initialize an empty array to store the results of the pairwise minimums.
    const nextReducedSequence = [];

    // Iterate through the current sequence starting from the second element
    // to calculate pairwise minimums and update the cumulative sum.
    // This loop effectively replaces the `reduce` call in the original code,
    // achieving the same logic explicitly.
    for (let i = 1; i < currentWorkingSequence.length; ++i) {
      const valueBefore = currentWorkingSequence[i - 1];
      const valueAtCurrent = currentWorkingSequence[i];

      // Add the minimum of the current and previous element to the next sequence.
      nextReducedSequence.push(Math.min(valueBefore, valueAtCurrent));

      // Add the current element to the cumulative sum.
      // Note: The first element of `currentWorkingSequence` was already added before this loop.
      cumulativeSum += valueAtCurrent;
    }

    // Replace the current sequence with the newly generated reduced sequence for the next iteration.
    currentWorkingSequence = nextReducedSequence;
  }

  // Return the final accumulated sum.
  return cumulativeSum;
}
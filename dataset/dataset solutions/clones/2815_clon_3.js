// Graph Topology Generator for Distance-2 Pairs
// This script constructs a graph with a specified number of nodes (N)
// and aims to achieve a target count of pairs (K) that are exactly
// two edges apart (shortest path distance of 2).
// Implemented: 2024-05-15 (re-implementation)

'use strict';

// A buffer to collect all output messages before printing them to console.
// This allows for more controlled output flow, especially with early exits.
const outputBuffer = [];

/**
 * Records a message to the internal output buffer.
 * @param {string} message - The string message to be recorded.
 */
function storeOutputMessage(message) {
    outputBuffer.push(message);
}

/**
 * Prints all messages currently stored in the output buffer to the console.
 */
function flushOutputBuffer() {
    outputBuffer.forEach(msg => console.log(msg));
}

/**
 * Main function to process graph parameters, find a suitable configuration,
 * and generate the corresponding edge list.
 * @param {string[]} inputDataLines - An array of strings, where the first element
 *                                    contains space-separated N and K values.
 */
function processGraphParameters(inputDataLines) {
    // --- Input Validation and Parsing ---
    if (!Array.isArray(inputDataLines) || inputDataLines.length === 0) {
        process.stderr.write("Input Error: No data lines provided.\n");
        process.exit(1); // Exit with an error code
    }

    const firstLineTokens = inputDataLines[0].split(' ');
    if (firstLineTokens.length < 2) {
        process.stderr.write("Input Error: Insufficient parameters on the first line. Expected N and K.\n");
        process.exit(1);
    }

    const totalNodes = parseInt(firstLineTokens[0], 10);
    const targetDistanceTwoPairs = parseInt(firstLineTokens[1], 10);

    // Further validation for parsed numerical values
    if (isNaN(totalNodes) || isNaN(targetDistanceTwoPairs) || totalNodes < 1 || targetDistanceTwoPairs < 0) {
        process.stderr.write(`Input Error: Invalid numeric values (N=${firstLineTokens[0]}, K=${firstLineTokens[1]}). N must be >= 1, K must be >= 0.\n`);
        process.exit(1);
    }

    let pathComponentLength = 0; // Represents 'M' from original, controlling the path segment length
    let validConfigurationFound = false; // Flag to indicate if a suitable 'M' was found

    // --- Search for the optimal pathComponentLength ---
    // The core logic iterates through possible values for 'pathComponentLength'
    // (from N down to 1) to find a configuration that yields 'targetDistanceTwoPairs'.
    // The graph structure is a path (1 to pathComponentLength+1) and a star
    // (nodes pathComponentLength+2 to totalNodes connected to pathComponentLength+1).
    for (let currentPathSegmentSize = totalNodes; currentPathSegmentSize >= 1; currentPathSegmentSize--) {
        // 'starSubGraphNodeCount' represents the number of nodes forming the 'star' part,
        // including the central node (pathComponentLength + 1).
        // Original: L = N - M + 1
        const starSubGraphNodeCount = totalNodes - currentPathSegmentSize + 1;

        // Calculate the number of distance-2 pairs generated by this specific 'currentPathSegmentSize'.
        // This formula is derived from the problem's graph construction and distance-2 definition.

        // Term 1: Pairs (u, v) where u, v are both from the 'star branches' (nodes from currentPathSegmentSize+2 to totalNodes).
        // These nodes are all connected to 'currentPathSegmentSize+1', so any pair of them are distance 2 via 'currentPathSegmentSize+1'.
        // Number of nodes in these branches: totalNodes - (currentPathSegmentSize + 1) = totalNodes - currentPathSegmentSize - 1.
        // This is (starSubGraphNodeCount - 1) - 1, if starSubGraphNodeCount is at least 2.
        // The number of pairs (combinations of 2) from these nodes is: (count) * (count - 1) / 2.
        const numStarBranchNodes = totalNodes - currentPathSegmentSize - 1;
        const starInternalPairs = (numStarBranchNodes > 1) ? (numStarBranchNodes * (numStarBranchNodes - 1)) / 2 : 0;

        // Term 2: Pairs (u, v) where u, v are both from the 'path' segment (nodes 1 to currentPathSegmentSize+1).
        // In a path graph, nodes (i, i+2) have a shortest path distance of 2 (via i+1).
        // For a path of length 'P' (P edges, P+1 nodes), there are 'P-1' such pairs.
        // Here, the path has 'currentPathSegmentSize' edges (nodes 1 to currentPathSegmentSize+1).
        // So, there are 'currentPathSegmentSize - 1' such pairs.
        const pathInternalPairs = (currentPathSegmentSize > 1) ? (currentPathSegmentSize - 1) : 0;
        
        const totalCalculatedPairs = starInternalPairs + pathInternalPairs;

        // Check if the calculated pairs match the target.
        if (totalCalculatedPairs === targetDistanceTwoPairs) {
            pathComponentLength = currentPathSegmentSize;
            validConfigurationFound = true;
            break; // Found the desired 'M', exit the loop
        }
    }

    // --- Output Generation ---
    if (!validConfigurationFound) {
        storeOutputMessage("-1"); // Indicate that no valid configuration was found
        flushOutputBuffer();
        return; // Exit function
    }

    // A connected graph with N nodes will always have N-1 edges in this specific construction.
    const finalEdgeCount = totalNodes - 1;
    storeOutputMessage(finalEdgeCount.toString());

    const generatedEdges = [];

    // First set of edges: forming the path from node 1 to pathComponentLength+1
    // Example: if pathComponentLength = 3, edges are (1,2), (2,3), (3,4)
    for (let nodeIterator = 1; nodeIterator <= pathComponentLength; nodeIterator++) {
        const nextNodeInPath = nodeIterator + 1;
        generatedEdges.push(`${nodeIterator} ${nextNodeInPath}`);
    }

    // Second set of edges: connecting remaining nodes to the central node (pathComponentLength+1)
    // This forms a star-like structure with (pathComponentLength+1) as the center.
    const centralNodeForStar = pathComponentLength + 1;
    for (let additionalNode = centralNodeForStar + 1; additionalNode <= totalNodes; additionalNode++) {
        generatedEdges.push(`${centralNodeForStar} ${additionalNode}`);
    }

    // Add all generated edges to the output buffer
    generatedEdges.forEach(edgeString => storeOutputMessage(edgeString));

    // Finally, print all buffered output to stdout
    flushOutputBuffer();
}

/**
 * Sets up the standard input stream to read data and then
 * calls the main processing function.
 */
function initializeStandardInputHandler() {
    let completeInputString = "";
    process.stdin.resume(); // Ensures the process stays active to receive input
    process.stdin.setEncoding("utf8"); // Specifies UTF-8 encoding for input data

    // Event listener for when data is received from stdin
    process.stdin.on("data", (incomingDataChunk) => {
        completeInputString += incomingDataChunk;
    });

    // Event listener for when the input stream has ended
    process.stdin.on("end", () => {
        // Split the accumulated input by newlines and filter out any empty lines
        const parsedInputLines = completeInputString.split("\n").filter(line => line.trim() !== '');
        processGraphParameters(parsedInputLines);
    });

    // Optional: Add an error handler for the input stream
    process.stdin.on("error", (streamError) => {
        process.stderr.write(`An error occurred during input processing: ${streamError.message}\n`);
        process.exit(1);
    });
}

// Begin the program execution by setting up the input handler
initializeStandardInputHandler();
/**
 * Defines the sales revenue threshold for an account to be considered high-value.
 * Accounts with total revenue at or above this amount will be included in the special report.
 * This constant makes the magic number 1,000,000 explicit and easily modifiable.
 */
const MINIMUM_HIGH_VALUE_THRESHOLD = 1000000;

/**
 * Specifies the expected number of numeric values on a line that signals the end
 * of a data batch and triggers a report generation.
 * This constant replaces the magic number 1 used for the signal line length.
 */
const END_OF_BATCH_SIGNAL_LENGTH = 1;

/**
 * Parses a raw string line into an array of numeric values.
 * It handles potential whitespace issues and filters out non-numeric results.
 *
 * @param {string} lineContent - The raw string input from a single line.
 * @returns {number[]} An array containing only valid numbers parsed from the line.
 */
function extractNumericDataFromLine(lineContent) {
    // Basic validation to prevent errors with null/undefined input.
    if (typeof lineContent !== 'string' || lineContent.trim() === '') {
        return [];
    }
    // Split by space, convert each segment to a number, and filter out any NaN results.
    return lineContent.split(" ").map(segment => Number(segment.trim())).filter(num => !isNaN(num));
}

/**
 * Computes the total revenue for a single sales transaction.
 * This helper function encapsulates the calculation logic.
 *
 * @param {number} quantitySold - The number of units sold in the transaction.
 * @param {number} unitSellingPrice - The price per unit for the item.
 * @returns {number} The total revenue generated by this transaction. Returns 0 if inputs are invalid.
 */
function calculateTransactionRevenue(quantitySold, unitSellingPrice) {
    // Defensive checks for valid numeric inputs.
    if (isNaN(quantitySold) || isNaN(unitSellingPrice)) {
        console.warn(`Warning: Invalid numeric input for transaction revenue calculation (Quantity: ${quantitySold}, Price: ${unitSellingPrice}). Returning 0.`);
        return 0;
    }
    return quantitySold * unitSellingPrice;
}

/**
 * Processes the current collection of accumulated sales records and generates a report
 * identifying accounts that have met the high-value sales threshold.
 * The report prints the identifiers of these qualifying accounts to the console.
 *
 * @param {Map<number, {identifier: number, totalRevenue: number}>} currentSalesLedger - A map
 *   where keys are account identifiers and values are objects containing the identifier
 *   and its accumulated total revenue.
 */
function produceHighValueAccountReport(currentSalesLedger) {
    const highPerformingAccountIDs = [];

    // Iterate over the values (account objects) in the Map.
    // Using for...of with Map.values() is an efficient way to access just the objects.
    for (const accountRecord of currentSalesLedger.values()) {
        if (accountRecord.totalRevenue >= MINIMUM_HIGH_VALUE_THRESHOLD) {
            highPerformingAccountIDs.push(accountRecord.identifier);
        }
    }

    // Check if any accounts qualified.
    if (highPerformingAccountIDs.length === 0) {
        console.log("NO_ACCOUNTS_MEET_CRITERIA"); // More descriptive than "NA"
    } else {
        // Sort the IDs numerically to ensure consistent output order.
        highPerformingAccountIDs.sort((a, b) => a - b);
        // Output each qualifying account ID.
        for (const accountID of highPerformingAccountIDs) {
            console.log(accountID);
        }
    }
}

/**
 * The primary function responsible for processing raw sales input data.
 * It reads line by line, accumulates sales figures for various accounts,
 * and triggers reports based on specific input signals.
 *
 * @param {string} rawSalesDataInput - The complete raw input string, typically from a file.
 */
function analyzeAndReportSalesData(rawSalesDataInput) {
    // Initial validation: Ensure the input data is a non-empty string.
    if (typeof rawSalesDataInput !== 'string' || rawSalesDataInput.trim() === '') {
        console.error("Error: Input data is empty or malformed. Cannot proceed with analysis.");
        return; // Exit early if input is invalid.
    }

    const allInputRecords = rawSalesDataInput.split("\n");

    // The first line might contain metadata (e.g., total number of records),
    // but its specific value is not directly used for loop control in this revised logic.
    // We still parse it to consume the line and move to actual data.
    const headerInformation = extractNumericDataFromLine(allInputRecords[0]);
    // Optional: headerInformation[0] could be used for initial setup or validation,
    // e.g., to reserve memory or pre-allocate structures, but it's not strictly necessary here.

    let recordPointer = 1; // Start processing from the second line of the input.
    // Using a Map for `accumulatedSalesData` allows for efficient O(1) average time
    // lookup and update of account records by their unique identifier,
    // replacing the original array-based linear search.
    let accumulatedSalesData = new Map(); // Stores { identifier: number, totalRevenue: number } objects.

    // Iterate through the input records until all lines have been processed.
    while (recordPointer < allInputRecords.length) {
        const currentDataLine = allInputRecords[recordPointer];

        // Skip any completely empty lines that might appear in the input.
        if (currentDataLine.trim() === '') {
            recordPointer++;
            continue;
        }

        const parsedNumericValues = extractNumericDataFromLine(currentDataLine);

        // Determine if the current line is a report trigger or a sales transaction.
        if (parsedNumericValues.length === END_OF_BATCH_SIGNAL_LENGTH) {
            // A single number on a line acts as a signal to generate a report.
            produceHighValueAccountReport(accumulatedSalesData);
            accumulatedSalesData.clear(); // Clear all accumulated data for the next batch.
        } else if (parsedNumericValues.length >= 3) {
            // A sales transaction line is expected to have at least three numbers:
            // Account ID, Quantity, and Unit Price.
            const accountID = parsedNumericValues[0];
            const transactionQuantity = parsedNumericValues[1];
            const transactionUnitPrice = parsedNumericValues[2];

            // Validate that the core components of a transaction are indeed numbers.
            if (isNaN(accountID) || isNaN(transactionQuantity) || isNaN(transactionUnitPrice)) {
                console.warn(`Skipping malformed transaction line at index ${recordPointer}: "${currentDataLine}". Contains non-numeric values for ID, Quantity, or Price.`);
                recordPointer++;
                continue; // Move to the next line.
            }

            const totalTransactionRevenue = calculateTransactionRevenue(transactionQuantity, transactionUnitPrice);

            // Fetch the existing account record or create a new one if it's a new account ID.
            let accountDetails = accumulatedSalesData.get(accountID);
            if (!accountDetails) {
                accountDetails = { identifier: accountID, totalRevenue: 0 };
                accumulatedSalesData.set(accountID, accountDetails); // Store new account in the Map.
            }
            // Update the total revenue for the identified account.
            accountDetails.totalRevenue += totalTransactionRevenue;
        } else {
            // Log a warning for any lines that do not fit the expected formats.
            console.warn(`Encountered an unrecognized line format at index ${recordPointer}: "${currentDataLine}". This line will be skipped.`);
        }

        recordPointer++; // Advance to the next line in the input.
    }

    // After processing all input lines, there might be a final batch of sales data
    // that wasn't followed by an explicit end-of-batch signal.
    // This guard clause ensures that any remaining data is processed and reported.
    if (accumulatedSalesData.size > 0) {
        // console.log("--- Processing final batch at end of input ---"); // Optional debug message
        produceHighValueAccountReport(accumulatedSalesData);
    }
}

// Entry point: Read data from standard input and initiate the analysis.
// This part remains similar to the original, adapting to the new function name.
analyzeAndReportSalesData(require('fs').readFileSync('/dev/stdin','utf8'));
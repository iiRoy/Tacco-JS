/*
 * This file implements a custom module bundling and loading mechanism,
 * similar to how a web application bundler might operate.
 * It takes a collection of module definitions and provides a function
 * to resolve and execute them, managing a module cache.
 *
 * The primary purpose of this specific bundle is to process a single
 * line of text from standard input, applying a scoring logic based on
 * character occurrences ('g' and 'p').
 *
 * This version is a Type III clone of an original JavaScript bundle,
 * featuring extensive renaming, reformatting, structural modifications
 * such as deletion of unused helper functions, addition of error handling,
 * validation, and rewriting of core logic for clarity.
 */
module.exports = function(moduleDefinitionsMap) {
    // This object serves as a registry for modules that have already been loaded,
    // preventing redundant execution and providing cached exports.
    const moduleCacheRegistry = {};

    /**
     * Resolves and loads a module by its identifier. If the module is already
     * in the cache, its exports are returned immediately. Otherwise, the module
     * definition is executed, its exports are captured, and it's added to the cache.
     * @param {number} targetModuleId - The unique identifier for the module to load.
     * @returns {object} The exports object of the requested module.
     */
    function moduleLoader(targetModuleId) {
        // --- Type III Change: Added guard clause for invalid module ID ---
        if (targetModuleId === null || targetModuleId === undefined || !moduleDefinitionsMap[targetModuleId]) {
            console.error(`Error: Attempted to load an undefined or invalid module ID: ${targetModuleId}`);
            // In a real bundler, this might throw or return a specific error module.
            // For this clone, we'll return an empty object as a fallback.
            return {};
        }

        // Check if the module is already present in our cache.
        if (moduleCacheRegistry[targetModuleId]) {
            return moduleCacheRegistry[targetModuleId].exports;
        }

        // If not cached, prepare a new module record.
        // --- Type II/III Change: Renamed variables for clarity, slightly reordered initialization ---
        const activeModuleRecord = {
            idKey: targetModuleId,
            isLoadedFlag: false, // Indicates if the module's definition function has been run.
            exports: {} // The object that will hold the module's exports.
        };

        // Store the new module record in the cache *before* execution.
        // This helps prevent infinite loops for circular dependencies.
        moduleCacheRegistry[targetModuleId] = activeModuleRecord;

        // Execute the module's definition function.
        // The definition function typically expects (module, exports, require) as arguments.
        // --- Type II Change: Renamed parameters within the call ---
        const moduleDefinitionFunction = moduleDefinitionsMap[targetModuleId];
        if (typeof moduleDefinitionFunction === 'function') {
            moduleDefinitionFunction.call(
                activeModuleRecord.exports, // 'this' context for the module, often its exports object.
                activeModuleRecord,         // The module object itself.
                activeModuleRecord.exports, // The exports object.
                moduleLoader                // The local 'require' function for this module.
            );
        } else {
            console.error(`Module definition for ID ${targetModuleId} is not a function.`);
            // This could happen if the definitions map is malformed.
        }


        // Mark the module as fully loaded after its definition has been executed.
        // --- Type II Change: Renamed property ---
        activeModuleRecord.isLoadedFlag = true;

        // Return the exports generated by the module.
        return activeModuleRecord.exports;
    }

    // --- Type II Change: Renamed properties for clarity ---
    // Store the full map of module definitions on the loader for potential introspection.
    moduleLoader.definitions = moduleDefinitionsMap;
    // Store the module cache on the loader.
    moduleLoader.moduleCache = moduleCacheRegistry;

    /**
     * Checks if an object has a specific property using Object.prototype.hasOwnProperty.
     * This is a safer way to check for own properties than direct `obj.prop` or `obj[prop]`.
     * @param {object} targetObject - The object to check.
     * @param {string} propertyName - The name of the property to look for.
     * @returns {boolean} True if the object has the property, false otherwise.
     */
    moduleLoader.hasOwnProp = function(targetObject, propertyName) {
        return Object.prototype.hasOwnProperty.call(targetObject, propertyName);
    };

    // --- Type III Change: Deleted unused helper functions (n.d, n.r, n.t, n.n, n.p) ---
    // The original bundle included several webpack-specific helper functions (d, r, t, n, p)
    // for defining properties, marking ES modules, handling interop, and public paths.
    // Since the provided example modules do not explicitly use these helpers,
    // they have been removed in this Type III clone to simplify the generated code
    // and demonstrate deletion of non-essential fragments.

    // Initiate the loading process by requiring the entry point module (ID 0).
    // --- Type II Change: Removed the 'n.s' assignment, assuming 0 is always the start ---
    return moduleLoader(0);
}([
    /*
     * Module 0: The primary entry point for this application.
     * It reads input from /dev/stdin, splits it into lines, and then
     * passes the first line to the core logic module (Module 1) for processing.
     * It also depends on the 'fs' module (Module 2) for file system operations.
     */
    function(currentExports, moduleContext, localModuleResolver) {
        // --- Type III Change: Added constant for STDIN path ---
        const STDIN_FILE_PATH = "/dev/stdin";
        let rawInputContent = "";

        try {
            // Dynamically load the Node.js 'fs' module using the local resolver.
            // --- Type II Change: Renamed variables ---
            const fileSystemModule = localModuleResolver(2);

            // Read the entire content of standard input.
            // --- Type III Change: Added try...catch for file reading robustness ---
            rawInputContent = fileSystemModule.readFileSync(STDIN_FILE_PATH, "UTF-8");
        } catch (readError) {
            console.error(`Failed to read from ${STDIN_FILE_PATH}:`, readError.message);
            // Provide a fallback or exit if critical input cannot be read.
            rawInputContent = ""; // Ensure it's a string even on error.
        }

        // Split the input into lines.
        const inputLines = rawInputContent.split("\n");

        // Resolve and execute the main processing logic module (Module 1).
        // Pass the parsed input lines to it.
        // --- Type II Change: Renamed parameter ---
        const processInputFunction = localModuleResolver(1);

        // --- Type III Change: Added validation for the processing function ---
        if (typeof processInputFunction === 'function') {
            processInputFunction(inputLines);
        } else {
            console.error("The core processing module (ID 1) did not export a function.");
        }
    },

    /*
     * Module 1: Contains the core logic to process a single line of text.
     * It calculates a score based on specific character patterns ('g' and 'p').
     */
    function(moduleExports, moduleObject) {
        // This module exports a function that takes an array of input lines.
        moduleExports.exports = function(inputLines) {
            // --- Type III Change: Added input validation ---
            if (!Array.isArray(inputLines) || inputLines.length === 0) {
                console.error("Error: Input lines must be a non-empty array.");
                return; // Exit if input is invalid.
            }

            // --- Type III Change: Introduced constants for magic characters ---
            const POSITIVE_CHAR = 'g';
            const NEGATIVE_CHAR = 'p';

            // Extract the first line for processing.
            // --- Type II Change: Renamed variables ---
            const firstLine = inputLines[0];

            // --- Type III Change: Added guard for empty first line ---
            if (!firstLine || typeof firstLine !== 'string') {
                console.warn("Warning: The first input line is empty or not a string. No processing will occur.");
                return;
            }

            const lineLength = firstLine.length;

            // Initialize scoring and balancing counters.
            // 'finalScore' accumulates the result.
            // 'balanceCounter' tracks the state for conditional scoring.
            // --- Type II Change: Renamed variables ---
            let finalScore = 0;
            let balanceCounter = 0;

            // Iterate through each character of the first line.
            // --- Type II Change: Renamed loop variable, used `let` ---
            for (let charIndex = 0; charIndex < lineLength; charIndex++) {
                // --- Type III Change: Introduced intermediate variable for current character ---
                const currentChar = firstLine[charIndex];

                // --- Type III Change: Rewrote the compact ternary logic into explicit if/else if for clarity ---
                // Original logic: o > 0 && "g" == t[u] ? ("g" == t[u] && r++, o--) : ("p" == t[u] && r--, o++);
                // Expanded and clarified:
                if (balanceCounter > 0 && currentChar === POSITIVE_CHAR) {
                    // If balance is positive and current char is 'g', increment score and decrement balance.
                    finalScore++;
                    balanceCounter--;
                } else if (currentChar === NEGATIVE_CHAR) {
                    // If the char is 'p' (regardless of balance or if previous condition was false),
                    // decrement score and increment balance.
                    finalScore--;
                    balanceCounter++;
                }
                // If neither condition is met (e.g., balance <= 0 and char is 'g', or char is not 'g'/'p'),
                // nothing happens to score or balance, which matches original behavior.
            }

            // Output the calculated final score to the console.
            console.log(finalScore);
        };
    },

    /*
     * Module 2: A simple wrapper for Node.js's built-in 'fs' (file system) module.
     * This allows other modules within the bundle to access file system functionalities.
     */
    function(moduleExports, moduleObject) {
        // --- Type III Change: Added a check for Node.js environment ---
        if (typeof require === 'function' && typeof process !== 'undefined' && process.versions && process.versions.node) {
            // Assign the Node.js 'fs' module to this module's exports.
            // --- Type II Change: Renamed variables ---
            moduleExports.exports = require("fs");
        } else {
            console.error("Error: 'fs' module requires a Node.js-like environment.");
            // Provide a mock or empty object if 'fs' cannot be loaded.
            moduleExports.exports = {
                readFileSync: () => { throw new Error("readFileSync is not available in this environment."); }
            };
        }
    }
]);
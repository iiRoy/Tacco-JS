"use strict";

// Helper function to safely destructure an iterable into an array with a limited size.
// This function mimics Babel's _slicedToArray and is used for robust destructuring.
function _destructureSafely(iterableObj, maxElements) {
  if (Array.isArray(iterableObj)) return iterableObj; // If it's already an array, return it directly.
  // Otherwise, attempt to extract elements from the iterable.
  return _extractLimitedFromIterable(iterableObj, maxElements) || _handleInvalidDestructure();
}

// Helper function to throw a specific error when an attempt to destructure a non-iterable instance occurs.
// This ensures runtime type safety for destructuring operations.
function _handleInvalidDestructure() {
  throw new TypeError("Invalid attempt to destructure non-iterable instance. Expected an array or iterable.");
}

// Helper function to iterate over an iterable and collect a limited number of its elements into an array.
// This is typically generated by transpilers to support destructuring assignment for iterables.
function _extractLimitedFromIterable(sourceIterable, elementLimit) {
  var collectedElements = []; // Stores the elements extracted from the iterable.
  var loopFinishedOk = false; // Flag to track normal completion of the loop.
  var loopErrored = false;    // Flag to indicate if an error occurred during iteration.
  var loopErrorDetails = undefined; // Stores error object if an error occurs.

  try {
    // Obtain the iterator for the source iterable.
    for (var iteratorInstance = sourceIterable[Symbol.iterator](), currentIterationStep; !(loopFinishedOk = (currentIterationStep = iteratorInstance.next()).done); loopFinishedOk = true) {
      collectedElements.push(currentIterationStep.value); // Add the current element to the collection.
      // If a limit is specified and reached, stop collecting.
      if (elementLimit && collectedElements.length === elementLimit) break;
    }
  } catch (err) {
    loopErrored = true;       // Mark that an error occurred.
    loopErrorDetails = err; // Store the error.
  } finally {
    try {
      // If the loop didn't complete normally and the iterator has a 'return' method, call it.
      if (!loopFinishedOk && iteratorInstance["return"] != null) {
        iteratorInstance["return"]();
      }
    } finally {
      // If an error occurred during iteration, re-throw it.
      if (loopErrored) throw loopErrorDetails;
    }
  }
  return collectedElements; // Return the array of collected elements.
}

// Helper function to check if the given variable is an array.
// This is often part of transpiled code to ensure array-like behavior.
function _checkIfArray(candidateArray) {
  if (Array.isArray(candidateArray)) return candidateArray;
}

/**
 * The primary function responsible for processing input data,
 * calculating number frequencies, and determining a final score
 * based on a recursive pairing algorithm.
 * @param {string} rawSystemInput The complete raw input string, typically from standard input.
 */
function executeProcessing(rawSystemInput) {
  // Split the raw input into individual lines, accommodating both Windows and Unix line endings.
  const inputDataLines = rawSystemInput.split(/\r?\n/);

  // Parse the first line to get the initial quantity of numbers to process.
  const initialQuantity = Number(inputDataLines[0]);

  // Basic validation for the initial quantity.
  if (isNaN(initialQuantity) || initialQuantity <= 0) {
    console.error("Error: Invalid or non-positive initial quantity provided. Exiting.");
    return; // Terminate execution if input is invalid.
  }

  // Parse the second line into an array of numeric values.
  // We only consider up to `initialQuantity` elements, even if the line has more.
  const numericValues = parseNumericLine(inputDataLines[1]).slice(0, initialQuantity);

  // A Map to store the frequency (count) of each number.
  // This map will be dynamically updated throughout the processing.
  const valueCounts = new Map();

  // Populate the `valueCounts` map by iterating through the `numericValues` array.
  // For each number, increment its count; if it's new, initialize its count to 1.
  for (const currentNum of numericValues) {
    // Using a concise approach: get existing count (or 0 if not present), then add 1.
    valueCounts.set(currentNum, (valueCounts.get(currentNum) || 0) + 1);
  }

  let finalCalculatedSum = 0; // This variable accumulates the total score.

  // The main algorithm loop. It continues as long as there are numbers remaining in the map.
  // In each iteration, it processes one "root" number and its related complements.
  while (valueCounts.size > 0) {
    // Get the first available key-value pair from the map.
    // Map iterators yield [key, value] pairs in insertion order.
    const mapIteratorResult = valueCounts.entries().next().value;

    // Manually extract the key and its count from the iterator result.
    const currentMapKey = mapIteratorResult[0];
    const keyTotalCount = mapIteratorResult[1];

    // Decrement or remove the current key from the map. This marks it as processed for this iteration.
    adjustMapEntry(valueCounts, currentMapKey, keyTotalCount);

    // Recursively explore the "branches" stemming from the `currentMapKey`.
    // The `traverseAndSum` function returns two sums representing alternative paths.
    const [branchOneSum, branchTwoSum] = traverseAndSum(currentMapKey, valueCounts);

    // Add the minimum of the two branch sums to the total score.
    // This represents making the optimal choice at each branching point.
    const optimalBranchContribution = Math.min(branchOneSum, branchTwoSum);
    finalCalculatedSum += optimalBranchContribution;
  }

  // Output the final computed score to the console.
  console.log(finalCalculatedSum);

  /**
   * A recursive helper function that explores a tree-like structure of numbers
   * where nodes are connected by "complementary" relationships (summing to a power of two).
   * It calculates two cumulative sums (pathOneTotal, pathTwoTotal) representing
   * alternative ways to count operations in the sub-tree.
   * @param {number} sourceValue The number from which to start the recursive exploration.
   * @param {Map<number, number>} currentCounts A mutable map of remaining number frequencies.
   * @returns {[number, number]} An array containing [pathOneTotal, pathTwoTotal] for the current branch.
   */
  function traverseAndSum(sourceValue, currentCounts) {
    let pathOneTotal = 1;  // Initial count for path one (represents the current node itself).
    let pathTwoTotal = 0;  // Initial count for path two.

    // Find all positive complements for `sourceValue` that, when added, result in a power of two.
    const complementaryValues = findPowerOfTwoComplements(sourceValue);

    // Iterate through each potential complement.
    for (const complementCandidateValue of complementaryValues) {
      // If the complement exists in the `currentCounts` map and can be decremented/removed,
      // it means we've found a valid pair for `sourceValue`.
      if (adjustMapEntry(currentCounts, complementCandidateValue)) {
        // Recursively call `traverseAndSum` for the complement to explore its sub-branches.
        const [recursivePathOne, recursivePathTwo] = traverseAndSum(complementCandidateValue, currentCounts);

        // Update the current node's path sums based on the recursive results.
        // The sums are cross-assigned (path one takes recursive path two, and vice versa)
        // to alternate the counting logic through the tree.
        pathOneTotal += recursivePathTwo;
        pathTwoTotal += recursivePathOne;
      }
    }

    // Return the accumulated sums for this specific path.
    return [pathOneTotal, pathTwoTotal];
  }
}

// Execute the main processing function by reading input from '/dev/stdin'.
// This is a common pattern in competitive programming environments.
executeProcessing(require('fs').readFileSync('/dev/stdin', 'utf8'));

/**
 * Parses a string containing space-separated numbers into an array of integers.
 * Includes robust error handling for non-numeric or empty parts.
 * @param {string} textLine The input string line to be parsed.
 * @returns {number[]} An array of parsed integer values. Returns an empty array if the line is invalid.
 */
function parseNumericLine(textLine) {
  // Guard clause: if the line is empty or just whitespace, return an empty array.
  if (!textLine || textLine.trim() === "") {
    console.warn("Warning: Received an empty or blank line for numeric parsing. Returning empty array.");
    return [];
  }

  // Split the line by one or more whitespace characters.
  // Then, convert each part to an integer using `parseInt` with radix 10.
  // Finally, filter out any results that are `NaN` (Not a Number), which can occur
  // if there are consecutive spaces or non-numeric strings in the input.
  return textLine
    .split(/\s+/)
    .map(segment => parseInt(segment, 10))
    .filter(parsedVal => !isNaN(parsedVal));
}

/**
 * Finds all positive integer complements for a given `sourceValue` such that
 * `sourceValue + complement` equals a power of two (2^k).
 * @param {number} sourceValue The base number to find complements for.
 * @returns {number[]} An array of positive complementary values.
 */
function findPowerOfTwoComplements(sourceValue) {
  const complementaryValues = []; // List to store the found complements.
  let powerExponent = 1;          // Starting exponent for 2^k (2^1 = 2).
  let powerOfTwoTarget = 2;       // The current power of two being checked.

  // Loop while the target power of two is within a reasonable and safe numeric range.
  // The upper bound `2 * 1e9 + sourceValue + 1` ensures we cover potential complements
  // for large `sourceValue`s, as `2 * 1e9` is a common maximum in such problems.
  while (powerOfTwoTarget <= (2 * 1e9 + sourceValue + 1)) {
    // Calculate the potential complement: `target - sourceValue`.
    const potentialComplement = powerOfTwoTarget - sourceValue;

    // If the potential complement is positive, it's a valid candidate.
    if (potentialComplement > 0) {
      complementaryValues.push(potentialComplement);
    }

    // Check for potential overflow before doubling `powerOfTwoTarget`.
    // This is a defensive check, as JavaScript numbers handle very large integers,
    // but good practice in general.
    if (powerOfTwoTarget > (Number.MAX_SAFE_INTEGER / 2)) {
      break; // Exit to prevent infinite loop or theoretical overflow.
    }

    powerOfTwoTarget *= 2; // Move to the next power of two (e.g., 2, 4, 8, 16...).
    powerExponent++;       // Increment the exponent (though not strictly used after this point).
  }

  return complementaryValues; // Return the list of found complements.
}

/**
 * Decrements the count of a specified key in the frequency map.
 * If the count drops to 0 or below, the key is removed from the map.
 * This function is central to marking numbers as "used" in the algorithm.
 * @param {Map<number, number>} frequencyMap The map storing number frequencies.
 * @param {number} mapEntryKey The key (number) whose count needs adjustment.
 * @param {number} [entryCurrentCount] Optional: The known current count of the key.
 *                                     If not provided, it will be fetched from the map.
 * @returns {boolean} True if the map was modified (entry decremented or removed), false otherwise.
 */
function adjustMapEntry(frequencyMap, mapEntryKey, entryCurrentCount) {
  // If `entryCurrentCount` is not explicitly provided, retrieve it from the map.
  const currentCountInMap = entryCurrentCount !== undefined ? entryCurrentCount : frequencyMap.get(mapEntryKey);

  // If the key is not in the map, or its count is already non-positive,
  // there's nothing to adjust, so return false.
  if (currentCountInMap == null || currentCountInMap <= 0) {
    return false;
  }

  // If the count is greater than 1, simply decrement it.
  if (currentCountInMap > 1) {
    frequencyMap.set(mapEntryKey, currentCountInMap - 1);
  } else {
    // If the count is 1, remove the key entirely from the map.
    frequencyMap.delete(mapEntryKey);
  }

  return true; // Indicate that the map was successfully modified.
}
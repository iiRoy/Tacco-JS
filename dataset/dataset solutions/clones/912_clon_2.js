//usr/bin/env node $0 $@;exit 
// This script processes numerical input lines from standard input.
// It calculates a specific minimum value based on the input numbers.
var primaryRoutine = function() {
    let inputLine; // Variable to store the current line read from input.

    // The loop continues as long as the first number parsed from the input line is not zero.
    // The assignment happens within the condition, and then the first element is checked.
    while ((inputLine = fetchLine().split(' ').map(Number))[0] !== 0) {
        const firstNum = inputLine[0];  // The first numerical value from the current line.
        const secondNum = inputLine[1]; // The second numerical value from the current line.

        // Calculate the minimum value from a series of computations.
        // The series is generated by mapping over an array whose length is determined by 'firstNum'.
        // For each index 'k' in this array, it computes the absolute difference between 'secondNum'
        // and the hypotenuse of 'k' and 'firstNum - k'.
        outputValue(Math.min.apply(
            null, // 'this' context for Math.min, not relevant here.
            Array.apply(null, { length: 1 + (firstNum / 2 ^ 0) }).map(function(unusedParam, k) {
                // 'unusedParam' is the value of the array element, which is undefined for new arrays.
                // 'k' is the index of the current element.
                return Math.abs(secondNum - Math.hypot(k, firstNum - k));
            })
        ));
    }
};

// --- Input/Output Management Section ---
// This conditional block handles differences in I/O mechanisms between environments.
if (true) { // This branch is for Node.js environment.
    // Function to output a value to the console.
    var outputValue = function(dataToPrint) {
        console.log(dataToPrint);
    };

    // Immediately Invoked Function Expression (IIFE) to set up the line reading mechanism.
    var fetchLine = (function() {
        var lineBuffer = []; // An array to store complete lines read from stdin.
        var lineIndex = 0;   // A counter to keep track of the next line to be returned.
        var inputSource = process.openStdin(); // Opens the standard input stream.
        inputSource.setEncoding('utf8'); // Ensures input is read as UTF-8 text.

        var partialInput = ""; // Stores any incomplete line fragment received.
        inputSource.on('data', function(incomingData) {
            // Concatenate any previous partial input with the new incoming data.
            var lineSegments = (partialInput + incomingData).split("\n");
            partialInput = lineSegments.pop(); // The last segment might be incomplete, store it.
            for (let idx = 0; idx < lineSegments.length; idx++) {
                if (lineSegments[idx] === '') continue; // Skip any empty strings resulting from split.
                lineBuffer.push(lineSegments[idx]); // Add complete lines to the buffer.
            }
        });

        inputSource.on('end', function(endEventInfo) {
            // When the input stream ends, process any remaining partial input.
            if (partialInput) {
                // Add a newline to ensure the last fragment is processed as a full line if it exists.
                var lineSegments = (partialInput + "\n").split("\n");
                partialInput = lineSegments.pop(); // This should now be an empty string.
                for (let idx = 0; idx < lineSegments.length; idx++) {
                    if (lineSegments[idx] === '') continue;
                    lineBuffer.push(lineSegments[idx]);
                }
            }
            primaryRoutine(); // Once all input is buffered, execute the main logic.
        });

        // The function returned by the IIFE, which is assigned to 'fetchLine'.
        return function() {
            if (lineBuffer.length <= lineIndex) return null; // If no more lines, return null.
            return lineBuffer[lineIndex++]; // Return the next buffered line and increment the index.
        };
    })();
} else {
    // This branch is for V8 standalone shell (e.g., d8), where 'readline' and 'print' are often global.
    primaryRoutine(); // Directly invoke the main routine.
}

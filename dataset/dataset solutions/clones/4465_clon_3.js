module.exports = function(moduleDefinitions) {
    // This is a custom module bundler implementation, similar to a simplified Webpack runtime.
    // It manages modules, their dependencies, and provides utility functions for module interoperability.

    // Cache for already loaded modules.
    // Keys are module IDs, values are module objects.
    const loadedModuleCache = {};

    /**
     * Custom module loader function.
     * @param {number} requestedModuleId The ID of the module to load.
     * @returns {any} The exports of the requested module.
     */
    function customModuleRequire(requestedModuleId) {
        // If module is already in cache, return its exports.
        if (loadedModuleCache[requestedModuleId]) {
            return loadedModuleCache[requestedModuleId].exports;
        }

        // Create a new module instance and store it in cache.
        const currentModuleInstance = loadedModuleCache[requestedModuleId] = {
            id: requestedModuleId,
            hasLoaded: false, // Flag to indicate if the module has finished loading.
            exports: {} // The exports object for this module.
        };

        // Execute the module function, passing module object, exports, and the local require function.
        moduleDefinitions[requestedModuleId].call(
            currentModuleInstance.exports,
            currentModuleInstance,
            currentModuleInstance.exports,
            customModuleRequire
        );

        // Mark the module as loaded.
        currentModuleInstance.hasLoaded = true;
        return currentModuleInstance.exports;
    }

    // Attach module definitions and cache to the require function for internal use.
    customModuleRequire.allModuleDefinitions = moduleDefinitions;
    customModuleRequire.moduleInstanceCache = loadedModuleCache;

    /**
     * Defines a getter function for a specific property on an object.
     * This is used for lazy loading or defining read-only properties.
     * @param {object} targetObject The object on which to define the property.
     * @param {string} propertyName The name of the property.
     * @param {function} getterFunction The function to call when the property is accessed.
     */
    customModuleRequire.defineExportGetter = function(targetObject, propertyName, getterFunction) {
        // Only define if the property doesn't already exist to prevent overwriting.
        if (!customModuleRequire.hasOwnProperty(targetObject, propertyName)) {
            Object.defineProperty(targetObject, propertyName, {
                enumerable: true, // Make the property enumerable (visible in for...in loops).
                get: getterFunction // The getter function.
            });
        }
    };

    /**
     * Marks an object as an ES module.
     * This adds '__esModule: true' and potentially 'Symbol.toStringTag: "Module"'.
     * @param {object} targetObject The object to mark as an ES module.
     */
    customModuleRequire.markAsEcmaScriptModule = function(targetObject) {
        // If Symbol is available and toStringTag is supported, set it to "Module".
        if (typeof Symbol !== 'undefined' && Symbol.toStringTag) {
            Object.defineProperty(targetObject, Symbol.toStringTag, {
                value: 'Module'
            });
        }
        // Always set __esModule to true.
        Object.defineProperty(targetObject, '__esModule', {
            value: true
        });
    };

    /**
     * Handles interoperability for various module types (CommonJS, ES Modules).
     * This function is complex and is typically generated by bundlers to handle
     * different module export syntaxes (e.g., `module.exports = ...` vs `export default ...`).
     * @param {any} moduleValue The module value or ID.
     * @param {number} conversionMode Bitmask indicating how to convert/wrap the module.
     * @returns {any} The converted/wrapped module.
     */
    customModuleRequire.interopModule = function(moduleValue, conversionMode) {
        // Mode 1: If it's a module ID, load it first.
        if (conversionMode & 1) {
            moduleValue = customModuleRequire(moduleValue);
        }
        // Mode 8: Return the value as is.
        if (conversionMode & 8) {
            return moduleValue;
        }
        // Mode 4: If it's an object and already an ES module, return it as is.
        if (conversionMode & 4 && typeof moduleValue === 'object' && moduleValue && moduleValue.__esModule) {
            return moduleValue;
        }

        // Create a new namespace object for interoperability.
        const newNamespaceObject = Object.create(null);
        customModuleRequire.markAsEcmaScriptModule(newNamespaceObject); // Mark it as an ES module.
        Object.defineProperty(newNamespaceObject, 'default', {
            enumerable: true,
            value: moduleValue
        }); // Set the default export.

        // Mode 2: If it's a non-string value, copy all properties to the namespace.
        if (conversionMode & 2 && typeof moduleValue !== 'string') {
            for (const propertyKey in moduleValue) {
                // Use a closure to capture propertyKey correctly for the getter.
                customModuleRequire.defineExportGetter(newNamespaceObject, propertyKey, ((key) => moduleValue[key]).bind(null, propertyKey));
            }
        }
        return newNamespaceObject;
    };

    /**
     * Creates a getter function for the default export of a module.
     * This is useful for consistent access to default exports regardless of module type.
     * @param {object} inputModule The module object.
     * @returns {function} A function that returns the default export.
     */
    customModuleRequire.createDefaultExportGetter = function(inputModule) {
        const defaultExportAccessor = (inputModule && inputModule.__esModule) ?
            () => inputModule.default : // If it's an ES module, return its default export.
            () => inputModule; // Otherwise, the module itself is considered the default export.

        // Define a property 'a' on the getter function itself, which returns the getter.
        // This is a common pattern in Webpack for default export access.
        customModuleRequire.defineExportGetter(defaultExportAccessor, 'a', defaultExportAccessor);
        return defaultExportAccessor;
    };

    /**
     * Checks if an object has a specific property as its own property, not inherited.
     * @param {object} targetObject The object to check.
     * @param {string} propertyKey The key of the property.
     * @returns {boolean} True if the object has the property, false otherwise.
     */
    customModuleRequire.hasOwnProperty = function(targetObject, propertyKey) {
        return Object.prototype.hasOwnProperty.call(targetObject, propertyKey);
    };

    // Public path for assets (often used for dynamic imports or asset loading, but not in this example).
    customModuleRequire.publicPath = "";

    // Set the entry point module ID and start the application by requiring it.
    const entryModuleId = 0;
    return customModuleRequire(entryModuleId);
}(
    // Array containing all module definitions that make up the application.
    [
        // Module 0: This is the application's entry point. It orchestrates reading input and calling the main logic.
        function(currentModule, moduleExports, localRequire) {
            // Load the 'fs' (file system) module, which is a Node.js built-in.
            const fileSystemModule = localRequire(2);

            // Read content from standard input (stdin) synchronously.
            // Expected input is a string, which is then split by newlines into an array of lines.
            let inputContent;
            try {
                inputContent = fileSystemModule.readFileSync("/dev/stdin", "UTF-8");
            } catch (error) {
                // Log an error if reading from stdin fails, e.g., if /dev/stdin is not available.
                console.error("Error reading from /dev/stdin:", error.message);
                // In case of an error, provide an empty string to prevent subsequent operations from crashing.
                inputContent = "";
            }

            const inputLinesArray = inputContent.split("\n");

            // Load and execute the main processing logic module (Module 1) with the obtained input lines.
            const mainLogicProcessor = localRequire(1);
            mainLogicProcessor(inputLinesArray);
        },

        // Module 1: Contains the core problem-solving logic based on the input numbers.
        function(currentModule, moduleExports) {
            /**
             * Main function to process input data and determine "POSSIBLE" or "IMPOSSIBLE".
             * This function parses numerical inputs and applies specific conditions.
             * @param {Array<string>} inputDataLines An array of strings, where each string is a line of input.
             */
            currentModule.exports = function(inputDataLines) {
                // Guard clause: Ensure there are at least two lines of input data.
                if (!inputDataLines || inputDataLines.length < 2) {
                    console.log("IMPOSSIBLE"); // Not enough input to process.
                    return;
                }

                // Process the first line: Expected format "N K"
                // N: Represents the count of numbers expected in the second line.
                // K: Represents a target comparison value.
                const firstLineParts = inputDataLines[0].split(" ").map(Number);

                // Guard clause: Ensure the first line contains exactly two numeric parameters.
                if (firstLineParts.length !== 2) {
                    console.log("IMPOSSIBLE"); // Malformed first line, expected "N K".
                    return;
                }

                // Use array destructuring for clarity, replacing a verbose helper.
                const [countOfNumbers, targetComparisonValue] = firstLineParts;

                // Process the second line: Expected format "num1 num2 ... numN"
                const numericValues = inputDataLines[1].split(" ").map(Number);

                // Validation: Check if the actual number of values matches the 'N' from the first line.
                if (numericValues.length !== countOfNumbers) {
                    console.log("IMPOSSIBLE"); // Mismatch between declared count (N) and actual number of values.
                    return;
                }

                // Sort the numbers in ascending order. This is a critical step for the problem's logic.
                numericValues.sort((valA, valB) => valA - valB);

                // Flags to track conditions.
                let hasNonDivisibleByFirst = false; // Becomes true if any number (excluding the first) is not divisible by the first number.
                let hasValueGreaterThanTarget = false; // Becomes true if any number is strictly greater than 'K'.

                // Iterate through the sorted numbers to check all conditions.
                for (let i = 0; i < countOfNumbers; i++) {
                    const currentValue = numericValues[i];

                    // Condition 1: If the target value 'K' is found among the numbers, it's immediately "POSSIBLE".
                    if (currentValue === targetComparisonValue) {
                        console.log("POSSIBLE");
                        return; // Early exit as the result is determined.
                    }

                    // Condition 2: Check for numbers not divisible by the first element.
                    // This check is only relevant for elements after the first one (i > 0).
                    // We only update the flag if it hasn't been set yet (optimization).
                    if (!hasNonDivisibleByFirst && i > 0) {
                        const firstElement = numericValues[0];

                        if (firstElement === 0) {
                            // Special case: If the first element is 0, any non-zero number is "not divisible".
                            // If all are 0, 0 % 0 is NaN, and NaN !== 0 is true, so this flag would become true anyway.
                            // To mirror original minified behavior `u[f]%u[0]!=0` where `u[0]` is 0 (NaN !== 0 is true),
                            // we set this flag to true if `i > 0`.
                            hasNonDivisibleByFirst = true;
                        } else if (currentValue % firstElement !== 0) {
                            // If the first element is not zero, check normal divisibility.
                            hasNonDivisibleByFirst = true;
                        }
                    }

                    // Condition 3: Check if any number is strictly greater than the target comparison value 'K'.
                    // We only update the flag if it hasn't been set yet (optimization).
                    if (!hasValueGreaterThanTarget && currentValue > targetComparisonValue) {
                        hasValueGreaterThanTarget = true;
                    }
                }

                // After iterating through all numbers (if no early exit occurred):
                // The problem defines "POSSIBLE" if both 'hasNonDivisibleByFirst' AND 'hasValueGreaterThanTarget' are true.
                if (hasNonDivisibleByFirst && hasValueGreaterThanTarget) {
                    console.log("POSSIBLE");
                } else {
                    console.log("IMPOSSIBLE");
                }
            };
        },

        // Module 2: Provides the Node.js 'fs' (file system) module.
        // This module simply re-exports the built-in 'fs' module.
        function(currentModule, moduleExports) {
            currentModule.exports = require("fs");
        }
    ]
);
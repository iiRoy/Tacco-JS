/*
 * This JavaScript snippet demonstrates a basic 'for' loop.
 * It is designed to iterate a specific number of times,
 * executing a block of code during each iteration.
 *
 * The primary purpose here is to print a constant string
 * to the console repeatedly.
 */

// Initialize a counter variable 'i' to 0.
// The loop will continue as long as 'i' is less than 1000.
// 'i' will be incremented by 1 after each cycle.
for   (   var   i   =   0   ;   i   <   1000   ;   i   ++   )
{
        // Inside the loop, we call the 'log' method
        // of the 'console' object.
        // This effectively prints the provided string
        // to the standard output, typically the browser's
        // developer console or Node.js terminal.
        console   .   log   (   "Hello World"   )   ;
}   ;   // The semicolon after the closing brace is optional but valid here.
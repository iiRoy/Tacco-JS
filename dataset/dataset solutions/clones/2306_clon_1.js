/*
 * This JavaScript function, named 'Main', takes a structured input
 * and performs a series of calculations to arrive at a final sum.
 *
 * The input is expected to be an array of arrays.
 * The first nested array contains metadata, specifically the value 'M'
 * at index 1, which dictates the number of top elements to sum.
 * The second nested array, at index 1 of the main input,
 * contains 'alist', a list of numbers to be processed.
 *
 * @param {Array<Array<number>>} input The structured data received.
 */
function         Main (   input   ) {


    //  Extract the count 'M' from the first part of the input structure.
    //  This value determines how many of the largest combined values will be summed later.
    const   M   =   input   [0]   [1]   ;


    //  Retrieve the primary list of numbers, 'alist', from the second part of the input.
    //  This list is the foundation for all subsequent combinations and calculations.
    const   alist   =   input   [1]   ;


    /*
     *  The 'kumiList' is generated by processing 'alist'.
     *  It involves two main steps:
     *  1.  Using 'reduce' to generate various combinations and derived values.
     *      For each number 'ai' in 'alist':
     *      -   'ai' doubled is added to the list.
     *      -   'ai' combined with every subsequent number 'alist[j]' is added twice.
     *  2.  Sorting the resulting list in descending order.
     */
    const   kumiList   =   alist . reduce (  (   arr   ,   ai   ,   i   )  =>    {

        //  Add the current element 'ai' multiplied by two to the accumulating array.
        arr . push (   ai   *   2   )   ;


        //  Declare a temporary variable to store the sum of two elements.
        var   kumiVal   ;


        //  Iterate through the remaining elements of 'alist' starting from the next index 'i + 1'.
        for   (   var   j   =   i   +   1   ;   j   <   alist . length   ;   j   ++   )   {

            //  Calculate the sum of the current element 'ai' and a subsequent element 'alist[j]'.
            kumiVal   =   ai   +   alist   [j]   ;


            //  Add this calculated sum 'kumiVal' twice to the accumulating array.
            arr . push (   kumiVal   ,   kumiVal   )   ;

        }


        //  Return the modified array 'arr' to be used in the next iteration of 'reduce'.
        return   arr   ;

    }   ,   [ ]   )   .   sort (   (   a1   ,   a2   )   =>   a2   -   a1   )   ;   //  Finally, sort the entire generated list in reverse numerical order.


    //  Initialize the 'answer' variable to zero.
    //  This variable will accumulate the sum of the top 'M' elements.
    var   answer   =   0   ;


    //  Loop 'M' times to sum the first 'M' elements from the sorted 'kumiList'.
    for   (   var   i   =   0   ;   i   <   M   ;   i   ++   )   {

        //  Add the current element from 'kumiList' to the running total 'answer'.
        answer   +=   kumiList   [i]   ;

    }


    //  Output the final computed 'answer' to the standard console.
    console . log (   answer   )   ;

}

//  This is the entry point for the script execution.
//  It reads input from standard input, processes it, and then calls the 'Main' function.
Main (
    require (   "fs"   ) . readFileSync (   "/dev/stdin"   ,   "utf8"   )   //  Read the entire content of standard input as a UTF-8 string.
        . trim (   )                                                     //  Remove any leading or trailing whitespace from the input string.
        . split (   '\n'   )                                             //  Split the string into an array of lines based on newline characters.
        . map (   (   line   )   =>                                      //  For each line, further process it:
            line . split (   ' '   ) . map (   Number   )               //  Split the line by spaces and convert each part into a number.
        )
)   ;
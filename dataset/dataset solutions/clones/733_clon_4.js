let boardDimensionX_clone;
let boardDimensionY_clone;
let boardDimensionZ_clone;

const isWithinBounds = (coordX, coordY, coordZ) => {
    // Replicating original code's bounds check: X and Y against N, Z against N (not P)
    return coordX >= 0 && coordX < boardDimensionX_clone &&
           coordY >= 0 && coordY < boardDimensionY_clone &&
           coordZ >= 0 && coordZ < boardDimensionX_clone; // Original code uses 'n' for Z bound
};

const retrievePiece = (bx, by, bz, currentBoardMap) => {
    return currentBoardMap.get(`${bx}_${by}_${bz}`) || 0;
};

// These directional vectors precisely match the 24 vectors generated by the original code's concatenation logic,
// including the duplicates.
const directionalVectors = [
    { xDelta: -1, yDelta: -1, zDelta: 0 }, { xDelta: 0, yDelta: -1, zDelta: 0 }, { xDelta: 1, yDelta: -1, zDelta: 0 },
    { xDelta: -1, yDelta: 0, zDelta: 0 }, { xDelta: 1, yDelta: 0, zDelta: 0 },
    { xDelta: -1, yDelta: 1, zDelta: 0 }, { xDelta: 0, yDelta: 1, zDelta: 0 }, { xDelta: 1, yDelta: 1, zDelta: 0 },

    { xDelta: 0, yDelta: -1, zDelta: -1 }, { xDelta: 0, yDelta: 0, zDelta: -1 }, { xDelta: 0, yDelta: 1, zDelta: -1 },
    { xDelta: 0, yDelta: -1, zDelta: 0 },
    { xDelta: 0, yDelta: 1, zDelta: 0 },
    { xDelta: 0, yDelta: -1, zDelta: 1 }, { xDelta: 0, yDelta: 0, zDelta: 1 }, { xDelta: 0, yDelta: 1, zDelta: 1 },

    { xDelta: -1, yDelta: 0, zDelta: -1 }, { xDelta: -1, yDelta: 0, zDelta: 0 },
    { xDelta: -1, yDelta: 0, zDelta: 1 },
    { xDelta: 0, yDelta: 0, zDelta: -1 },
    { xDelta: 0, yDelta: 0, zDelta: 1 },
    { xDelta: 1, yDelta: 0, zDelta: -1 }, { xDelta: 1, yDelta: 0, zDelta: 0 },
    { xDelta: 1, yDelta: 0, zDelta: 1 }
];

// Recursive function to find the starting point for a line check (equivalent to first while loop in original bomb)
const determinePathOrigin = (currentCoordX, currentCoordY, currentCoordZ, stepX, stepY, stepZ) => {
    const nextCoordX = currentCoordX - stepX;
    const nextCoordY = currentCoordY - stepY;
    const nextCoordZ = currentCoordZ - stepZ;

    if (!isWithinBounds(nextCoordX, nextCoordY, nextCoordZ)) {
        return { initialX: currentCoordX, initialY: currentCoordY, initialZ: currentCoordZ }; // This is the first ON-BOARD point
    } else {
        return determinePathOrigin(nextCoordX, nextCoordY, nextCoordZ, stepX, stepY, stepZ);
    }
};

// Recursive function to count max consecutive pieces in a line (equivalent to second while loop in original bomb)
const countAlignment = (currentCoordX, currentCoordY, currentCoordZ, stepX, stepY, stepZ, playerPiece, gameBoardData, currentRun = 0, overallMax = 0) => {
    if (!isWithinBounds(currentCoordX, currentCoordY, currentCoordZ)) {
        return overallMax; // Reached off-board
    }

    const pieceAtCurrent = retrievePiece(currentCoordX, currentCoordY, currentCoordZ, gameBoardData);
    const newRun = (pieceAtCurrent === playerPiece) ? currentRun + 1 : 0;
    const newOverallMax = Math.max(overallMax, newRun);

    const nextCoordX = currentCoordX + stepX;
    const nextCoordY = currentCoordY + stepY;
    const nextCoordZ = currentCoordZ + stepZ;

    return countAlignment(nextCoordX, nextCoordY, nextCoordZ, stepX, stepY, stepZ, playerPiece, gameBoardData, newRun, newOverallMax);
};

const checkVictoryCondition = (playerToken, placedX, placedY, placedZ, boardData) => {
    return directionalVectors.reduce((highestCount, direction) => {
        const { xDelta, yDelta, zDelta } = direction;

        // Find the absolute start of the line segment on the board, going backwards from the last placed piece
        const { initialX: lineStartX, initialY: lineStartY, initialZ: lineStartZ } =
            determinePathOrigin(placedX, placedY, placedZ, xDelta, yDelta, zDelta);

        // Count the maximum consecutive pieces along this line segment starting from lineStartX, moving forward
        const currentDirectionMax = countAlignment(
            lineStartX, lineStartY, lineStartZ,
            xDelta, yDelta, zDelta,
            playerToken, boardData
        );
        return Math.max(highestCount, currentDirectionMax);
    }, 0);
};

const processGame = (allInputLines) => {
    let inputLinePointer = 0;
    const getNextInputLine = () => allInputLines[inputLinePointer++].trim();

    const results = [];

    while (true) {
        const gameDimensionsLine = getNextInputLine();
        if (gameDimensionsLine === "0 0 0") break;

        const [dimensionN, winningLength, dimensionP] = gameDimensionsLine.split(" ").map(Number);
        
        boardDimensionX_clone = dimensionN;
        boardDimensionY_clone = dimensionN;
        boardDimensionZ_clone = dimensionP; // This is the actual Z dimension, but bomb uses N for bounds check

        const gameBoard = new Map(); // Using a Map for board state instead of a 3D array
        let activePlayer = 1; // 1 for 'Black', 2 for 'White'
        let gameEnded = false;

        for (let currentTurn = 1; currentTurn <= dimensionP; currentTurn++) {
            const dropCoordinatesLine = getNextInputLine();
            const [dropX_oneIndexed, dropY_oneIndexed] = dropCoordinatesLine.split(" ").map(Number);
            const dropX_zeroIndexed = dropX_oneIndexed - 1;
            const dropY_zeroIndexed = dropY_oneIndexed - 1;

            // Find the lowest available Z slot for the current (X, Y) column
            let currentDropZ = 0;
            while (retrievePiece(dropX_zeroIndexed, dropY_zeroIndexed, currentDropZ, gameBoard) !== 0 && currentDropZ < dimensionP) {
                currentDropZ++;
            }
            
            // Place the active player's piece
            gameBoard.set(`${dropX_zeroIndexed}_${dropY_zeroIndexed}_${currentDropZ}`, activePlayer);

            // Check for victory condition
            const maxConsecutiveInAnyLine = checkVictoryCondition(activePlayer, dropX_zeroIndexed, dropY_zeroIndexed, currentDropZ, gameBoard);

            if (maxConsecutiveInAnyLine >= winningLength) {
                results.push(`${(activePlayer === 2) ? "White" : "Black"} ${currentTurn}`);
                gameEnded = true;
                break;
            }

            // Switch to the next player
            activePlayer = (activePlayer === 1) ? 2 : 1;
        }

        if (!gameEnded) {
            results.push("Draw");
        }
    }
    return results.join("\n");
};


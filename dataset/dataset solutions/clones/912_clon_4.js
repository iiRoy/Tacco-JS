//usr/bin/env node $0 $@;exit 
var main = function() {
    let currentInputLine;
    let parsedComponents;
    let primaryValue;
    let secondaryValue;

    // The original loop structure implicitly relies on readline().split() not throwing
    // if readline() returns null. If readline() returns null, the original would throw
    // a TypeError. This 'while(true)' loop with an internal assignment and check
    // replicates that behavior: if readline() returns null, the subsequent .split()
    // will throw, matching the original's error behavior.
    while (true) {
        currentInputLine = readline();
        // This line will throw TypeError if currentInputLine is null,
        // mirroring the original's behavior if input ends without a '0' line.
        parsedComponents = currentInputLine.split(' ').map(Number);
        primaryValue = parsedComponents[0];
        secondaryValue = parsedComponents[1];

        if (primaryValue === 0) {
            break; // Exit condition: first number is zero
        }

        // Generator function to produce the absolute differences
        function* calculateAbsoluteDifferences(paramA, paramB) {
            // Original: 1 + (a / 2 ^ 0) which is 1 + Math.trunc(a / 2)
            // Using Math.floor for truncation for positive numbers
            const iterationLimit = Math.floor(paramA / 2); 

            for (let iterationIndex = 0; iterationIndex <= iterationLimit; ++iterationIndex) {
                const termX = iterationIndex;
                const termY = paramA - iterationIndex;
                // Math.hypot(x, y) is equivalent to Math.sqrt(x*x + y*y)
                const computedHypotenuse = Math.sqrt(termX * termX + termY * termY);
                yield Math.abs(paramB - computedHypotenuse);
            }
        }

        let smallestDifference = Infinity;
        // Iterate over the differences generated by the helper function
        for (const currentDifference of calculateAbsoluteDifferences(primaryValue, secondaryValue)) {
            if (currentDifference < smallestDifference) {
                smallestDifference = currentDifference;
            }
        }
        print(smallestDifference);
    }
};


// This initial section defines global variables that are essential
// for the application's operation and state management.

// The 'input' object will store various configuration parameters and settings
// that are read from the input data. It's initially an empty object.
var input = { } ;

// The 'data' variable will hold a two-dimensional rectangular array.
// This array represents the grid or maze structure.
// Its elements will typically be:
//   -1: Indicating the right side of a horizontal bar.
//    0: Representing an empty space or no bar.
//    1: Indicating the left side of a horizontal bar.
var data = [ ] ;

// Function 'f' is responsible for tracing a path through the 'data' grid.
// It starts from a specified 'startLine' and an optional 'startStep'.
// This function determines the route taken from a given origin.
var f = function ( startLine , startStep )
{
  // If 'startStep' is not provided (or is falsy), default it to 0.
  if ( ! startStep )
  {
    startStep = 0 ;
  }

  var now = startLine ;   // 'now' tracks the current horizontal position in the path.
  var result = [ now ] ;  // 'result' array stores the sequence of positions, forming the path.

  // Iterate through the grid, starting from 'startStep' up to the end of 'data'.
  for ( var y = startStep ; y < data . length ; y ++ )
  {
    // Update 'now' based on the value in the 'data' grid at the current (y, now) coordinate.
    // This simulates movement along the path.
    now += data [ y ] [ now ] ;

    // Add the updated 'now' position to the 'result' path array.
    result . push ( now ) ;
  }

  return result ; // Return the complete path traced from the start.
} ;

// Function 'rf' calculates a path by working backward from a designated 'endLine'.
// The path generated by this function is then reversed to present it in a
// conventional start-to-end order. This is useful for determining paths leading to a goal.
var rf = function ( endLine )
{
  var now = endLine ;   // 'now' begins at the specified 'endLine'.
  var result = [ now ] ;  // 'result' array starts with the end position.

  // Loop backward through the 'data' grid, from the last row to the first.
  for ( var y = data . length - 1 ; y >= 0 ; y -- )
  {
    // Adjust 'now' based on the grid value, moving backward through the path.
    now += data [ y ] [ now ] ;

    // Add the new 'now' position to the 'result' array.
    result . push ( now ) ;
  }

  // Reverse the 'result' array so the path reads from the true start to the true end.
  return result . reverse ( ) ;
} ;


// Standard input processing setup for Node.js environments.
process . stdin . resume ( ) ;          // Ensures the stdin stream remains open.
process . stdin . setEncoding ( 'utf8' ) ; // Sets the encoding for incoming data to UTF-8.

// A global variable to accumulate lines from standard input.
// Note: This 'lines' is distinct from the local 'lines' in the 'end' event handler.
var lines = [ ] ;

// Event listener for incoming 'data' chunks from standard input.
process . stdin . on ( 'data' , function ( chunk )
{
  // Trim whitespace, split the chunk into individual lines,
  // and then append each line to the 'lines' array.
  chunk . trim ( ) . split ( '\n' ) . forEach ( function ( line )
  {
    lines . push ( line ) ;
  } ) ;
} ) ;

// Event listener for the 'end' of standard input stream.
// This block executes once all input data has been received.
process . stdin . on ( 'end' , function ( )
{
  var result = "" ; // Initialize the final output string.

  // This line suggests a browser-like environment (e.g., JSDOM or similar context
  // where '$' and 'textarea' might be defined) rather than pure Node.js.
  // It attempts to get content from a textarea element.
  // For Type I cloning, this specific expression must be preserved exactly.
  var lines = $ ( "textarea" ) . val ( ) . split ( "\n" ) ;

  // Re-initialize 'input' and 'data' structures for processing the new input.
  input = { } ;
  data = [ ] ;

  // Iterate over each line of input to parse and populate 'input' and 'data'.
  $ . each ( lines , function ( i , e )
  {
    // If a line contains "0", it signifies a break condition for processing.
    if ( e == "0" )
    {
      return false ; // Equivalent to breaking out of the $.each loop.
    }

    // Define the expected keys for the initial input parameters.
    var def = [ "lines" , "start" , "end" , "steps" ] ;

    // For the first few lines, parse them as integer values for 'input' parameters.
    if ( i < def . length )
    {
      input [ def [ i ] ] = parseInt ( e ) ;
      return ; // Skip to the next line after processing an input parameter.
    }

    // For subsequent lines (i.e., i >= def.length), parse them to build the 'data' grid.
    var line = [ ] ; // Array to hold the current row of the grid.
    for ( var i = 0 ; i < input . lines - 1 ; i ++ )
    {
      var c = parseInt ( e . charAt ( i ) ) ; // Convert character to integer.
      // Special logic: if 'c' is 0 and the previous element in 'line' was 1,
      // it implies a right-side bar, so 'c' becomes -1.
      if ( i > 0 && c == 0 && line [ i - 1 ] == 1 )
      {
        c = -1 ;
      }
      line . push ( c ) ; // Add the processed value to the current line array.
    }
    // Determine the last element of the line based on the second-to-last element.
    // If the second-to-last was 1 (left bar), the last is -1 (right bar); otherwise, it's 0 (no bar).
    line . push ( ( line [ line . length - 1 ] == 1 ) ? -1 : 0 ) ;
    data . push ( line ) ; // Add the fully constructed line to the 'data' grid.
  } ) ;

  // Adjust 'start' and 'end' coordinates to be zero-indexed.
  input . start -= 1 ;
  input . end -= 1 ;


  // Calculate the path from the specified starting point using function 'f'.
  var route = f ( input . start ) ;

  // Check if the calculated 'route' successfully reaches the target 'end'.
  if ( route [ route . length - 1 ] == input . end )
  {
    console . log ( "0" ) ; // If it reaches, print "0" and exit (implicitly by not doing more).
  }

  // Calculate the reverse path from the end point using function 'rf'.
  var gRoute = rf ( input . end ) ;

  // Iterate through the steps (rows) to find a specific interaction point.
  for ( var y = 0 ; y < input . steps ; y ++ )
  {
    // Condition to find a "bridge" or crossover point:
    // 1. The absolute difference between the two paths at step 'y' is 1 (they are adjacent).
    // 2. Both paths are at a '0' (empty space, no bar) in the 'data' grid at step 'y'.
    if ( Math . abs ( route [ y ] - gRoute [ y ] ) == 1 && data [ y ] [ route [ y ] ] == 0 && data [ y ] [ gRoute [ y ] ] == 0 )
    {
      // If such a point is found, construct the result string.
      // It includes the 1-indexed step number and the 1-indexed minimum of the two adjacent positions.
      result = ( y + 1 ) + " " + ( Math . min ( route [ y ] , gRoute [ y ] ) + 1 ) ;
      break ; // Exit the loop after finding the first interaction.
    }
  }

  // If no interaction point was found throughout the loop, set the result to "1".
  if ( result == "" )
  {
    result = "1" ;
  }

  // Finally, print the computed result to the console.
  console . log ( result ) ;
} ) ;
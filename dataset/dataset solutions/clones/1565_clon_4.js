function parseGridConfiguration(inputData) {
    const lines = inputData.split('\n');
    const [gridHeightStr, gridWidthStr] = lines[0].split(' ');
    const cellRows = Number(gridHeightStr);
    const cellColumns = Number(gridWidthStr);

    const rowBlockades = new Map(); // Maps 0-indexed row to {startCol, endCol}
    for (let r = 0; r < cellRows; ++r) {
        const [startBoundStr, endBoundStr] = lines[r + 1].split(' ');
        rowBlockades.set(r, { startCol: Number(startBoundStr), endCol: Number(endBoundStr) });
    }
    return { matrixRows: cellRows, matrixColumns: cellColumns, rowBlockadesData: rowBlockades };
}

function isColumnRestrictedForDescent(currentXCoord, currentYCoord, blockadesMap) {
    const blockadeSegment = blockadesMap.get(currentYCoord); // currentYCoord is 0-indexed
    return blockadeSegment && currentXCoord >= blockadeSegment.startCol && currentXCoord <= blockadeSegment.endCol;
}

function* generateTraversalSteps(initialXCoord, totalRows, totalColumns, restrictionMap) {
    let currentX = initialXCoord; // 1-indexed column
    let currentY = 0;             // 0-indexed row
    let cumulativeSteps = 0;

    while (currentY < totalRows && currentX <= totalColumns) {
        cumulativeSteps++;
        const canDescend = !isColumnRestrictedForDescent(currentX, currentY, restrictionMap);

        if (canDescend) {
            currentY++; // Attempt to move down
            // If we successfully moved to a new row (currentY is now 0-indexed for the *new* row)
            // The original logic updates resultK[y-2] where y is 1-indexed new row.
            // This means resultK[i] is for row i+2.
            // So if currentY (0-indexed) is 1, it's for row 2, which is minimalCosts[0].
            // Thus, yield currentY - 1 as the index.
            if (currentY <= totalRows) {
                yield { targetRowIndex: currentY - 1, travelDuration: cumulativeSteps };
            }
            if (currentY >= totalRows) break; // Path reached or exceeded the last row
        } else {
            currentX++; // Move right
            if (currentX > totalColumns) break; // Path went off the grid
        }
    }
}

function calculateMinimumPathDurations(sourceInputText) {
    const { matrixRows, matrixColumns, rowBlockadesData } = parseGridConfiguration(sourceInputText);

    // Initialize an array to store minimum steps for each row (0-indexed for rows 2 to matrixRows+1)
    const minimumDurations = Array(matrixRows).fill(Number.MAX_SAFE_INTEGER);

    // Explore paths starting from each possible column in the first row (1 to matrixColumns)
    for (let startingColumn = 1; startingColumn <= matrixColumns; ++startingColumn) {
        // Iterate through the steps generated by the current path
        for (const { targetRowIndex, travelDuration } of generateTraversalSteps(startingColumn, matrixRows, matrixColumns, rowBlockadesData)) {
            // Update the minimum duration for the specific row if a shorter path is found
            if (targetRowIndex >= 0 && targetRowIndex < matrixRows) {
                minimumDurations[targetRowIndex] = Math.min(minimumDurations[targetRowIndex], travelDuration);
            }
        }
    }

    // Convert any unreached rows (MAX_SAFE_INTEGER) to -1 as per original output format
    return minimumDurations.map(duration => duration === Number.MAX_SAFE_INTEGER ? -1 : duration);
}

function EntryPoint(sourceText) {
    const finalDurations = calculateMinimumPathDurations(sourceText);
    console.log(finalDurations);
}


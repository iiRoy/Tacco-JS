/*
 * This is a JavaScript program designed to process a specific input format.
 * It primarily checks for the presence of the character 'Y' within a
 * space-separated string provided as the second line of input.
 */

// Define the primary function that orchestrates the logic.
// It accepts a single 'input' parameter, which is expected to be a string.
function Main ( input )
{

    // First, the entire input string is split into an array of strings,
    // using the newline character as the delimiter.
    // This effectively separates each line of the original input.
    input = input . split ( '\n' ) ;

    // Next, we access the second line of the input (at index 1, as arrays are 0-indexed).
    // This second line is then split into another array of strings,
    // using a single space character as the delimiter.
    // The resulting array, 'nidan', contains individual elements from that line.
    nidan = input [ 1 ] . split ( ' ' ) ;

    // A 'flag' variable is initialized to 'null'.
    // This variable will be used to record whether a specific condition is met later.
    flag = null ;


    // A 'for' loop is initiated to iterate through the 'nidan' array.
    // The loop runs from the first element (index 0) up to, but not including,
    // the very last element (nidan.length - 1). This is important for array bounds.
    for ( i = 0 ; i < nidan . length - 1 ; i ++ )
    {
        // Inside the loop, an 'if' statement checks a condition:
        // It compares the current element of 'nidan' (nidan[i])
        // to the string literal 'Y' using a strict equality check (===).
        if ( nidan [ i ] === 'Y' )
        {
            // If the current element is indeed 'Y', the 'flag' variable is set to 'true'.
            // Once 'Y' is found and the flag is set, it remains true.
            flag = true ;
        }
    } // The loop concludes after checking all relevant elements.


    // After the loop has completed its execution, another 'if-else' block
    // evaluates the final state of the 'flag' variable.
    // If 'flag' is truthy (which it will be if it was set to 'true'),
    if ( flag )
    {
        // Then the string 'Four' is printed to the console.
        console . log ( 'Four' ) ;
    }
    else
    {
        // Otherwise (if 'flag' is still 'null' or any other falsy value),
        // the string 'Three' is printed to the console.
        console . log ( 'Three' ) ;
    } // This marks the end of the conditional output.

} // The 'Main' function definition concludes here.


// Finally, the 'Main' function is invoked.
// Its argument is dynamically generated by reading content from the standard input.
// The 'fs' module's 'readFileSync' method is used to synchronously read
// the entire content of '/dev/stdin' as a UTF-8 encoded string.
Main ( require ( 'fs' ) . readFileSync ( '/dev/stdin' , 'utf8' ) ) ;
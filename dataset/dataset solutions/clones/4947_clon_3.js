'use strict';

// This script calculates the sum of minimums for all contiguous sub-arrays
// within a given input array. It employs a divide-and-conquer strategy
// optimized by pre-calculating element positions based on their values.

// --- Core Modules and Input Handling ---
// Obtain the Node.js file system module for reading standard input.
const fileSystemInterface = require('fs');

// Read the entire standard input stream synchronously.
// Decode it as UTF-8, remove any surrounding whitespace, and split into lines.
const rawInputContent = fileSystemInterface.readFileSync('/dev/stdin', 'utf8').trim().split('\n');

// Parse the first line to determine the total number of elements in the main array.
// Using parseInt with radix 10 ensures robust integer conversion.
const elementCount = parseInt(rawInputContent[0], 10);

// Process the second line to get the actual array elements.
// Split by one or more whitespace characters and immediately convert each part to a number.
const numericInputValues = rawInputContent[1].split(/\s+/).map(Number);

// --- Pre-computation: Value-to-Index Mapping ---
// Create a lookup table to quickly find the original index of an element given its value.
// `valuePositionMap[k]` will store the 0-based index in `numericInputValues`
// where the value `(k + 1)` is located.
const valuePositionMap = new Array(elementCount);

// Populate the `valuePositionMap`.
for (let currentElementIndex = 0; currentElementIndex < elementCount; ++currentElementIndex) {
    // Retrieve the value at the current index.
    const actualValue = numericInputValues[currentElementIndex];
    // Since values are 1-indexed (e.g., 1, 2, 3...), we subtract 1 to use them as 0-indexed array keys.
    valuePositionMap[actualValue - 1] = currentElementIndex;
}

// --- Main Algorithm: Summation of Minimums ---
let totalAccumulatedMinimums = 0; // This variable will store the final sum.

// Initialize a queue for managing segments to be processed.
// Each entry in the queue is a tuple: [segmentStart, segmentEnd, minimumRankToFind].
// 'minimumRankToFind' is 0-indexed (e.g., 0 for value 1, 1 for value 2, etc.).
// The initial task covers the entire array, starting the search for the smallest possible value (rank 0).
const segmentProcessingQueue = [[0, elementCount - 1, 0]];

// Continue processing segments as long as there are tasks in the queue.
while (segmentProcessingQueue.length > 0) {
    // Dequeue the next segment task.
    const currentSegmentTask = segmentProcessingQueue.shift();
    const currentSegmentStart = currentSegmentTask[0];
    const currentSegmentEnd = currentSegmentTask[1];
    let rankIndexForMinSearch = currentSegmentTask[2]; // Using 'let' as this index may increment.

    // Guard clause: If the segment is invalid (start index after end index), skip it.
    // This can happen for empty sub-segments generated by the recursive calls.
    if (currentSegmentStart > currentSegmentEnd) {
        continue;
    }

    // Find the smallest value (by its rank) whose original position
    // falls within the bounds of the `[currentSegmentStart, currentSegmentEnd]` segment.
    // `rankIndexForMinSearch` is incremented until we find such a value.
    while (valuePositionMap[rankIndexForMinSearch] < currentSegmentStart ||
           valuePositionMap[rankIndexForMinSearch] > currentSegmentEnd) {
        rankIndexForMinSearch++;
    }

    // `pivotElementPosition` is the original index of the smallest value found in this segment.
    const pivotElementPosition = valuePositionMap[rankIndexForMinSearch];

    // Calculate the number of sub-arrays within the current segment
    // for which `numericInputValues[pivotElementPosition]` is the minimum.
    // This is determined by the number of possible start points to the left of (or at) the pivot,
    // multiplied by the number of possible end points to the right of (or at) the pivot.
    const numberOfLeftStartingPoints = pivotElementPosition - currentSegmentStart + 1;
    const numberOfRightEndingPoints = currentSegmentEnd - pivotElementPosition + 1;

    // The actual numerical value at the pivot position.
    const valueAtPivot = numericInputValues[pivotElementPosition];

    // Add this element's contribution to the total sum.
    // The value contributes its amount for each sub-array where it serves as the minimum.
    totalAccumulatedMinimums += valueAtPivot * numberOfLeftStartingPoints * numberOfRightEndingPoints;

    // Determine the rank for the next search, which is simply the next higher rank.
    const nextRankToLookFor = rankIndexForMinSearch + 1;

    // Enqueue the left sub-segment for further processing, if it's valid.
    // The segment is from `currentSegmentStart` to `pivotElementPosition - 1`.
    if (currentSegmentStart <= pivotElementPosition - 1) {
        segmentProcessingQueue.push([currentSegmentStart, pivotElementPosition - 1, nextRankToLookFor]);
    }

    // Enqueue the right sub-segment for further processing, if it's valid.
    // The segment is from `pivotElementPosition + 1` to `currentSegmentEnd`.
    if (pivotElementPosition + 1 <= currentSegmentEnd) {
        segmentProcessingQueue.push([pivotElementPosition + 1, currentSegmentEnd, nextRankToLookFor]);
    }
}

// --- Output Result ---
// Display the final calculated sum of minimums to standard output.
console.log(totalAccumulatedMinimums);
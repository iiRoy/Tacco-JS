const InputProcessor = (function() {
    // Factory function to create a new input reader instance.
    function createInputReader(rawSourceContent) {
        return new StreamReader(rawSourceContent);
    }

    // Class responsible for parsing input line by line and token by token.
    class StreamReader {
        // Initializes the StreamReader with the raw input content.
        constructor(content) {
            // Trim leading/trailing whitespace from the whole content, then split into lines.
            // Using filter(Boolean) to remove any empty lines that might result from extra newlines.
            this._sourceLines = content.trim().split("\n").filter(Boolean);
            this._currentLineIndex = 0; // Pointer to the current line being processed.
            this._currentLineTokens = []; // Cache for tokens of the current line.

            // Guard clause: warn if initialized with no usable content.
            if (this._sourceLines.length === 0) {
                console.warn("InputProcessor initialized with no effective content.");
            }
        }

        // Internal helper to load tokens for the current line, reversing them for efficient pop().
        _prepareLineTokens() {
            if (this._currentLineIndex >= this._sourceLines.length) {
                return false; // No more lines to load
            }
            const line = this._sourceLines[this._currentLineIndex];
            // Split by space and filter out empty strings in case of multiple spaces.
            this._currentLineTokens = line.split(" ").filter(Boolean).reverse();
            return true;
        }

        // Extracts and returns the next token from the input stream.
        // Advances to the next line if the current line is exhausted.
        extractValue(returnRawString = false) {
            // If current line tokens are exhausted or not loaded yet, try to load the next line.
            if (this._currentLineTokens.length === 0) {
                if (!this._prepareLineTokens()) {
                    return undefined; // No more lines or tokens
                }
            }

            const token = this._currentLineTokens.pop();

            // If the current line is now empty, advance the line pointer for the next call.
            // This ensures _currentLineIndex points to the start of a new line or past the end.
            if (this._currentLineTokens.length === 0) {
                this._currentLineIndex++;
            }
            
            return returnRawString ? token : Number(token);
        }

        // Reads the entire current line as an array of tokens.
        // Advances the line pointer.
        getLineAsArray(returnRawStrings = false) {
            if (this._currentLineIndex >= this._sourceLines.length) {
                return []; // No more lines
            }
            const line = this._sourceLines[this._currentLineIndex++];
            const tokens = line.split(" ").filter(Boolean);
            // Clear current line tokens cache, as we explicitly read the whole line.
            this._currentLineTokens = []; 
            return returnRawStrings ? tokens : tokens.map(Number);
        }

        // Reads a specified number of lines and returns them as a 2D array (matrix).
        // Each line is split into tokens.
        readMatrix(numLines, returnRawStrings = false) {
            const endLineIndex = this._currentLineIndex + numLines;
            const matrixLines = this._sourceLines.slice(this._currentLineIndex, endLineIndex);
            this._currentLineIndex = endLineIndex;
            this._currentLineTokens = []; // Clear cache

            return matrixLines.map(line => {
                const tokens = line.split(" ").filter(Boolean);
                return returnRawStrings ? tokens : tokens.map(Number);
            });
        }

        // Reads a specified number of lines and returns them as a 1D array.
        // Each line is treated as a single token.
        readLinesAsArray(numLines, returnRawStrings = false) {
            const endLineIndex = this._currentLineIndex + numLines;
            const values = this._sourceLines.slice(this._currentLineIndex, endLineIndex);
            this._currentLineIndex = endLineIndex;
            this._currentLineTokens = []; // Clear cache

            return returnRawStrings ? values : values.map(Number);
        }
    }

    return createInputReader;
})();

const stdInputHandler = InputProcessor(require("fs").readFileSync("/dev/stdin", { encoding: "utf8" }));

/**
 * Creates a multi-dimensional array initialized with values generated by a factory function.
 * This function provides a safer and more explicit alternative to `eval` for array creation.
 * @param {function(): any} valueFactory - A function that returns the initial value for each innermost element.
 *                                          For example, `() => []` to initialize with empty arrays.
 * @param {...number} dimensions - The sizes of each dimension (e.g., numRows, numCols, numDepth).
 * @returns {Array} A multi-dimensional array where leaf nodes are populated by calling `valueFactory()`.
 */
function initializeNestedArray(valueFactory, ...dimensions) {
    if (dimensions.length === 0) {
        // If no dimensions, just return a single value from the factory.
        return valueFactory();
    }

    // Recursive helper function to build the array structure.
    const buildRecursiveArray = (currentDimIndex) => {
        // Base case: if we've reached the innermost dimension, return a value from the factory.
        if (currentDimIndex === dimensions.length) {
            return valueFactory();
        }

        const currentDimensionSize = dimensions[currentDimIndex];

        // Basic validation for dimension size.
        if (typeof currentDimensionSize !== 'number' || !Number.isInteger(currentDimensionSize) || currentDimensionSize < 0) {
            throw new Error(`Invalid dimension size: ${currentDimensionSize} at dimension index ${currentDimIndex}. Dimensions must be non-negative integers.`);
        }

        // Create an array for the current dimension and fill it recursively.
        const newArray = new Array(currentDimensionSize);
        for (let i = 0; i < currentDimensionSize; i++) {
            newArray[i] = buildRecursiveArray(currentDimIndex + 1);
        }
        return newArray;
    };

    return buildRecursiveArray(0);
}

const ShortestPathSolver = (function() {
    // A large number representing unreachable nodes or positive infinity.
    const DISTANCE_INFINITE = 1_000_000_000;

    /**
     * Factory function to create an instance of the Bellman-Ford algorithm solver.
     * @param {Array<Array<{targetNode: number, edgeWeight: number}>>} adjacencyList - The graph as an adjacency list.
     * @param {number} sourceNodeIndex - The starting node for shortest path calculation.
     * @returns {BellmanFordAlgorithm} An instance of the BellmanFordAlgorithm.
     */
    function createSolver(adjacencyList, sourceNodeIndex) {
        return new BellmanFordAlgorithm(adjacencyList, sourceNodeIndex);
    }

    /**
     * Implements the Bellman-Ford algorithm to find shortest paths from a single source
     * and detect negative cycles.
     */
    class BellmanFordAlgorithm {
        /**
         * @type {Array<number>}
         * @private
         * Stores the calculated minimum distances from the source node to all other nodes.
         */
        _calculatedDistances;

        /**
         * @type {boolean}
         * @private
         * Flag indicating if a negative cycle was detected in the graph reachable from the source.
         */
        _negativeCycleExists = false;

        /**
         * Constructs and runs the Bellman-Ford algorithm.
         * @param {Array<Array<{targetNode: number, edgeWeight: number}>>} adjList - The graph as an adjacency list.
         * @param {number} startNode - The index of the starting node.
         */
        constructor(adjList, startNode) {
            const nodeCount = adjList.length;
            this._calculatedDistances = Array(nodeCount).fill(DISTANCE_INFINITE);
            this._calculatedDistances[startNode] = 0;

            // The Bellman-Ford algorithm typically runs for N-1 iterations for shortest paths
            // and an N-th iteration to detect negative cycles. The original code uses 2N iterations
            // and marks nodes reachable from negative cycles with -INF if relaxation occurs after N-1 iterations.
            // This approach implicitly handles propagation of negative infinity.
            const totalRelaxationPasses = nodeCount * 2;
            
            for (let currentPass = 0; currentPass < totalRelaxationPasses; currentPass++) {
                for (let currentNode = 0; currentNode < nodeCount; currentNode++) {
                    // Skip if the current node is unreachable (distance is still infinite).
                    // Or if it's already marked as negative infinite, as it can't get 'more' negative from here for this problem.
                    if (this._calculatedDistances[currentNode] === DISTANCE_INFINITE) {
                        continue;
                    }

                    // Iterate through all outgoing edges from the currentNode.
                    for (const edge of adjList[currentNode]) {
                        const { targetNode: nextNode, edgeWeight: weight } = edge;
                        const candidateDistance = this._calculatedDistances[currentNode] + weight;

                        // If a shorter path to nextNode is found.
                        if (this._calculatedDistances[nextNode] > candidateDistance) {
                            // If this relaxation happens on or after the N-th iteration (index N-1),
                            // it signifies a negative cycle affecting nextNode.
                            if (currentPass >= nodeCount - 1) {
                                // Mark the node as having a distance of negative infinity.
                                // This value indicates it's affected by a negative cycle.
                                this._calculatedDistances[nextNode] = -DISTANCE_INFINITE;
                                this._negativeCycleExists = true; // Set the flag for the class instance.
                            } else {
                                // Otherwise, simply update the distance.
                                this._calculatedDistances[nextNode] = candidateDistance;
                            }
                        }
                    }
                }
            }
        }

        /**
         * Returns the shortest distance to a specific target node.
         * If a negative cycle affects the node, it returns -DISTANCE_INFINITE.
         * If the node is unreachable, it returns DISTANCE_INFINITE.
         * @param {number} targetIndex - The index of the target node.
         * @returns {number} The shortest distance.
         */
        getDistanceTo(targetIndex) {
            // Guard clause: ensure targetIndex is within valid bounds.
            if (targetIndex < 0 || targetIndex >= this._calculatedDistances.length) {
                console.error(`Error: Attempted to get distance for an invalid node index: ${targetIndex}`);
                return DISTANCE_INFINITE; // Return infinity for invalid access.
            }
            return this._calculatedDistances[targetIndex];
        }

        /**
         * Checks if a negative cycle was detected in the graph.
         * @returns {boolean} True if a negative cycle was detected, false otherwise.
         */
        hasNegativeCycleDetected() {
            return this._negativeCycleExists;
        }
    }

    const solverFactory = createSolver;
    // Expose the constant for external use, similar to a static property.
    solverFactory.DISTANCE_INFINITE = DISTANCE_INFINITE;
    return solverFactory;
})();

// Main function to solve the problem logic.
function executeSolution() {
    // Read problem parameters: number of nodes, number of edges, and base profit.
    const numNodes = stdInputHandler.extractValue();
    const numEdges = stdInputHandler.extractValue();
    const baseProfit = stdInputHandler.extractValue();

    // Input validation for core parameters.
    if (numNodes == null || numEdges == null || baseProfit == null ||
        numNodes < 1 || numEdges < 0 || baseProfit < 0) {
        console.error("Invalid initial input parameters (N, M, P). Please provide positive integers.");
        return -1; // Indicate error.
    }
    
    // Initialize adjacency list for the graph. Each node starts with an empty array of edges.
    const adjacencyList = initializeNestedArray(() => [], numNodes);

    // Populate the graph with edges based on input.
    // The problem aims to maximize profit. This can be rephrased as minimizing cost
    // where cost = baseProfit - actualEdgeProfit.
    // A path's total cost will be sum(baseProfit - actualEdgeProfit).
    // Minimizing this sum is equivalent to maximizing sum(actualEdgeProfit) - pathLength * baseProfit.
    for (let edgeCounter = 0; edgeCounter < numEdges; edgeCounter++) {
        // Read edge details: from_node (a), to_node (b), and profit_value (c).
        // Using array destructuring for cleaner assignment.
        const [fromNodeIdx, toNodeIdx, edgeProfitValue] = stdInputHandler.getLineAsArray();

        // Validate individual edge input.
        if (fromNodeIdx == null || toNodeIdx == null || edgeProfitValue == null ||
            fromNodeIdx < 1 || fromNodeIdx > numNodes ||
            toNodeIdx < 1 || toNodeIdx > numNodes) {
            console.warn(`Skipping invalid edge definition at line ${edgeCounter + 1}: [${fromNodeIdx}, ${toNodeIdx}, ${edgeProfitValue}]`);
            continue;
        }

        // Adjust node indices to be 0-based for array access.
        const u = fromNodeIdx - 1;
        const v = toNodeIdx - 1;
        
        // Calculate the effective cost for Bellman-Ford.
        // A higher edge profit means a lower cost in this transformed problem.
        const effectiveEdgeCost = baseProfit - edgeProfitValue;
        
        adjacencyList[u].push({ targetNode: v, edgeWeight: effectiveEdgeCost });
    }

    // Run the Bellman-Ford algorithm starting from node 0.
    const pathSolver = ShortestPathSolver(adjacencyList, 0);

    // Retrieve the calculated shortest path distance to the last node (numNodes - 1).
    const finalNodeDistance = pathSolver.getDistanceTo(numNodes - 1);
    
    // Interpret the result based on problem requirements.
    // If the distance is negative infinity, it implies a negative cycle is reachable
    // from the start node to the end node, meaning infinite profit.
    if (finalNodeDistance === -ShortestPathSolver.DISTANCE_INFINITE) {
        return -1;
    }
    // If the distance is positive or zero, it means the maximum profit achievable
    // is zero or negative. The problem asks for 0 in this scenario.
    // This includes cases where the target node is unreachable (distance is positive infinity).
    if (finalNodeDistance >= 0) {
        return 0;
    }
    
    // If the distance is negative (but not negative infinity), it means a positive profit was found.
    // The cost is `sum(baseProfit - p_uv)`, so the profit is `-cost`.
    return -finalNodeDistance;
}

// Execute the solution and print the final result.
console.log(executeSolution());
/*
 * This file contains a pair of distinct utility functions
 * designed for basic numerical computations.
 * The primary goal is to illustrate simple arithmetic operations.
 */

// This routine computes the multiplicative result of two supplied numbers.
function      obtainProduct
(
    firstValue,  // The initial numeric input for the operation.
    secondValue  // The subsequent numeric input to be multiplied.
)
{
    // The core logic is to return the outcome of multiplying the two arguments.
    return firstValue   *   secondValue;
}


// This routine calculates the sum of two parameters and then doubles that total.
function calculateSumThenDouble (
    inputParamA, // The first numerical operand provided to the function.
    inputParamB  // The second numerical operand, complementing the first.
)
{
    // The sequence of operations involves addition followed by multiplication by two.
    return (inputParamA + inputParamB)  *  2
    ;
}



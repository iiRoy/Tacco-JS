(function() {
    'use strict';

    // A dynamically growing buffer to store all lines read from the standard input stream.
    // Renamed from 'lines' to 'inputLineBuffer' for improved clarity.
    const inputLineBuffer = [];

    // Initialize the interface for reading data line by line from standard input.
    // The 'readline' module is a built-in Node.js utility.
    const stdInputInterface = require('readline').createInterface({
        input: process.stdin,
        output: process.stdout // Although not actively used for output, it's part of the API.
    });

    // Register an event handler to process each line as it is received.
    // The parameter 'currentSegment' represents a single line of text from the input.
    stdInputInterface.on('line', (currentSegment) => {
        // Append the current line to our buffer for later processing.
        inputLineBuffer.push(currentSegment);
    });

    // Register an event handler for when the standard input stream ends.
    // All accumulated input will be processed at this point.
    process.stdin.on('end', () => {
        // Pre-computation validation: Ensure that input data was actually provided.
        if (inputLineBuffer.length === 0) {
            console.error("Execution Aborted: No input data detected.");
            return; // Terminate execution gracefully if no input is present.
        }

        // --- Begin Primary Algorithm Execution ---

        // The very first line of input specifies the total number of operational establishments.
        // Renamed 'N' to 'establishmentCount'. Using parseInt with radix for best practice.
        const establishmentCount = parseInt(inputLineBuffer[0].trim(), 10);

        // Input validation: Check if the parsed count is a valid positive number.
        if (isNaN(establishmentCount) || establishmentCount < 1) {
            console.error("Input Parsing Error: The specified establishment count is invalid or missing.");
            return;
        }

        // Data structure to hold the feature set (e.g., operating hours) for each establishment.
        // Renamed 'F' to 'establishmentFeatures'. Using 0-based indexing for array access.
        const establishmentFeatures = new Array(establishmentCount);
        // Data structure to hold the profit matrix for each establishment based on feature matches.
        // Renamed 'P' to 'profitMatrixPerMatch'. Also using 0-based indexing.
        const profitMatrixPerMatch = new Array(establishmentCount);

        // Populate the 'establishmentFeatures' array.
        // Original code used 1-based indexing; adjusting 'inputLineBuffer' access for 0-based 'establishmentFeatures'.
        // Lines 1 through 'establishmentCount' (inclusive) contain feature data.
        for (let idx = 0; idx < establishmentCount; idx++) {
            // Each line is split by space to form an array of feature indicators (as strings).
            establishmentFeatures[idx] = inputLineBuffer[idx + 1].trim().split(' ');
        }

        // Populate the 'profitMatrixPerMatch' array.
        // Lines 'establishmentCount + 1' through '2 * establishmentCount' (inclusive) contain profit data.
        for (let idx = 0; idx < establishmentCount; idx++) {
            // Each line is split by space, and values are converted to numbers immediately.
            profitMatrixPerMatch[idx] = inputLineBuffer[idx + 1 + establishmentCount].trim().split(' ').map(Number);
        }

        // Initialize the maximum profit found so far to the smallest possible safe integer value.
        // Renamed 'maxuriage' to 'currentGlobalMaxProfit'.
        let currentGlobalMaxProfit = Number.MIN_SAFE_INTEGER;

        // Constant defining the fixed length of the binary operating pattern.
        const BINARY_PATTERN_FIXED_LENGTH = 10;
        // Calculate the total number of unique operating patterns (2^10 combinations).
        const totalPatternIterations = 1 << BINARY_PATTERN_FIXED_LENGTH; // More efficient than Math.pow(2, 10).

        // Iterate through every conceivable operating pattern.
        // Each 'patternCode' is an integer that will be converted to a binary string.
        // Renamed 'i' to 'patternCode'.
        for (let patternCode = 0; patternCode < totalPatternIterations; patternCode++) {
            // Transform the integer 'patternCode' into a zero-padded binary string.
            // Renamed 'plan' to 'activeOperationalMask'.
            const activeOperationalMask = generatePaddedBinaryString(patternCode, BINARY_PATTERN_FIXED_LENGTH);

            // Accumulator for profit generated by the current 'activeOperationalMask'.
            // Renamed 'uriage' to 'cumulativePatternProfit'.
            let cumulativePatternProfit = 0;

            // Iterate through each establishment to sum up its profit contribution for the current pattern.
            // Renamed 't' to 'establishmentIndex'.
            for (let establishmentIndex = 0; establishmentIndex < establishmentCount; establishmentIndex++) {
                // Calculate the number of matching features between the current pattern and the establishment's features.
                const featureOverlapCount = computeFeatureOverlap(
                    activeOperationalMask,
                    establishmentFeatures[establishmentIndex],
                    BINARY_PATTERN_FIXED_LENGTH
                );

                // Add the specific profit for this establishment based on the 'featureOverlapCount'.
                cumulativePatternProfit += profitMatrixPerMatch[establishmentIndex][featureOverlapCount];
            }

            // Compare the 'cumulativePatternProfit' with the highest profit recorded so far.
            if (cumulativePatternProfit > currentGlobalMaxProfit) {
                currentGlobalMaxProfit = cumulativePatternProfit;
            }
        }

        // Output the ultimate maximum profit determined across all patterns.
        console.log(currentGlobalMaxProfit);

        // --- End Primary Algorithm Execution ---
    });

    // Utility Function: Converts an integer to a binary string, ensuring it's padded with leading zeros
    // to a specified 'targetLength'.
    // Renamed from 'dump_int' to 'generatePaddedBinaryString'.
    // Parameters: 'numericValue' (original 'i'), 'targetLength' (new parameter for dynamic length).
    function generatePaddedBinaryString(numericValue, targetLength) {
        // Convert the number to its raw binary string representation.
        let binaryString = numericValue.toString(2);
        // Prepend '0's until the string reaches the desired length.
        while (binaryString.length < targetLength) {
            binaryString = '0' + binaryString;
        }
        return binaryString;
    }

    // Utility Function: Determines the number of positions where both input binary strings contain a '1'.
    // Renamed from 'matchNum' to 'computeFeatureOverlap'.
    // Parameters: 'patternOne' (original 'a'), 'patternTwo' (original 'b'), 'comparisonSpan' (new parameter).
    function computeFeatureOverlap(patternOne, patternTwo, comparisonSpan) {
        // Initialize a counter for the shared '1' bits.
        // Renamed 'mnum' to 'sharedFeatureCounter'.
        let sharedFeatureCounter = 0;

        // Iterate through each character (bit position) up to the defined comparison length.
        // Renamed 'i' to 'bitPositionIndex'.
        for (let bitPositionIndex = 0; bitPositionIndex < comparisonSpan; bitPositionIndex++) {
            // Increment the counter if both patterns have a '1' at the current bit position.
            // The condition 'a[i] == b[i] && a[i] == "1"' is simplified to 'patternOne[idx] === "1" && patternTwo[idx] === "1"'.
            if (patternOne[bitPositionIndex] === '1' && patternTwo[bitPositionIndex] === '1') {
                sharedFeatureCounter++;
            }
        }
        return sharedFeatureCounter;
    }

})();
/**
 * Reads standard input, assuming UTF-8 encoding.
 * Splits the input by newlines and returns an array of lines.
 * This function is designed to handle both Unix-style (\n) and Windows-style (\r\n) newlines.
 */
function stdin ( )
{
    // The 'fs' module is used for file system operations, specifically reading from /dev/stdin.
    var stdin = require( "fs" ) . readFileSync( "/dev/stdin" , "utf8" ) ;

    // Split the input string into an array of lines.
    // The regex /\\n\\r?/ handles both \\n and \\r\\n line endings.
    return stdin . split( /\\n\\r?/ ) ;
}


/**
 * Generates an array of numbers within a specified range, inclusive.
 *
 * @param {number} from - The starting number of the range.
 * @param {number} to   - The ending number of the range.
 * @returns {Array<number>} An array containing numbers from 'from' to 'to'.
 */
function range ( from , to )
{
    // Initialize an empty array to store the generated numbers.
    var ret = [ ] ;

    // Loop from 'from' to 'to' (inclusive) and push each number into the 'ret' array.
    for ( var i = from ; i <= to ; i ++ )
        ret . push( i ) ;

    return ret ;
}


